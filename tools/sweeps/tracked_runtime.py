"""Метёлка: под учётом git не лежит ничего, что породил прогон.

Зачем. База стенда, её спутники `-wal`/`-shm` и каталог Tor-сервиса
появляются рядом с исполняемым файлом сами, без спроса. В `db.tor/keys/`
лежит секретный ключ onion-адреса **открытым текстом**, в базе — зерно
личности. Попав под учёт, они уезжают в открытый репозиторий, и обратно
их не вернуть: выложенное считается выложенным.

Поломка, по которой метёлка заведена. Коммит c4333e0 (8 ноября) принёс
в репозиторий шесть таких файлов: `db.db`, `db.db-shm`, `db.db-wal`,
`db.tor/keys/hostname`, `hs_ed25519_public_key` и `hs_ed25519_secret_key`.
Их добавил `git add -A` из корня дерева, где лаборатория держала своё
хранилище. Запись в `.gitignore` «локальные базы и ключи — не должны
попадать в репозиторий никогда» существовала **с сентября** и была
бесполезна: образцы в ней знали `*.sqlite`, а лаборатория пишет `db.db`.
Правило было названо словами верно и проверено по неверному признаку.

Поэтому проверка идёт **по содержимому, а не по имени**: переименование
артефакта не должно выводить его из-под правила. Имя — выбор того, кто
запускал; подпись формата — нет.

Чего метёлка **не** стережёт:

* историю. Файл, убранный из учёта сегодня, остаётся в прежних коммитах
  и у всех, кто успел их забрать. Метёлка смотрит только текущий учёт,
  и зелень здесь не означает, что секрет не утёк, — только что он
  не утекает дальше;
* секреты, которых не видно по подписи: токен в текстовом файле или
  ключ, записанный шестнадцатеричной строкой, она не узнает;
* файлы вне учёта. То, что лежит в дереве и не добавлено, — не её дело:
  это `.gitignore`.
"""
import pathlib
import re
import subprocess
import sys

# Корень дерева считается от самого файла: метёлку зовут и из корня, и из CI.
ROOT_DIR = pathlib.Path(__file__).resolve().parents[2]

# Подписи форматов, которые порождает прогон и которые не бывают исходным
# кодом. Каждая — первые байты файла, кроме PEM: его заголовок бывает
# не в самом начале, поэтому для него отдельное правило ниже.
SIGNATURES = (
    (b"SQLite format 3\x00", "хранилище SQLite: это база стенда, а не исходник"),
    (b"== ed25519v1-secret:", "секретный ключ onion-адреса открытым текстом"),
    (b"== ed25519v1-public:", "ключ Tor-сервиса: каталог сервиса не наш исходник"),
)

# PEM-заголовок секретного ключа — любой: OpenSSH, RSA, EC.
PEM = re.compile(rb"-----BEGIN [A-Z0-9 ]*PRIVATE KEY-----")

# Имя файла Tor-сервиса с адресом: не секрет, но артефакт прогона, и его
# появление означает, что под учёт уехал весь каталог.
ONION = re.compile(rb"^[a-z2-7]{56}\.onion\s*$")

# Поимённые исключения — с причиной. Пусто: ни одного файла, похожего
# на артефакт прогона, в дереве быть не должно. Тест-векторы §16 правилу
# не противоречат — они текстовые и ни одной подписи не несут.
EXCEPTIONS: dict[str, str] = {}

found = []
seen = 0

listing = subprocess.run(
    ["git", "-C", str(ROOT_DIR), "ls-files", "-z"],
    capture_output=True,
    check=False,
)
if listing.returncode != 0:
    found.append("git ls-files не ответил — метёлка смотрит не туда")
else:
    for name in listing.stdout.split(b"\0"):
        if not name:
            continue
        rel = name.decode("utf-8", "surrogateescape")
        if rel in EXCEPTIONS:
            continue
        path = ROOT_DIR / rel
        if not path.is_file():
            # Подмодуль или файл, убранный из дерева, но оставшийся в учёте.
            continue
        seen += 1
        head = path.open("rb").read(256)
        for mark, why in SIGNATURES:
            if head.startswith(mark):
                found.append(f"{rel}: {why}")
                break
        else:
            if PEM.search(head):
                found.append(f"{rel}: секретный ключ в формате PEM")
            elif path.name == "hostname" and ONION.match(head):
                found.append(f"{rel}: адрес onion-сервиса — каталог сервиса под учётом")

for line in found:
    print(line)
print(f"файлов под учётом осмотрено: {seen}")
print("-- всего", len(found) if found else "чисто")

# Находок должно быть **ноль**.
sys.exit(1 if found else 0)
