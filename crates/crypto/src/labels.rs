pub const BEACON: &str = "ratatosk v0 beacon";

/// §8.3: идентификатор сессии из транскрипта Noise.
pub const SESSION_ID: &str = "ratatosk v0 sid";
/// §8.3: корневой ключ сессии.
pub const ROOT: &str = "ratatosk v0 root";
/// §8.3: цепочка инициатора.
pub const CHAIN_A: &str = "ratatosk v0 chain-a";
/// §8.3: цепочка получателя.
pub const CHAIN_B: &str = "ratatosk v0 chain-b";

/// §8.4: ключ сообщения из состояния цепочки.
pub const MSG: &str = "ratatosk v0 msg";
/// §8.4: шаг цепочки.
pub const CHAIN: &str = "ratatosk v0 chain";

/// §10.1: идентификатор чанка файла.
pub const FILE: &str = "ratatosk v0 file";

/// §11.1: шаг sender-цепочки в группе.
pub const SENDER_CHAIN: &str = "ratatosk v0 sender-chain";
/// §11.1: ключ группового сообщения.
pub const SENDER_MSG: &str = "ratatosk v0 sender-msg";

/// §12: токен поискового индекса из `db_key` и слова.
///
/// В индексе лежат не слова, а их хэши на ключе базы: полнотекстовый индекс
/// по открытым телам свёл бы `body_enc` к декорации — файл базы отдал бы
/// всю переписку тому, у кого нет PIN.
pub const SEARCH_TOKEN: &str = "ratatosk v0 search-token";

/// Контекст вывода `db_key` из секрета, хранимого ОС (§8.6, дополнение).
///
/// §8.6 обещает, что при отказе от PIN ключ базы уедет в Android Keystore.
/// Уехать туда он может только так: сам ключ Keystore не отдаёт наружу
/// никогда, поэтому наружу приходит **секрет**, а `db_key` выводится из него
/// вместе с солью базы.
///
/// Соль в материале обязательна: без неё один секрет устройства дал бы один
/// и тот же `db_key` всем аккаунтам на телефоне, и «отдельные файлы —
/// отдельные ключи» (см. `core::accounts`) перестало бы быть правдой.
pub const DEVICE_KEY: &str = "ratatosk v0 device-key";

/// §13.4: идентификатор сопряжённого устройства из его ключа сопряжения.
///
/// Выводится, а не назначается случайно, и это существенно: телефон
/// и десктоп обязаны назвать одну и ту же запись, не обменявшись ни одним
/// лишним кадром. Случайный идентификатор пришлось бы передавать —
/// то есть завести ещё одно поле, которое можно передать неверно.
pub const COMPANION_DEVICE: &str = "ratatosk v0 companion-device";

/// §13.4: ключ, которым десктоп запечатывает свой кэш переписки.
///
/// Выводится из **зерна сопряжения**, то есть из того же материала, из
/// которого десктоп строит свой статический ключ. Отсюда и честная граница
/// того, что это защищает: зерно десктоп обязан хранить открыто — иначе он
/// не переподключится без пароля, — значит ключ кэша лежит рядом с кэшем.
/// Защита получается от скопированного файла и от бэкапа, но не от
/// забранного профиля, и сказать это человеку в тексте настройки
/// обязательно (§14).
pub const COMPANION_CACHE: &str = "ratatosk v0 companion-cache";

/// §13.4: ключ, которым телефон говорит отозванному десктопу, что он отозван.
///
/// Выводится из статического DH — секретный `IK` телефона против ключа
/// сопряжения десктопа. Оба вычисляют одно и то же, не обменявшись ничем,
/// и **сессия для этого не нужна**: в том и дело, что у отозванного её
/// больше нет и не будет.
///
/// Почему это не ослабляет `IK`: тот же ключ уже участвует в Noise IK,
/// но там он идёт через транскрипт, а здесь — через свой ярлык. Ярлык
/// и есть разделение: материал один, ключи разные, и ни один из них
/// не выводится из другого.
///
/// Что это защищает: подделать такой кадр может только владелец одного
/// из двух секретов. Повторить перехваченный — можно, но лишь тому же
/// десктопу, который и так отозван: новое сопряжение заводится новым
/// зерном, то есть другим статическим ключом, и старый кадр под ним
/// не открывается.
pub const COMPANION_REVOKED: &str = "ratatosk v0 companion-revoked";

/// §13.4: зерно onion-сервиса десктопа.
///
/// Выводится из **зерна сопряжения** — как и [`COMPANION_CACHE`], и по той
/// же причине: другого долговременного секрета у десктопа нет, а заводить
/// ему отдельный файл с ключом значит завести то, что теряют, забывают
/// защитить и переносят отдельно от всего остального.
///
/// **Это противоположно решению §3 для телефона**, где `onion_key`
/// в зерно не входит и живёт своей строкой. Причина разницы в том, что
/// зерно там — это то, что человек записывает и чем восстанавливается:
/// два устройства, поднятые из одной записи, не должны получить один
/// onion-адрес. У сопряжения такого восстановления нет вовсе — второй
/// десктоп заводится новым QR, то есть новым зерном, — а два десктопа
/// с одним зерном уже одно и то же устройство по статическому ключу,
/// и совпадение адресов там не новость.
///
/// Честная граница у этого та же, что у ключа кэша: зерно десктоп хранит
/// открыто, иначе он не переподключится без пароля. Значит тот, кто забрал
/// профиль, может поднять сервис по тому же адресу. Он же может просто
/// стать вторым экраном — то есть новой возможности это не даёт.
pub const COMPANION_ONION: &str = "ratatosk v0 companion-onion";

/// Идентификатор подписанного блока состава (§11.5).
///
/// **Локальный ключ строки, а не протокольное значение**: по проводу он
/// не едет ни разу. Хранилище держит блоки по нему, чтобы тот же блок,
/// пришедший вторым транспортом (§9.2), лёг в ту же строку и не подменил
/// подписанных байт.
///
/// Ярлык здесь не ради тайны — прятать нечего, блок и так уезжает
/// участникам. Он ради того же, ради чего `chunk_id` (§10.2) выводится
/// через `derive_key`, а не через голый хэш: в этой программе **всё**
/// хэшируемое проходит через названный контекст, и исключение однажды
/// стало бы вторым.
pub const GROUP_BLOCK: &str = "ratatosk v0 group-block";

