    #[test]
    fn mail_refuses_files_it_cannot_finish() {
        assert!(may_send_over(MAIL_FILE_LIMIT_BYTES, Transport::Mail));
        assert!(!may_send_over(MAIL_FILE_LIMIT_BYTES + 1, Transport::Mail));
        assert!(may_send_over(u64::MAX, Transport::Onion));
        // Предел почты — про время, а не про место, и потому он **меньше**
        // общего предела файла, а не равен ему. Сравняй их — и гигабайт
        // уехал бы почтой, то есть не уехал бы никуда.
        assert!(MAIL_FILE_LIMIT_BYTES < MAX_FILE_BYTES);
    }

    #[test]
    fn nostr_carries_no_file_at_any_size() {
        // Отказ безусловный, и это существенно: предел по размеру,
        // как у почты, не спас бы ничего — не проходит **любой** чанк,
        // потому что класс у него всегда L, а событие реле меряется
        // десятками килобайт.
        //
        // Проверяется и ноль: «файл в ноль байт» — законный случай
        // (`chunk_count` отвечает на него нулём), и ветка, написанная
        // через сравнение, пропустила бы его молча.
        for size in [0, 1, CHUNK_BYTES as u64, MAIL_FILE_LIMIT_BYTES, MAX_FILE_BYTES, u64::MAX] {
            assert!(!may_send_over(size, Transport::Nostr), "{size} байт всё равно не поедет");
        }
    }

    #[test]
    fn the_air_carries_files_and_pays_for_them_in_time() {
        // Разрешение выдано измерением (`HANDOFF.md`, 6з), и проверяется
        // здесь не оно само, а то, что вместе с ним сошлись сроки:
        // разрешить файлы и оставить срок молчания короче окна — значит
        // получить передачу, которая сама себя разгоняет в обратную
        // сторону («файл начинает загружаться и никогда не догружается»).
        for size in [0, 1, CHUNK_BYTES as u64, MAIL_FILE_LIMIT_BYTES, MAX_FILE_BYTES] {
            assert!(may_send_over(size, Transport::Bt), "{size} байт: эфир везёт файлы");
        }
        // Предела по размеру у эфира нет, в отличие от почты: §10.3
        // разрешает большие файлы прямым каналом, а эфир прямой.
        assert!(may_send_over(u64::MAX, Transport::Bt));
        assert!(Transport::Bt.is_direct());

        // И цена названа числом: окно в два чанка при скромной скорости
        // ступени обязано помещаться в срок молчания. То же самое для
        // всех ступеней держит
        // `the_stall_deadline_outlasts_a_window_on_every_transport`;
        // здесь — про эфир поимённо, потому что именно ему разрешение
        // выдано последним.
        let speed =
            crate::transport_policy::floor_bytes_per_sec(Transport::Bt).expect("ступень прямая");
        let window_ms = chunk_window(Transport::Bt) * CHUNK_BYTES as u64 * 1_000 / speed;
        assert!(
            stall_ms(Transport::Bt) > window_ms,
            "окно идёт {window_ms} мс, а застой объявляется через {}",
            stall_ms(Transport::Bt)
        );
    }

