//! Ошибки криптослоя.

use thiserror::Error;

/// Отказ криптографической операции.
///
/// Формулировки намеренно скупые: подробность здесь — источник оракулов.
/// Диагностика идёт в `tracing` на уровне `debug`, а не в текст ошибки,
/// который может дойти до другой стороны.
#[derive(Debug, Error)]
pub enum CryptoError {
    /// Проверка тега AEAD не прошла.
    ///
    /// Единственная реакция — отбросить кадр и увеличить счётчик аномалий
    /// по источнику (§7.3, шаг 4). Различать «не тот ключ» и «испорченные
    /// байты» нельзя: это и есть оракул.
    #[error("не удалось расшифровать кадр")]
    Decrypt,

    /// Ошибка внутри Noise-рукопожатия.
    #[error("рукопожатие отклонено")]
    Handshake,

    /// Повторно предъявленное рукопожатие (§8.3, anti-replay).
    #[error("повтор рукопожатия")]
    HandshakeReplay,

    /// Запрошен ключ сообщения, который уже был выдан и стёрт (§8.4).
    ///
    /// Ключ сообщения стирается сразу после использования — в этом и состоит
    /// forward secrecy. Повторный запрос означает либо дубль, который должен
    /// был отсеяться дедупликацией (§9.2), либо попытку повтора.
    #[error("ключ сообщения уже использован")]
    MessageKeyConsumed,

    /// Счётчик ушёл слишком далеко вперёд.
    ///
    /// Предел нужен, чтобы кадр с `counter = u64::MAX` не заставлял выводить
    /// невообразимое число ключей (§7.3, шаг 3).
    #[error("счётчик за пределом допустимого скачка")]
    CounterTooFarAhead,

    /// Некорректная контакт-карточка или ключевой материал в ней.
    #[error("некорректный ключевой материал")]
    BadKeyMaterial,

    /// Некорректный формат кадра.
    #[error("некорректный кадр: {0}")]
    Wire(#[from] ratatosk_wire::WireError),
}

/// Результат криптографической операции.
pub type Result<T> = core::result::Result<T, CryptoError>;
