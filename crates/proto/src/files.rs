    fn the_stall_deadline_outlasts_a_window_on_every_transport() {
        // Ошибка, которую это стережёт: срок молчания короче времени передачи
        // не ускоряет возобновление, а ломает её совсем. Получатель объявляет
        // молчанием чанк, который прямо сейчас идёт по проводу, отправитель
        // отматывает окно и кладёт в ту же линию второй экземпляр того же
        // мебибайта — и передача разгоняет сама себя в обратную сторону.
        // Снаружи: «файл начинает загружаться и никогда не догружается».
        //
        // Скорость берётся **из политики** (`floor_bytes_per_sec`), а не
        // пишется здесь числом. Второе такое число однажды разошлось бы
        // с первым, и разошлось бы молча: сроки остались бы посчитанными
        // по скорости, в которую ступень давно не укладывается.
        //
        // У почты своей скорости нет (ждать её ответа бессмысленно),
        // и для неё остаётся прежнее скромное число: одна цепочка Tor
        // через три реле это не канал, а обещание канала.
        const SLOW_BYTES_PER_SEC: u64 = 30 * 1024;
        for via in [Transport::Bt, Transport::Onion, Transport::Mail] {
            // Почтой байты проходят сеть дважды: до сервера и с сервера,
            // — и едут раздутыми в письме, а не голым кадром.
            let (window_bytes, hops) = match via {
                Transport::Mail => (mail_window_bytes(), 2),
                _ => (chunk_window(via) * CHUNK_BYTES as u64, 1),
            };
            let speed =
                crate::transport_policy::floor_bytes_per_sec(via).unwrap_or(SLOW_BYTES_PER_SEC);
            let needed_ms = window_bytes * hops * 1_000 / speed;
            assert!(
                stall_ms(via) >= needed_ms,
                "в срок молчания обязано помещаться целое окно {via:?}: нужно {needed_ms} мс, \
                 отведено {}",
                stall_ms(via)
            );
        }
        // По локальной сети мебибайт уходит за миллисекунды, и срок там нужен
        // не для скорости, а чтобы оборванная передача вообще возобновилась.
        assert!(
            stall_ms(Transport::Lan) < stall_ms(Transport::Onion),
            "у транспортов разная цена мебибайта — значит и сроки разные"
        );
        assert!(
            stall_ms(Transport::Onion) < stall_ms(Transport::Mail),
            "круг почты — минуты, и срок обязан это признавать"
        );
    }

    #[test]
    fn the_backoff_grows_and_stops() {
        // Без отступления брошенная почтовая передача спрашивала бы письмом
        // каждые полчаса вечно: сорок восемь писем в сутки и столько же
        // следов у сервера.
        let via = Transport::Mail;
        assert_eq!(stall_backoff_ms(via, 0), stall_ms(via), "первая попытка — обычный срок");
        assert_eq!(stall_backoff_ms(via, 1), stall_ms(via) * 2);
        assert!(stall_backoff_ms(via, 3) > stall_backoff_ms(via, 2));
        assert_eq!(stall_backoff_ms(via, 30), MAX_STALL_MS, "потолок обязан быть достижим");
        // И потолок обязан именно потолком быть, а не паникой на сдвиге.
        assert_eq!(stall_backoff_ms(via, u32::MAX), MAX_STALL_MS);
        assert_eq!(stall_backoff_ms(Transport::Lan, u32::MAX), MAX_STALL_MS);
    }

