    #[tokio::test]
    async fn a_second_attempt_to_come_up_is_a_real_attempt() {
        // Разбор поломки со стенда: после перезапуска меш не работал,
        // и чинился выключением и включением руками.
        //
        // Причина была здесь: отказ подъёма сбрасывал признак «включено»
        // обратно в «выключено», и повторное «включить» становилось
        // бесплатным повтором — то есть ступень, не поднявшаяся по случайной
        // причине, не поднималась больше никогда.
        //
        // Признак — **намерение человека**, а не «поднято сейчас». Поднято
        // ли, говорит `is_ready`, и врать ему нечем.
        let mut runner = YggRunner::start(YggConfig::default(), &[]).await.expect("выключенный");
        let on = TransportCommand::SetEnabled { transport: Transport::Ygg, enabled: true };

        // Первая попытка: имени нет, подняться не на чем.
        assert!(matches!(runner.execute(on.clone()).await, Err(TransportError::NoAddress)));
        assert!(!runner.is_ready(), "и ступень честно не работает");

        // Вторая — **не** бесплатный повтор: тот же отказ, а не `Ok(())`.
        // Именно эта разница и означает, что настройка, приехавшая позже
        // включения, поднимет ступень, а не застанет её выключенной.
        assert!(
            matches!(runner.execute(on).await, Err(TransportError::NoAddress)),
            "повтор при неподнятой ступени обязан быть второй попыткой"
        );
    }

