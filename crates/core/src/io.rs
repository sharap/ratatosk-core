//! Вход и выход ядра.
//!
//! Ядро — чистая функция состояния: `(состояние, вход, время) → (состояние,
//! эффекты)`. Оно ничего не ждёт и ничего не делает само; всё, что должно
//! случиться во внешнем мире, возвращается списком [`Effect`].
//!
//! Из этого следует главное свойство, ради которого §17 требует делать
//! харнесс первым: чтобы прогнать неделю разделения сети (§16), достаточно
//! подавать входы и исполнять эффекты в цикле с виртуальным временем.

use ratatosk_crdt::MsgId;
use ratatosk_proto::transport_policy::Transport;
use ratatosk_proto::DeliveryStatus;

/// Идентификатор чата — 1:1 или группы.
pub type ChatId = [u8; 16];

/// Что пользователь просит сделать.
#[derive(Debug, Clone)]
pub enum Command {
    /// Отправить текст.
    SendText {
        /// Куда.
        chat: ChatId,
        /// Что.
        text: String,
    },
    /// Отправить файлы — одним сообщением, с подписью или без (§10).
    ///
    /// К одному сообщению можно приложить несколько файлов
    /// (`ratatosk_proto::files::MAX_FILES_PER_MESSAGE`): «скинуть фотографии» —
    /// обычный случай, а не расширение.
    ///
    /// Файл **не копируется**: ядро читает его с диска по пути, когда дело
    /// доходит до чанков. Копировать гигабайт в своё хранилище ради отправки
    /// значит требовать вдвое больше места, чем у файла есть, — и это же
    /// означает, что исчезнувший исходник останавливает передачу.
    SendFiles {
        /// Куда.
        chat: ChatId,
        /// Что отправляем.
        files: Vec<OutgoingFile>,
        /// Подпись к вложениям. Пустая строка — законно.
        text: String,
    },
    /// Принять входящий файл к загрузке.
    ///
    /// Нужна только тем файлам, которые не прошли по порогу автоприёма
    /// ([`Command::SetAutoAcceptBytes`]). Согласие переживает перезапуск:
    /// спрашивать дважды об одном файле незачем.
    AcceptFile {
        /// Какой.
        file_id: [u8; 16],
    },
    /// Отказаться от входящего файла.
    ///
    /// Сведения о файле и всё, что успело приехать, удаляются. Собеседнику
    /// не сообщается ничего: отказ — решение о своей памяти, а не сообщение
    /// о себе.
    DeclineFile {
        /// Какой.
        file_id: [u8; 16],
    },
    /// Порог автоматического приёма файлов, в байтах.
    ///
    /// `None` — принимать только вручную. Настройка переживает перезапуск.
    /// По умолчанию — `ratatosk_proto::files::DEFAULT_AUTO_ACCEPT_BYTES`:
    /// мелочь вроде фотографии приезжает сама, всё крупнее ждёт нажатия,
    /// потому что чужой клиент не должен уметь занять память телефона,
    /// не спросив.
    SetAutoAcceptBytes(Option<u64>),
    /// Добавить контакт по карточке из QR или ссылки (§4.2).
    AddContact {
        /// Канонические байты карточки.
        card_bytes: Vec<u8>,
        /// Получена при личной встрече — отпечаток сверять не нужно (§4.2).
        met_in_person: bool,
    },
    /// Подтвердить сверку отпечатка голосом (§4.2).
    MarkVerified {
        /// Чей отпечаток сверили.
        peer_ik: [u8; 32],
    },
    /// Отозвать сверку отпечатка (§4.2).
    ///
    /// Отдельная команда, а не `MarkVerified { verified: false }`: снятие
    /// доверия — не то же действие, что его выдача, и логический флаг в этом
    /// месте слишком легко передать не тот. Собеседнику при этом не уходит
    /// ничего: отзыв — решение пользователя о себе, а не сообщение о нём.
    RevokeVerification {
        /// У кого.
        peer_ik: [u8; 32],
    },
    /// Подписать контакт своим именем — или снять подпись (`None`).
    ///
    /// Имя **локальное**: по проводу не едет никогда. Имя из карточки задаёт
    /// собеседник, и §4.1 прямо называет его не доверенным; это — своя
    /// пометка, и отправить её значило бы и сообщить человеку, как его
    /// записали, и завести поле, которое он может подделать.
    SetLocalName {
        /// Кого.
        peer_ik: [u8; 32],
        /// Как. `None` — вернуться к имени из карточки.
        name: Option<String>,
    },
    /// Удалить контакт.
    ///
    /// Личность уходит всегда: карточка, отметка о сверке (§4.2), аватарка,
    /// сессия и её ключевой материал (§8.3). Переписка — по решению человека,
    /// и решает его клиент: ядро не вправе ни выбросить её за него, ни
    /// оставить, если он просил убрать.
    DeleteContact {
        /// Кого.
        peer_ik: [u8; 32],
        /// Удалить ли вместе с ним переписку.
        purge_history: bool,
    },
    /// Создать группу.
    CreateGroup {
        /// Название.
        title: String,
    },
    /// Пригласить в группу (§11.2).
    InviteToGroup {
        /// Группа.
        chat: ChatId,
        /// Кого.
        peer_ik: [u8; 32],
    },
    /// Исключить из группы. Только создатель (§11.2).
    EvictFromGroup {
        /// Группа.
        chat: ChatId,
        /// Кого.
        peer_ik: [u8; 32],
    },
    /// Удалить сообщения **у себя**.
    ///
    /// Тихо и без трафика: собеседник не узнает. Работает и над своими,
    /// и над чужими сообщениями — это своя история, и распоряжается ей
    /// пользователь.
    DeleteMessages {
        /// Из какого чата.
        chat: ChatId,
        /// Какие.
        msg_ids: Vec<MsgId>,
    },
    /// Удалить у себя и **попросить** собеседника удалить у себя.
    ///
    /// Именно попросить: что сделает с просьбой чужой клиент, протокол
    /// не знает и обещать не может (§14). Просьба уходит только про **свои**
    /// сообщения — чужие удаляются локально, как при [`Command::DeleteMessages`].
    RetractMessages {
        /// Из какого чата.
        chat: ChatId,
        /// Какие.
        msg_ids: Vec<MsgId>,
    },
    /// Ответить на сообщение.
    ///
    /// По проводу едет **ссылка** (`msg_id`), а не отрывок цитаты: цитату
    /// каждая сторона рисует из своей копии, и подделать её поэтому нельзя
    /// (`ratatosk_proto::reply`). Отвечать можно на любое сообщение этого чата —
    /// и на своё, и на чужое.
    ///
    /// Если у получателя исходного сообщения нет — удалил, не дошло, вычистила
    /// уборка (§12), — ответ всё равно сохраняется, а цитировать нечего:
    /// UI обязан сказать это прямо, а не придумывать текст.
    SendReply {
        /// Куда.
        chat: ChatId,
        /// На что отвечаем.
        reply_to: MsgId,
        /// Что.
        text: String,
    },
    /// Заменить текст своего сообщения и попросить собеседника сделать то же.
    ///
    /// Именно попросить — устройство то же, что у [`Command::RetractMessages`]:
    /// правка едет обычной очередью §5.4, а что сделает с ней чужой клиент,
    /// протокол не знает (§14).
    ///
    /// **Прежний текст не сохраняется ни у кого**, но у сообщения появляется
    /// отметка «изменено»: молча подменить слова в чужой истории §14 запрещает.
    /// Править можно только своё и только в течение недели
    /// (`ratatosk_proto::MAX_EDIT_AGE_MS`) — оба правила проверяет и отправитель,
    /// и получатель.
    EditMessage {
        /// В каком чате.
        chat: ChatId,
        /// Какое сообщение.
        msg_id: MsgId,
        /// Новый текст. Пустой — не правка, а удаление: для него есть отзыв.
        text: String,
    },
    /// Переслать сообщения в другой чат.
    ///
    /// Каждое уезжает **своим новым сообщением** с пометкой «переслано»
    /// и **без имени автора**: подпись §6 при пересылке не сохраняется, и имя
    /// рядом с чужими словами было бы утверждением, которое получатель
    /// проверить не может (`ratatosk_proto::forward`).
    ForwardMessages {
        /// Куда пересылать.
        chat: ChatId,
        /// Что пересылать. Источник может быть любым чатом.
        msg_ids: Vec<MsgId>,
    },
    /// Поставить или снять свою реакцию на сообщение.
    ///
    /// Одна реакция от человека: новая заменяет прежнюю, пустая строка
    /// снимает. Отдельной команды для снятия нет намеренно — по проводу это
    /// такое же состояние, как и любое другое, а второе представление того же
    /// самого однажды разошлось бы с первым.
    SetReaction {
        /// В каком чате.
        chat: ChatId,
        /// На какое сообщение — своё или собеседника.
        msg_id: MsgId,
        /// Эмодзи. Пустая строка — снять свою реакцию. Пределы —
        /// в `ratatosk_proto::reaction`.
        emoji: String,
    },
    /// Очистить чат целиком — **у себя**.
    ///
    /// Отзыва здесь нет намеренно: просьба удалить всю переписку — это кадр
    /// с сотнями идентификаторов и решение за собеседника о его истории.
    /// Убрать разговор у себя и стереть его у другого — разные намерения,
    /// и второе, если нужно, выражается явным отзывом выбранных сообщений.
    ClearChat {
        /// Какой.
        chat: ChatId,
    },
    /// Отметить сообщения прочитанными.
    MarkRead {
        /// Чат.
        chat: ChatId,
        /// До какого сообщения включительно.
        up_to: MsgId,
    },
    /// Поставить или снять свою аватарку.
    ///
    /// Пустые байты означают «снять»: отдельного варианта для этого нет
    /// нарочно, потому что по проводу «у меня нет аватарки» — такое же
    /// сообщение, как и любое другое, и второе представление того же самого
    /// разошлось бы с первым.
    ///
    /// Аватарка уходит **только сверенным контактам** (§4.2) и только прямым
    /// каналом. Правила и пределы — в `ratatosk_proto::avatar`.
    SetAvatar(Vec<u8>),
    /// Включить или выключить LAN (§5.1).
    SetLanEnabled(bool),
    /// Сеть под ногами сменилась: другой Wi-Fi, переход на мобильный,
    /// пробуждение устройства.
    ///
    /// Команда, а не догадка ядра: заметить это может только система —
    /// на Android `ConnectivityManager`, — а ядро не имеет ни сокетов,
    /// ни часов, чтобы отличить смену сети от тишины собеседника.
    ///
    /// Всё, что известно о локальной сети, после этого недействительно:
    /// адреса принадлежали прежней сети, соединения оборваны, объявление
    /// mDNS ушло вместе с интерфейсом.
    NetworkChanged,
}

/// Файл, который пользователь просит отправить.
#[derive(Debug, Clone)]
pub struct OutgoingFile {
    /// Путь на диске. Читается лениво, по чанку за раз.
    pub path: std::path::PathBuf,
    /// Превью изображения до 32 КиБ (§10.3).
    ///
    /// Готовит **клиент**, как и аватарку: декодер изображений — большая
    /// поверхность атаки, и в процессе, который держит ключи, ему делать
    /// нечего. Без превью человек на той стороне решает «принимать или нет»
    /// по имени файла, то есть вслепую.
    pub preview: Option<Vec<u8>>,
}

/// Что нашла и убрала уборка осиротевших вложений (§12).
///
/// Три числа, а не одно, потому что это три разных случая, и человеку,
/// который смотрит на «освободить место», полезно знать какой у него.
/// Целые вложения без записи в базе — это переписка, удалённая вместе
/// с контактом; обрывки — след от процесса, убитого системой между записью
/// чанка и отметкой о нём.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct Swept {
    /// Сколько вложений убрано целиком: в базе о них нет ни строчки.
    pub files: u64,
    /// Сколько отдельных чанков убрано у вложений, которые база знает.
    pub chunks: u64,
    /// Сколько байт освободилось всего.
    pub bytes: u64,
}

/// Что произошло снаружи.
#[derive(Debug, Clone)]
pub enum Input {
    /// Команда от UI.
    Command(Command),
    /// Пришли байты из транспорта.
    Received {
        /// Каким транспортом.
        via: Transport,
        /// Байты кадра.
        frame: Vec<u8>,
    },
    /// Контакт замечен в LAN (§5.1).
    SeenOnLan {
        /// Чей маяк совпал.
        peer_ik: [u8; 32],
    },
    /// Соединение установлено.
    Connected {
        /// С кем.
        peer_ik: [u8; 32],
        /// Каким транспортом.
        via: Transport,
    },
    /// Соединение разорвано или не удалось (§5.4).
    ConnectionLost {
        /// С кем.
        peer_ik: [u8; 32],
        /// Каким транспортом.
        via: Transport,
    },
    /// Сработал таймер, поставленный эффектом [`Effect::SetTimer`].
    Timer {
        /// Метка таймера.
        token: u64,
    },
}

/// Что ядро просит сделать внешний мир.
#[derive(Debug, Clone)]
pub enum Effect {
    /// Отправить кадр. Ровно один транспорт на эффект (§5.4).
    Send {
        /// Кому.
        peer_ik: [u8; 32],
        /// Каким транспортом.
        via: Transport,
        /// Готовый кадр.
        frame: Vec<u8>,
    },
    /// Установить соединение.
    Connect {
        /// С кем.
        peer_ik: [u8; 32],
        /// Каким транспортом.
        via: Transport,
    },
    /// Поставить таймер.
    SetTimer {
        /// Через сколько мс.
        after_ms: u64,
        /// Метка, которая вернётся во [`Input::Timer`].
        token: u64,
    },
    /// Включить или выключить объявление в LAN.
    SetLanEnabled(bool),
    /// Поднять LAN-транспорт заново: занять порт, объявиться, забыть адреса.
    ///
    /// Отдельно от `SetLanEnabled(false)` + `SetLanEnabled(true)`, потому что
    /// это не то же самое: выключение LAN — решение пользователя, и оно
    /// сохраняется, а переоткрытие ничего не решает за него.
    RestartLan,
    /// Чьи маяки искать в эфире LAN (§5.1).
    ///
    /// Маяк ротируется и вычисляется от `IK` контакта, поэтому транспорт
    /// обязан знать список известных контактов: сравнивать принятую
    /// TXT-запись ему иначе не с чем. Список едет эффектом, а не читается
    /// транспортом из ядра, потому что §13.3 запрещает протокольному
    /// состоянию просачиваться вниз иначе как через эту границу.
    WatchLanPeers(Vec<[u8; 32]>),
    /// Сообщить UI о событии.
    Notify(Event),
}

/// Событие для UI.
#[derive(Debug, Clone)]
pub enum Event {
    /// Пришло сообщение.
    MessageReceived {
        /// В каком чате.
        chat: ChatId,
        /// Идентификатор.
        msg_id: MsgId,
    },
    /// Изменился статус доставки (§9.4).
    StatusChanged {
        /// Какое сообщение.
        msg_id: MsgId,
        /// Новый статус.
        status: DeliveryStatus,
    },
    /// Добавлен контакт.
    ContactAdded {
        /// Чей.
        peer_ik: [u8; 32],
        /// Отпечаток для показа пользователю (§3).
        fingerprint: String,
        /// Сверен ли отпечаток. Пока нет — UI обязан пометить контакт
        /// непроверенным (§4.2).
        verified: bool,
    },
    /// Сообщения исчезли из чата: удалены у себя или отозваны собеседником.
    ///
    /// Одно событие на список: удаление редко бывает поштучным, а UI всё
    /// равно перерисовывает чат целиком.
    MessagesDeleted {
        /// В каком чате.
        chat: ChatId,
        /// Какие.
        msg_ids: Vec<MsgId>,
    },
    /// Сообщение изменилось: автор его поправил.
    ///
    /// Прежнего текста нет ни у кого — UI перечитывает сообщение и обязан
    /// показать отметку «изменено» (`FfiMessage::edited_at_ms`). Без отметки
    /// подмена текста в истории была бы молчаливой, а §14 это запрещает.
    MessageEdited {
        /// В каком чате.
        chat: ChatId,
        /// Какое сообщение.
        msg_id: MsgId,
    },
    /// Реакция появилась, сменилась или исчезла.
    ///
    /// Что именно стало — событием не едет: реакция читается вместе с
    /// сообщением, и класть её сюда значило бы завести второй источник того же
    /// сведения. Клиент перечитывает сообщение.
    ReactionChanged {
        /// В каком чате.
        chat: ChatId,
        /// На каком сообщении.
        msg_id: MsgId,
        /// Чья реакция изменилась. Своя — собственный `IK`.
        author_ik: [u8; 32],
    },
    /// Контакт изменился: сверка, локальное имя.
    ///
    /// Одно событие на все изменения контакта, кроме появления и удаления:
    /// клиент всё равно перечитывает список целиком, а десять узких событий
    /// он бы просто свёл в одно — но уже у себя, и с ошибками.
    ContactChanged {
        /// Чей.
        peer_ik: [u8; 32],
    },
    /// Контакт удалён.
    ContactRemoved {
        /// Чей.
        peer_ik: [u8; 32],
    },
    /// У контакта появилась, сменилась или исчезла аватарка.
    ///
    /// Байты событием не едут: они большие, а событие может ждать в очереди.
    /// Клиент забирает их запросом, когда дойдёт до отрисовки.
    AvatarChanged {
        /// Чья.
        peer_ik: [u8; 32],
    },
    /// Изменился состав группы (§11.2).
    GroupMembershipChanged {
        /// Какая группа.
        chat: ChatId,
    },
    /// Ход передачи файла (§10.2).
    FileProgress {
        /// Какой файл.
        file_id: [u8; 16],
        /// Принято чанков.
        received: u64,
        /// Всего чанков.
        total: u64,
    },
    /// Сообщение, которое обязано быть показано дословно (§14).
    ///
    /// Отдельный вариант нужен, чтобы формулировки из §14 нельзя было
    /// «улучшить» в клиенте: раздел существует ровно затем, чтобы обещания
    /// продукта не разошлись со свойствами протокола.
    HonestNotice {
        /// Текст.
        text: &'static str,
    },
}
