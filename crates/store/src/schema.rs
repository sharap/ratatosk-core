/// Один файл — несколько сообщений (§10 + пересылка).
///
/// **Что это чинит.** Пересылка везла только тело сообщения, а у сообщения
/// с вложениями тело — это подпись к ним. Нет подписи — у получателя
/// пустое сообщение, и файлы не доехали вовсе.
///
/// Переслать файл — значит переслать **ключ и хэш**, как и было записано
/// в `proto::forward` с самого начала. Но байты чанка запечатаны с `file_id`
/// в AAD (§10.1): под новым `file_id` те же байты не откроются, а
/// перешифровать гигабайт ради пересылки — не то, что делают на телефоне.
/// Значит `file_id` обязан остаться прежним, и один файл обязан уметь
/// принадлежать нескольким сообщениям.
///
/// Отсюда таблица связки. Ключ и содержимое живут в `files` (там же они
/// и запечатаны — по `file_id`, а не по сообщению, так что перевешивать
/// ничего не пришлось), а «в каком сообщении и на каком месте» — здесь.
///
/// # Каскад пришлось достроить, и это выяснилось тестом
///
/// Раньше удаление сообщения уносило файл через `files.msg_id`. Со связкой
/// каскад доходит только до **строки связки** — и первая же редакция
/// оставляла запись файла жить после удаления чата. Поймал это
/// `deleting_a_message_takes_its_files_and_their_chunk_tally`: путей,
/// удаляющих сообщение, больше одного, и «не забыть убрать сироту»
/// в каждом — та самая забывчивость, от которой заводят инварианты.
///
/// Поэтому инвариант держит **сама схема**: триггер `files_drop_orphans`
/// убирает файл, у которого не осталось ни одной связки, по какому бы
/// пути связка ни ушла — явным `DELETE`, каскадом от сообщения, уборкой
/// §12. «Файл без ссылок» после этого просто не существует.
///
/// Байты триггер не трогает и не может: они лежат в `Blobs`, а не в базе.
/// Их убирает вызывающий — по списку, который отдаёт `detach_files_of`,
/// а то, что ушло мимо него, подбирает сверка каталога с базой
/// (`Engine::sweep_orphan_files`): для неё файл без строки — мусор,
/// и это её обычная работа.
pub const MIGRATION_0024: &str = r#"
CREATE TABLE message_files (
    msg_id   BLOB NOT NULL REFERENCES messages(msg_id) ON DELETE CASCADE,
    file_id  BLOB NOT NULL REFERENCES files(file_id) ON DELETE CASCADE,
    ordinal  INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (msg_id, file_id)
) STRICT;
CREATE INDEX message_files_by_file ON message_files(file_id);

INSERT INTO message_files (msg_id, file_id, ordinal)
     SELECT msg_id, file_id, ordinal FROM files;

DROP INDEX files_by_message;
ALTER TABLE files DROP COLUMN msg_id;
ALTER TABLE files DROP COLUMN ordinal;

CREATE TRIGGER files_drop_orphans AFTER DELETE ON message_files
BEGIN
    DELETE FROM files
     WHERE file_id = OLD.file_id
       AND NOT EXISTS (SELECT 1 FROM message_files WHERE file_id = OLD.file_id);
END;
"#;

/// Отложенные групповые кадры переживают перезапуск (§11.5 + §9.2).
