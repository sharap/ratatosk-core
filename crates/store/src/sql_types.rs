//! Преобразование 64-битных значений к типам SQLite.
//!
//! В SQLite нет беззнаковых целых: `INTEGER` — это `i64`. Поэтому `rusqlite`
//! сознательно не реализует `ToSql` для `u64`, и любое `as i64` по месту —
//! это молча принятое решение о том, что делать с половиной диапазона.
//!
//! В протоколе два разных вида 64-битных значений, и путать их нельзя:
//!
//! * **величины** — метки времени, счётчики, размеры. Они заведомо меньше
//!   `i64::MAX` (миллисекунды Unix упрутся в него через 292 миллиона лет),
//!   их можно сравнивать в SQL, и по ним строятся индексы возраста (§12);
//! * **непрозрачные идентификаторы** — `session_id` из хэша транскрипта
//!   (§8.3). Он равномерно занимает все 64 бита, то есть **в половине
//!   случаев больше `i64::MAX`**. Сохранять его можно только побитово,
//!   а сравнивать в SQL на «больше-меньше» — нельзя: порядок будет рваться
//!   ровно посередине.
//!
//! Разделение сделано типами функций, а не комментарием: перепутать их можно,
//! но для этого придётся написать другое имя.

/// Переводит величину в то, что понимает SQLite.
///
/// Предназначено для меток времени, счётчиков и размеров. В отладочной сборке
/// выход за `i64::MAX` — паника: это означало бы, что сюда попал непрозрачный
/// идентификатор, для которого есть [`id_to_sql`]. В релизе значение
/// насыщается, потому что уронить мессенджер хуже, чем записать заведомо
/// большое число.
#[must_use]
pub fn to_sql(value: u64) -> i64 {
    debug_assert!(
        value <= i64::MAX as u64,
        "величина {value} не помещается в i64: для непрозрачных идентификаторов есть id_to_sql"
    );
    i64::try_from(value).unwrap_or(i64::MAX)
}

/// Читает величину обратно.
///
/// Отрицательное значение в столбце величины означает порчу данных или
/// запись мимо [`to_sql`]; вместо тихого превращения в огромное число
/// возвращается ноль.
#[must_use]
pub fn from_sql(value: i64) -> u64 {
    u64::try_from(value).unwrap_or(0)
}

/// Сохраняет непрозрачный 64-битный идентификатор побитово.
///
/// Применяется к `session_id` (§8.3) и любым другим значениям, полученным
/// из хэша. Обратное преобразование — [`id_from_sql`]; пара сохраняет все
/// 64 бита. Сравнивать такие столбцы в SQL можно **только на равенство**.
#[must_use]
pub const fn id_to_sql(value: u64) -> i64 {
    value as i64
}

/// Восстанавливает непрозрачный идентификатор.
#[must_use]
pub const fn id_from_sql(value: i64) -> u64 {
    value as u64
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn magnitudes_round_trip() {
        for v in [0u64, 1, 1_000, 1_760_000_000_000, i64::MAX as u64] {
            assert_eq!(from_sql(to_sql(v)), v);
        }
    }

    #[test]
    fn timestamps_are_nowhere_near_the_limit() {
        // Миллисекунды Unix на 2026 год против i64::MAX — запас есть.
        let now_ms = 1_776_000_000_000u64;
        assert!(now_ms < i64::MAX as u64 / 1_000_000);
    }

    #[test]
    fn opaque_ids_round_trip_across_the_whole_range() {
        // Значения из хэша равномерны по всем 64 битам, поэтому проверяем
        // именно верхнюю половину — ту, где наивное `as i64` даёт минус.
        for v in [0u64, 1, i64::MAX as u64, i64::MAX as u64 + 1, u64::MAX, 0xDEAD_BEEF_CAFE_F00D] {
            assert_eq!(id_from_sql(id_to_sql(v)), v);
        }
    }

    #[test]
    fn high_ids_really_do_go_negative() {
        // Фиксируем то, из-за чего эти функции разделены: половина
        // идентификаторов сессий хранится в SQLite отрицательными числами,
        // и порядок по ним бессмыслен.
        assert!(id_to_sql(u64::MAX) < 0);
        assert!(id_to_sql(i64::MAX as u64 + 1) < 0);
        assert!(id_to_sql(i64::MAX as u64) > 0);
    }

    #[test]
    fn corrupt_negative_magnitude_becomes_zero() {
        assert_eq!(from_sql(-1), 0);
        assert_eq!(from_sql(i64::MIN), 0);
    }

    #[test]
    fn magnitude_conversion_saturates_in_release() {
        // debug_assert в отладке ловит ошибку раньше, но поведение релиза
        // тоже должно быть определённым.
        assert_eq!(i64::try_from(u64::MAX).unwrap_or(i64::MAX), i64::MAX);
    }
}
