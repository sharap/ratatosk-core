//! Tor onion-to-onion (§5.2).
//!
//! Каждое устройство поднимает onion-сервис v3 через встроенный arti. Это
//! одновременно решает три задачи:
//!
//! * NAT-traversal — у onion-адреса нет NAT, hole punching не нужен,
//!   STUN/TURN не нужны (и потому вынесены в §15 как «не нужны», а не
//!   «отложены»);
//! * стабильную адресацию при смене сети — адрес не зависит от IP;
//! * сокрытие IP обеих сторон.
//!
//! Цена, которую §5.2 называет прямо: 300–800 мс односторонней задержки,
//! единицы секунд на установление, десятки мегабайт памяти на Tor-клиент.
//!
//! # Что уже проверено по документации arti-client 0.45
//!
//! Исходящая сторона:
//!
//! ```text
//! TorClient::create_bootstrapped(config).await? -> Arc<TorClient>
//! client.connect((address, port)).await?        -> DataStream
//! ```
//!
//! `DataStream` реализует `AsyncRead` и `AsyncWrite`, поэтому кадрирование
//! берётся готовым из `crate::link` — тем же, что работает на LAN.
//!
//! Входящая сторона:
//!
//! ```text
//! client.launch_onion_service(config)?
//!     -> Option<(Arc<RunningOnionService>, impl Stream<Item = RendRequest>)>
//! tor_hsservice::handle_rend_requests(stream)
//!     -> impl Stream<Item = StreamRequest>
//! request.accept(connected).await? -> DataStream
//! ```
//!
//! `Ok(None)` означает «сервис выключен в конфиге» — не ошибку.
//!
//! # Откуда берётся ключ
//!
//! `launch_onion_service` принимает только конфиг: ключ arti ищет у себя
//! по `nickname`, и передать его аргументом нельзя. Своё хранилище он
//! заполняет сам, а **чужое читает только в формате C Tor** — этим и
//! пользуемся: `core::accounts::write_onion_keystore` раскладывает наш ключ
//! в каталог, объявленный как `ctor`-хранилище.
//!
//! Цена названа в `ARCHITECTURE.md` (5ф) и повторена здесь, потому что
//! умалчивать её нельзя: ключ при этом лежит на диске **открытым**,
//! и PIN (§8.6) его не защищает. Взамен адрес принадлежит базе — считается
//! до всякого bootstrap и переживает восстановление на другом устройстве.
//!
//! # Два предупреждения из документации, касающиеся всего процесса
//!
//! * arti может вызвать `exit(1)`, получив консенсус с пометкой «эта версия
//!   устарела». Не при старте, а в работе — то есть приложение способно
//!   умереть посреди переписки, и это поведение библиотеки, а не наше.
//! * После создания async-рантайма процессу нельзя делать `fork`.

/// Ожидаемая односторонняя задержка, нижняя граница (§5.2).
