    #[test]
    fn an_offer_with_a_full_sized_preview_fits_its_frame() {
        // **Замер, а не оценка** — третий раз в этом файле и по той же
        // причине. Превью §10.3 едет в первой просьбе выгрузки вместе
        // с именем и подписью; не влезь оно в кадр, `frames::seal` вернул бы
        // отказ, и отправка картинки с ноутбука не работала бы вовсе —
        // а виновата была бы «сеть».
        //
        // Имя взято предельное — на него граница есть
        // (`MAX_FILE_NAME_CHARS`), и кириллица в UTF-8 идёт по два байта.
        // Подпись пустая **нарочно**: предела у неё нет вовсе, и мерить
        // с ней значило бы мерить выдуманное число. Сколько её влезает,
        // говорит второе утверждение.
        let full = Request::FileOffer {
            chat: [1u8; 16],
            name: "и".repeat(crate::files::MAX_FILE_NAME_CHARS),
            size_bytes: u64::MAX,
            preview: Some(vec![0xa5; crate::files::PREVIEW_LIMIT_BYTES]),
        };
        let encoded =
            canonical::encode(&request_payload(u64::MAX, &full)).expect("просьба кодируется");
        let limit = ratatosk_wire::SizeClass::L.max_payload();
        assert!(
            encoded.len() <= limit,
            "предложение с полным превью заняло {} байт при пределе {}",
            encoded.len(),
            limit
        );
        // И сколько осталось на подпись. Предела у неё нет — значит есть
        // длина, на которой кадр перестанет собираться, и знать её порядок
        // обязан тот, кто рисует поле ввода. Четыре килобайта — это заведомо
        // больше любой подписи к картинке; если однажды не останется и их,
        // сломается этот тест, а не отправка у человека.
        assert!(
            limit - encoded.len() >= 4096,
            "на подпись осталось {} байт — это уже мало",
            limit - encoded.len()
        );
    }

