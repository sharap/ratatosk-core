pub const MAX_LABEL_CHARS: usize = 64;

/// Наибольшее число исчезнувших сообщений в одной новости.
///
/// Предел не от вкуса, а от кадра: «очистить чат» уносит всю переписку
/// разом, и список идентификаторов в один кадр (§5.5) может не влезть.
/// Не влезший он не уехал бы **вовсе** — то есть десктоп продолжал бы
/// показывать стёртое, — поэтому телефон режет список на части, а не
/// надеется, что он окажется коротким.
pub const MAX_GONE_IDS: usize = 256;

/// Версия провода компаньона.
///
/// **Заведена по живому расхождению.** Стенд-десктоп, поговорив с телефоном
/// сборки постарше, показывал сообщения без вложений и без реакций — и это
/// выглядело в точности как ошибка в коде. Выглядело так потому, что кодек
/// здесь прощающий: необязательные поля, которых нет, читаются как «нет
/// вложений» и «нет реакций». Прощающий кодек — правильное решение (сборки
/// обязаны переживать друг друга), но у него есть цена: **молчаливая
/// деградация неотличима от поломки**, и §14 такого не разрешает.
///
/// Число растёт на каждое изменение, которое старая сторона не сможет
/// показать: новый вид просьбы, ответа или новости, новое поле в сообщении
/// или вложении. Не растёт — на правки текста и комментариев.
///
/// Единица означала «первая объявленная», а не «первая существовавшая»:
/// сборки до неё версии не называют вовсе, и узнаются они по молчанию
/// в ответ на [`Request::Hello`].
///
/// Двойка — просьба [`Request::PauseFile`] и согласие в
/// [`Notice::FileProgress`]. Тройка — новость [`Notice::FileGone`].
/// Четвёрка — выгрузка файла **с** десктопа: [`Request::FileOffer`]
/// и её продолжение.
///
/// Пятёрка — **убранное** поле, а не добавленное: из [`ChatSummary`] ушёл
/// `peer_ik`. Растёт версия по тому же правилу и по той же причине: сборка,
/// требовавшая это поле, на новом ответе не разберёт **весь список чатов**,
/// а не одну строку в нём. Убыль ломает старую сторону злее, чем прибыль:
/// прощающий кодек прощает лишнее, но не пропавшее.
///
/// Шестёрка — превью (§10.3): признак [`Attachment::has_preview`],
/// просьба [`Request::FilePreview`] и ответ [`Response::FilePreview`].
/// Семёрка — превью в обратную сторону: поле у [`Request::FileOffer`].
///
/// Восьмёрка — несколько вложений в одном сообщении. Подпись переехала
/// из [`Request::FileOffer`] в [`Request::FileSend`], а тот стал называть
/// список файлов вместо одного. Оба поля **сменили форму**, а не появились:
/// сборка версии 7 не разберёт ни ту просьбу, ни эту.
///
/// Девятка — продолжение прерванной выгрузки: [`Request::Staged`]
/// и ответ [`Response::Staged`].
///
/// Десятка — аватарки: поле [`ChatSummary::avatar_ms`], просьба
/// [`Request::Avatar`], ответ [`Response::Avatar`] и новость
/// [`Notice::AvatarChanged`]. Поле в списке чатов **появилось**, а не сменило
/// форму: сборка версии 9 разберёт список как прежде, просто не увидит меток.
///
/// Одиннадцать — смена своей аватарки с десктопа: [`Request::SetMyAvatar`].
/// Только просьба: ответ у неё общий (`Done` или `Refused`), а новость
/// о смене — та же [`Notice::AvatarChanged`], что была в десятке.
///
/// Двенадцать — прощание при отзыве: [`Notice::Revoked`]. Константы
/// «с какой версии» у неё нет и не нужно: десктоп её не спрашивает, а телефон
/// постарше просто не пришлёт — то есть будет вести себя ровно так, как
/// вёл себя до неё.
///
/// Тринадцать — адрес десктопа в **рукопожатии** ([`DeviceAddress`]).
/// Ни просьбы, ни ответа, ни новости: нагрузка первого сообщения Noise,
/// которая до этого была пуста. Телефон постарше её не читает вовсе,
/// десктоп постарше не шлёт — обе стороны остаются при локальной сети,
/// как и были.
/// Четырнадцать — группы в списке чатов: поле [`ChatSummary::is_group`].
/// Появилось, а не сменило форму, — как и метка аватарки в десятке: сборка
/// версии 13 разберёт список как прежде, просто сочтёт все чаты личными.
///
/// Признак нужен ровно затем, что без него десктоп нарисовал бы группе
/// «не проверен»: у группы сверки нет и быть не может (§4.2 — про людей),
/// а `verified` у неё поэтому всегда `false`. Вывести одно из другого
/// нельзя: несверенный контакт выглядит точно так же.
///
/// Двадцать один — **нарезка вложения**: [`Attachment::chunk_bytes`]
/// и [`Response::FileOffer::chunk_bytes`]. Оба поля появились, а не сменили
/// форму: сборка версии 20 разберёт и то и другое как прежде.
///
/// Появились они поздно, и опоздание стоило дорого. Своя нарезка у файла
/// есть с миграции 0026 — в эфире кусок четыре килобайта, на прочих
/// ступенях мебибайт, — а провод возил только **число** кусков. Десктоп
/// считал смещение своим умолчанием, и всё сходилось ровно до того дня,
/// когда на телефоне включили Bluetooth: приём складывал файл
/// в одиннадцать килобайт тремя кусками в трёх мебибайтах пустоты,
/// а отдача не ехала вовсе — телефон отвергал кусок за куском как
/// «не той длины». Снаружи и то и другое выглядело как «файлы через
/// компаньона приходят битыми».
///
/// Двадцать два — **пачка кусков за просьбу**: поле `count`
/// у [`Request::FileChunk`]. Появилось, а не сменило форму; телефон
/// постарше его не прочтёт и ответит одним куском, как отвечал всегда,
/// а десктоп постарше не пришлёт — и получит то же самое.
///
/// Причина — та же нарезка эфира. Просьба о куске стоит круга по сети,
/// и пока кусок был мебибайтом, один кусок за круг ничего не стоил:
/// сто мегабайт — сотня кругов. С куском в четыре килобайта те же сто
/// мегабайт стали двадцатью восемью тысячами кругов, и вложения через
/// компаньона поползли даже по локальной сети. Кадр ответа при этом
/// рассчитан на мебибайт и вёз четыре килобайта.
pub const WIRE_VERSION: u32 = 22;

/// Наибольшее число сообщений в одной просьбе десктопа.
///
/// Отдельная константа от [`MAX_GONE_IDS`], хотя число то же, и разделены
/// они намеренно: то предел на то, что телефон **говорит**, этот — на то,
/// о чём его **просят**. Стороны разные, и доверие к ним разное. Список
/// в новости телефон режет сам и знает, сколько там; длину в просьбе называет
/// другое устройство, и «сотри вот эти сто тысяч» — это работа телефона,
/// а не ошибка десктопа. Сведи их в одну константу — и первая же причина
/// подвинуть одну молча подвинула бы вторую.
pub const MAX_REQUEST_IDS: usize = 256;

/// Сколько выгрузок с десктопа телефон держит разом.
///
/// Незаконченная выгрузка — это чужие байты в хранилище телефона и запись
/// в его памяти; без предела десктоп, начавший сотню и не досказавший ни
/// одной, занял бы всё место.
///
/// **Было два, стало десять, и число не выдумано.** Сообщение с несколькими
/// вложениями собирается из готовых выгрузок: десктоп заводит по одной
/// на файл и называет их все в [`Request::FileSend`]. Значит потолок здесь
/// обязан быть не меньше [`MAX_ATTACHMENTS`] — иначе сообщение из десяти
/// картинок нельзя было бы собрать в принципе, и упёрлось бы оно
/// в неочевидное «телефон уже принимает другие файлы».
///
/// Больше — незачем: собрать сообщение из большего числа вложений всё равно
/// не даст [`MAX_ATTACHMENTS`].
pub const MAX_UPLOADS: usize = MAX_ATTACHMENTS;

/// Сколько живёт незаконченная выгрузка, если о ней забыли (§13.4).
///
/// **Срок нужен, потому что брошенную выгрузку никто не закрывает.** Десктоп,
/// у которого сдох процесс посреди третьего файла, не пришлёт ни `FileSend`,
/// ни `FileAbort`, а сверка сирот его куски нарочно пропускает — она принимает
/// их за идущую выгрузку. Без срока это место не вернулось бы никогда.
///
/// Семь суток, а не часы: человек, закрывший ноутбук на выходные, вправе
/// вернуться и продолжить. И не месяц: чужие байты в хранилище телефона —
/// это место, за которое платит владелец телефона, а не тот, кто их прислал.
pub const STAGED_TTL_MS: u64 = 7 * 24 * 60 * 60 * 1_000;

/// С какой версии провода телефон отвечает на [`Request::Staged`].
///
/// **Нужна затем, чтобы не ждать ответа вечно.** Телефон постарше просьбы
/// не поймёт и отбросит её молча — так устроено узнавание старой сборки
/// (5бр), — а терминал в это время держит незаконченную выгрузку и ждёт
/// разрешения продолжить. Версия приезжает `Hello` раньше всех прочих
/// ответов, и по ней видно, стоит ли вообще спрашивать.
pub const STAGED_SINCE_WIRE: u32 = 9;

/// С какой версии провода телефон знает про аватарки.
///
/// Отдельная константа от [`STAGED_SINCE_WIRE`] по той же причине, по какой
/// та отдельна от версии провода: числа совпадать не обязаны, а сведённые
/// в одно разъедутся на первой же новой возможности.
///
/// Нужна не ради ответа, а ради **молчания в кэше**. Телефон постарше просьбу
/// [`Request::Avatar`] отбросит, десктоп ответа не дождётся и покажет пустой
/// кружок — что само по себе не беда. Беда в том, что пустой кружок
/// неотличим от «аватарки нет», и десктоп спрашивал бы заново на каждом
/// подключении. Зная версию, он не спрашивает вовсе.
pub const AVATARS_SINCE_WIRE: u32 = 10;

/// С какой версии провода телефон принимает свою аватарку от десктопа.
///
/// Отдельно от [`AVATARS_SINCE_WIRE`], хотя разница в одну версию: показ
/// и смена приехали разными поставками, и телефон, умеющий первое, вправе
/// не уметь второго. Сведи их в одно число — и десктоп, поговорив с таким
/// телефоном, отправил бы картинку в тишину.
///
/// Здесь молчание дороже, чем при чтении: человек **нажал кнопку**. Не
/// сказав ему ничего, десктоп оставил бы его смотреть на прежнее лицо
/// и гадать, дошло ли, — а §14 запрещает ровно это.
pub const SET_AVATAR_SINCE_WIRE: u32 = 11;

/// Наибольшее число реакций на одном сообщении в кадре.
///
/// В переписке 1:1 их две, и предел выглядит щедрым до бессмысленности.
/// Он не про 1:1: реакции едут **внутри** сообщения, сообщения — страницей
/// до [`MAX_PAGE`], и без предела на вложенный список длину кадра называла
/// бы та сторона провода. Тридцать две — это заведомо больше, чем нужно
/// разговору двоих, и заведомо меньше, чем нужно, чтобы страница перестала
/// влезать (§5.5).
///
/// Лишние **отбрасываются**, а не отвергают сообщение: реакция — украшение
/// поверх текста, и терять из-за неё саму переписку было бы обменом не в ту
/// сторону.
pub const MAX_REACTIONS: usize = 32;

/// Наибольшая страница истории за один запрос.
///
/// Сто сообщений — это экран с запасом, и они укладываются в один кадр
/// без фрагментации (§9.3) при любом разумном тексте. Просить больше
/// десктопу незачем: он листает, а не выкачивает.
pub const MAX_PAGE: u32 = 100;

