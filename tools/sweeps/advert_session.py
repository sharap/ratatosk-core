#!/usr/bin/env python3
"""Метелка: объявление регистрируется своим соединением, а не общим.

Правило словами: **каждое объявление уезжает вместе со своим
соединением с BlueZ — его открывает `advert_session`, а держит
`Announced`.**

Заведена по настоящей поломке, снятой с PinePhone 26 ноября, и заменяет
прежнюю `advert_settle`, которая стерегла **не ту** причину.

Эфир на том устройстве жил ровно один слот маяка: объявился в 10:34:02
(слот 1995210), а на первом переобъявлении в 10:45:04 получил
`Failed to register advertisement` — и дальше лежал. Первая починка
ставила паузу между снятием и регистрацией (снятие в `bluer`
асинхронно, прочитано в его исходнике) и не помогла ни на полсекунды,
ни на секунду.

Причина оказалась другой, и нашлась она чужим кодом в одном соединении:

    $ printf 'advertise on\\nadvertise off\\nadvertise on\\nquit\\n' | bluetoothctl
    advertise on   → удалось
    advertise off  → снято
    advertise on   → Failed to register advertising object

Клиент, однажды зарегистрировавший и снявший объявление, не может
зарегистрировать его снова. Два отдельных процесса работают всегда —
с любой паузой, включая нулевую, — потому что каждый процесс новый
клиент D-Bus. Значит дело не в сроке, а в личности клиента.

Проверить это прогоном **нельзя**: `bluer::Session` открывает
соединение с живым `bluetoothd`, подделки у нас нет, а отказ приходит
от чужой службы. Поставь сюда общий адаптер — ни одна проверка
не покраснеет, а эфир на легаси-контроллере умрёт через четверть часа.
Та же причина, что у `platform_gates` и `power_watched`.

Чего эта метелка **не** стережёт: что новое соединение помогает. Это
проверяется только устройством — эфир обязан пережить границу слота.

Комментарии снимаются перед сличением: разбор правки поминает и
`advert_session`, и `Announced` вплотную к коду, так что ложная зелень
была бы вероятна (это пятый случай одной ошибки в наборе).

Находок должно быть ноль. Поломка проверяется так: позвать
`advertise` у общего адаптера — метелка краснеет; убрать
`advert_session` — тоже; убрать соединение из `Announced` — тоже.
"""
import pathlib
import re
import sys

# Корень дерева считается от самого файла, а не от текущего каталога:
# метелку зовут и из корня, и из CI, и по одной из редактора.
ROOT = pathlib.Path(__file__).resolve().parents[2]

RADIO = "crates/transport/src/bluetooth/local.rs"


def without_comments(source: str) -> str:
    """Убирает строчные и документирующие комментарии целиком."""
    kept = []
    for line in source.split("\n"):
        if line.lstrip().startswith("//"):
            continue
        kept.append(re.sub(r"\s//.*$", "", line))
    return "\n".join(kept)


MUST = [
    {
        "образец": "async fn advert_session()",
        "зачем": "соединение под объявление открывается отдельно от общего",
    },
    {
        "образец": "_session: bluer::Session",
        "зачем": "объявление держит своё соединение: уйдёт оно — уйдёт и клиент",
    },
    {
        "образец": "speaker.advertise(",
        "зачем": "регистрирует объявление адаптер из нового соединения, а не общий",
    },
]

bad = []
path = ROOT / RADIO
code = ""
if not path.exists():
    bad.append(f"{RADIO}: файла нет — метёлке нечего смотреть")
else:
    code = without_comments(path.read_text(encoding="utf-8"))

if code:
    for rule in MUST:
        if rule["образец"] not in code:
            bad.append(f"{RADIO}: нет `{rule['образец']}` — {rule['зачем']}")
    # Обращений `.advertise(` должно быть ровно два — оба у `speaker`,
    # то есть у адаптера из нового соединения: основное объявление
    # и отступление по интервалу. Третье означало бы путь, где
    # соединение переиспользуют.
    # Пробелы сжимаются: `rustfmt` переносит длинный вызов, и образец,
    # не знающий про перенос, дал бы ложную находку — так и вышло
    # на первом же прогоне этой метелки.
    flat = re.sub(r"\s+", " ", code)
    calls = re.findall(r"(\w+) ?\. ?advertise\(", flat)
    if calls != ["speaker", "speaker"]:
        bad.append(
            f"{RADIO}: `advertise` зовут у {calls}, а должно быть "
            f"ровно дважды у `speaker` — иначе соединение переиспользуют"
        )

# Молчание — не «чисто»: сколько правил осмотрено, видно всегда.
print("\n".join(bad) if bad else "чисто (правил вокруг соединения объявления осмотрено: 4)")
sys.exit(1 if bad else 0)
