//! Поисковый индекс: слова превращаются в хэши на ключе базы (§12).
//!
//! # Почему не полнотекстовый индекс
//!
//! База целиком не шифруется — это обычный SQLite, шифруются отдельные поля
//! (§12), тела сообщений в их числе. Полнотекстовый индекс по открытым телам
//! положил бы рядом с зашифрованными сообщениями их же незашифрованную
//! копию: `body_enc` стал бы декорацией, а файл базы отдал бы всю переписку
//! тому, у кого есть телефон, но нет PIN. Прежнее оправдание («§2.2:
//! скомпрометированное устройство вне защиты») говорило про устройство
//! с малварью, а `body_enc` защищает от другого — от потерянного и изъятого.
//!
//! Поэтому в индексе лежит `BLAKE3_keyed(db_key, слово)`, обрезанный
//! до [`TOKEN_LEN`]. Запрос хэшируется тем же ключом и ищется по равенству.
//!
//! # Что за это заплачено
//!
//! **Ищутся только целые слова.** Хэш от «дом» и хэш от «дома» не связаны
//! ничем, поэтому нет ни префиксов, ни подстрок, ни морфологии, ни
//! ранжирования по релевантности. Это не недоделка, которую можно закрыть
//! позже: возможность искать по префиксу означала бы возможность перебирать
//! индекс по префиксу, то есть ровно ту утечку, ради которой всё и затеяно.
//!
//! **Видна структура.** По индексу без ключа читается, сколько в переписке
//! разных слов, в скольких сообщениях каждое встречается и какие слова ходят
//! вместе. Содержимого это не выдаёт, статистику выдаёт. Честнее назвать это
//! здесь, чем обещать «поиск, который ничего не раскрывает».
//!
//! **«ё» и «е» — разные слова**, как и любые две формы одного. Нормализация
//! ограничена приведением к нижнему регистру: всё, что сложнее, — это
//! языковые правила, а они у каждого языка свои и в хранилище им не место.

use ratatosk_crypto::{kdf, labels};

/// Версия формата индекса.
///
/// Увеличивается, когда меняется что угодно, влияющее на токены: деривация,
/// длина, правила разбиения на слова, приведение регистра. База со старшим
/// номером перестраивает индекс целиком при первом открытии.
///
/// Без этого номера смена формата была бы самой тихой поломкой из возможных:
/// приложение работает, поиск не падает, просто ничего не находит из того,
/// что записано до обновления, — и списать это не на что.
pub const INDEX_FORMAT: u32 = 1;

/// Длина токена в байтах.
///
/// Шестнадцати достаточно: столкновение двух разных слов на 128 битах
/// невозможно на практике, а лишние байты — это лишний размер индекса,
/// который лежит на телефоне годами.
pub const TOKEN_LEN: usize = 16;

/// Токен поискового индекса.
pub type Token = [u8; TOKEN_LEN];

/// Разбивает текст на слова.
///
/// Словом считается непрерывная цепочка букв и цифр; всё остальное —
/// разделитель. Одна функция и на запись, и на запрос: разойдись они,
/// поиск молча перестал бы находить написанное.
pub fn words(text: &str) -> Vec<String> {
    let mut found = Vec::new();
    let mut current = String::new();
    for ch in text.chars() {
        if ch.is_alphanumeric() {
            // `to_lowercase` посимвольно, а не по строке: так не нужен
            // промежуточный буфер на всё сообщение.
            current.extend(ch.to_lowercase());
        } else if !current.is_empty() {
            found.push(std::mem::take(&mut current));
        }
    }
    if !current.is_empty() {
        found.push(current);
    }
    found
}

/// Считает токен одного слова.
///
/// Слово приводится к нижнему регистру здесь же, а не только в [`words`]:
/// запрос приходит от человека, и «Привет» обязан находить «привет».
#[must_use]
pub fn token(db_key: &[u8; 32], word: &str) -> Token {
    let lowered: String = word.chars().flat_map(char::to_lowercase).collect();
    let derived = kdf::derive_concat(labels::SEARCH_TOKEN, &[db_key, lowered.as_bytes()]);
    let mut out = [0u8; TOKEN_LEN];
    out.copy_from_slice(&derived[..TOKEN_LEN]);
    out
}

/// Токены всего текста, без повторов и в порядке возрастания.
///
/// Повторы схлопываются намеренно: «сколько раз слово встретилось
/// в сообщении» — сведение, без которого поиск обходится, а частотный
/// анализ обходится хуже.
#[must_use]
pub fn tokens_of(db_key: &[u8; 32], text: &str) -> Vec<Token> {
    let mut all: Vec<Token> = words(text).iter().map(|word| token(db_key, word)).collect();
    all.sort_unstable();
    all.dedup();
    all
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn words_split_on_everything_that_is_not_a_letter() {
        assert_eq!(words("Привет, мир!"), vec!["привет", "мир"]);
        assert_eq!(words("файл-2024.pdf"), vec!["файл", "2024", "pdf"]);
        assert_eq!(words("   "), Vec::<String>::new());
        assert_eq!(words("конец"), vec!["конец"], "слово в конце строки не теряется");
    }

    #[test]
    fn the_query_is_tokenised_like_the_text() {
        // Разойдись эти два пути — поиск молча перестал бы находить
        // написанное, и заметили бы это не тестом, а жалобой.
        let key = [7u8; 32];
        let from_text = tokens_of(&key, "Привет");
        assert_eq!(from_text, vec![token(&key, "привет")]);
        assert_eq!(token(&key, "ПРИВЕТ"), token(&key, "привет"));
    }

    #[test]
    fn the_key_is_what_makes_the_token_unreadable() {
        // Тот же текст на другом ключе даёт другой индекс. Иначе индекс
        // одной базы годился бы для проверки догадок о другой.
        assert_ne!(token(&[1u8; 32], "тайна"), token(&[2u8; 32], "тайна"));
    }

    #[test]
    fn repeats_inside_one_message_collapse() {
        let key = [7u8; 32];
        assert_eq!(tokens_of(&key, "да да да").len(), 1, "частота слова наружу не выходит");
    }

    #[test]
    fn the_token_matches_the_vector() {
        // Из `crates/crypto/tests/vectors/derive_key.txt`: ключ 0x66×32,
        // слово «привет», длина 16. Вектор посчитан независимой реализацией
        // BLAKE3 (`tools/gen_vectors.py`), поэтому это проверка формата,
        // а не проверка кода самим собой.
        //
        // Пин нужен затем, что индекс лежит на устройствах: поменяв порядок
        // склейки или длину обрезки, мы сделали бы нечитаемым уже записанное,
        // и поиск молча перестал бы находить всё, что было до обновления.
        assert_eq!(
            token(&[0x66u8; 32], "привет"),
            [
                0x59, 0xb3, 0xe6, 0x49, 0x4b, 0x52, 0xc2, 0x7d, 0x59, 0xef, 0x7a, 0x84, 0xaf, 0x94,
                0x9f, 0x92
            ]
        );
    }

    #[test]
    fn different_forms_of_a_word_are_different_words() {
        // Не украшение, а зафиксированное ограничение: искать по префиксу
        // значит дать перебирать индекс по префиксу.
        let key = [7u8; 32];
        assert_ne!(token(&key, "дом"), token(&key, "дома"));
    }
}
