//! Эфир Bluetooth через границу §13.3 (0.4.7).
//!
//! Здесь нет ни одного протокольного решения, и это проверяемое
//! утверждение, а не намерение. Формат объявления, ротация по слотам,
//! опознание маяком, кадрирование, выбор канала по классу, сроки —
//! всё это живёт в `transport::bluetooth` и остаётся там одним
//! экземпляром кода на оба радио. Этот модуль переводит вызовы: шесть
//! вниз, восемь наверх, и ничего сверх того.
//!
//! # Почему радио вообще приходит снаружи
//!
//! На Linux эфиром правит `bluer` — обвязка BlueZ. На Android BlueZ нет:
//! объявляет `BluetoothLeAdvertiser`, сканирует `BluetoothLeScanner`,
//! канал открывает `BluetoothSocket`, и все трое живут в Java. Значит
//! радио обязано приходить с той стороны границы, а всё остальное —
//! остаться с этой.
//!
//! # Почему вызовы вниз ничего не возвращают
//!
//! Потому что все они долгие. `connect` у `BluetoothSocket` блокирует
//! поток на секунды, запись в `OutputStream` — на время передачи, а вызов
//! через UniFFI синхронный: «вернуть результат» означало бы держать поток
//! ядра всё это время. Договор поэтому такой: **сказали — делай, об исходе
//! сообщи событием.** То же правило, по которому живёт `Runner::execute`,
//! только по другую сторону границы.

use std::sync::Arc;

use ratatosk_transport::{BridgedAir, BtRadio};

/// Сколько байт в адресе радио. Шесть, и это не наше решение.
const ADDRESS_LEN: usize = 6;

/// Радио платформы — то, чего в Rust на Android нет.
///
/// Реализуется на Kotlin. Через границу ходят **только байты и числа**:
/// ни адреса контакта, ни ключа, ни имени собеседника платформа не видит
/// и видеть не должна — опознание живёт по эту сторону.
///
/// `foreign`, а не `rust, foreign`: трейт реализует только платформа,
/// и Rust-версии через границу не ходят — так не генерируется
/// неиспользуемый скаффолдинг. Тот же выбор, что у `EventObserver`.
///
/// **Ни один метод не ждёт исхода** — см. заголовок модуля.
#[uniffi::export(foreign)]
pub trait FfiBtRadio: Send + Sync {
    /// Поднять слушающий сокет L2CAP и начать сканировать эфир.
    ///
    /// Номер занятого канала приезжает обратно вызовом
    /// [`FfiBluetooth::on_ready`], беда — [`FfiBluetooth::on_lost`].
    ///
    /// Отдельно от [`FfiBtRadio::advertise`] потому, что объявлять
    /// **нечего**, пока номера нет: он едет в самом объявлении. Порядок
    /// поэтому один и тот же на обеих платформах: сокет, номер,
    /// объявление.
    fn start(&self);

    /// Объявлять вот эти байты, пока не сказано иное.
    ///
    /// Нагрузка приходит готовой — 18 байт. Собирать её платформе нельзя
    /// и не нужно: формат, живущий и в Rust, и в Kotlin, разошёлся бы
    /// на первой же правке, причём молча.
    ///
    /// Зовётся и при подъёме, и на каждой смене слота. Прежнее объявление
    /// платформа обязана **заменить**, а не добавить второе: два объявления
    /// одного радио — подсказка тому, кто их сличает.
    fn advertise(&self, payload: Vec<u8>);

    /// Перестать объявляться и сканировать, закрыть все каналы.
    ///
    /// Человек выключил ступень именно затем, чтобы перестать быть
    /// слышимым, — поэтому немедленно.
    fn stop(&self);

    /// Открыть канал к устройству; исход — событием.
    ///
    /// Номер канала даёт **Rust**: платформе остаётся его запомнить.
    /// Иначе номера пришлось бы согласовывать в обе стороны, а это лишний
    /// повод им разойтись.
    ///
    /// `random` — вид адреса. Набирать надо тем же видом, каким устройство
    /// объявилось: тот же адрес, прочитанный как публичный, не найдётся.
    fn open(&self, channel: u64, address: Vec<u8>, random: bool, psm: u16);

    /// Записать байты в открытый канал.
    ///
    /// Платформа ставит их в свою очередь и пишет своим потоком: запись
    /// в `OutputStream` блокирует, а этот вызов — нет.
    fn write(&self, channel: u64, bytes: Vec<u8>);

    /// Закрыть канал.
    fn close(&self, channel: u64);
}

/// Переходник между двумя договорами об одном и том же.
///
/// Их два потому, что `transport` о UniFFI не знает и знать не должен:
/// крейт транспортов собирается и в стенде, и в симуляции, где границы
/// нет вовсе. Переходник — цена этой независимости, и он ровно такой,
/// какой надо: шесть строк без единого решения.
struct Radio(Arc<dyn FfiBtRadio>);

impl BtRadio for Radio {
    fn start(&self) {
        self.0.start();
    }

    fn advertise(&self, payload: Vec<u8>) {
        self.0.advertise(payload);
    }

    fn stop(&self) {
        self.0.stop();
    }

    fn open(&self, channel: u64, addr: Vec<u8>, random: bool, psm: u16) {
        self.0.open(channel, addr, random, psm);
    }

    fn write(&self, channel: u64, bytes: Vec<u8>) {
        self.0.write(channel, bytes);
    }

    fn close(&self, channel: u64) {
        self.0.close(channel);
    }
}

/// Ручка эфира, которую держит платформа.
///
/// Отдельным объектом, а не методами на клиенте, и причина не в порядке:
/// эфиром занимается своя часть приложения (служба переднего плана
/// с разрешениями), и давать ей весь клиент значило бы давать ей переписку.
#[derive(uniffi::Object)]
pub struct FfiBluetooth {
    air: BridgedAir,
}

impl FfiBluetooth {
    /// Заводит ручку поверх моста, который уже стоит в ступени.
    ///
    /// Не `pub`: мост один на ядро, и второй, заведённый клиентом, был бы
    /// мостом в никуда — ступень слушала бы первый.
    pub(crate) fn new(air: BridgedAir) -> FfiBluetooth {
        FfiBluetooth { air }
    }

    /// Адрес радио из того, что пришло с той стороны.
    ///
    /// Длина проверяется, потому что её обещает платформа, а не тип.
    /// Молча дополнить нулями до шести было бы худшим из решений: набор
    /// уехал бы по адресу, которого никто не называл.
    fn address(bytes: &[u8]) -> Option<[u8; ADDRESS_LEN]> {
        bytes.try_into().ok()
    }
}

#[uniffi::export]
impl FfiBluetooth {
    /// Вручает ядру радио платформы.
    ///
    /// До этого вызова ступень не поднимается **никак**: подниматься
    /// нечем, и молчаливое согласие было бы обманом — §5.4 считал бы
    /// ступень живой и жёг бы на ней попытки. Включённая без радио,
    /// она честно объявляется потерянной.
    ///
    /// # В сборке со своим радио вызов не делает ничего
    ///
    /// На Linux с признаком `bt` эфиром правит `bluer`, и вручать нечего:
    /// радио уже есть, оно наше. Отказывать за такой вызов не за что —
    /// клиент мог быть написан на оба случая, — но и делать вид, что мы
    /// приняли чужое радио, нельзя: ступень его не спросит ни разу,
    /// и человек искал бы потом, почему «вручили, а не работает».
    /// Поэтому вызов записывается в журнал и кончается ничем.
    pub fn set_radio(&self, radio: Arc<dyn FfiBtRadio>) {
        if cfg!(all(feature = "bt", target_os = "linux")) {
            let _ = radio;
            tracing::info!("эфир: у этой сборки своё радио — вручённое не нужно");
            return;
        }
        self.air.set_radio(Arc::new(Radio(radio)));
    }

    /// Есть ли чем поднимать эфир.
    ///
    /// Нужно экрану настроек: «ступень включена, но радио не вручено» —
    /// это состояние приложения, а не сети, и показывать его надо словами,
    /// а не тишиной.
    ///
    /// # Вопрос именно «есть ли чем», а не «вручили ли нам»
    ///
    /// Разница видна ровно в одной сборке — Linux с признаком `bt`, —
    /// и там она решающая: радио есть, вручать его не надо, а буквальный
    /// ответ «нам ничего не вручали» был бы неправдой о работоспособности.
    /// Клиент показал бы «эфир недоступен» над живой ступенью.
    pub fn has_radio(&self) -> bool {
        cfg!(all(feature = "bt", target_os = "linux")) || self.air.has_radio()
    }

    /// Сокет поднят, слушаем на этом номере канала.
    ///
    /// Номер PSM выдаёт система тому, кто открыл серверный сокет, — то есть
    /// платформа. Отсюда он и приходит; объявление собирается уже после.
    pub fn on_ready(&self, psm: u16) {
        self.air.on_ready(psm);
    }

    /// Эфир не поднялся или отвалился, и вот почему.
    ///
    /// Причина словами, а не кодом: показывать её человеку («включите
    /// Bluetooth», «нет разрешения») будет клиент, и разбирать для этого
    /// числа он не должен.
    pub fn on_lost(&self, reason: String) {
        self.air.on_lost(&reason);
    }

    /// Услышано объявление под нашим кодом производителя.
    ///
    /// Чьё оно — решает маяк по эту сторону границы. Платформа сообщает
    /// «слышал такие байты с такого адреса» и не знает, чьи они: радио,
    /// опознающее контакты само, было бы радио, знающим, кто с кем
    /// переписывается.
    pub fn on_heard(&self, payload: Vec<u8>, address: Vec<u8>, random: bool) {
        let Some(address) = FfiBluetooth::address(&address) else {
            // Через `tracing`, как и весь остальной журнал. Стояло здесь
            // `eprintln!` с оговоркой «у этого крейта журнала нет» — и это
            // было правдой ровно до `enable_logging`: на Android системный
            // поток ошибок уходит в никуда, так что строка была написана
            // в пустоту.
            tracing::warn!(длина = address.len(), "эфир: адрес не шести байт");
            return;
        };
        self.air.on_heard(&payload, address, random);
    }

    /// Канал, который просили открыть, открылся.
    pub fn on_opened(&self, channel: u64) {
        self.air.on_opened(channel);
    }

    /// Канал открыть не удалось.
    pub fn on_open_failed(&self, channel: u64, reason: String) {
        self.air.on_open_failed(channel, &reason);
    }

    /// К нам подключились.
    ///
    /// Такой канал работает **только на чтение**: соединения односторонние,
    /// и отвечать мы будем по своему, который наберём сами. Читать его
    /// платформа обязана до самого закрытия, отдавая куски
    /// [`FfiBluetooth::on_bytes`].
    pub fn on_incoming(&self, channel: u64) {
        self.air.on_incoming(channel);
    }

    /// Из канала пришли байты.
    ///
    /// Куски произвольные — ровно те, что вернуло чтение сокета. Резать
    /// их по кадрам платформе не нужно и нельзя: где кончается кадр, знает
    /// кадрирование, и знает оно это по эту сторону границы.
    pub fn on_bytes(&self, channel: u64, data: Vec<u8>) {
        self.air.on_bytes(channel, data);
    }

    /// Канал закрылся — с той стороны или по ошибке записи.
    ///
    /// Сообщать об этом обязательно. Молчание здесь стоит дороже всего:
    /// связь считала бы кадры записанными, §5.4 ждал бы квитанцию полный
    /// срок, а человек видел бы «отправляется» на мёртвом канале.
    pub fn on_closed(&self, channel: u64) {
        self.air.on_closed(channel);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Радио, которого нет: считает, что ему велели.
    #[derive(Default)]
    struct Counting {
        started: std::sync::atomic::AtomicUsize,
    }

    impl FfiBtRadio for Counting {
        fn start(&self) {
            self.started.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
        }

        fn advertise(&self, _payload: Vec<u8>) {}
        fn stop(&self) {}
        fn open(&self, _channel: u64, _address: Vec<u8>, _random: bool, _psm: u16) {}
        fn write(&self, _channel: u64, _bytes: Vec<u8>) {}
        fn close(&self, _channel: u64) {}
    }

    #[cfg(not(all(feature = "bt", target_os = "linux")))]
    #[test]
    fn a_radio_handed_over_is_a_radio_the_core_has() {
        // Состояние «ступень включена, а радио не вручено» — настоящее:
        // ядро открывается раньше, чем служба с разрешениями успевает
        // отдать своё радио. Экран настроек обязан уметь его назвать.
        let bt = FfiBluetooth::new(BridgedAir::new());
        assert!(!bt.has_radio(), "до вручения радио нет");
        bt.set_radio(Arc::new(Counting::default()));
        assert!(bt.has_radio());
    }

    #[cfg(all(feature = "bt", target_os = "linux"))]
    #[test]
    fn a_build_with_its_own_radio_needs_nothing_handed_to_it() {
        // Другая сборка — другой договор, и проверка обязана быть своей.
        // Здесь эфиром правит `bluer`: радио есть **до** всякого вручения,
        // и вручённое ему не нужно.
        //
        // Правда о работоспособности здесь важнее буквы. Ответь `has_radio`
        // «нам ничего не вручали» — и клиент написал бы «эфир недоступен»
        // над живой ступенью; а прими мы чужое радио молча — человек искал
        // бы потом, почему вручил, а оно не спрашивается ни разу.
        let bt = FfiBluetooth::new(BridgedAir::new());
        assert!(bt.has_radio(), "у сборки со своим радио эфир поднимаем сразу");

        let handed = Arc::new(Counting::default());
        bt.set_radio(Arc::clone(&handed) as Arc<dyn FfiBtRadio>);
        assert!(bt.has_radio(), "ответ от вручения не меняется");
        assert_eq!(
            handed.started.load(std::sync::atomic::Ordering::Relaxed),
            0,
            "вручённое радио не трогают: эфиром правит своё"
        );
    }

    #[test]
    fn an_address_that_is_not_six_bytes_is_refused() {
        // Длину обещает платформа, а не тип. Дополнить нулями до шести
        // значило бы набрать по адресу, которого никто не называл.
        assert_eq!(FfiBluetooth::address(&[1, 2, 3, 4, 5, 6]), Some([1, 2, 3, 4, 5, 6]));
        assert_eq!(FfiBluetooth::address(&[1, 2, 3]), None);
        assert_eq!(FfiBluetooth::address(&[0; 7]), None);
        assert_eq!(FfiBluetooth::address(&[]), None);
    }
}
