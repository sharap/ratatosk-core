/// Отказ хранилища.
///
/// Ошибка нарочно **не** упоминает SQLite. Трейт [`Store`] имеет две
/// реализации — файловую и in-memory для симуляции (§16), и тип ошибки,
/// содержащий `rusqlite::Error`, заставлял бы вторую тянуть первую вместе
/// со всем C-кодом. Конкретная причина приходит строкой от бэкенда.
#[derive(Debug, thiserror::Error)]
pub enum StoreError {
    /// Ошибка нижележащего хранилища.
    #[error("ошибка хранилища: {0}")]
    Backend(String),

    /// Операция не поддерживается этой реализацией.
    ///
    /// In-memory хранилище не умеет, например, экспорт архива (§12), и должно
    /// сказать об этом прямо, а не сделать вид, что всё получилось.
    #[error("операция не поддерживается этим хранилищем: {0}")]
    Unsupported(&'static str),
    /// Схема новее, чем понимает эта сборка.
    #[error("схема версии {found} новее поддерживаемой {supported}")]
    FutureSchema {
        /// Версия в файле.
        found: u32,
        /// Версия сборки.
        supported: u32,
    },
    /// БД зашифрована, а ключ не предоставлен (§8.6).
    #[error("база заблокирована")]
    Locked,
}

impl From<rusqlite::Error> for StoreError {
    fn from(e: rusqlite::Error) -> Self {
        StoreError::Backend(e.to_string())
    }
}

/// Результат операции хранилища.
pub type Result<T> = core::result::Result<T, StoreError>;

/// Сообщение в том виде, в каком оно лежит на диске.
#[derive(Debug, Clone)]
pub struct StoredMessage {
    /// Идентификатор.
    pub msg_id: MsgId,
    /// Чат.
    pub chat_id: [u8; 16],
    /// Отправитель.
    pub sender_ik: [u8; 32],
    /// Метка порядка (§9.1).
    pub hlc: Hlc,
    /// Расшифрованное тело.
    pub body: Vec<u8>,
    /// Момент приёма, мс.
    pub received_ms: u64,
    /// Код статуса доставки (§9.4), если он известен.
    ///
    /// Число, а не перечисление: лестница статусов — это протокол, и жить
    /// она должна в `ratatosk-proto`, а не в слое хранения. Отображение
    /// в обе стороны — `DeliveryStatus::code` и `from_code`.
    ///
    /// `None` означает «неизвестно», и это не то же самое, что «ждёт
    /// отправки»: у принятого сообщения статуса нет вовсе, а у записи,
    /// поднятой с диска, живой попытки доставки уже не осталось.
    pub status: Option<u8>,
    /// Когда сообщение правили — по местным часам. `None` — не правили.
    ///
    /// Прежний текст **не хранится**: правка, оставляющая старые слова
    /// доступными, — не правка. Но отметка обязательна, и потому это поле
    /// есть: молча подменить текст в чужой истории §14 запрещает.
    pub edited_ms: Option<u64>,
    /// Переслано из другого разговора.
    ///
    /// Автор при этом **не хранится и не едет** — см. `ratatosk_proto::forward`:
    /// подпись §6 при пересылке не сохраняется, и имя рядом с чужими словами
    /// было бы утверждением, которое получатель не может проверить.
    pub forwarded: bool,
    /// Сообщение, на которое это отвечает. `None` — ответом не является.
    ///
    /// Ссылка **мягкая**: сообщения с таким `msg_id` может не быть вовсе —
    /// ответ мог опередить исходное сообщение, а исходное — быть удалено или
    /// вычищено уборкой (§12). Тогда цитировать нечего, и UI обязан сказать
    /// это прямо; сам ответ остаётся (`ratatosk_proto::reply`).
    ///
    /// Отрывка цитаты рядом нет намеренно: цитата рисуется из своей копии,
    /// и присланный текст был бы утверждением, которое проверить нечем.
    pub reply_to: Option<MsgId>,
}

/// Реакция на сообщение в том виде, в каком она лежит на диске.
///
/// Одна на пару «сообщение, автор»: новая заменяет прежнюю, снятая уходит
/// строкой. Правила — в `ratatosk_proto::reaction`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct StoredReaction {
    /// На какое сообщение.
    pub msg_id: MsgId,
    /// Чья. Своя — собственный `IK`.
    pub author_ik: [u8; 32],
    /// Сама реакция.
    pub emoji: String,
    /// Метка порядка (§9.1).
    ///
    /// Нужна, чтобы запоздавшая реакция не затирала свежую: реакция законно
    /// приезжает с опозданием (§9.2), и «последняя пришедшая» не значит
    /// «последняя поставленная».
    pub hlc: Hlc,
}

/// Контакт в том виде, в каком он лежит на диске (§4).
///
/// Поля продублированы рядом с `card_bytes` не от лени: §6 требует считать
/// подпись над **принятыми** байтами, поэтому карточка обязана храниться
/// целиком и неизменной. Разобранные поля рядом — чтобы список контактов
/// открывался запросом, а не разбором CBOR у каждой строки.
#[derive(Debug, Clone)]
pub struct StoredContact {
    /// Статический ключ Noise.
    pub ik: [u8; 32],
    /// Ключ подписи.
    pub sk: [u8; 32],
    /// Onion-адрес (§5.2). Пустая строка — адреса нет.
    pub onion: String,
    /// Chatmail-адрес (§5.3). Пустая строка — адреса нет.
    pub chatmail: String,
    /// Отображаемое имя. Получателем не доверяется (§4.1).
    pub display_name: String,
    /// Версия карточки, монотонная (§4.3).
    pub card_version: u64,
    /// Принятые байты карточки — то, над чем считается подпись (§6).
    pub card_bytes: Vec<u8>,
    /// Отпечаток сверен голосом (§4.2).
    pub verified: bool,
    /// Момент добавления, мс.
    pub created_ms: u64,
    /// Как этого человека подписал у себя пользователь.
    ///
    /// **По проводу не едет никогда.** [`StoredContact::display_name`] задаёт
    /// собеседник, и §4.1 прямо называет его не доверенным; это — своя
    /// пометка, и отправить её значило бы и сообщить человеку, как его
    /// записали, и завести поле, которое он может подделать.
    pub local_name: Option<String>,
}

/// Сессия в том виде, в каком она лежит на диске (§8.3).
///
/// `snapshot` — непрозрачные байты из `ratatosk_crypto::Session::export`.
/// Хранилище их не разбирает: оно решает, что шифровать, но не что внутри.
#[derive(Debug, Clone)]
pub struct StoredSession {
    /// Идентификатор сессии.
    pub session_id: u64,
    /// `IK` собеседника.
    pub peer_ik: [u8; 32],
    /// Живёт ли сессия в LAN. Иначе — в семействе Tor (§5.4).
    pub lan: bool,
    /// Снимок состояния ретчета целиком.
    pub snapshot: Vec<u8>,
    /// Момент установления, мс. Вход в правило §8.5.
    pub established_ms: u64,
}

/// Аватарка в том виде, в каком она лежит на диске.
///
/// Байты непрозрачны: хранилище решает, что шифровать, но не что внутри.
/// Проверку формата и размера делает `ratatosk_proto::avatar` — до записи.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct StoredAvatar {
    /// Байты изображения.
    pub bytes: Vec<u8>,
    /// Когда установлена — по метке отправителя для чужой, по своим часам
    /// для своей.
    ///
    /// Нужно, чтобы запоздавшая копия не затирала свежую: аватарка уходит
    /// заново при каждом установлении сессии, и порядок прихода двух таких
    /// отправок ничем не гарантирован.
    pub updated_ms: u64,
}

/// Сообщение, ожидающее отправки (§5.4).
///
/// Хранится **конверт**, а не кадр: кадр запечатывается под текущую сессию
/// в момент отправки, и сохранённый заранее оказался бы закрыт ключом сессии,
/// которой к тому времени может уже не быть (§8.4).
#[derive(Debug, Clone)]
pub struct StoredOutbox {
    /// Идентификатор сообщения — он же ключ строки.
    pub msg_id: MsgId,
    /// Кому.
    pub recipient_ik: [u8; 32],
    /// Конверт целиком, в открытом виде для ядра.
    pub envelope: Vec<u8>,
    /// Когда человек нажал «отправить».
    pub queued_ms: u64,
}

/// Файл в том виде, в каком он лежит на диске (§10).
///
/// Байты здесь не хранятся — только сведения о них: сами чанки живут
/// в [`Blobs`]. Ключ файла, имя и превью — содержимое, поэтому в базе они
/// зашифрованы (§12).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct StoredFile {
    /// Идентификатор — им адресуются чанки.
    pub file_id: FileId,
    /// Сообщение, к которому файл приложен. К одному сообщению их может быть
    /// несколько.
    pub msg_id: MsgId,
    /// Имя для показа. **Не путь** — проверяется `ratatosk_proto::files`.
    pub name: String,
    /// Размер открытого содержимого.
    pub size_bytes: u64,
    /// Сколько всего чанков.
    pub chunk_total: u64,
    /// Ключ файла (§10.1).
    pub key: [u8; 32],
    /// Превью изображения, если оно есть (§10.3).
    pub preview: Option<Vec<u8>>,
    /// Входящий файл. Исходящий читается с диска по [`StoredFile::source_path`].
    pub incoming: bool,
    /// Откуда читать исходящий файл. У входящего — `None`.
    ///
    /// Путь, а не байты: копировать гигабайт в своё хранилище ради отправки
    /// значит потребовать вдвое больше места, чем у файла есть.
    pub source_path: Option<String>,
    /// Принят к загрузке — автоматически по порогу или человеком.
    ///
    /// У исходящего всегда `true`: своё отправляем, ничего не спрашивая.
    pub accepted: bool,
    /// Собран целиком и проверен по хэшу.
    pub complete: bool,
}

/// Карточка контакта, присланная в чат третьим человеком (§4.1, дополнение).
///
/// Одна на сообщение. Признака «уже добавлен» здесь нет намеренно: он
/// вычисляется наличием контакта с таким `ik`, а отдельный флаг разошёлся бы
/// с правдой в первый же раз, когда человека добавят из QR или удалят.
///
/// Признака «сверен» здесь нет и быть не может. Присланный контакт непроверен
/// всегда, даже если у отправителя он сверен: §4.2 — про сверку отпечатка
/// голосом с самим человеком, а поручительство друга это не она. Подробности
/// и почему подпись не помогла бы — в `ratatosk_proto::contact_share`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct StoredContactShare {
    /// Сообщение, которым карточку прислали.
    pub msg_id: MsgId,
    /// Чей это контакт.
    pub ik: [u8; 32],
    /// Принятые байты карточки (§6) — то, из чего её разбирают.
    ///
    /// Байты, а не разобранные поля: карточка добавляется тем же путём, что
    /// и пришедшая из QR, и путь этот принимает именно байты. Разобрав их
    /// здесь, мы завели бы вторую дорогу к [`Store::put_contact`] — и она
    /// однажды разошлась бы с первой в проверках.
    pub card_bytes: Vec<u8>,
}

/// Интерфейс хранилища.
///
/// Трейт, а не конкретный тип, — ради двух вещей: подмены на in-memory
/// реализацию в симуляции (§16) и возможности прогнать одни и те же
/// сценарии против обеих.
pub trait Store {
    /// Открывает или создаёт БД, применяя миграции.
    fn migrate(&mut self) -> Result<()>;

    /// Записывает сообщение.
    fn put_message(&mut self, message: &StoredMessage) -> Result<()>;

    /// Записывает контакт, заменяя прежнюю запись с тем же `ik`.
    fn put_contact(&mut self, contact: &StoredContact) -> Result<()>;

    /// Читает все контакты.
    fn contacts(&self) -> Result<Vec<StoredContact>>;

    /// Удаляет контакт.
    ///
    /// Сессии уходят вместе с ним каскадом по внешнему ключу (§8.3): без
    /// контакта они не только бесполезны, но и опасны — ключевой материал
    /// для собеседника, которого у пользователя больше нет.
    ///
    /// Переписку **не** трогает: удалить её или оставить — решение человека,
    /// и принимать его за него хранилище не вправе. Для этого есть
    /// [`Store::delete_chat`].
    fn delete_contact(&mut self, ik: &[u8; 32]) -> Result<()>;

    /// Удаляет чат вместе со всеми сообщениями.
    fn delete_chat(&mut self, chat_id: &[u8; 16]) -> Result<()>;

    /// Читает одно сообщение по идентификатору.
    ///
    /// Нужно там, где решение зависит от того, **чьё** сообщение и в каком
    /// чате: отозвать чужие слова из своей переписки не должен уметь никто
    /// (§4.2 по духу), и проверить это можно только заглянув в запись.
    fn message(&self, msg_id: &MsgId) -> Result<Option<StoredMessage>>;

    /// Помечает сообщение удалённым и **стирает его содержимое**.
    ///
    /// Надгробие хранит идентификатор, а не текст, и это существенно. Запись
    /// остаётся, чтобы копия, пришедшая позже другим транспортом (§9.2), не
    /// воскресила удалённое; тело при этом не нужно ни для чего — держать его
    /// на диске девяносто суток (§12) после того, как человек нажал «удалить»,
    /// значит не удалить.
    ///
    /// Возвращает `false`, если такого сообщения нет.
    fn tombstone_message(&mut self, msg_id: &MsgId, now_ms: u64) -> Result<bool>;

    /// Помечает удалёнными все сообщения чата. Возвращает, сколько их было.
    fn tombstone_chat(&mut self, chat_id: &[u8; 16], now_ms: u64) -> Result<u64>;

    /// Заменяет текст сообщения и ставит отметку о правке.
    ///
    /// Прежнее тело затирается, а не сохраняется рядом: см.
    /// `ratatosk_proto::edit` — правка, при которой старые слова остаются
    /// доступны, обещает пользователю обратное тому, что он нажал.
    ///
    /// Возвращает `false`, если сообщения нет или оно уже удалено. Правка
    /// удалённого не воскрешает его: надгробие сильнее (§9.2).
    fn edit_message(&mut self, msg_id: &MsgId, body: &[u8], edited_ms: u64) -> Result<bool>;

    /// Ставит реакцию, заменяя прежнюю от того же автора.
    ///
    /// Пустая строка — **снятие**, и она тоже пишется строкой, а не удаляет
    /// её. Строка со снятием несёт метку HLC, и без неё запоздавшая реакция
    /// возвращала бы то, что человек убрал: удалив запись, мы забыли бы, что
    /// снятие вообще было (§9.2 — приход не равен порядку).
    ///
    /// Сравнение меток здесь **не** делается: правило «кто позже по HLC, тот
    /// и прав» живёт в ядре, как и лестница статусов (§9.4). Записанное дважды,
    /// оно однажды разойдётся.
    fn put_reaction(&mut self, reaction: &StoredReaction) -> Result<()>;

    /// Читает запись о реакции автора **как есть** — включая снятие.
    ///
    /// Нужна ровно для сравнения меток: показывать снятую реакцию нельзя,
    /// а знать о ней, чтобы не воскресить её опоздавшей копией, — обязательно.
    fn reaction(&self, msg_id: &MsgId, author_ik: &[u8; 32]) -> Result<Option<StoredReaction>>;

    /// Читает реакции на сообщение — только те, что **есть**.
    ///
    /// Снятые (с пустой строкой) не отдаются: это записи для сравнения меток,
    /// а не то, что рисуют. Фильтр живёт здесь, а не у каждого читателя, —
    /// иначе первый забывший его нарисует пустой пузырёк.
    fn reactions(&self, msg_id: &MsgId) -> Result<Vec<StoredReaction>>;

    /// Записывает сессию, заменяя прежнюю с тем же идентификатором.
    ///
    /// **Вызывается до того, как кадр уйдёт в сеть.** Счётчик отправки,
    /// откатившийся после падения процесса, означает повтор пары «ключ,
    /// nonce» — то есть разрушение шифрования кадра, а не потерю сообщения.
    fn put_session(&mut self, session: &StoredSession) -> Result<()>;

    /// Читает все сессии.
    fn sessions(&self) -> Result<Vec<StoredSession>>;

    /// Удаляет сессию — при перерукопожатии (§8.5) или разрыве LAN (§5.4).
    fn delete_session(&mut self, session_id: u64) -> Result<()>;

    /// Читает служебное значение.
    ///
    /// Здесь живёт то, что не является ни сообщением, ни контактом:
    /// зерно собственной идентичности (§3), соль для `db_key` (§8.6),
    /// состояние гибридных часов (§9.1).
    fn meta(&self, key: &str) -> Result<Option<Vec<u8>>>;

    /// Пишет служебное значение.
    fn put_meta(&mut self, key: &str, value: &[u8]) -> Result<()>;

    /// Читает окно сообщений чата в порядке HLC (§9.1).
    fn messages(
        &self,
        chat_id: &[u8; 16],
        limit: usize,
        before: Option<Hlc>,
    ) -> Result<Vec<StoredMessage>>;

    /// Читает текущий код статуса сообщения (§9.4).
    ///
    /// `None` — сообщения нет либо статус не выставлен.
    fn status(&self, msg_id: &MsgId) -> Result<Option<u8>>;

    /// Записывает код статуса как есть. Возвращает `false`, если сообщения
    /// с таким идентификатором нет.
    ///
    /// Отличать «записали» от «такого сообщения нет» приходится потому, что
    /// по очереди доставки §5.4 ездят не только сообщения: отзыв (`retract`)
    /// — такая же запись в очереди, но в истории его нет и статуса у него
    /// быть не может. Событие о статусе того, чего пользователь не видит,
    /// UI только запутает.
    ///
    /// Никакой логики: **какой переход допустим — решает `ratatosk-proto`**
    /// (`receipts::advance`). Правило это неочевидное — `Undeliverable`
    /// перекрывает только `Pending`, — и записанное в двух местах оно
    /// разойдётся. Гонки здесь нет: ядро sans-io, писатель ровно один.
    fn set_status(&mut self, msg_id: &MsgId, status: u8) -> Result<bool>;

    /// Записывает аватарку, заменяя прежнюю.
    ///
    /// `owner_ik` собственной аватарки — собственный `IK`.
    fn put_avatar(&mut self, owner_ik: &[u8; 32], avatar: &StoredAvatar) -> Result<()>;

    /// Читает аватарку.
    fn avatar(&self, owner_ik: &[u8; 32]) -> Result<Option<StoredAvatar>>;

    /// Есть ли аватарка, без чтения и расшифровки байтов.
    ///
    /// Отдельный вопрос, потому что ответ нужен на каждый показ списка чатов,
    /// а картинка весит до тридцати двух килобайт: расшифровывать их все,
    /// чтобы нарисовать заглушки, — работа на пустом месте.
    fn has_avatar(&self, owner_ik: &[u8; 32]) -> Result<bool>;

    /// Удаляет аватарку — контакт снял её у себя или пользователь у себя.
    fn delete_avatar(&mut self, owner_ik: &[u8; 32]) -> Result<()>;

    /// Запоминает сообщение, ожидающее отправки.
    ///
    /// Очередь на диске существует ради одного обещания: статус
    /// «собеседника нет в сети, отправим когда появится» должен переживать
    /// перезапуск. В памяти он не переживал бы убитый процесс — а на Android
    /// это происходит постоянно, — и на экране оставалось бы обещание без
    /// исполнителя, то есть ровно то, что запрещает §14.
    fn put_outbox(&mut self, entry: &StoredOutbox) -> Result<()>;

    /// Читает всю очередь ожидающих.
    fn outbox(&self) -> Result<Vec<StoredOutbox>>;

    /// Убирает сообщение из очереди: ушло, удалено или больше не поедет.
    fn delete_outbox(&mut self, msg_id: &MsgId) -> Result<()>;

    /// Записывает сведения о файле, заменяя прежние с тем же `file_id`.
    fn put_file(&mut self, file: &StoredFile) -> Result<()>;

    /// Читает сведения о файле.
    fn file(&self, file_id: &FileId) -> Result<Option<StoredFile>>;

    /// Читает все файлы, приложенные к сообщению, в порядке `file_id`.
    fn files_of(&self, msg_id: &MsgId) -> Result<Vec<StoredFile>>;

    /// Кладёт присланную карточку контакта (§4.1, дополнение).
    fn put_contact_share(&mut self, share: &StoredContactShare) -> Result<()>;

    /// Читает карточку, присланную этим сообщением. `None` — её там нет.
    fn contact_share_of(&self, msg_id: &MsgId) -> Result<Option<StoredContactShare>>;

    /// Отмечает файл принятым к загрузке. Возвращает `false`, если его нет.
    fn accept_file(&mut self, file_id: &FileId) -> Result<bool>;

    /// Отмечает файл собранным. Возвращает `false`, если его нет.
    fn complete_file(&mut self, file_id: &FileId) -> Result<bool>;

    /// Отмечает чанк принятым.
    ///
    /// Зовётся **после** записи байтов в [`Blobs`]: отметка о чанке, которого
    /// нет на диске, превращает файл в собранный из пустоты.
    fn note_chunk(&mut self, file_id: &FileId, index: u64) -> Result<()>;

    /// Есть ли уже этот чанк.
    ///
    /// Спрашивается на каждом принятом кадре, поэтому и отдельным вопросом:
    /// повтор чанка законен (§9.2), но обрабатывать его как новый нельзя —
    /// иначе он тянет за собой и подтверждение, и срок молчания, и передача
    /// начинает разгонять сама себя.
    fn has_chunk(&self, file_id: &FileId, index: u64) -> Result<bool>;

    /// Сколько чанков уже принято — для показа хода передачи (§10.2).
    fn received_chunks(&self, file_id: &FileId) -> Result<u64>;

    /// Первый чанк, которого ещё нет. `None` — все на месте.
    ///
    /// Это и есть точка возобновления (§10.2): её получатель называет
    /// отправителю, и по ней же решается, собран ли файл.
    fn next_missing_chunk(&self, file_id: &FileId, chunk_total: u64) -> Result<Option<u64>>;

    /// Незавершённые входящие передачи — то, что надо продолжить после
    /// перезапуска.
    fn unfinished_files(&self) -> Result<Vec<StoredFile>>;

    /// Вложения всех сообщений чата — только идентификаторы.
    ///
    /// Нужно ровно перед [`Store::delete_chat`]: тот уносит сообщения, каскад
    /// внешних ключей уносит записи о файлах, и после него спросить, какие
    /// вложения тут были, уже не у кого — а байты лежат отдельно, в [`Blobs`],
    /// и каскад до них не достаёт.
    fn file_ids_of_chat(&self, chat_id: &[u8; 16]) -> Result<Vec<FileId>>;

    /// Все известные базе файлы — только идентификаторы, по возрастанию.
    ///
    /// Это половина ответа на вопрос «что на диске лишнее»; вторую половину
    /// знает [`Blobs::stored_files`]. Идентификаторы, а не записи: сверка
    /// идёт по ним, а тянуть ради неё имена и ключи всех вложений — значит
    /// расшифровать половину базы, чтобы ничего из этого не прочесть.
    fn all_file_ids(&self) -> Result<Vec<FileId>>;

    /// Убирает файл и всё, что о нём известно. Байты удаляет вызывающий:
    /// они лежат в [`Blobs`], а не здесь.
    fn delete_file(&mut self, file_id: &FileId) -> Result<()>;

    /// Ищет сообщения по словам. Возвращает идентификаторы, новые первыми.
    ///
    /// `chat_id = None` — по всей переписке. Слов может быть несколько, и
    /// тогда нужны **все**: человек, уточняющий запрос вторым словом, ждёт
    /// меньше находок, а не больше. Пустой запрос — пустой ответ, а не вся
    /// история.
    ///
    /// Ищутся **целые слова** и только они: индекс хранит хэши слов на ключе
    /// базы ([`tokens`]), поэтому ни префиксов, ни подстрок, ни морфологии
    /// тут нет и быть не может. Это цена за то, что файл базы не отдаёт
    /// переписку тому, у кого нет PIN.
    ///
    /// Идентификаторы, а не сообщения: находок бывает много, а показывает
    /// их вызывающий по одной странице.
    fn search(&self, chat_id: Option<&[u8; 16]>, query: &str, limit: usize) -> Result<Vec<MsgId>>;

    /// Отмечает `msg_id` как виденный. Возвращает `false`, если уже видели (§9.2).
    fn note_seen(&mut self, msg_id: &MsgId, now_ms: u64) -> Result<bool>;

    /// Выполняет одну задачу уборки (§12).
    fn compact(&mut self, task: Task, now_ms: u64) -> Result<u64>;

    /// Выгружает переписку в зашифрованный архив (§12).
    ///
    /// Единственный путь переноса истории на другое устройство в v1.
    fn export(&self, destination: &std::path::Path) -> Result<()>;
}
