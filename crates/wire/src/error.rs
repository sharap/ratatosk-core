//! Ошибки разбора кадра.
//!
//! Крейт без зависимостей, поэтому `thiserror` здесь не используется —
//! `Display`/`Error` написаны руками.

use core::fmt;

/// Причина, по которой байты не являются корректным кадром Ratatosk.
///
/// Все варианты означают одно действие на приёме (§7.3, шаг 4): кадр
/// отбрасывается, счётчик аномалий по источнику увеличивается. Различаются они
/// только для диагностики и для отчётов фаззера — на поведение не влияют.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WireError {
    /// Длина не совпадает ни с одним классом из §5.5.
    ///
    /// Проверяется первой (§7.3, шаг 1): это самая дешёвая проверка и она
    /// отсекает основную массу мусора.
    BadFrameLength {
        /// Фактическая длина полученных байтов.
        got: usize,
    },
    /// Байт версии в заголовке не тот, который умеет разбирать эта сборка.
    UnsupportedVersion {
        /// Значение из байта версии.
        got: u8,
    },
    /// Байт типа не соответствует ни `0x01`, ни `0x02` (§7.1).
    UnknownFrameType {
        /// Значение из байта типа.
        got: u8,
    },
    /// Полезная нагрузка не влезает в выбранный класс размера.
    PayloadTooLarge {
        /// Длина полезной нагрузки.
        got: usize,
        /// Максимум для класса.
        max: usize,
    },
    /// Буфер под запечатанную часть кадра не той длины, что требует класс.
    SealedLengthMismatch {
        /// Фактическая длина.
        got: usize,
        /// Ожидаемая длина.
        want: usize,
    },
    /// Расшифрованный открытый текст не заканчивается корректным паддингом
    /// `0x80 0x00*` (§7.2).
    ///
    /// Возникает уже **после** успешной проверки тега AEAD, то есть означает
    /// либо баг отправителя, либо несовместимую версию — но не атаку:
    /// подделать содержимое, прошедшее AEAD, нельзя.
    MalformedPadding,
}

impl fmt::Display for WireError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            WireError::BadFrameLength { got } => {
                write!(f, "длина кадра {got} не совпадает ни с одним классом размера")
            }
            WireError::UnsupportedVersion { got } => {
                write!(f, "неподдерживаемая версия кадра: {got}")
            }
            WireError::UnknownFrameType { got } => write!(f, "неизвестный тип кадра: {got:#04x}"),
            WireError::PayloadTooLarge { got, max } => {
                write!(f, "полезная нагрузка {got} байт больше предела класса {max}")
            }
            WireError::SealedLengthMismatch { got, want } => {
                write!(f, "запечатанная часть {got} байт вместо {want}")
            }
            WireError::MalformedPadding => write!(f, "некорректный паддинг открытого текста"),
        }
    }
}

impl std::error::Error for WireError {}
