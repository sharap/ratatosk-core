    #[test]
    fn the_table_list_matches_what_the_migrations_create() {
        // **Список обязан отставать от схемы шумно.** Вывоз графа оставляет
        // перечисленное и опустошает остальное; таблица, не попавшая
        // в список, уехала бы вместе с графом молча — а в ней могла
        // оказаться переписка.
        fn name_after(line: &str, prefix: &str) -> Option<String> {
            let rest = line.strip_prefix(prefix)?;
            Some(rest.chars().take_while(|c| c.is_alphanumeric() || *c == '_').collect())
        }

        let mut created: Vec<String> = Vec::new();
        for migration in MIGRATIONS {
            for line in migration.lines() {
                let line = line.trim();
                if let Some(name) = name_after(line, "CREATE TABLE ") {
                    created.push(name);
                    continue;
                }
                // Переименование учитывается, иначе перестройка таблицы
                // через временное имя выглядела бы новой таблицей. Приём
                // этот у SQLite штатный — иначе первичный ключ не сменить,
                // — и первая же перестройка (очередь доставки, 0021)
                // на нём и споткнулась.
                if let Some(from) = name_after(line, "ALTER TABLE ") {
                    if let Some(to) = line.split(" RENAME TO ").nth(1) {
                        let to: String =
                            to.chars().take_while(|c| c.is_alphanumeric() || *c == '_').collect();
                        for name in &mut created {
                            if *name == from {
                                name.clone_from(&to);
                            }
                        }
                    }
                }
            }
        }
        created.sort();
        // Пересозданную миграцией таблицу считаем **одной**: перестройка
        // таблицы — обычный приём SQLite, а имя от этого не двоится.
        created.dedup();
        let mut known: Vec<String> = ALL_TABLES.iter().map(|t| (*t).to_owned()).collect();
        known.sort();
        assert_eq!(created, known, "список таблиц разошёлся с миграциями");
    }

