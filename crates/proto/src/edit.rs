//! Правка отправленного сообщения.
//!
//! **Спецификация v0.1 этого не описывает.** Дополнение, и §17 просит такие
//! вещи называть отдельно, а не растворять в коде.
//!
//! # Это просьба, как и отзыв
//!
//! Устройство то же, что у `crate::retract`: кадр уезжает обычной очередью
//! §5.4, а что с ним сделает чужой клиент — протокол не знает и обещать
//! не может (§14). Разница только в том, что отзыв стирает текст, а правка
//! его заменяет.
//!
//! # Старый текст не хранится
//!
//! Ни у отправителя, ни у получателя. Решение сознательное: правка, при которой
//! прежние слова остаются доступны, — не правка, а приписка, и человек, нажавший
//! «изменить», имел в виду первое. История версий превратила бы кнопку
//! в обещание, обратное тому, которое она даёт.
//!
//! Взамен обязательна **отметка**: у сообщения появляется признак «изменено»
//! и момент правки. Молча подменить текст в чужой истории — ровно то, что §14
//! запрещает: собеседник имеет право знать, что слова изменились. Отметка
//! обходится дешевле правды.
//!
//! # Окно правки
//!
//! [`MAX_EDIT_AGE_MS`] — неделя. Предел нужен, потому что без него правка
//! становится способом переписать давний разговор: сообщение годичной
//! давности могло бы стать другим, и собеседник, помнящий прежнее, не смог бы
//! ничего показать. Неделя выбрана под наш способ доставки: собеседник
//! законно бывает офлайн несколько дней (§5.1 пока единственный транспорт),
//! и сутки, как в других мессенджерах, означали бы правку, которая
//! не доезжает.
//!
//! Срок считает **получатель**, а не только отправитель, и по своим часам:
//! `wall_ms` в метке HLC приходит от собеседника (§9.1), и доверять ему
//! в проверке, которая его же и ограничивает, нельзя.
//!
//! # Что нельзя править
//!
//! Только своё — как и с отзывом, проверяет это получатель. Пустой текст
//! правкой не считается: «заменить на ничего» — это удаление, у него своё
//! намерение и своя команда (`crate::retract`), и подменять одно другим
//! значило бы дать удалить сообщение, не сказав об этом пользователю.

use ratatosk_codec::{canonical, CodecError, Value};
use ratatosk_crdt::MsgId;

/// Ключ идентификатора правимого сообщения.
const KEY_TARGET: u64 = 1;
/// Ключ нового текста.
const KEY_TEXT: u64 = 2;

/// Сколько времени сообщение можно править — неделя.
pub const MAX_EDIT_AGE_MS: u64 = 7 * 24 * 60 * 60 * 1_000;

/// Почему правка не принята.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum EditError {
    /// Пустой текст — это удаление, а не правка.
    #[error("пустая правка — это удаление; для него есть отзыв")]
    Empty,
    /// Сообщение старше [`MAX_EDIT_AGE_MS`].
    #[error("сообщение слишком старое, чтобы его править")]
    TooLate,
    /// Правится чужое сообщение или сообщение из другого чата.
    #[error("править можно только свои сообщения")]
    NotYours,
}

/// Годится ли текст в правку.
///
/// # Errors
///
/// [`EditError::Empty`], если после обрезки пробелов ничего не осталось.
pub fn check(text: &str) -> Result<(), EditError> {
    if text.trim().is_empty() {
        return Err(EditError::Empty);
    }
    Ok(())
}

/// Не поздно ли править сообщение, полученное (или отправленное) в `origin_ms`.
///
/// Оба момента — **по местным часам**: у отправителя это когда он нажал
/// «отправить», у получателя — когда кадр пришёл. Метку HLC здесь брать нельзя,
/// её физическая компонента приходит от собеседника.
#[must_use]
pub const fn within_window(origin_ms: u64, now_ms: u64) -> bool {
    now_ms.saturating_sub(origin_ms) <= MAX_EDIT_AGE_MS
}

/// Собирает полезную нагрузку правки.
#[must_use]
pub fn payload(target: MsgId, text: &str) -> Value {
    Value::Map(vec![
        (Value::Integer(KEY_TARGET.into()), Value::Bytes(target.to_vec())),
        (Value::Integer(KEY_TEXT.into()), Value::Text(text.to_owned())),
    ])
}

/// Разбирает полезную нагрузку правки.
///
/// Всё здесь приходит от собеседника, поэтому проверяется всё: и длина
/// идентификатора, и то, что текст не пуст.
///
/// # Errors
///
/// [`CodecError::TypeMismatch`], если структура не та или текст пуст.
pub fn from_payload(value: &Value) -> Result<(MsgId, String), CodecError> {
    let map = canonical::as_map(value)?;
    let target = canonical::as_array::<16>(canonical::require(map, KEY_TARGET)?)?;
    let Value::Text(text) = canonical::require(map, KEY_TEXT)? else {
        return Err(CodecError::TypeMismatch);
    };
    // Пустая правка — это удаление, и приехать в виде правки она не должна.
    // Приняв её, мы стёрли бы текст, не сказав пользователю, что сообщение
    // удалили: у отзыва для этого своя отметка.
    if check(text).is_err() {
        return Err(CodecError::TypeMismatch);
    }
    Ok((target, text.clone()))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn an_edit_round_trips() {
        let (target, text) = from_payload(&payload([7u8; 16], "исправил")).unwrap();
        assert_eq!(target, [7u8; 16]);
        assert_eq!(text, "исправил");
    }

    #[test]
    fn an_empty_edit_is_refused_on_both_sides() {
        // Своя проверка — до отправки, чтобы человек узнал сразу.
        assert_eq!(check("   "), Err(EditError::Empty));
        // И на приёме: пустая правка стёрла бы текст молча, а удаление
        // обязано выглядеть удалением.
        assert!(from_payload(&payload([1u8; 16], "")).is_err());
    }

    #[test]
    fn a_wrong_sized_identifier_is_refused() {
        let bad = Value::Map(vec![
            (Value::Integer(KEY_TARGET.into()), Value::Bytes(vec![0u8; 8])),
            (Value::Integer(KEY_TEXT.into()), Value::Text("а".into())),
        ]);
        assert!(from_payload(&bad).is_err());
    }

    #[test]
    fn the_window_is_inclusive_and_saturating() {
        assert!(within_window(1_000, 1_000));
        assert!(within_window(1_000, 1_000 + MAX_EDIT_AGE_MS), "ровно граница — ещё можно");
        assert!(!within_window(1_000, 1_001 + MAX_EDIT_AGE_MS));
        // Часы собеседника могли уйти вперёд: «отправлено в будущем» — не
        // повод отказать в правке, это не та проверка.
        assert!(within_window(10_000, 1_000));
    }

    #[test]
    fn the_window_outlives_a_weekend_offline() {
        // Смысл предела — не дать переписать давний разговор, а не помешать
        // правке доехать. Собеседник, которого не было три дня, обязан
        // получить её.
        let three_days = 3 * 24 * 60 * 60 * 1_000;
        assert!(within_window(0, three_days));
    }
}
