    fn the_migration_reads_the_old_narezka_out_of_what_was_stored() {
        // **Проверяется задним числом, а не на новых записях.** Столбец
        // с размером чанка появился в 0026, и живые базы к тому моменту
        // уже держали и файлы с провода (кусок в мебибайт), и файлы
        // из эфира (кусок в 3765 байт). Проставь миграция всем умолчание —
        // и пересылка эфирного файла, принятого вчера, читала бы его
        // кусками по мебибайту: смещения поехали бы с первого же куска,
        // и наружу это вышло бы не отказом, а испорченным файлом.
        //
        // Место 0026 в списке ищется **по содержимому, а не по концу**.
        // Раньше здесь стояло `MIGRATIONS.len() - 1`, и проверка молча
        // означала «последняя»: первая же следующая миграция превратила
        // её в проверку не того. Тихо это не прошло — но могло бы,
        // окажись следующая миграция безобидной для `files`.
        let up_to = MIGRATIONS.iter().position(|m| *m == MIGRATION_0026).expect("0026 в списке");
        let conn = rusqlite::Connection::open_in_memory().expect("база в памяти");
        for migration in &MIGRATIONS[..up_to] {
            conn.execute_batch(migration).expect("прежние миграции накатываются");
        }

        // Три файла, нарезанные по-разному, и все — до появления столбца.
        // Числа взяты не на глаз: у каждого своё число кусков, и по нему
        // нарезка и узнаётся.
        let rows: [(u8, i64, i64); 3] = [
            // Эфирный: 10 000 байт кусками по 3765 — три куска.
            (1, 10_000, 3),
            // Проводной: 3 МиБ кусками по 1 048 245 — тоже три, но размер
            // другой, и спутать их нельзя.
            (2, 3 * 1024 * 1024, 4),
            // Пустой: кусков нет вовсе, и не подходит ни одна нарезка.
            (3, 0, 0),
        ];
        for (tag, size, total) in rows {
            conn.execute(
                "INSERT INTO files (
                     file_id, name_enc, size_bytes, chunk_total, file_key_enc,
                     incoming, accepted, complete
                 ) VALUES (?1, x'00', ?2, ?3, x'00', 1, 1, 0)",
                rusqlite::params![&[tag; 16][..], size, total],
            )
            .expect("старая запись ложится");
        }

        conn.execute_batch(MIGRATIONS[up_to]).expect("0026 накатывается");

        let got = |tag: u8| -> i64 {
            conn.query_row(
                "SELECT chunk_bytes FROM files WHERE file_id = ?1",
                rusqlite::params![&[tag; 16][..]],
                |row| row.get(0),
            )
            .expect("размер чанка прочитан")
        };
        assert_eq!(got(1), 3765, "эфирный файл обязан остаться эфирным");
        assert_eq!(got(2), 1_048_245, "проводной — проводным");
        assert_eq!(got(3), 1_048_245, "пустому нарезка безразлична, но нулём быть не должна");
    }

