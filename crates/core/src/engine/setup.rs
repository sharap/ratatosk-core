//! Настройка транспортов и собственных адресов (§5.1, §5.4).
//!
//! Включение и выключение ступеней, почтовый ящик, Yggdrasil, Nostr —
//! и то, что из них следует: какие адреса объявлять о себе и какие
//! снимать. Ступень объявляется только после того, как поднялась;
//! адрес снимается, когда ступень отпала.

use super::*;

impl<S: Store> Engine<S> {
    /// Человек включил или выключил транспорт (§5.4).
    ///
    /// Один обработчик на все транспорты, а не по одному на каждый, и это
    /// главное, ради чего переключатель стал общим: транспортов станет
    /// больше, а мест, где о них принимают решение, — нет.
    ///
    /// Что здесь происходит по порядку и почему именно так:
    ///
    /// * набор пишется **на диск** до всего остального. Выбор человека
    ///   не должен зависеть от того, доживёт ли процесс до следующего шага;
    /// * копия набора расходится по контактам: §5.4 принимает решение
    ///   по [`PeerAvailability`], и рассогласование её с состоянием ядра
    ///   означало бы, что лестница живёт по устаревшему разрешению;
    /// * транспорту уходит [`Effect::SetTransportEnabled`] — это его дело,
    ///   поднимать он себя будет или гасить;
    /// * включение даёт отложенным сообщениям новый шанс: появилась ступень,
    ///   которой раньше не было.
    ///
    /// Выключение очередь **не** трогает. Сообщение, ждавшее LAN, ждёт
    /// теперь onion, а если и его выключили — упрётся в «отправить некуда»
    /// своим чередом и честно скажет об этом (§14). Отменять обещание
    /// доставки из-за переключателя нельзя: человек выключил транспорт,
    /// а не отказался от переписки.
    pub(super) fn on_set_transport_enabled(
        &mut self,
        now_ms: u64,
        transport: Transport,
        enabled: bool,
    ) -> Result<Vec<Effect>, EngineError> {
        if self.enabled.contains(transport) == enabled {
            // Повтор того же — обычное дело: клиент выставляет все
            // переключатели при старте. Молча и бесплатно.
            return Ok(Vec::new());
        }
        self.enabled.set(transport, enabled);
        self.store.put_meta(ratatosk_store::META_TRANSPORTS, &[self.enabled.bits()])?;
        self.apply_transport(now_ms, transport)
    }

    /// Приводит транспорт в то состояние, которое следует из настроек (§5.4).
    ///
    /// Отделено от [`Engine::on_set_transport_enabled`] затем, что менять
    /// состояние транспорта умеют **двое**: выбор человека и уход аккаунта
    /// с экрана. Первый пишется на диск, второй — нет, а всё остальное
    /// у них общее: доступность контактов, готовность, эффект раннеру,
    /// уборка видимости в эфире. Два экземпляра этого «остального» разошлись
    /// бы, и разошлись бы молча.
    ///
    /// Действующее значение берётся из [`Engine::announcing`], а не из
    /// разрешения: разрешённая, но не объявляемая локальная сеть — это
    /// выключенная локальная сеть, и раннер обязан узнать именно это.
    pub(super) fn apply_transport(
        &mut self,
        now_ms: u64,
        transport: Transport,
    ) -> Result<Vec<Effect>, EngineError> {
        let announcing = self.announcing();
        let enabled = announcing.contains(transport);
        for contact in self.contacts.values_mut() {
            contact.availability.enabled = announcing;
        }

        // Готовность идёт следом за разрешением, но не совпадает с ним.
        // Выключенный транспорт не работает по определению; включённый —
        // работает не сразу, и у Tor это десятки секунд. Кто ждать
        // не заставляет, тот готов вместе с включением.
        self.ready.set(transport, enabled && IMMEDIATE_TRANSPORTS.contains(transport));
        for contact in self.contacts.values_mut() {
            contact.availability.ready = self.ready;
        }

        // Ключ nostr заводится ровно здесь — при первом включении ступени,
        // а не при заведении аккаунта. Он долговременный опознаватель,
        // и заводить его тому, кто ступенью не пользуется, незачем: пустое
        // поле в карточке честно означает «ступени у меня нет».
        //
        // И заводится он **до** эффекта раннеру: настройка едет вниз тем же
        // шагом, и приди она раньше ключа, раннер поднял бы ступень без него.
        if transport == Transport::Nostr && enabled {
            self.ensure_nostr_key()?;
        }

        let mut effects = vec![Effect::SetTransportEnabled { transport, enabled }];
        if transport == Transport::Nostr {
            // Ступень включили или выключили — раннеру надо сказать, что
            // с ключом и реле делать, а карточке, возможно, вырасти: ключ
            // в ней появляется вместе с первым включением.
            effects.extend(self.apply_nostr(now_ms)?);
        }
        // **Оба эфира, а не один.** Правило здесь про обнаружение: маяк
        // ловится, пока эфир открыт, и перестаёт ловиться, едва его закрыли.
        // Локальной сети это было написано сразу, а шестая ступень (0.4)
        // приехала позже и правила не получила — отметка «слышно» переживала
        // выключение радио, и §5.4 при следующем включении шёл в Bluetooth
        // по устаревшему свидетельству: «слышно» есть, адреса нет, срок
        // уплачен. На стенде это читалось как `bt=адреса нет` сразу после
        // `/bt on`.
        if matches!(transport, Transport::Lan | Transport::Bt) {
            // Прежние «не слышно» устарели: эфир только что открылся или
            // закрылся, и каждому контакту снова полагается срок на
            // обнаружение.
            self.awaited_discovery.clear();
            if enabled {
                effects.push(self.watch_peers());
            } else if transport == Transport::Lan {
                // И «слышно» устарело тоже. Видимость в эфире — не память
                // о том, что когда-то слышали, а знание о том, что слышим
                // сейчас; с выключенным эфиром маяков никто не ловит.
                for contact in self.contacts.values_mut() {
                    contact.availability.seen_on_lan = false;
                }
                self.seen_on_lan.clear();
                // И отметку времени тоже: иначе включённая заново ступень
                // считала бы собеседника слышимым по свидетельству, которое
                // само же и объявила устаревшим.
                for heard in self.heard.values_mut() {
                    heard.lan_ms = None;
                }
            } else {
                for contact in self.contacts.values_mut() {
                    contact.availability.seen_on_bt = false;
                }
                self.seen_on_bt.clear();
                for heard in self.heard.values_mut() {
                    heard.bt_ms = None;
                }
            }
        }

        if enabled {
            // Ступень появилась — у отложенных сообщений появился шанс.
            effects.extend(self.retry_deferred(None)?);
        } else {
            effects.extend(self.release_from(transport)?);
            effects.extend(self.withdraw_address(now_ms, transport)?);
        }
        Ok(effects)
    }

    /// Заводит почтовый ящик или убирает его (§5.3).
    ///
    /// Три вещи разом, и все три обязательны.
    ///
    /// **Настройки на диск.** Иначе ящик пришлось бы вводить при каждом
    /// запуске, а хранить его у клиента §13.3 не разрешает.
    ///
    /// **Адрес — в карточку** (§4.3). Пока собеседник не знает нашего
    /// chatmail-адреса, почта не ступень §5.4 **для него**: `has_chatmail`
    /// берётся из карточки, а не из наших настроек. Убрали ящик — адрес
    /// снимается той же дорогой, что и onion при выключении Tor: обещать
    /// путь, которого нет, нельзя.
    ///
    /// **Готовность — снять.** Заведение ящика не делает почту работающей:
    /// работает она с того момента, как транспорт вошёл на сервер и сказал
    /// об этом ([`Input::TransportReady`]). А вот убранный ящик означает
    /// «не работает» немедленно и наверняка — тут ждать нечего, и всё,
    /// что ехало почтой, снимается с неё сразу.
    pub(super) fn on_set_mail_account(
        &mut self,
        now_ms: u64,
        account: Option<MailAccount>,
    ) -> Result<Vec<Effect>, EngineError> {
        if let Some(account) = &account {
            account.check()?;
        }
        if self.mail == account {
            // Повтор того же — обычное дело: клиент выставляет настройки
            // при старте. Молча и бесплатно.
            return Ok(Vec::new());
        }

        match &account {
            Some(account) => {
                self.store.put_meta(ratatosk_store::META_MAIL_ACCOUNT, &account.encode()?)?
            }
            // Пустая запись, а не удаление строки: у хранилища нет
            // «забыть ключ», и заводить его ради одного случая незачем.
            // Разобрать пустоту нельзя — значит «ящика нет» (см. `restore`).
            None => self.store.put_meta(ratatosk_store::META_MAIL_ACCOUNT, &[])?,
        }

        let address = account.as_ref().map(|a| a.address.clone()).unwrap_or_default();
        self.mail = account.clone();
        // Пределы принадлежат серверу, а не нам: сменился ящик — сменился
        // и сервер, и прежние числа стали чужими. Оставь их, и переезд
        // со скупого сервера на щедрый оставил бы файлы запрещёнными
        // до перезапуска.
        self.mail_limits = ratatosk_proto::mail::MailLimits::default();

        let mut effects = vec![Effect::SetMailAccount(account)];
        // И сказать об этом: у клиента на экране остались бы числа прежнего
        // сервера рядом с адресом нового.
        effects.extend(self.tell_mail_limits());
        if address.is_empty() {
            // Ящика больше нет: почта перестала работать в тот же миг.
            self.ready.set(Transport::Mail, false);
            for contact in self.contacts.values_mut() {
                contact.availability.ready = self.ready;
            }
            effects.extend(self.release_from(Transport::Mail)?);
        }
        // Названа только почта: onion этой команды не касается.
        effects.extend(self.on_announce_addresses(now_ms, None, Some(address))?);
        Ok(effects)
    }

    /// Ставит открытый ключ узла внешнего демона (0.2).
    ///
    /// Ключ **чужой**: его завёл `yggdrasil` на устройстве, человек перенёс
    /// открытую половину руками из его окна. Наше дело — запомнить,
    /// объявить и вывести из него адрес.
    ///
    /// Ключ запоминается **всегда**, даже в чужом режиме: он останется
    /// назван, и переключение на внешний демон подхватит его без второго
    /// ввода. А вот действующим именем он становится только в режиме
    /// [`YggMode::External`] — в режиме своего узла имя выводится из нашего
    /// зерна, и чужой ключ туда не встанет.
    ///
    /// **Готовность здесь не объявляется и не может.** Поднят ли демон
    /// и назначен ли адрес, знает только раннер, и он скажет об этом
    /// [`Input::TransportReady`] после удачной привязки. Объяви мы её тут,
    /// §5.4 выбрал бы ступень, которой нет.
    ///
    /// # Errors
    ///
    /// [`EngineError::BadYggKey`] — длина не тридцать два байта и не ноль.
    /// [`EngineError::YggKeyNotYours`] — режим встроенного узла: чужой ключ
    /// там не имя, а недоразумение, и молчать о нём нельзя.
    ///
    /// [`YggMode::External`]: ratatosk_proto::ygg::YggMode::External
    pub(super) fn on_set_ygg_key(
        &mut self,
        now_ms: u64,
        key: Vec<u8>,
    ) -> Result<Vec<Effect>, EngineError> {
        use ratatosk_proto::ygg::YggMode;

        if !key.is_empty() && key.len() != ratatosk_codec::YGG_KEY_LEN {
            return Err(EngineError::BadYggKey);
        }
        // Отказ, а не тихое запоминание «на будущее». Человек в режиме узла,
        // который вводит чужой ключ, чего-то не понял про настройку — и
        // узнать об этом он обязан сейчас, а не через неделю по тому, что
        // до него не дозваниваются.
        if self.ygg_mode == YggMode::Embedded {
            return Err(EngineError::YggKeyNotYours);
        }
        if key == self.ygg_named {
            // Тот же ключ — не событие. Иначе повторное нажатие в настройках
            // растило бы версию карточки и рассылало обновление всем
            // контактам ни за чем.
            return Ok(Vec::new());
        }
        self.ygg_named.clone_from(&key);
        self.store.put_meta(ratatosk_store::META_YGG_KEY, &key)?;
        if self.ygg_mode != YggMode::External {
            // Режим не тот — имя не меняется, рассылать нечего. Запомнили
            // и всё: переключатся — подхватится.
            return Ok(Vec::new());
        }
        self.apply_ygg(now_ms)
    }

    /// Выбирает, откуда берётся меш (0.2).
    ///
    /// Переход **в** режим своего узла заводит зерно, если его ещё нет.
    /// Один раз за всю жизнь базы: адрес в меше выводится из него и уезжает
    /// в карточке, а новое зерно при каждом включении означало бы новое имя
    /// и рассылку всем контактам — то есть настройку, которую нельзя
    /// потрогать без последствий.
    ///
    /// Уход **из** режима зерна не стирает. Вернувшийся туда человек обязан
    /// получить прежний адрес: его карточка уже у контактов, и второе имя
    /// на том же устройстве им ничего не объяснит.
    ///
    /// # Errors
    ///
    /// Отказ хранилища.
    pub(super) fn on_set_ygg_mode(
        &mut self,
        now_ms: u64,
        mode: ratatosk_proto::ygg::YggMode,
    ) -> Result<Vec<Effect>, EngineError> {
        use ratatosk_proto::ygg::YggMode;

        if mode == self.ygg_mode {
            return Ok(Vec::new());
        }
        if mode == YggMode::Embedded && self.ygg_seed.is_empty() {
            let mut seed = [0u8; ratatosk_crypto::mesh::MESH_SEED_LEN];
            self.entropy.fill(&mut seed);
            let key = ratatosk_crypto::MeshKey::from_seed(seed);
            self.ygg_seed = key.seed().to_vec();
            self.store.put_meta(ratatosk_store::META_YGG_SEED, &self.ygg_seed)?;
            tracing::info!(
                адрес = %ratatosk_proto::ygg::address_text(&key.public()),
                "заведён свой узел меша"
            );
        }
        self.ygg_mode = mode;
        self.store.put_meta(ratatosk_store::META_YGG_MODE, &[mode.code()])?;
        self.apply_ygg(now_ms)
    }

    /// Называет пиров своего узла (0.2).
    ///
    /// Список заменяется целиком. В карточке он не отражается никак:
    /// собеседнику важно наше имя в меше, а не то, через кого мы в него
    /// вошли, — поэтому рассылки §4.3 здесь нет и версия карточки не растёт.
    ///
    /// # Errors
    ///
    /// Отказ хранилища или кодирования списка.
    pub(super) fn on_set_ygg_peers(
        &mut self,
        now_ms: u64,
        peers: Vec<String>,
    ) -> Result<Vec<Effect>, EngineError> {
        if peers == self.ygg_peers {
            return Ok(Vec::new());
        }
        let encoded = ratatosk_proto::ygg::peers_encode(&peers)?;
        self.ygg_peers = peers;
        self.store.put_meta(ratatosk_store::META_YGG_PEERS, &encoded)?;
        // Имя не поменялось — а вот узлу перезвонить есть куда. `apply_ygg`
        // разошлёт карточку только если имя действительно разошлось,
        // так что второй рассылки отсюда не будет.
        self.apply_ygg(now_ms)
    }

    /// Приводит меш в соответствие с настройками (0.2).
    ///
    /// Одно место на все три команды, и это не экономия строк. Действующее
    /// имя, настройка раннера и карточка обязаны меняться **вместе**:
    /// разойдись они, получилось бы «слушаем один адрес, называем в карточке
    /// другой», и обнаружилось бы это только по тому, что до нас никто
    /// не дозванивается. Три вызывающих — три способа однажды забыть шаг.
    ///
    /// Порядок внутри тоже не случаен: сперва раннеру, потом рассылка.
    /// Раннер снимет прежнюю привязку и поставит новую, а карточка поедет
    /// уже про новое имя.
    ///
    /// # Errors
    ///
    /// Отказ хранилища при рассылке карточки.
    pub(super) fn apply_ygg(&mut self, now_ms: u64) -> Result<Vec<Effect>, EngineError> {
        self.ygg = self.ygg_name();
        let mut effects = vec![Effect::SetYgg(self.ygg_setup())];
        effects.extend(self.on_announce_addresses(now_ms, None, None)?);
        Ok(effects)
    }

    /// Наше действующее имя в меше — то, что уезжает в карточке (0.2).
    ///
    /// **Единственный** способ его посчитать, и это не стилистика. Считай
    /// его подъём и настройка порознь — они однажды разошлись бы, и наружу
    /// это вышло бы как «после перезапуска до меня перестали дозваниваться».
    pub(super) fn ygg_name(&self) -> Vec<u8> {
        use ratatosk_proto::ygg::YggMode;

        match self.ygg_mode {
            YggMode::Off => Vec::new(),
            YggMode::External => self.ygg_named.clone(),
            YggMode::Embedded if self.ygg_seed.len() == ratatosk_crypto::mesh::MESH_SEED_LEN => {
                let mut seed = [0u8; ratatosk_crypto::mesh::MESH_SEED_LEN];
                seed.copy_from_slice(&self.ygg_seed);
                ratatosk_crypto::MeshKey::from_seed(seed).public().to_vec()
            }
            // Зерна нет или оно чужой длины. Имени тоже нет — и это честнее,
            // чем назвать адрес, по которому нас не найти.
            YggMode::Embedded => Vec::new(),
        }
    }

    /// Что сказать раннеру меша про текущие настройки (0.2).
    pub(super) fn ygg_setup(&self) -> ratatosk_proto::ygg::YggSetup {
        use ratatosk_proto::ygg::{NodeSeed, YggMode, YggSetup};

        match self.ygg_mode {
            YggMode::Off => YggSetup::Off,
            YggMode::External => YggSetup::External { key: self.ygg_named.clone() },
            YggMode::Embedded => YggSetup::Embedded {
                seed: NodeSeed::new(self.ygg_seed.clone()),
                peers: self.ygg_peers.clone(),
            },
        }
    }

    /// Называет реле nostr (0.3). Список заменяется целиком.
    ///
    /// Негодные адреса **отбрасываются здесь**, до записи на диск: правило
    /// одно и живёт в `ratatosk_proto::nostr::relay_target`. Настройка,
    /// которая сохраняется и не работает, хуже отвергнутой — человек видит
    /// её в списке и считает, что ступень настроена.
    ///
    /// Отброшенные называются в журнале поимённо: молча съесть введённую
    /// строку значит оставить человека гадать, куда она делась.
    ///
    /// **В карточке список отражается, и это отличает его от пиров меша.**
    /// Пир меша — это через кого мы вошли в сеть, собеседнику до него дела
    /// нет. Реле — это где нас **читать**, и не скажи мы этого, собеседник
    /// класть события будет не туда. Поэтому смена списка растит версию
    /// карточки и уезжает обновлением §4.3, как смена onion-адреса.
    ///
    /// Цена названа прямо: правка списка реле — это рассылка всем контактам.
    /// Она приемлема ровно потому, что редка и осознанна; будь она частой,
    /// правильнее было бы возить список отдельным сообщением, а не картой.
    ///
    /// # Errors
    ///
    /// Отказ хранилища или кодирования списка.
    pub(super) fn on_set_nostr_relays(
        &mut self,
        now_ms: u64,
        relays: Vec<String>,
    ) -> Result<Vec<Effect>, EngineError> {
        let (good, bad): (Vec<String>, Vec<String>) =
            relays.into_iter().partition(|url| ratatosk_proto::nostr::relay_target(url).is_some());
        for url in &bad {
            tracing::warn!(%url, "адрес реле nostr не годится — не сохраняем");
        }
        if good == self.nostr_relays {
            return Ok(Vec::new());
        }
        let encoded = ratatosk_proto::nostr::relays_encode(&good)?;
        self.nostr_relays = good;
        self.store.put_meta(ratatosk_store::META_NOSTR_RELAYS, &encoded)?;
        self.apply_nostr(now_ms)
    }

    /// Запоминает, до какого времени ступень nostr досмотрела события (0.3).
    ///
    /// Только на диск: ни одно решение §5.4 на эту отметку не опирается,
    /// человеку она не показывается. Нужна она ровно затем, чтобы пережить
    /// перезапуск, — а диск есть только здесь.
    ///
    /// Назад отметка не ходит. Раннер считает её по принятым событиям,
    /// и убывающее значение означало бы либо перепутанные реле, либо чужие
    /// часы; в обоих случаях правильный ответ — оставить прежнюю.
    ///
    /// # Errors
    ///
    /// Отказ хранилища.
    pub(super) fn on_nostr_since(&mut self, created_at: u64) -> Result<Vec<Effect>, EngineError> {
        if created_at <= self.nostr_since {
            return Ok(Vec::new());
        }
        self.nostr_since = created_at;
        self.store.put_meta(ratatosk_store::META_NOSTR_SINCE, &created_at.to_be_bytes())?;
        Ok(Vec::new())
    }

    /// Ходить ли на реле мимо Tor (0.3).
    ///
    /// Размен, а не настройка скорости: реле начинает видеть адрес
    /// устройства рядом с постоянным ключом. Цену человеку называет клиент
    /// **до** переключения (`crate::honest::NOSTR_DIRECT_WARNING`) — здесь
    /// решение уже принято, и дело ядра его исполнить.
    ///
    /// # Errors
    ///
    /// Отказ хранилища.
    pub(super) fn on_set_nostr_direct(
        &mut self,
        now_ms: u64,
        direct: bool,
    ) -> Result<Vec<Effect>, EngineError> {
        if direct == self.nostr_direct {
            return Ok(Vec::new());
        }
        self.nostr_direct = direct;
        self.store.put_meta(ratatosk_store::META_NOSTR_DIRECT, &[u8::from(direct)])?;
        if direct {
            tracing::warn!("nostr: путь мимо Tor — реле увидит адрес устройства");
        }
        self.apply_nostr(now_ms)
    }

    /// Заводит ключ nostr, если его ещё нет (0.3).
    ///
    /// Зовётся при включении ступени, а не при заведении аккаунта, и это
    /// осознанно: ключ — долговременный опознаватель, и заводить его тому,
    /// кто ступенью не пользуется, незачем. Пустое поле в карточке означает
    /// «ступени у меня нет», и это правда до первого включения.
    ///
    /// # Errors
    ///
    /// Отказ хранилища.
    pub(super) fn ensure_nostr_key(&mut self) -> Result<(), EngineError> {
        if !self.nostr_seed.is_empty() {
            return Ok(());
        }
        let mut seed = [0u8; ratatosk_crypto::nostr::NOSTR_SEED_LEN];
        // Скаляр secp256k1 обязан лежать строго между нулём и порядком
        // группы, и случайные байты попадают туда **почти** всегда. Почти —
        // значит не всегда, и один человек из невообразимого числа получил
        // бы ступень, которая не заводится.
        let key = loop {
            self.entropy.fill(&mut seed);
            if let Ok(key) = ratatosk_crypto::nostr::NostrKey::from_seed(seed) {
                break key;
            }
        };
        self.nostr_seed = key.seed().to_vec();
        self.store.put_meta(ratatosk_store::META_NOSTR_SEED, &self.nostr_seed)?;
        self.nostr = key.public().to_vec();
        tracing::info!(
            ключ = %ratatosk_proto::nostr::NostrKey::new(key.public()).npub(),
            "заведён ключ nostr"
        );
        Ok(())
    }

    /// Действующий открытый ключ nostr — тем видом, каким он едет в карточке.
    ///
    /// Одно место на всё ядро, как и `ygg_name`: второй способ вывести
    /// то же самое однажды разошёлся бы с первым, и разошёлся бы молча.
    /// Пусто — ключа нет, то есть ступень ни разу не включали.
    pub(super) fn nostr_name(&self) -> Vec<u8> {
        let Ok(seed) =
            <[u8; ratatosk_crypto::nostr::NOSTR_SEED_LEN]>::try_from(self.nostr_seed.as_slice())
        else {
            return Vec::new();
        };
        match ratatosk_crypto::nostr::NostrKey::from_seed(seed) {
            Ok(key) => key.public().to_vec(),
            // Испорченное зерно — не повод подставить другой ключ: это
            // сменило бы наше имя на реле молча. Пусто означает «ступени
            // нет», и это честнее.
            Err(_) => Vec::new(),
        }
    }

    /// Что сказать раннеру nostr про текущие настройки (0.3).
    pub(super) fn nostr_setup(&self) -> ratatosk_proto::nostr::NostrSetup {
        use ratatosk_proto::nostr::{NostrSecret, NostrSetup};

        if !self.enabled.contains(Transport::Nostr) {
            return NostrSetup::Off;
        }
        let Ok(seed) =
            <[u8; ratatosk_crypto::nostr::NOSTR_SEED_LEN]>::try_from(self.nostr_seed.as_slice())
        else {
            return NostrSetup::Off;
        };
        NostrSetup::On {
            secret: NostrSecret::new(seed),
            relays: self.nostr_relays.clone(),
            via_tor: !self.nostr_direct,
            since: self.nostr_since,
        }
    }

    /// Приводит ступень nostr в соответствие с настройками (0.3).
    ///
    /// Одно место на все три команды — включение, список реле, путь, — и это
    /// не экономия строк, а та же причина, что у `apply_ygg`: действующий
    /// ключ, настройка раннера и карточка обязаны меняться **вместе**.
    /// Разойдись они, вышло бы «в карточке один ключ, подписываем другим»,
    /// и обнаружилось бы это только по тому, что до нас никто не достучался.
    ///
    /// Порядок внутри тот же: сперва раннеру, потом рассылка карточки.
    ///
    /// # Errors
    ///
    /// Отказ хранилища при рассылке карточки.
    pub(super) fn apply_nostr(&mut self, now_ms: u64) -> Result<Vec<Effect>, EngineError> {
        self.nostr = self.nostr_name();
        let mut effects = vec![Effect::SetNostr(self.nostr_setup())];
        effects.extend(self.on_announce_addresses(now_ms, None, None)?);
        Ok(effects)
    }

    /// Просит транспорт завести новый ящик на chatmail-сервере (§5.3).
    ///
    /// Ссылка разбирается **здесь**, до всякой сети, и по двум причинам.
    /// Отказать надо до того, как человек нажал и стал ждать. И «только
    /// `https`» — решение протокольного уровня, а не сетевого: по `http`
    /// пароль приехал бы открытым текстом любому на пути, а этот пароль
    /// открывает переписку.
    ///
    /// Выбор пути (`via_tor`) запоминается до ответа: он относится и
    /// к самой регистрации, и к заведённому ящику. Сходить за паролем
    /// напрямую, а потом ходить за письмами через Tor значило бы один раз
    /// показать серверу свой IP — и связать его с адресом навсегда.
    pub(super) fn on_create_mail_account(
        &mut self,
        url: &str,
        via_tor: bool,
    ) -> Result<Vec<Effect>, EngineError> {
        AccountUrl::parse(url)?;
        self.mail_via_tor = Some(via_tor);
        Ok(vec![Effect::CreateMailAccount { url: url.to_owned(), via_tor }])
    }

    /// Сервер завёл ящик — складываем его в настройки (§5.3).
    ///
    /// Дальше всё то же самое, что и при вводе руками: откуда взялись адрес
    /// и пароль, не имеет значения ни для хранения, ни для карточки (§4.3),
    /// ни для §5.4. Поэтому здесь нет своей ветки — только сборка настроек
    /// и общий путь.
    pub(super) fn on_mail_account_created(
        &mut self,
        now_ms: u64,
        address: &str,
        password: &Secret,
    ) -> Result<Vec<Effect>, EngineError> {
        let mut account = MailAccount::from_address(address, password.as_str());
        // Выбор человека, а не умолчание типа: он мог отказаться от Tor
        // ещё до регистрации, и регистрация уже прошла его дорогой.
        account.via_tor = self.mail_via_tor.take().unwrap_or(true);

        let mut effects = self.on_set_mail_account(now_ms, Some(account))?;
        effects.push(Effect::Notify(Event::MailAccountReady { address: address.to_owned() }));
        Ok(effects)
    }

    /// Настройки почтового ящика, если он заведён (§5.3).
    ///
    /// Пароль внутри печатать нельзя — за этим следит его тип.
    #[must_use]
    pub fn mail_account(&self) -> Option<&MailAccount> {
        self.mail.as_ref()
    }

    /// Снимает с карточки адрес выключенного транспорта (§4.3, §14).
    ///
    /// Выключенный Tor означает, что по нашему onion-адресу больше никого
    /// нет. Оставить адрес в карточке — обещать путь, которого не существует:
    /// собеседник будет честно набирать его при каждой отправке и платить
    /// за это сроком ожидания, а потом видеть «не доставлено» там, где
    /// правильный ответ — «он выключил Tor».
    ///
    /// Плата названа прямо: версия карточки растёт на каждое выключение
    /// и на каждое включение обратно. Это приемлемо ровно потому, что
    /// переключатель — редкое и осознанное действие; будь он частым,
    /// правильнее было бы не снимать адрес, а везти в карточке признак
    /// «сейчас недоступен», и это уже другая форма §4.3.
    ///
    /// Обратно адрес возвращает не эта функция, а сам транспорт: поднявшийся
    /// сервис объявляет свой адрес (`TransportEvent::TorReady`), и объявляет
    /// он тот, который **действительно** обслуживает.
    pub(super) fn withdraw_address(
        &mut self,
        now_ms: u64,
        transport: Transport,
    ) -> Result<Vec<Effect>, EngineError> {
        // Локальная сеть в карточке не живёт: её адрес меняется при каждом
        // подключении, и в §4.1 его нет.
        // Снимается **только своя** половина, вторая не называется вовсе.
        // Прежняя запись перечисляла обе — и была верной ровно потому, что
        // вторую бережно копировала из текущего состояния. Такая верность
        // держится на внимательности, а `None` держится сам.
        let (onion, chatmail) = match transport {
            // Локальная сеть в карточке не живёт: её адрес меняется при
            // каждом подключении, и в §4.1 его нет.
            //
            // Ключ меша — тоже не адрес, а **имя**: он наш от заведения
            // и остаётся верным, пока узел выключен. Onion-адрес обслуживает
            // сервис, и с ним сервис исчезает; ключ Yggdrasil не обслуживает
            // никто — по нему нас ищут, как по маяку в локальной сети.
            //
            // Плата названа прямо: собеседник, у которого ключ есть,
            // потратит на выключенный меш одну попытку, прежде чем §5.4
            // пойдёт дальше. Дороже была бы противоположность — версия
            // карточки, растущая на каждый переключатель, и рассылка
            // обновления по сети, которую только что выключили. Если
            // попытка окажется дорогой, честный ответ не здесь, а в §4.3:
            // признак «сейчас недоступен» вместо снятия адреса.
            //
            // Ключ nostr — тоже имя, и у него довод даже прямее, чем у меша.
            // Onion-адрес с выключенным сервисом ведёт в никуда: кадр,
            // посланный туда, теряется. Событие nostr не теряется —
            // оно лежит на реле и дожидается, пока ступень включат
            // обратно. Снять ключ значило бы выбросить то, что дошло бы.
            // Bluetooth здесь же, и довод тот же, что у локальной сети:
            // адреса в карточке у него нет вовсе — ступень адресуется
            // эфиром (0.4). Снимать нечего.
            Transport::Lan | Transport::Bt | Transport::Ygg | Transport::Nostr => {
                return Ok(Vec::new())
            }
            Transport::Onion => (Some(String::new()), None),
            Transport::Mail => (None, Some(String::new())),
        };
        // Снимать нечего — и объявлять нечего: §4.3 не рассылает то, что
        // не изменилось, но проверить дешевле здесь, чем разбираться потом,
        // почему версия выросла на ровном месте.
        let already_gone = match transport {
            Transport::Onion => self.addresses.onion.is_empty(),
            _ => self.addresses.chatmail.is_empty(),
        };
        if already_gone {
            return Ok(Vec::new());
        }
        self.on_announce_addresses(now_ms, onion, chatmail)
    }

    /// Снимает с выключенного транспорта всё, что на нём ехало (§5.4).
    ///
    /// Без этого выключатель действовал только на **новые** отправки, а всё,
    /// что уже успело выбрать этот транспорт, продолжало его ждать. Снаружи
    /// это выглядит так: Tor выключен, а сообщение «ждёт отправки через Tor»
    /// — и не уезжает даже по включённой позже локальной сети, потому что
    /// оно висит не в очереди ожидающих, а в попытке, привязанной к onion.
    ///
    /// Освобождение делается тем же путём, что и отказ транспорта: для §5.4
    /// «человек выключил» и «не сработало» — один и тот же исход одной
    /// ступени, и вести себя дальше надо одинаково. Разница только в причине,
    /// а причина в лестницу не входит.
    ///
    /// Сессии при этом не закрываются. Ключевой материал к транспорту
    /// не привязан, и выбрасывать его из-за переключателя значило бы платить
    /// новым рукопожатием за каждое включение-выключение. §5.4 выключенную
    /// ступень всё равно не выберет, а входящие кадры по ней — если они ещё
    /// придут — расшифровать надо: принять сообщение мы можем всегда.
    pub(super) fn release_from(
        &mut self,
        transport: Transport,
    ) -> Result<Vec<Effect>, EngineError> {
        // Собеседники, у которых на этом транспорте что-то висит: отправка
        // в полёте либо рукопожатие, которого ждут сообщения. Список сначала,
        // потому что дальше идёт `&mut self`.
        let mut peers: BTreeSet<[u8; 32]> = self
            .outbox
            .iter()
            .filter(|d| matches!(d.state, DeliveryState::InFlight { via, .. } if via == transport))
            .map(|d| d.peer_ik)
            .collect();
        peers.extend(
            self.pending
                .iter()
                .filter(|p| p.attempt.tried().last() == Some(&transport))
                .map(|p| p.peer_ik),
        );

        let mut effects = Vec::new();
        for peer_ik in peers {
            // Именно `Unreachable`: ступени на выключенном транспорте нет
            // вовсе, и это ближе к «не удалось соединиться», чем к обрыву.
            // Для LAN отсюда же забудется адрес — и правильно: слушать
            // выключенный транспорт некому.
            effects.extend(self.on_delivery_failed(peer_ik, transport, Failure::Unreachable)?);
        }
        Ok(effects)
    }

    /// Транспорт доложил, что заработал (§5.4).
    ///
    /// Для Tor это не конец bootstrap, а **публикация сервиса**: пока
    /// дескриптор не разошёлся по HSDir, дозвониться по адресу нельзя,
    /// и объявлять ступень рабочей значит обещать путь, которого ещё нет.
    ///
    /// Здесь же — второй шанс всему, что ждало: ступень появилась, и это
    /// ровно то событие, ради которого очередь отложенных и существует.
    pub(super) fn on_transport_ready(
        &mut self,
        now_ms: u64,
        transport: Transport,
    ) -> Result<Vec<Effect>, EngineError> {
        // Готовым может быть только разрешённый. Иначе выключенный
        // человеком транспорт, чей подъём успел договорить своё последнее
        // слово, тихо вернулся бы в лестницу.
        if !self.enabled.contains(transport) || self.ready.contains(transport) {
            return Ok(Vec::new());
        }
        self.ready.set(transport, true);
        for contact in self.contacts.values_mut() {
            contact.availability.ready = self.ready;
        }
        let mut effects = self.retry_deferred(None)?;
        // И недокачанные файлы. Для почты это единственный повод спросить
        // после перезапуска: рукопожатия там не будет — сессия поднимается
        // с диска целой (`resume_all_files`).
        effects.extend(self.resume_all_files(now_ms)?);
        Ok(effects)
    }

    /// Транспорт доложил, что перестал работать (§5.4).
    ///
    /// Обратный ход к [`Engine::on_transport_ready`], и до сих пор его
    /// не было вовсе: готовность выставлялась и не гасла никогда. Снаружи
    /// это выглядело как ложь — в разборе со стенда в журнале стояло
    /// `ygg=годен` ровно в ту минуту, когда меш не работал, — и стоило
    /// полного срока ожидания каждому сообщению.
    ///
    /// # Что здесь делается и в каком порядке
    ///
    /// Сперва ступень уходит из доступности: пока она там, §5.4 продолжает
    /// её выбирать. Потом всё, что на ней висело, уводится дальше по
    /// лестнице — тем же путём, каким уводит обрыв, и по той же причине:
    /// платить сроком за то, что уже известно, нечестно.
    ///
    /// **Цена у этого есть, и она известна.** Кадр мог на самом деле
    /// доехать, и тогда у получателя окажется вторая копия — её съест
    /// дедупликация (§9.2). Обратная цена больше: восемь секунд на меше
    /// и сорок пять на onion человек платит **за каждое** сообщение,
    /// а копии не замечает никто.
    ///
    /// # Чего здесь не делается
    ///
    /// **Выбор человека не трогается.** [`Engine::transports`] остаётся
    /// прежним: ступень не выключена, она сломалась. Как только она снова
    /// заработает и скажет об этом, [`Engine::on_transport_ready`] вернёт
    /// её в лестницу — и вернёт вместе с отложенным.
    ///
    /// Повтор отбрасывается молча, как и повторная готовность: транспорт,
    /// у которого сеть мигает, не должен превращать это в поток работы
    /// для ядра.
    ///
    /// # Errors
    ///
    /// Отказ хранилища при переносе доставок на следующую ступень.
    pub(super) fn on_transport_lost(
        &mut self,
        transport: Transport,
    ) -> Result<Vec<Effect>, EngineError> {
        if !self.ready.contains(transport) {
            return Ok(Vec::new());
        }
        self.ready.set(transport, false);
        for contact in self.contacts.values_mut() {
            contact.availability.ready = self.ready;
        }
        tracing::info!(?transport, "ступень перестала работать — §5.4 её больше не выбирает");
        self.release_from(transport)
    }

    /// Сводит два разговора с сервером в одну новость для человека.
    ///
    /// Предел письма сообщает SMTP, объём ящика — IMAP, и приходят они
    /// в разные моменты. Клиенту эта география не нужна: он показывает
    /// состояние почты, а не устройство протокола (§13.3). Поэтому наружу
    /// уезжает картина целиком, а вместе с ней — два готовых вывода,
    /// потому что правила, по которым они делаются, обязаны быть одни
    /// (`proto::mail`), а не пересчитываться в каждом клиенте.
    pub(super) fn tell_mail_limits(&self) -> Vec<Effect> {
        vec![Effect::Notify(Event::MailLimits {
            letter_bytes: self.mail_limits.letter_bytes,
            mailbox_used: self.mail_limits.mailbox_used,
            mailbox_limit: self.mail_limits.mailbox_limit,
            crowded: self.mail_limits.crowded(),
            carries_files: self.mail_limits.carries_file_chunks(),
        })]
    }

    /// Что надо сделать один раз при запуске, до первой команды клиента.
    ///
    /// Две вещи: сказать транспортам, кого из них человек оставил включённым
    /// в прошлый раз (вместе со списком маяков и ящиком), и **вернуться
    /// к недоделанным доставкам**.
    ///
    /// Отдельно от [`Engine::restore`] потому, что `restore` эффектов
    /// не возвращает по устройству: он зовётся до того, как появился
    /// драйвер, и вернуть их было бы некуда. Здесь же они нужны — и зовёт
    /// это драйвер, когда уже готов их исполнить.
    ///
    /// **Почему возврат к доставкам стоит здесь, а не ждёт события.**
    /// `restore` кладёт поднятое с диска в очередь ожидающих, а трогает её
    /// событие: включили транспорт, сменилась сеть, собеседник объявился.
    /// События эти приходят — но не всегда и не сразу, а у локальной сети
    /// готовность и вовсе выставлена с рождения (`IMMEDIATE_TRANSPORTS`),
    /// так что `TransportReady` для неё после старта не приходит вообще.
    /// Получалось, что переживший перезапуск исход зависел от того, объявится
    /// ли собеседник в эфире. Обещание, которое сбывается «обычно», —
    /// не обещание (§14).
    ///
    /// Отказ хранилища здесь не останавливает запуск: до первой команды
    /// человека ещё далеко, а открыть приложение важнее, чем дослать одно
    /// сообщение. В журнал он уходит.
    #[must_use = "не исполнив их, транспорты останутся выключенными, \
                  а недоделанные доставки — недоделанными"]
    pub fn startup_effects(&mut self) -> Vec<Effect> {
        let mut effects = Vec::new();

        // **Сперва настройки, потом выключатели**, и порядок здесь стоил
        // отдельного разбора. Раннер поднимается по той настройке, которая
        // у него есть на момент включения. Приди «включить» раньше — он
        // поднимет прежнюю: раннер меша, ещё не знающий про свой узел,
        // полезет привязываться к адресу несуществующего демона, откажет,
        // и приехавшая следом настройка застанет ступень уже выключенной.
        //
        // Наружу это выглядело так: после перезапуска меш не работает,
        // и чинится он выключением и включением руками. То есть настройка
        // была на диске, была в ядре, доехала до раннера — и всё равно
        // не действовала, потому что доехала второй.
        effects.push(Effect::SetMailAccount(self.mail.clone()));
        effects.push(Effect::SetYgg(self.ygg_setup()));
        effects.push(Effect::SetNostr(self.nostr_setup()));
        // Список маяков — тоже настройка, и тоже вперёд выключателей.
        // Отправляется **без оглядки** на то, включена ли локальная сеть:
        // список чистый, ничего не занимает и не раскрывает, а раннер,
        // получивший его заранее, при включении сразу знает, кого слушать.
        // Прежде он ехал следом за включением, и это работало по счастливой
        // случайности — обнаружение непрерывно, и пропущенные полсекунды
        // никто не замечал.
        effects.push(self.watch_peers());

        // **Все** ступени, а не выписанный руками список. Прежняя редакция
        // перечисляла три, и появившаяся четвёртая (меш, 0.2) в неё не попала:
        // ядро поднимало настройку с диска, а раннер о ней не узнавал.
        // Список из `Reachability` растёт сам.
        let announcing = self.announcing();
        for rung in Reachability::of(PeerAvailability::default()).rungs {
            effects.push(Effect::SetTransportEnabled {
                transport: rung.transport,
                enabled: announcing.contains(rung.transport),
            });
        }

        match self.retry_deferred(None) {
            Ok(resumed) => effects.extend(resumed),
            Err(error) => tracing::warn!(?error, "к недоделанным доставкам вернуться не вышло"),
        }
        effects
    }

    /// Какие транспорты мы **объявляем сейчас** (§5.1, §5.4).
    ///
    /// Разрешение человека минус то, что молчит по обстоятельствам. Пока
    /// обстоятельство одно: аккаунт ушёл с экрана, и его маяк в локальной
    /// сети гаснет — иначе одно устройство с тремя аккаунтами объявляло бы
    /// в эфир три присутствия сразу.
    ///
    /// Onion и почты это не касается: они не объявляют присутствия, а ждут
    /// входящих по адресу из карточки. Гасить их при уходе с экрана значило
    /// бы переставать принимать сообщения — совсем другое обещание.
    #[must_use]
    pub(super) fn announcing(&self) -> TransportSet {
        if self.foreground {
            self.enabled
        } else {
            self.enabled.without(Transport::Lan)
        }
    }

    /// Этот аккаунт вышел на экран или ушёл с него (§5.1).
    ///
    /// Гасит и зажигает **маяк**, а не настройку. Выбор человека остаётся
    /// на диске нетронутым, и вернувшийся на экран аккаунт объявляется
    /// ровно тогда, когда локальная сеть ему разрешена, — не потому, что
    /// его показали, а потому, что её включали.
    ///
    /// Разница не теоретическая: прежде реестр аккаунтов звал сюда
    /// «включить LAN», и локальная сеть включалась человеку, который её
    /// не включал. Маяк §5.1 уходил в эфир без спроса, а `lan_warning()`
    /// перед этим никто не показывал.
    ///
    /// # Errors
    ///
    /// Отказ хранилища при уборке за выключенной ступенью.
    pub(super) fn on_set_foreground(
        &mut self,
        now_ms: u64,
        front: bool,
    ) -> Result<Vec<Effect>, EngineError> {
        if front == self.foreground {
            return Ok(Vec::new());
        }
        let was = self.announcing();
        self.foreground = front;
        if was == self.announcing() {
            // Локальная сеть человеком и так не разрешена — гасить нечего
            // и зажигать нечего. Молча: клиент зовёт это на каждом
            // переключении экрана.
            return Ok(Vec::new());
        }
        self.apply_transport(now_ms, Transport::Lan)
    }

    /// Сеть сменилась: всё, что известно о прежней, устарело (§5.1, §5.4).
    ///
    /// Видимость сбрасывается **до** переоткрытия транспорта, и порядок
    /// важен: пока `seen_on_lan` держится, §5.4 продолжает выбирать LAN
    /// и отправлять по адресам прежней сети. Сообщения при этом не теряются
    /// — они честно упрутся в отказ и уйдут дальше по §5.4, — но каждое
    /// заплатит таймаутом за то, что и так уже известно.
    ///
    /// Сессии не трогаем. Ключевой материал к сети не привязан: если оба
    /// устройства оказались в новой сети вместе, переписка продолжится без
    /// нового рукопожатия. Сессию, чьё соединение оборвалось, закроет
    /// `Input::ConnectionLost` своим чередом (§5.4).
    pub(super) fn on_network_changed(&mut self) -> Result<Vec<Effect>, EngineError> {
        for contact in self.contacts.values_mut() {
            contact.availability.seen_on_lan = false;
        }
        self.seen_on_lan.clear();
        // Отметка времени устарела вместе с сетью: слышали мы его **там**,
        // а мы уже здесь. Эфир Bluetooth к сети не привязан и остаётся.
        for heard in self.heard.values_mut() {
            heard.lan_ms = None;
        }
        // Сеть другая — значит и ответ «здесь его не слышно» относился
        // к прежней. Срок на обнаружение выдаётся заново.
        self.awaited_discovery.clear();

        // Сессии живут дальше: смена сети — событие сокетов, а не ретчета.
        // Собеседник, оставшийся в прежней сети, о переезде не знает, и
        // выбрасывать общее состояние из-за него значит ломать связь ровно
        // тогда, когда она вот-вот восстановится.
        //
        // **Говорится всем ступеням, а не одной локальной сети.** Прежде
        // здесь стоял выход, если LAN выключен, — и это было верно, пока
        // эффект назывался `RestartLan`. Но сеть меняется у всех сразу:
        // соединения меша и onion после переезда мертвы точно так же,
        // а узнавали они об этом первой неудачной записью, то есть сроком
        // ожидания на каждое сообщение.
        let mut effects = vec![Effect::NetworkChanged];
        // Список маяков — обоим эфирам сразу и без оглядки на выключатели:
        // раннер, поднявшийся после переезда, обязан знать, кого слушать,
        // ещё до того, как его включат.
        effects.push(self.watch_peers());
        // Сеть появилась — самое время попробовать то, что не уехало.
        // Именно здесь, а не по таймеру: смена сети — единственное событие,
        // которое действительно меняет шансы у **всех** сразу.
        effects.extend(self.retry_deferred(None)?);
        Ok(effects)
    }

    /// Пиры встроенного узла меша, как их назвал человек (0.2).
    #[must_use]
    pub fn ygg_peers(&self) -> &[String] {
        &self.ygg_peers
    }

    /// Названные человеком реле nostr (0.3).
    ///
    /// Настройка, а не живое состояние: что из неё работает, знает раннер
    /// и сообщает событием. Различать обязательно — «реле не названы»
    /// и «названы, но не отвечают» чинятся по-разному.
    #[must_use]
    pub fn nostr_relays(&self) -> &[String] {
        &self.nostr_relays
    }

    /// Реле, объявляемые в карточке, — первые из названных (0.3).
    ///
    /// Читаем мы со **всех** названных, а объявляем три: карточка едет
    /// в QR, и каждый лишний адрес — это плотность кода
    /// (`ratatosk_codec::MAX_CARD_RELAYS`). Усечение делается здесь, одним
    /// местом на всё ядро: сравнение с объявленным и сборка карточки
    /// обязаны усекать **одинаково**, иначе версия карточки росла бы
    /// на каждом шаге сама по себе.
    pub(super) fn nostr_card_relays(&self) -> Vec<String> {
        self.nostr_relays.iter().take(ratatosk_codec::MAX_CARD_RELAYS).cloned().collect()
    }

    /// Наш открытый ключ nostr — тот, что стоит в карточке (0.3).
    ///
    /// Пусто — ступень ни разу не включали, и ключа нет вовсе.
    #[must_use]
    pub fn nostr_key(&self) -> &[u8] {
        &self.nostr
    }
}
