#!/usr/bin/env python3
"""Метелка: за питанием адаптера следят, и ступень умеет подняться заново.

Правило словами: **выключение адаптера гасит эфирную ступень, а включение
её поднимает — и то и другое в коде радио, а не в чьей-то памяти.**

Заведена по настоящей поломке, снятой со стенда 24 ноября. Половины этой
ступени умирают порознь и молча. Сброс адаптера (`bluetoothctl power
off/on`, переключатель Bluetooth в настройках) оставляет живым объявление
и обзор — обзор даже восстанавливается сам, его поток событий кончается
и цикл заходит заново, — а слушающий сокет убивает. `accept()` после
этого стоит на мёртвом сокете вечно и не говорит ни слова.

Снаружи: устройство объявляется, его слышно, а набрать его нельзя никому
— до перезапуска приложения. На стенде pinephone две с лишним минуты
набирал ПК и повисал, сообщение лежало в ожидании; стенд ПК перезапустили
— и через десять секунд входящий канал пришёл вместе с этим сообщением.

Проверить это прогоном **нельзя**, и ровно поэтому здесь метелка.
Настоящего BlueZ в прогоне нет: `local.rs` целиком живёт за признаком
`bt` и под Linux с живым `bluetoothd`, подделки адаптера у нас нет, а
единственное место, где свойство питания читается, — чужой поток
событий. Поломка «перестали следить за питанием» не роняет ни одной
проверки: ступень по-прежнему поднимается, объявляется и слышит
соседей. Та же причина, что у `platform_gates`.

Чего эта метелка **не** стережёт: что слежение работает. Что поток
свойств у BlueZ приходит, что `Powered` меняется в нём, что подъём
заново удаётся — видно только на устройстве, и доказательство лежит
в `HANDOFF.md`. Стережётся то, что слежение не выкинут незаметно:
снаружи его отсутствие неотличимо от исправной ступени.

Лестницу подъёма (`raise_again_after`) стережёт проверка прогоном —
числа там чистые. Здесь только связь с радио.

Находок должно быть ноль. Поломка проверяется так: убрать `powered_off`
из `run` — метелка краснеет; убрать `powered_again` из подъёма — тоже;
убрать чтение свойства `Powered` — тоже; дать подъёму считать ответом
нынешнее состояние (`Now::Counts`) — тоже.
"""
import pathlib
import sys

# Корень дерева считается от самого файла, а не от текущего каталога:
# метелку зовут и из корня, и из CI, и по одной из редактора.
ROOT = pathlib.Path(__file__).resolve().parents[2]

RADIO = "crates/transport/src/bluetooth/local.rs"

# Одна строка — одно место правила. Образцы **в кавычках там, где это
# имя из чужого крейта**: без них фраза нашлась бы в соседнем
# комментарии, которым правка и объясняется. Это уже случалось трижды
# (`advert_interval`, `enum_arms`, `incoming_said`), и лечится оно
# образцом, а не исключением.
MUST = [
    {
        "образец": "AdapterProperty::Powered(",
        "зачем": "свойство питания читается у адаптера, а не угадывается",
    },
    {
        "образец": "powered_off(&adapter)",
        "зачем": "выключение адаптера гасит ступень: иначе слушающий сокет мёртв молча",
    },
    {
        "образец": "powered_again(&adapter)",
        "зачем": "включение адаптера поднимает ступень, не дожидаясь срока лестницы",
    },
    {
        "образец": "raise_again_after(attempt)",
        "зачем": "подъём заново идёт по лестнице, а не в тугой петле",
    },
    {
        "образец": "watch_powered(&adapter, true, Now::DoesNot)",
        "зачем": (
            "подъём ждёт **перемены** питания, а не состояния: отказ подъёма "
            "бывает и не про питание (на PinePhone отказывала регистрация "
            "объявления), а адаптер при этом включён — и «дождались включения» "
            "срабатывало сразу, обходя лестницу. В журнале это были попытки "
            "1, 2 и 3 в одну секунду"
        ),
    },
]

bad = []
path = ROOT / RADIO
if not path.exists():
    bad.append(f"{RADIO}: файла нет — метёлке нечего смотреть")
else:
    source = path.read_text(encoding="utf-8")
    for rule in MUST:
        if rule["образец"] not in source:
            bad.append(
                f"{RADIO}: нет `{rule['образец']}` — {rule['зачем']}"
            )

# Молчание — не «чисто»: сколько мест осмотрено, видно всегда.
print("\n".join(bad) if bad else f"чисто (мест слежения за питанием осмотрено: {len(MUST)})")
sys.exit(1 if bad else 0)
