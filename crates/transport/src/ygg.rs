//! Меш Yggdrasil: внешний демон или свой узел (0.2).
//!
//! **По умолчанию выключен**, и не из осторожности к чужому коду: ступень
//! не работает, пока человек не назвал пира, а адрес в меше — долговременный
//! опознаватель, выведенный из открытого ключа. Транзит чужого трафика сюда
//! не относится: он требует двух и более пиров, а узел с одним пиром — лист
//! (см. `Transport::Ygg`). Включается сознательно, с объяснением в UI
//! (`ratatosk_core::honest::YGG_WARNING`).
//!
//! # Два способа оказаться в меше, и различаются они одной строкой
//!
//! **Внешний демон.** Узел — обычный `yggdrasil` на устройстве: пакетом
//! на стенде, официальным приложением на Android. Наше дело — соединиться
//! по его туннелю и отдать поток кадрам. Зависимостей у этого пути нет
//! вовсе: адрес `200::/7` выводится из открытого ключа арифметикой
//! ([`ratatosk_proto::ygg`]), дальше идёт обычный TCP.
//!
//! **Свой узел** (признак `ygg-node`). Меш живёт в нашем процессе поверх
//! `ygg_stream`. Он адресует **ключами**, а не адресами (TCP/KEY), поэтому
//! вывод адреса ему не нужен вовсе, — и его `TcpConnection` реализует
//! `AsyncRead + AsyncWrite`, то есть ложится в тот же [`crate::link`],
//! что и `TcpStream`.
//!
//! Различие между ними — ровно одна строка в `ensure_link`: чем открыт
//! поток. Кадры, полосы записи, сроки, отказы, готовность — общие. Так
//! и было обещано, когда писался первый из двух путей.
//!
//! Режимы взаимоисключающи (`ratatosk_proto::ygg::YggMode`): у демона ключ
//! чужой, у своего узла наш, и работай оба разом — в карточке стояло бы
//! одно имя, а слушали бы мы два.
//!
//! # Свой узел не выключается до конца, и это надо знать
//!
//! Выключение ступени отпускает нашу ссылку и останавливает стек TCP/KEY
//! (у него есть `Drop`, отменяющий задачи). Сам узел Yggdrasil при этом
//! **продолжает работать**: `Core` раздаёт `Arc` на себя в вечные задачи,
//! а способа остановиться у него в этой ревизии нет. Соединения с пирами
//! живут, и чужой трафик через нас идёт — до перезапуска приложения.
//!
//! Недоделка чужая, платит за неё наш человек, поэтому она названа ему
//! прямо (`ratatosk_core::honest::YGG_NODE_STOP_NOTICE`), а не спрятана.
//! Прятать её было бы ровно тем расхождением обещания с устройством,
//! которое запрещает §14.
//!
//! # Имя своего узла сверяется, а не принимается на веру
//!
//! Открытую половину зерна выводят двое: наш `ratatosk_crypto::MeshKey`
//! и чужой `ygg_stream`. Разойдись они — собеседники звонили бы по одному
//! адресу, а слушали бы мы под другим, и обе стороны видели бы исправную
//! ступень, по которой никто не дозванивается. Поэтому при подъёме узла
//! его `public_key()` сверяется с тем, что уже стоит в карточке, и
//! несовпадение — отказ.
//!
//! # Обнаружения нет, и оно не нужно
//!
//! У локальной сети адрес меняется при каждом подключении, поэтому там
//! маяк mDNS. Здесь адрес — **функция от ключа**, а ключ приезжает
//! в карточке (§4.1, поле 0.2). Справочника адресов нет вовсе, и забывать
//! при отказе тоже нечего: неудачное соединение говорит «его сейчас нет
//! в сети», а не «адрес устарел».
//!
//! # Порт постоянный
//!
//! Объявить его негде — обнаружения нет, — поэтому обе стороны обязаны
//! знать его заранее. Плата у демона названа прямо: **два узла на одной
//! машине по мешу не поговорят**, у них один адрес на двоих и один порт.
//!
//! У своего узла этой платы нет: порт здесь принадлежит узлу, а не системе,
//! и два процесса с разными зёрнами — это два разных имени в меше. Так что
//! проверить меш на одной машине можно — но только своими узлами.
//!
//! # Слушаем свой адрес, а не всё подряд
//!
//! У демона сокет привязывается к **нашему адресу в меше**, а не к `[::]`.
//! Две причины, и обе весомые. Первая: `[::]` открыл бы порт и в обычном
//! интернете, то есть ступень меша раздала бы точку входа тем, кто про
//! меш ничего не знает. Вторая: удачная привязка **и есть** доказательство,
//! что демон поднят и адрес назначен, — иначе готовность ступени пришлось
//! бы угадывать.
//!
//! У своего узла обе заботы отпадают: в обычный интернет он не слушает
//! по построению, а доказательством подъёма служит он сам.
//!
//! # Соединения односторонние
//!
//! Как и везде (`ARCHITECTURE.md`, 5ц): каждая сторона набирает своё
//! соединение и пишет только в него. Личность устанавливает рукопожатие
//! (§8.2), а не адрес — и здесь это не формальность: адрес меша **сжимает**
//! ключ до четырнадцати байт, так что по нему собеседник не опознаётся
//! даже в принципе.

use std::collections::BTreeMap;
use std::net::{IpAddr, Ipv6Addr, SocketAddr};
use std::time::Duration;

use ratatosk_proto::transport_policy::{Transport, YGG_CONNECT_TIMEOUT_MS};
use ratatosk_proto::ygg::{address_of, YggSetup, KEY_LEN};
use tokio::net::{TcpListener, TcpStream};
use tokio::sync::mpsc;

use crate::link::{spawn_read_loop, Link};
use crate::runner::{Runner, TransportCommand, TransportError, TransportEvent};

/// Порт, на котором стороны ищут друг друга в меше.
///
/// Число выбрано свободным в диапазоне динамических портов и постоянно:
/// объявить его негде. Менять его после первой выдачи сборок нельзя —
/// разошедшиеся стороны просто не найдут друг друга, и выглядеть это будет
/// как «меш не работает».
pub const YGG_PORT: u16 = 42425;

/// Чем отвечать, когда свой узел просят у сборки, где его нет.
///
/// Отдельной строкой, потому что говорится это из двух мест — при смене
/// настройки и при включении ступени, — и два разных текста на один случай
/// человек прочёл бы как две разные неисправности.
#[cfg(not(feature = "ygg-node"))]
const NO_NODE: &str = "встроенный узел меша в эту сборку не включён";

/// Таймаут соединения по мешу.
///
/// Число берётся из §5.4 (`transport_policy`), а не задаётся здесь. Оно
/// связано со сроком ожидания ответа на той же ступени: тот обязан вмещать
/// целый такой набор, и наш, и чужой. Здесь они и разошлись — восемь секунд
/// набора против пятисекундного срока, — и групповые сообщения после офлайна
/// пропадали.
pub const CONNECT_TIMEOUT: Duration = Duration::from_millis(YGG_CONNECT_TIMEOUT_MS);

/// Настройки транспорта.
#[derive(Debug, Clone)]
pub struct YggConfig {
    /// Включён ли меш. По умолчанию — нет (см. заголовок модуля).
    pub enabled: bool,
    /// Порт. Меняется только в проверках; в продукте — [`YGG_PORT`].
    pub port: u16,
}

impl Default for YggConfig {
    fn default() -> YggConfig {
        YggConfig { enabled: false, port: YGG_PORT }
    }
}

/// Меш целиком: слушающий сокет на своём адресе и исходящие соединения.
pub struct YggRunner {
    events_tx: mpsc::Sender<TransportEvent>,
    events_rx: mpsc::Receiver<TransportEvent>,
    /// Куда писать каждому контакту.
    links: BTreeMap<[u8; 32], Link>,
    /// Открытый ключ **нашего** узла. Пусто — меша у нас нет.
    my_key: Vec<u8>,
    port: u16,
    enabled: bool,
    /// Последнее, что сказало ядро: откуда берётся меш (0.2).
    ///
    /// Держится целиком, а не разобранным на части: включение происходит
    /// позже команды и обязано поднять **то**, что назвали, — а не то,
    /// что от неё осталось в отдельных полях.
    setup: YggSetup,
    /// Свой узел, пока он поднят.
    ///
    /// `Option`, а не всегда-есть: узел занимает сокеты и держит соединения
    /// с пирами, и выключенная ступень не должна платить за это ничем.
    #[cfg(feature = "ygg-node")]
    node: Option<std::sync::Arc<ygg_stream::AsyncNode>>,
    /// Подъём своего узла, пока он идёт.
    ///
    /// Заводится включением ступени и вычитывается в
    /// [`Runner::next_event`] — то есть в опросах драйвера, как и подъём
    /// Tor у [`crate::Switched`]. Ждать его на месте нельзя: соединение
    /// с пирами это секунды, а ждались они внутри `Driver::apply`, то есть
    /// **до первого ответа на запрос UI**. Так «включённый меш» и означал
    /// «приложение не показывает переписку до тех пор, пока не соединится
    /// с сетью, которой может не быть».
    #[cfg(feature = "ygg-node")]
    rising: Option<tokio::sync::oneshot::Receiver<Risen>>,
    /// Задача приёма. Держится затем, чтобы выключение освобождало порт:
    /// оставленный слушатель принимал бы соединения по выключенной ступени.
    accepting: Option<tokio::task::JoinHandle<()>>,
}

/// Поднявшийся свой узел — всё, что задача подъёма отдаёт раннеру.
///
/// Событий здесь нет: о готовности задача рассказывает сама, тем же
/// [`TransportEvent::Ready`], каким рассказывал бы подъём на месте. Сюда
/// уезжает только то, чем **владеть** обязан раннер: узел нужен набору,
/// а задача приёма — выключению.
#[cfg(feature = "ygg-node")]
struct Risen {
    /// Сам узел.
    node: std::sync::Arc<ygg_stream::AsyncNode>,
    /// Задача приёма входящих.
    accepting: tokio::task::JoinHandle<()>,
}

impl YggRunner {
    /// Заводит транспорт, ничего пока не занимая.
    ///
    /// Порт занимается не здесь, а при включении, и это не мелочь: привязка
    /// к своему адресу удаётся только при поднятом демоне, а поднят он или
    /// нет — вопрос момента, а не запуска приложения. Выключенный меш порта
    /// не держит вовсе.
    ///
    /// # Errors
    ///
    /// Отказ привязки, если меш просят включить сразу.
    pub async fn start(config: YggConfig, my_key: &[u8]) -> Result<YggRunner, TransportError> {
        let (events_tx, events_rx) = mpsc::channel(64);
        let mut runner = YggRunner {
            events_tx,
            events_rx,
            links: BTreeMap::new(),
            my_key: my_key.to_vec(),
            port: config.port,
            enabled: false,
            // Пока ядро не сказало иного — «внешний демон с этим ключом».
            // Так же вёл себя раннер до появления режимов, и так же
            // поднимается стенд с `--ygg`: ключ известен раньше настроек.
            setup: YggSetup::External { key: my_key.to_vec() },
            #[cfg(feature = "ygg-node")]
            node: None,
            #[cfg(feature = "ygg-node")]
            rising: None,
            accepting: None,
        };
        if config.enabled {
            runner.set_enabled(true).await?;
        }
        Ok(runner)
    }

    /// Наш адрес в меше, если ключ у нас есть.
    #[must_use]
    pub fn my_address(&self) -> Option<Ipv6Addr> {
        key_of(&self.my_key).map(|key| Ipv6Addr::from(address_of(&key)))
    }

    /// Занят ли порт прямо сейчас — то есть работает ли ступень.
    #[must_use]
    pub fn is_ready(&self) -> bool {
        self.accepting.is_some()
    }

    /// Принимает настройку меша и, если ступень включена, переезжает (0.2).
    ///
    /// Переезд — именно выключить и включить, а не «доперепривязать»:
    /// слушающий сокет привязан к прежнему адресу, и оставить его значило бы
    /// принимать по адресу, который мы больше не называем в карточке.
    /// Соединения при этом закрываются, и это правильно: они шли с прежнего
    /// адреса, и собеседник ответит уже не нам.
    ///
    /// **Без признака `ygg-node` свой узел не поднимается**, и об этом
    /// говорится отказом, а не тишиной: человек выбрал режим и ждёт, что
    /// меш заработает, — узнать, что в его сборке узла нет, он обязан
    /// в тот же момент.
    ///
    /// # Errors
    ///
    /// Отказ привязки к новому адресу. Ступень при этом остаётся выключенной
    /// — молчаливое «включено, но не работает» человеку не объяснить.
    ///
    /// [`TransportError::Refused`] — выбран свой узел, а его в сборке нет.
    async fn set_setup(&mut self, setup: YggSetup) -> Result<(), TransportError> {
        // Сравнивается настройка целиком, а не выведенное из неё имя.
        // Пиры меняются при том же имени, и сравнение по ключу объявило бы
        // такую смену «ничем» — узел остался бы звонить прежним.
        if setup == self.setup {
            return Ok(());
        }
        let key = our_key(&setup)?;
        // Прежнее опускается **всегда**, а не только когда ступень была
        // поднята: настройка сменилась, и всё, что стояло по старой,
        // теперь ведёт не туда.
        self.lower();
        self.my_key = key;
        self.setup = setup;
        // И поднимается заново, если человек ступень включал. Условие
        // на `enabled`, а не на «была ли она поднята», и это исправление
        // настоящей поломки: при подъёме приложения раннер получал
        // «включить» раньше, чем узнавал про свой узел, отказывал — и
        // приехавшая следом настройка не поднимала ничего, потому что
        // поднято ничего и не было. Ступень оставалась выключенной
        // до тех пор, пока человек не переключит её руками.
        if self.enabled {
            self.raise().await
        } else {
            Ok(())
        }
    }

    /// Опускает всё поднятое, не трогая выбор человека.
    ///
    /// Отдельно от [`YggRunner::set_enabled`] потому, что опускать нужно
    /// в двух случаях — выключили ступень и сменили настройку, — а «человек
    /// её выключил» верно только в первом.
    fn lower(&mut self) {
        // Соединения закрываются вместе с портом. Оставить их значило бы
        // писать по выключенной ступени — §5.4 её больше не выберет,
        // а кадры по ней всё равно шли бы.
        self.links.clear();
        if let Some(task) = self.accepting.take() {
            task.abort();
        }
        // Наша ссылка на узел отпускается. Стек TCP/KEY на этом
        // действительно останавливается — у `TcpStack` есть `Drop`,
        // и он отменяет свои задачи.
        //
        // **А сам узел Yggdrasil — нет**, и обещать обратное нельзя.
        // `Core` раздаёт `Arc` на себя в вечные задачи (`core.rs`:
        // обработчик протокола, обновление сертификатов), а способа
        // остановиться у него в этой ревизии нет вовсе. То есть после
        // выключения ступени соединения с пирами живут, и чужой трафик
        // через нас идёт — до перезапуска приложения.
        //
        // Это чужая недоделка, а не наша, но платит за неё наш человек,
        // поэтому она названа ему прямо (`honest::YGG_NODE_STOP_NOTICE`),
        // а не спрятана. Появится у них остановка — здесь станет одной
        // строкой больше и одним предупреждением меньше.
        #[cfg(feature = "ygg-node")]
        {
            self.node = None;
            // И ожидание незавершённого подъёма тоже.
            //
            // Сказать «подъём отменяется» было бы неправдой, и разница
            // важна: задача досоединяется с пирами до конца, а потом
            // обнаруживает, что ждать её некому, и роняет узел сама.
            // То есть выключение освобождает ступень сразу
            // (`is_ready` смотрит на приём, а его тут нет), но соединения
            // с пирами живут ещё столько, сколько занимал бы подъём.
            //
            // Терпимо потому, что этот `Option` — единственное место, где
            // поднявшийся узел мог бы к нам вернуться: включив ступень
            // заново, человек получит **новый** подъём, а не этот.
            self.rising = None;
        }
    }

    /// Включает или выключает ступень (§5.4).
    ///
    /// `enabled` здесь — **намерение человека**, а не «поднято сейчас».
    /// Различие стоило поломки: прежде отказ подъёма сбрасывал признак
    /// обратно в «выключено», и повторное «включить» становилось бесплатным
    /// повтором — то есть ступень, не поднявшаяся по случайной причине,
    /// не поднималась больше никогда. Поднято ли на самом деле, говорит
    /// [`YggRunner::is_ready`], и врать ему нечем: он смотрит на задачу
    /// приёма.
    ///
    /// Отсюда и повтор «включить» при неподнятой ступени — не пустой,
    /// а вторая попытка.
    async fn set_enabled(&mut self, on: bool) -> Result<(), TransportError> {
        if on == self.enabled && (!on || self.is_ready()) {
            return Ok(());
        }
        self.enabled = on;
        if !on {
            self.lower();
            return Ok(());
        }
        self.raise().await
    }

    /// Поднимает ступень по текущей настройке (§5.4).
    ///
    /// **Не трогает `enabled`.** Отказ здесь означает «сейчас не вышло»,
    /// а не «человек передумал»; сбрось мы признак, следующая попытка
    /// показалась бы повтором и не случилась бы.
    ///
    /// # Errors
    ///
    /// Настройка не позволяет подняться: меша нет, имени нет, демон
    /// не запущен, узла в сборке нет, узел не поднялся.
    async fn raise(&mut self) -> Result<(), TransportError> {
        // Свой узел поднимается своим путём: ему не к чему привязываться,
        // он **и есть** тот, к кому привязывались бы.
        //
        // `matches!`, а не `if let`: связывать здесь нечего, а заём поля
        // рядом с `&mut self`-вызовом внутри — лишний повод объяснять
        // компилятору очевидное.
        if matches!(self.setup, YggSetup::Embedded { .. }) {
            #[cfg(feature = "ygg-node")]
            {
                return self.start_node();
            }
            // Без признака сюда попасть нечем — `set_setup` отвергает такую
            // настройку раньше, — но отказ стоит: он собирается в обеих
            // сборках и не даёт молча включить то, чего нет.
            #[cfg(not(feature = "ygg-node"))]
            {
                return Err(TransportError::Refused(NO_NODE.to_owned()));
            }
        }

        // Нет ключа — нет и меша. Отказ здесь честнее молчаливого согласия:
        // человек включил ступень и ждёт, что она заработает.
        let Some(addr) = self.my_address() else {
            return Err(TransportError::NoAddress);
        };
        let listener = match TcpListener::bind(SocketAddr::new(IpAddr::V6(addr), self.port)).await {
            Ok(listener) => listener,
            Err(error) => {
                // **Две причины, и обе выглядят одинаково**: демон не запущен
                // — или запущен, но ключ у нас чужой. Различить их привязкой
                // нельзя: система отвечает одним и тем же «такого адреса
                // здесь нет». Поэтому не гадаем, а называем обе и печатаем
                // адрес, который пробовали, — сверить его с `yggdrasilctl
                // getSelf` человек может одним взглядом.
                //
                // Первая редакция говорила только про незапущенный демон,
                // и это отправляло бы искать не туда: ключ в шестьдесят
                // четыре знака переносится руками, а значит переносится
                // и с опечаткой.
                tracing::info!(
                    %addr,
                    port = self.port,
                    ?error,
                    "меш не поднялся: адреса нет в системе — не запущен демон \
                     или наш ключ не тот; сверьте адрес с `yggdrasilctl getSelf`"
                );
                return Err(error.into());
            }
        };
        self.accepting = Some(spawn_accept_loop(listener, self.events_tx.clone()));
        // Готовность объявляется **после** удачной привязки, а не при
        // включении: §5.4 не должен выбирать ступень, которой ещё нет.
        let _ = self.events_tx.send(TransportEvent::Ready { transport: Transport::Ygg }).await;
        self.announce_key().await;
        Ok(())
    }

    /// Заводит подъём своего узла меша (0.2). **Не ждёт его.**
    ///
    /// Возвращается мгновенно: соединение с пирами это секунды, а ждались
    /// они внутри `Driver::apply` — то есть в теле цикла, который отвечает
    /// на запросы UI, и до первого его оборота приложение не показывало
    /// ничего. Сам подъём доводится в опросах драйвера
    /// ([`Runner::next_event`]), как и подъём Tor у [`crate::Switched`].
    ///
    /// # Что проверяется здесь, а что там
    ///
    /// Здесь — то, что видно **без сети**: режим, пиры, наличие узла
    /// в сборке. Это и есть отказы, которые человеку надо назвать сразу:
    /// он только что нажал «включить» и ждёт ответа.
    ///
    /// Там — то, что известно только после подъёма: поднялся ли узел
    /// и назвался ли он нашим ключом. Открытый ключ узла сверяется с тем,
    /// который мы **уже назвали в карточке**: вывод из зерна делают двое —
    /// наш `MeshKey` и чужой `ygg_stream`, — и разойдись они, вышло бы
    /// худшее из возможного: собеседники звонят по одному адресу, а слушаем
    /// мы под другим, и обе стороны видят исправно работающую ступень,
    /// по которой никто не дозванивается.
    ///
    /// Поздний отказ возвращать некому, и он уходит в журнал, а ступень
    /// остаётся неготовой: [`YggRunner::is_ready`] смотрит на задачу приёма,
    /// а её при отказе не появляется, и экран настроек честно показывает
    /// «включено, но не работает».
    ///
    /// # Errors
    ///
    /// [`TransportError::Unavailable`] — настройка не про свой узел.
    ///
    /// [`TransportError::Refused`] — пиров не назвали.
    #[cfg(feature = "ygg-node")]
    fn start_node(&mut self) -> Result<(), TransportError> {
        let YggSetup::Embedded { seed, peers } = self.setup.clone() else {
            return Err(TransportError::Unavailable);
        };
        if peers.is_empty() {
            // Отказ, а не молчаливое «поднято». Узел без пиров ни с кем
            // не соединён, и объявить ступень готовой значило бы отправить
            // §5.4 звонить в пустоту — с полным сроком ожидания на каждое
            // сообщение. Это же самая частая причина «меш не работает».
            return Err(TransportError::Refused(
                "у своего узла меша нет пиров: назовите хотя бы один (tcp://узел:порт)".to_owned(),
            ));
        }
        // Повторное «включить» при идущем подъёме — не второй узел.
        // Иначе два узла с одним ключом соединялись бы с пирами наперегонки,
        // а слушал бы в итоге тот, чья задача успела позже.
        if self.rising.is_some() {
            return Ok(());
        }

        let my_key = self.my_key.clone();
        let port = self.port;
        let events = self.events_tx.clone();
        let (risen_tx, risen_rx) = tokio::sync::oneshot::channel();
        self.rising = Some(risen_rx);

        tokio::spawn(async move {
            let node = match ygg_stream::AsyncNode::new_with_key(seed.bytes(), peers).await {
                Ok(node) => node,
                Err(error) => {
                    tracing::warn!(%error, "свой узел меша не поднялся");
                    return;
                }
            };
            if node.public_key() != my_key {
                tracing::error!(
                    "узел меша назвался не тем ключом, который стоит в карточке: \
                     собеседники будут звонить по адресу, по которому мы не слушаем"
                );
                return;
            }

            let listener = node.listen(port).await;
            let accepting = spawn_node_accept_loop(listener, events.clone());
            let risen = Risen { node: std::sync::Arc::new(node), accepting };
            // **Сперва узел раннеру, потом новость наверх**, и порядок здесь
            // не вкус. Ядро, узнав о готовности ступени, немедленно шлёт
            // по ней отложенное; приди новость первой, набор пришёлся бы
            // на раннер, у которого узла ещё нет, и первая же доставка
            // после подъёма ушла бы следующей ступенью.
            if risen_tx.send(risen).is_err() {
                // Ждать некому: ступень выключили, пока мы поднимались.
                tracing::info!("свой узел меша поднялся, но ступень уже выключена");
                return;
            }
            // Готовность — **после** подъёма, как и у демона. Разница лишь
            // в том, что доказательством здесь служит не привязка к адресу,
            // а сам поднявшийся узел: имя у него наше по построению.
            let _ = events.send(TransportEvent::Ready { transport: Transport::Ygg }).await;
            // Ключ наверх — вслед за готовностью. Молчание при негодном
            // ключе законно: его же ловит `my_address`, и ступень без ключа
            // не поднимается вовсе.
            if let Some(key) = key_of(&my_key) {
                let _ = events.send(TransportEvent::YggReady { key }).await;
                tracing::info!(адрес = %Ipv6Addr::from(address_of(&key)), "свой узел меша поднят");
            }
        });
        Ok(())
    }

    /// Принимает поднявшийся узел из задачи подъёма.
    ///
    /// Отдельно от [`YggRunner::start_node`], потому что случается это
    /// в другой момент и в другом месте: подъём заводится командой,
    /// а въезжает узел в опросе драйвера.
    #[cfg(feature = "ygg-node")]
    fn install(&mut self, risen: Risen) {
        // Ступень могли выключить и включить заново, пока этот узел
        // поднимался. Прежний приём в таком случае снимается: слушать
        // в двух местах на одном порту нельзя.
        if let Some(task) = self.accepting.take() {
            task.abort();
        }
        self.accepting = Some(risen.accepting);
        self.node = Some(risen.node);
    }

    /// Объявляет свой ключ наверх — вслед за готовностью ступени.
    ///
    /// Одно место на оба режима (демон и свой узел): ключ у них один
    /// и тот же, а разъехавшись, объявление досталось бы только одному —
    /// и режим компаньона (§13.4) работал бы через раз, по выбору человека
    /// в настройках.
    ///
    /// Молчание при негодном ключе законно: его же ловит и `my_address`,
    /// и ступень без ключа не поднимается вовсе.
    async fn announce_key(&mut self) {
        if let Some(key) = key_of(&self.my_key) {
            let _ = self.events_tx.send(TransportEvent::YggReady { key }).await;
        }
    }

    /// Связь с контактом — существующая или набираемая.
    ///
    /// **Не ждёт соединения**: набор уезжает в свою задачу
    /// ([`Link::dialing`]), а кадры до его конца ждут в полосах записи.
    /// Восемь секунд набора до того, кого нет в сети, ждались раньше в теле
    /// цикла драйвера — вместе с запросами UI, таймерами и приёмом
    /// по остальным ступеням.
    ///
    /// Отказ приезжает ядру [`TransportEvent::ConnectFailed`], и §5.4
    /// уводит доставку на следующую ступень тем же путём, что и при обрыве.
    fn ensure_link(&mut self, peer: &crate::runner::PeerAddress) -> Result<Link, TransportError> {
        if let Some(link) = self.links.get(&peer.ik) {
            if !link.is_closed() {
                return Ok(link.clone());
            }
            self.links.remove(&peer.ik);
        }

        // Адрес не хранится и не устаревает: он выводится из ключа, а ключ
        // приезжает в карточке. Нет ключа — нет ступени, и §5.4 узнаёт
        // об этом тем же отказом, что и при пустом onion-адресе.
        let key = peer.ygg.ok_or(TransportError::NoAddress)?;

        // Своим узлом звоним **по ключу**, а не по адресу: `ygg_stream`
        // адресует ключами (TCP/KEY), и вывод адреса ему не нужен вовсе.
        // Внешнему демону — по выведенному адресу: он умеет только туннель.
        // Разница ровно в этой строке, всё остальное ниже общее.
        #[cfg(feature = "ygg-node")]
        if matches!(self.setup, YggSetup::Embedded { .. }) {
            // Узла ещё нет — значит подъём не кончился. Отказ, а не набор
            // через демона: демона в этом режиме нет вовсе, и попытка
            // привязаться к адресу `200::/7` упёрлась бы в систему, которая
            // о нём не знает. Ждать здесь тоже нельзя — ради этого весь
            // подъём и уехал в фон.
            let Some(node) = self.node.clone() else {
                return Err(TransportError::Unavailable);
            };
            let port = self.port;
            let link = Link::dialing(
                async move {
                    // Ручка связывается именем, а не остаётся временным
                    // значением внутри `timeout`: будущее держит ссылку
                    // на неё через ожидание, и жизнь временного здесь
                    // пришлось бы вычислять глазами.
                    let handle = node.handle();
                    let opening = handle.connect(ygg_stream::Addr::from(key), port);
                    tokio::time::timeout(CONNECT_TIMEOUT, opening)
                        .await
                        .map_err(|_| TransportError::Timeout)?
                        .map_err(|error| TransportError::Refused(error.to_string()))
                },
                peer.ik,
                Transport::Ygg,
                self.events_tx.clone(),
            );
            self.links.insert(peer.ik, link.clone());
            return Ok(link);
        }

        let addr = SocketAddr::new(IpAddr::V6(Ipv6Addr::from(address_of(&key))), self.port);
        let link = Link::dialing(
            async move {
                let stream = tokio::time::timeout(CONNECT_TIMEOUT, TcpStream::connect(addr))
                    .await
                    .map_err(|_| TransportError::Timeout)??;
                // Кадры уже дополнены до класса размера (§5.5): склейка
                // Нейгла добавила бы задержку, ничего не экономя.
                stream.set_nodelay(true)?;
                // Тип ошибки назван прямо: он определяется только договором
                // `Link::dialing`, а `?` выше просят его знать раньше.
                Ok::<_, TransportError>(stream)
            },
            peer.ik,
            Transport::Ygg,
            self.events_tx.clone(),
        );
        self.links.insert(peer.ik, link.clone());
        Ok(link)
    }

    /// Сообщает ядру о неудаче, а не только возвращает ошибку.
    ///
    /// Забывать при этом нечего — справочника адресов у меша нет, — и это
    /// содержательная разница с локальной сетью: там отказ означает
    /// «адрес устарел», здесь — «его сейчас нет в сети». Ключ остаётся
    /// верным, и следующая попытка пойдёт по тому же адресу.
    async fn report_failure(&self, peer_ik: [u8; 32]) {
        let _ = self
            .events_tx
            .send(TransportEvent::ConnectFailed { peer_ik, via: Transport::Ygg })
            .await;
    }
}

impl Runner for YggRunner {
    async fn execute(&mut self, command: TransportCommand) -> Result<(), TransportError> {
        match command {
            TransportCommand::Send { peer, via, frame, .. } => {
                if via != Transport::Ygg || !self.enabled {
                    return Err(TransportError::Unavailable);
                }
                match self.ensure_link(&peer) {
                    Ok(link) => match link.send(frame).await {
                        Ok(()) => Ok(()),
                        // Забитая очередь чанков — не обрыв: соединение живо,
                        // просто пишет медленнее, чем в него кладут.
                        Err(TransportError::Busy) => Err(TransportError::Busy),
                        Err(error) => {
                            self.links.remove(&peer.ik);
                            self.report_failure(peer.ik).await;
                            Err(error)
                        }
                    },
                    Err(error) => {
                        self.report_failure(peer.ik).await;
                        Err(error)
                    }
                }
            }
            TransportCommand::Connect { peer, via } => {
                if via != Transport::Ygg || !self.enabled {
                    return Err(TransportError::Unavailable);
                }
                match self.ensure_link(&peer) {
                    Ok(_) => Ok(()),
                    Err(error) => {
                        self.report_failure(peer.ik).await;
                        Err(error)
                    }
                }
            }
            TransportCommand::Disconnect { peer } => {
                self.links.remove(&peer.ik);
                Ok(())
            }
            // Чужой транспорт сюда попасть не может — составной раннер
            // разводит по адресату, — но проверка стоит: молча включиться
            // по чужой команде хуже, чем отказать.
            TransportCommand::SetEnabled { transport: Transport::Ygg, enabled } => {
                self.set_enabled(enabled).await
            }
            TransportCommand::SetYgg(setup) => self.set_setup(setup).await,
            TransportCommand::SetEnabled { .. }
            | TransportCommand::RestartLan
            | TransportCommand::WatchLanPeers(_)
            | TransportCommand::SetMailAccount(_)
            | TransportCommand::CreateMailAccount { .. } => Err(TransportError::Unavailable),
        }
    }

    /// Ждёт новостей — и заодно двигает подъём своего узла.
    ///
    /// Второе здесь потому же, почему у [`crate::Switched`]: подъём обязан
    /// кончаться вместе с драйвером, а не жить сам по себе. Задача его
    /// исполняет, но **въезжает** узел в раннера здесь — то есть в опросе,
    /// который драйвер делает и так.
    async fn next_event(&mut self) -> Option<TransportEvent> {
        #[cfg(not(feature = "ygg-node"))]
        return self.events_rx.recv().await;

        #[cfg(feature = "ygg-node")]
        loop {
            // `biased`, и это не вкус: задача подъёма кладёт узел в свой
            // канал **раньше**, чем новость о готовности, — и порядок
            // сохраняется только если приёмник узла опрашивается первым.
            // Иначе ядро узнало бы о готовности ступени раньше, чем раннер
            // получил узел, и первая же доставка после подъёма ушла бы
            // следующей ступенью.
            //
            // Половины `self` берутся по отдельности: `select!` держит оба
            // будущих разом, и один `&mut self` на двоих компилятор
            // не разрешит.
            let waiting = &mut self.rising;
            let news = &mut self.events_rx;
            let arrived = tokio::select! {
                biased;
                arrived = risen(waiting) => arrived,
                event = news.recv() => return event,
            };
            // `None` — подъём кончился отказом: он уже сказал о себе
            // в журнал, а ступень осталась неготовой. Ждать больше нечего:
            // `risen` погасил приёмник, и следующий круг уйдёт в вечное
            // ожидание, а не закрутится вхолостую.
            if let Some(arrived) = arrived {
                self.install(arrived);
            }
        }
    }
}

/// Ждёт конца подъёма своего узла; без подъёма — не возвращается никогда.
///
/// Отдельной функцией по той же причине, что и у [`crate::Switched`]:
/// `select!` не умеет ветку, которой может не быть. Вечное ожидание вместо
/// отсутствующей ветки — то же самое по смыслу и читается честнее, чем
/// `Option` внутри макроса.
///
/// Приёмник гасится **любым** исходом, и это обязательно: оставленный
/// закрытый приёмник отдавал бы «подъём кончился» мгновенно и на каждом
/// круге, то есть цикл раскрутился бы вхолостую.
#[cfg(feature = "ygg-node")]
async fn risen(slot: &mut Option<tokio::sync::oneshot::Receiver<Risen>>) -> Option<Risen> {
    match slot {
        Some(waiting) => {
            let outcome = waiting.await.ok();
            *slot = None;
            outcome
        }
        None => std::future::pending().await,
    }
}

/// Ключ из байтов карточки: пусто и чужая длина — одинаково «нет».
fn key_of(bytes: &[u8]) -> Option<[u8; KEY_LEN]> {
    bytes.try_into().ok()
}

/// Открытый ключ **нашего** узла для этой настройки (0.2).
///
/// У внешнего демона он назван человеком, у своего узла выводится из зерна.
/// Вывод здесь, а не в ядре: ядро тот же вывод уже сделало для карточки,
/// и второй его экземпляр — второй способ однажды разойтись. Здесь он ради
/// проверки, о которой ниже (`start_node`): под каким именем узел
/// представится сети, знает только узел, и сверить его есть с чем.
///
/// # Errors
///
/// [`TransportError::Refused`] — выбран свой узел, а его в сборке нет.
fn our_key(setup: &YggSetup) -> Result<Vec<u8>, TransportError> {
    match setup {
        // «Меша нет» — это отсутствие ключа: адреса нет, включаться не на чем.
        YggSetup::Off => Ok(Vec::new()),
        YggSetup::External { key } => Ok(key.clone()),
        #[cfg(feature = "ygg-node")]
        YggSetup::Embedded { seed, .. } => {
            Ok(<[u8; ratatosk_crypto::mesh::MESH_SEED_LEN]>::try_from(seed.bytes())
                .map(|seed| ratatosk_crypto::MeshKey::from_seed(seed).public().to_vec())
                .unwrap_or_default())
        }
        #[cfg(not(feature = "ygg-node"))]
        YggSetup::Embedded { .. } => Err(TransportError::Refused(NO_NODE.to_owned())),
    }
}

fn spawn_accept_loop(
    listener: TcpListener,
    events: mpsc::Sender<TransportEvent>,
) -> tokio::task::JoinHandle<()> {
    tokio::spawn(async move {
        loop {
            match listener.accept().await {
                Ok((stream, _)) => {
                    let _ = stream.set_nodelay(true);
                    spawn_read_loop(stream, Transport::Ygg, events.clone());
                }
                // Исчерпание дескрипторов лечится ожиданием, а не выходом
                // из цикла: выйдя, транспорт замолчал бы навсегда.
                Err(error) => {
                    tracing::debug!(?error, "меш: не удалось принять соединение");
                    tokio::time::sleep(Duration::from_millis(100)).await;
                }
            }
        }
    })
}

/// Приём соединений своим узлом (0.2).
///
/// Отличается от TCP-петли одним, и это не мелочь: у `ygg_stream` отказ
/// приёма означает **закрытый стек**, а не занятость или нехватку
/// дескрипторов (`TcpListener::accept` отдаёт ошибку ровно тогда, когда
/// канал закрыт). Поэтому здесь выход из цикла, а не сон и повтор: спать
/// в ожидании того, что уже не вернётся, значило бы держать задачу вечно.
#[cfg(feature = "ygg-node")]
fn spawn_node_accept_loop(
    mut listener: ygg_stream::TcpListener,
    events: mpsc::Sender<TransportEvent>,
) -> tokio::task::JoinHandle<()> {
    tokio::spawn(async move {
        loop {
            match listener.accept().await {
                Ok(conn) => spawn_read_loop(conn, Transport::Ygg, events.clone()),
                Err(error) => {
                    tracing::debug!(?error, "меш: приём закрыт, узел остановлен");
                    return;
                }
            }
        }
    })
}

