//! Журнал ядра: заводится ли он вообще и туда ли пишет.
//!
//! **Проверка здесь одна, и это не лень, а устройство `tracing`.**
//! Подписчик — вещь **процесса**: он ставится один раз и на всю жизнь,
//! а `cargo test` гоняет все проверки одного файла в одном процессе.
//! Вторая проверка получила бы подписчика первой и писала бы не в свой
//! файл — то есть падала бы, ничего при этом не доказывая. (Проверено:
//! ровно так она и упала, будучи написанной отдельно.)
//!
//! Отсюда же и отдельный файл вместо строки в `client.rs`: свой файл —
//! свой процесс, и журнал не отнимается у остальных проверок.

#[test]
fn the_log_goes_into_the_file_it_was_told_about() {
    // **Ради чего файл вообще заведён.** У упакованного приложения нет
    // видимого потока ошибок: компаньон на десктопе запускают ярлыком,
    // а на Android поток ошибок уходит в никуда всегда. Файл — то
    // единственное место, откуда журнал можно достать и прислать,
    // а именно это и нужно, когда разбирают поломку на чужом устройстве.
    let dir = std::env::temp_dir().join(format!("ratatosk-log-{}", std::process::id()));
    std::fs::create_dir_all(&dir).expect("каталог для журнала");
    let path = dir.join("journal.log");

    // Отбор нарочно негодный: отказывать за опечатку в нём нечем
    // и незачем — «журнал не включается, и непонятно почему» хуже
    // всего остального. Поэтому берётся обычный, а о подмене говорится
    // в самом журнале.
    ratatosk_ffi::enable_file_logging(
        "=== это не отбор ===".to_owned(),
        path.to_string_lossy().into_owned(),
    );

    tracing::info!(проверка = 1, "строка из ядра");
    let text = std::fs::read_to_string(&path).expect("файл журнала обязан существовать");
    assert!(text.contains("строка из ядра"), "в журнале нет того, что в него писали:\n{text}");
    assert!(text.contains("отбор не разобрался"), "о подмене отбора обязано быть сказано:\n{text}");

    // **Второй вызов ничего не делает и не роняет.** Клиент, открывающий
    // второй аккаунт, позовёт эту функцию снова, и отказывать ему не за что.
    let second = dir.join("second.log");
    ratatosk_ffi::enable_file_logging(String::new(), second.to_string_lossy().into_owned());
    ratatosk_ffi::enable_logging(String::new());
    tracing::info!("строка после повторных вызовов");
    let first = std::fs::read_to_string(&path).expect("первый журнал на месте");
    assert!(
        first.contains("строка после повторных вызовов"),
        "писать обязан по-прежнему первый подписчик:\n{first}"
    );

    let _ = std::fs::remove_dir_all(&dir);
}
