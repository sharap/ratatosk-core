//! Порядок и слияние состояния в сети без общего порядка.
//!
//! Три вещи, на которых держится вся асинхронная часть протокола:
//!
//! * [`hlc`] — гибридные логические часы, единственный источник порядка (§9.1).
//!   Системное время источником порядка не является никогда.
//! * [`orset`] — OR-Set для состава группы (§11.2), включая схлопывание
//!   в baseline при compaction (§12).
//! * [`dedup`] — окно дедупликации по `msg_id` (§9.2). Одно сообщение может
//!   законно прийти дважды разными транспортами — это нормальный режим.
//!
//! Крейт без зависимостей и без ввода-вывода: всё время приходит параметром.
//! Это то, что делает сценарии из §16 воспроизводимыми по номеру сида.

#![forbid(unsafe_code)]
#![warn(missing_docs)]

pub mod dedup;
pub mod hlc;
pub mod orset;

pub use dedup::{DedupVerdict, DedupWindow, MsgId, DEDUP_CAPACITY, DEDUP_WINDOW_MS};
pub use hlc::{Hlc, HlcClock, HlcError, MAX_FUTURE_SKEW_MS};
pub use orset::{ActorId, OrSet, OrSetOp, Tag};
