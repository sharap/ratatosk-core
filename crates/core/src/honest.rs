#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn all_seven_points_are_present() {
        assert_eq!(NOTICES.len(), 7, "§14 состоит из семи пунктов");
        for n in NOTICES {
            assert!(!n.is_empty());
        }
    }

    #[test]
    fn notices_state_limits_not_features() {
        // Грубая проверка тональности: раздел §14 про то, чего продукт
        // не делает. Пункт без отрицания почти наверняка переписан в рекламный.
        let negatives = ["не ", "нет", "только"];
        for n in NOTICES {
            assert!(
                negatives.iter().any(|neg| n.contains(neg)),
                "пункт §14 потерял ограничение: {n}"
            );
        }
    }

    #[test]
    fn calls_are_explicitly_absent() {
        assert!(NOTICES.contains(&"Звонков нет."));
    }
}
