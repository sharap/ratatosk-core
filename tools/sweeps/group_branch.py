#!/usr/bin/env python3
"""Метелка: чат ищут в **обоих** пространствах, а не только среди переписок.

Идентификаторы чатов у групп и у переписок живут в одном пространстве,
но лежат в разных картах: `by_chat` — переписки, `groups` — группы.
Обработчик, который спросил только `by_chat`, на группу отвечает
«собеседник неизвестен» — то есть отказом на совершенно законную просьбу.

Так уже было трижды, и каждый раз находил это человек за другим экраном:

* выгрузка файла с десктопа отказывалась на первом шаге, не приняв ни
  байта («файлы не отправляются через компаньона в группы»);
* отправка выгруженного отказалась бы следом, на третьем шаге;
* «человек дочитал» в группе отвечало отказом, хотя делать там нечего:
  квитанций в группе нет (§11.3).

Причина у всех одна: путь писался до групп, а когда группы появились,
правили тот файл, который про группы. Компилятор молчит — `by_chat`
существует и типы сходятся.

Правило: в функции, которая берёт `chat: ChatId` и ищет его в `by_chat`,
обязано быть **сказано вслух**, что делать с группой. Годится любое
из трёх: ветка `self.groups.contains_key(&chat)`, проверка на оба
пространства сразу либо строка `// групп здесь не бывает: <почему>`.

Третий выход — не лазейка, а необходимость: есть места, куда групповой
чат не приходит по построению (обработка кадра от известного собеседника,
например). Разница в том, что теперь это написано, а не подразумевается.
"""
import pathlib
import re
import sys

# Корень дерева считается от самого файла, а не от текущего каталога:
# метелку зовут и из корня, и из CI, и по одной из редактора.
ROOT_DIR = pathlib.Path(__file__).resolve().parents[2]
ROOT = ROOT_DIR / "crates"

LOOKUP = re.compile(r"by_chat\.(?:get|contains_key)\(&chat\)")
# `&chat` и `chat` — обе формы: во втором случае имя уже ссылка
# (например, после `filter`), и разница чисто синтаксическая.
GROUPS = re.compile(r"groups\.contains_key\(&?chat\)")
# Сказанное вслух «сюда группа не приходит». Пишется рядом с поиском.
EXCUSE = re.compile(r"//.*групп\w* здесь не бывает", re.IGNORECASE)


def bodies(src: str) -> list[tuple[str, int, str]]:
    """Тела функций: имя, строка объявления, текст до закрывающей скобки."""
    found = []
    for m in re.finditer(r"\n    (?:pub )?(?:pub\(super\) )?(?:pub\(crate\) )?(?:const )?fn (\w+)\s*\(", src):
        name = m.group(1)
        # Тело — от `{` после списка доводов до скобки на том же отступе.
        open_at = src.find("{", m.end())
        if open_at < 0:
            continue
        end = src.find("\n    }\n", open_at)
        if end < 0:
            continue
        line = src[: m.start()].count("\n") + 2
        found.append((name, line, src[open_at:end]))
    return found


def main() -> int:
    bad = 0
    watched = 0
    for path in sorted(ROOT.glob("*/src/**/*.rs")):
        src = path.read_text(encoding="utf-8")
        rel = path.relative_to(ROOT_DIR).as_posix()
        for name, line, body in bodies(src):
            if not LOOKUP.search(body):
                continue
            watched += 1
            if GROUPS.search(body) or EXCUSE.search(body):
                continue
            print(
                f"{rel}:{line}: `{name}` ищет чат только среди переписок. "
                "Либо ветка на группу, либо строка «групп здесь не бывает: <почему>»"
            )
            bad += 1

    print(f"обработчиков под присмотром: {watched}")
    print("чисто" if not bad else f"НАХОДОК: {bad}")
    return 0 if not bad else 1


if __name__ == "__main__":
    sys.exit(main())
