/// Очередь доставки — по паре «сообщение и получатель» (§11.3).
///
/// Исправление поломки, из-за которой в группах терялись сообщения:
/// «доходят не всегда и не до всех, недошедшие не доходят никогда».
///
/// # Что было
///
/// Первая редакция схемы (`MIGRATION_0001`) держала правильный ключ —
/// `PRIMARY KEY (msg_id, recipient_ik)`. Миграция 0004 пересобрала таблицу
/// ради переименования столбца (`frame` → `envelope_enc`) и **потеряла
/// вторую половину ключа**: с тех пор на живых устройствах стоит
/// `msg_id BLOB PRIMARY KEY`.
///
/// Сообщение в группу — это N доставок с одним номером (§11.3: копию
/// каждому шлёт сам отправитель). При таком ключе `INSERT OR REPLACE`
/// не добавлял строки, а **заменял** их: из скольких угодно копий на диске
/// оставалась последняя. Ядро при этом вело себя правильно, ставило в
/// очередь всех — а переживал перезапуск один.
///
/// # Чего эта миграция не делает
///
/// Не возвращает внешний ключ на `messages`, который был в 0001 и пропал
/// там же. Соблазн велик, но у живых баз есть строки очереди без
/// сообщения — уборка §12 сносит историю, а очередь переживает её, — и
/// добавленное ограничение уронило бы миграцию у тех, у кого такие строки
/// есть. Чинить ключ и вводить ограничение разом значит рисковать первым
/// ради второго.
///
/// Не меняет и associated data у `envelope_enc`: она по-прежнему `msg_id`
/// без получателя. Строки одного сообщения теперь различимы, а их конверты
/// **побайтно одинаковы** — копия каждому участнику одна и та же (§11.3), —
/// так что связать шифртекст со строкой плотнее нечем и незачем. Смена
/// AAD к тому же сделала бы нечитаемым всё, что уже лежит.
pub const MIGRATION_0021: &str = r#"
CREATE TABLE outbox_by_pair (
    msg_id          BLOB NOT NULL,               -- 16 байт
    recipient_ik    BLOB NOT NULL,               -- 32 байта
    envelope_enc    BLOB NOT NULL,               -- конверт целиком (§9.1)
    queued_ms       INTEGER NOT NULL,            -- когда человек нажал «отправить»
    PRIMARY KEY (msg_id, recipient_ik)
) STRICT;
INSERT INTO outbox_by_pair (msg_id, recipient_ik, envelope_enc, queued_ms)
    SELECT msg_id, recipient_ik, envelope_enc, queued_ms FROM outbox;
DROP TABLE outbox;
ALTER TABLE outbox_by_pair RENAME TO outbox;
CREATE INDEX outbox_by_peer ON outbox(recipient_ik);
"#;

/// Метка поворота у sender-цепочки (§11.5 + дополнение).
///
/// # Что было
///
/// Каждое вступление проворачивает цепочку каждого участника — так требует
/// §11.5, и иначе новичок вывел бы ключи прошлых сообщений. Объявление
/// новой цепочки едет отдельным кадром, а §9.2 разрешает переставлять
/// кадры. Два приглашения подряд — и до участника едут **два** объявления
/// одной цепочки, с одинаковым номером: после поворота он всегда нулевой.
///
/// Отличить свежее от опоздавшего было нечем, и получатель брал последнее
/// пришедшее. Примерно в половине случаев это опоздавшее: номер верный,
/// ключ мёртвый. Дальше сообщения этого отправителя не открывались —
/// молча, потому что снаружи неудачная расшифровка неотличима от порчи.
/// Выглядело это как «сообщения доходят не всегда и не до всех, потом
/// чинится, а недошедшие так и не доходят».
///
/// # Что стало
///
/// Метку ставит **владелец** цепочки в момент поворота, его же часами
/// (§9.1). Получатель берёт объявленную цепочку, только если метка строго
/// новее уже лежащей. Порядок сравним всегда: две метки одной цепочки
/// выданы одними часами — при пересылке чужого ключа (§11.5) метка едет
/// как есть, а не выдаётся заново пересылающим.
///
/// # Почему по умолчанию ноль
///
/// Ноль означает «старшинства не называли» — так выглядят и строки, уже
/// лежащие на диске, и блоки от сборки, не знавшей этого поля. Первое же
/// названное старшинство их обгонит; пока не назвал никто, поведение
/// остаётся прежним. Это единственная уступка совместимости, и она
/// временная: обе стороны обязаны обновиться.
pub const MIGRATION_0022: &str = r#"
ALTER TABLE sender_chains ADD COLUMN chain_wall INTEGER NOT NULL DEFAULT 0;
ALTER TABLE sender_chains ADD COLUMN chain_logical INTEGER NOT NULL DEFAULT 0;
"#;

