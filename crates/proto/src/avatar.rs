//! Аватарка профиля.
//!
//! **Спецификация v0.1 аватарок не описывает.** Это добавление, и §17 просит
//! такие вещи записывать явно, а не растворять в коде. Здесь — правила,
//! которые должны попасть в спецификацию отдельным пунктом к §4.2.
//!
//! # Почему не в карточке (§4.1)
//!
//! Карточка контакта едет в QR-коде. QR версии 40 с коррекцией L держит
//! около 2.9 КиБ — меньше, чем самая скромная картинка, и это не считая
//! того, что карточка обязана оставаться читаемой камерой с экрана телефона.
//! Поэтому аватарка едет **отдельным сообщением по установленной сессии**,
//! то есть уже зашифрованной и уже адресованной.
//!
//! # Симметричное правило §4.2
//!
//! Аватарка отправляется **только сверенным** контактам и показывается
//! **только для сверенных**. Оба направления обязательны, и по разным
//! причинам.
//!
//! Не отправлять несверенным: аватарка — это, как правило, лицо. Отдавать
//! его тому, чей отпечаток не сверен, значит отдавать его тому, кто, может
//! быть, не тот, за кого себя выдаёт, — а §4.2 ровно про эту возможность.
//!
//! Не показывать для несверенных: картинка убеждает сильнее имени. Имя
//! в карточке уже помечено «не доверенное» (§4.1), но текст пользователь
//! читает, а лицо — узнаёт, не читая. Подставив чужую фотографию, самозванец
//! получает доверие бесплатно и мимо всех предупреждений. Поэтому до сверки
//! аватарки нет — не «серая», не «с предупреждением», а нет.
//!
//! # Ядро не разбирает изображение
//!
//! Байты остаются непрозрачными: ни декодирования, ни масштабирования,
//! ни проверки размеров в пикселях. Декодер изображений — большая
//! поверхность атаки, и тащить её в процесс, который держит ключи, незачем.
//! Проверяется ровно две вещи: длина и сигнатура формата.
//!
//! Сигнатура — не «валидация картинки», а **сужение множества**: клиент
//! отдаст эти байты системному декодеру, и чем уже список форматов, тем
//! меньше того декодера окажется под чужим влиянием. Заодно это мешает
//! использовать аватарку как канал для произвольных файлов.

/// Наибольший размер аватарки в байтах.
///
/// 32 КиБ хватает на 256×256 в JPEG или WebP приличного качества — больше
/// для кружка в списке чатов не нужно ни на одном экране. Верхняя граница
/// выбрана так, чтобы конверт с аватаркой укладывался в класс размера M
/// (§5.5) целиком: фрагментация (§9.3) ради картинки в профиле — лишний
/// механизм на пути, который и без того не критичен.
pub const MAX_AVATAR_BYTES: usize = 32 * 1024;

/// Почему аватарка не принята.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum AvatarError {
    /// Больше [`MAX_AVATAR_BYTES`].
    #[error("аватарка больше {MAX_AVATAR_BYTES} байт")]
    TooLarge,
    /// Формат не из списка: PNG, JPEG, WebP.
    #[error("формат аватарки не поддерживается: нужен PNG, JPEG или WebP")]
    UnsupportedFormat,
}

/// Проверяет байты аватарки перед отправкой или сохранением.
///
/// Пустые байты — законное значение: это «аватарки у меня нет».
///
/// # Errors
///
/// [`AvatarError::TooLarge`] или [`AvatarError::UnsupportedFormat`].
pub fn check(bytes: &[u8]) -> Result<(), AvatarError> {
    if bytes.is_empty() {
        return Ok(());
    }
    if bytes.len() > MAX_AVATAR_BYTES {
        return Err(AvatarError::TooLarge);
    }
    if !looks_like_image(bytes) {
        return Err(AvatarError::UnsupportedFormat);
    }
    Ok(())
}

/// Начинаются ли байты с сигнатуры PNG, JPEG или WebP.
///
/// Это проверка **начала файла**, а не его правильности: содержимое может
/// быть каким угодно, и ядро об этом ничего не утверждает. Смысл ровно один —
/// не пускать в системный декодер то, что даже не притворяется картинкой
/// известного формата.
#[must_use]
pub fn looks_like_image(bytes: &[u8]) -> bool {
    const PNG: &[u8] = &[0x89, b'P', b'N', b'G', 0x0D, 0x0A, 0x1A, 0x0A];
    const JPEG: &[u8] = &[0xFF, 0xD8, 0xFF];

    if bytes.starts_with(PNG) || bytes.starts_with(JPEG) {
        return true;
    }
    // WebP: "RIFF" ‖ длина (4 байта) ‖ "WEBP".
    bytes.len() >= 12 && bytes.starts_with(b"RIFF") && &bytes[8..12] == b"WEBP"
}

#[cfg(test)]
mod tests {
    use super::*;

    fn png() -> Vec<u8> {
        let mut bytes = vec![0x89, b'P', b'N', b'G', 0x0D, 0x0A, 0x1A, 0x0A];
        bytes.extend_from_slice(&[0u8; 64]);
        bytes
    }

    #[test]
    fn an_empty_avatar_means_there_is_none() {
        assert_eq!(check(&[]), Ok(()));
    }

    #[test]
    fn known_signatures_pass() {
        assert!(looks_like_image(&png()));
        assert!(looks_like_image(&[0xFF, 0xD8, 0xFF, 0xE0, 0, 0]));

        let mut webp = b"RIFF".to_vec();
        webp.extend_from_slice(&[0u8; 4]);
        webp.extend_from_slice(b"WEBPVP8 ");
        assert!(looks_like_image(&webp));
    }

    #[test]
    fn anything_else_is_refused() {
        assert_eq!(check(b"GIF89a....."), Err(AvatarError::UnsupportedFormat));
        assert_eq!(check(b"<svg></svg>"), Err(AvatarError::UnsupportedFormat));
        // Обрезанный WebP: "RIFF" есть, а до тега формата данные не дошли.
        assert!(!looks_like_image(b"RIFF1234"));
    }

    #[test]
    fn size_is_checked_before_the_signature() {
        // Порядок важен: иначе на слишком большой блоб придёт «неверный
        // формат», и клиент будет чинить не то.
        let mut huge = png();
        huge.resize(MAX_AVATAR_BYTES + 1, 0);
        assert_eq!(check(&huge), Err(AvatarError::TooLarge));
    }

    #[test]
    fn the_limit_fits_the_medium_size_class() {
        // §5.5: конверт с аватаркой обязан уложиться в класс M целиком,
        // иначе картинка в профиле потянет за собой фрагментацию (§9.3).
        // Запас — на CBOR-обвязку конверта и тег AEAD.
        let m = ratatosk_wire::SizeClass::M.max_payload();
        assert!(MAX_AVATAR_BYTES + 1024 < m, "аватарка не помещается в класс M: {m}");
    }
}
