/// Учёт впусков в канал (фаза 2, §6.5).
///
/// # Это учёт, а не принуждение
///
/// Впускающий держит ключ чтения и может передать его мимо протокола —
/// следа не останется. Таблица показывает владельцу тех, кто действовал
/// **по правилам**, и ничего не говорит про остальных. Чинится это
/// не записью, а поворотом (§6.4): впущенный мимо учёта отваливается
/// на ближайшем повороте, если впустивший не кормит его дальше.
///
/// # Сырые байты и подпись — как у представления
///
/// Запись подписывает **впускающий**, а не владелец, и владелец обязан
/// мочь показать подпись, а не своё пересказанное мнение о ней. То же
/// правило, что у `messages.envelope_bytes`: проверяется принятое,
/// а не пересобранное.
///
/// # Окно сидирования эту таблицу не обрезает
///
/// §6.5 говорит это прямо, по тому же правилу, по которому из обрезки
/// исключены блоки состава. Обрежь её — и «кто кого впустил»
/// превратится в «неизвестно», то есть учёт перестанет быть учётом.
/// Чистки здесь нет и заводить её нельзя.
///
/// # Ключ строки — пара, а не тройка с впускающим
///
/// Одного человека впускают один раз. Впусти его второй кто-нибудь
/// другой — это не второй впуск, а спор о том, чей след останется;
/// разрешается он так же, как и всё прочее в этой базе: первым пришедшим,
/// потому что `INSERT OR IGNORE` не трогает уже лежащее.
pub const MIGRATION_0030: &str = r#"
CREATE TABLE channel_admits (
    chat_id         BLOB NOT NULL REFERENCES chats(chat_id) ON DELETE CASCADE,
    who             BLOB NOT NULL,               -- кого впустили, 32 байта
    admitted_by     BLOB NOT NULL,               -- кто впустил, 32 байта
    generation      INTEGER NOT NULL,            -- на каком поколении ключа (§6.4)
    block_bytes     BLOB NOT NULL,               -- принятые байты под подписью (§6)
    signature       BLOB NOT NULL,               -- 64 байта, подпись впускающего
    created_ms      INTEGER NOT NULL,
    PRIMARY KEY (chat_id, who)
) STRICT;
CREATE INDEX channel_admits_by_admitter ON channel_admits(chat_id, admitted_by);
"#;

