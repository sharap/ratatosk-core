//! Лестница доставки (§5.4): как довезти то, что решили сказать.
//!
//! Сессии, рукопожатия, очередь неотправленного, выбор ступени
//! и отступление при отказе. Ступени пробуются сверху вниз, и провал
//! одной — не провал доставки: сообщение остаётся в очереди и уходит
//! следующей.
//!
//! Что именно везётся, здесь не решают: это `messages`,
//! `files` и `group_msg`.

//! Сборка кадра живёт в [`crate::frames`], а не здесь, и это не вкусовщина:
//! с появлением терминала (§13.4) сторон стало две, и правила сборки у них
//! обязаны совпадать до байта. Здесь остаётся ровно то, чего у той стороны
//! нет: источник случайности, реестр сессий и запись на диск.

use super::*;

impl<S: Store> Engine<S> {
    /// Регистрирует новую сессию и убирает то, что она вытеснила насовсем.
    ///
    /// «Насовсем» — потому что прежняя сессия семейства уходит **на покой**,
    /// а не в небытие: отправлять по ней нельзя, принимать можно, и с диска
    /// она не убирается (разбор — в [`SessionRegistry::insert`]). Убирается
    /// поколением позже, и вот тогда её надо стереть и с диска: оставленная,
    /// она вернулась бы после перезапуска и снова участвовала бы в выборе.
    pub(super) fn supersede(
        &mut self,
        session: Session,
        binding: SessionBinding,
    ) -> Result<(), EngineError> {
        for stale in self.sessions.insert(session, binding) {
            self.store.delete_session(stale)?;
        }
        Ok(())
    }

    /// Складывает состояние сессии на диск (§8.3, §12).
    ///
    /// **Вызывается до того, как кадр уйдёт в сеть.** Порядок здесь — не
    /// аккуратность, а корректность: счётчик отправки, откатившийся после
    /// того как система убила процесс, означает второй кадр с той же парой
    /// «ключ, nonce». Для XChaCha20-Poly1305 это не потеря сообщения,
    /// а раскрытие обоих.
    ///
    /// На приёме порядок обратный и это безопасно: если процесс умрёт между
    /// расшифровкой и записью, кадр после перезапуска расшифруется тем же
    /// ключом ещё раз, а дубль съест дедупликация (§9.2).
    pub(super) fn persist_session(&mut self, session_id: u64) -> Result<(), EngineError> {
        let Some(bound) = self.sessions.get(session_id) else {
            return Ok(());
        };

        // **Сессия с сопряжённым устройством (§13.4) на диск не ложится.**
        //
        // Начиналось это как отказ базы, а не как решение. Столбец
        // `sessions.peer_ik` объявлен `REFERENCES contacts(ik)`, устройство
        // контактом не является нарочно — и первая же сессия с десктопом
        // упиралась во внешний ключ. Наружу это выглядело как остановка
        // ядра: `step` возвращал отказ хранилища, драйвер печатал
        // «ядро остановилось», телефон переставал отвечать вообще.
        //
        // Не всплыло в тестах потому, что и они, и стенд без `--data` живут
        // на `MemoryStore`, у которого внешних ключей нет. Урок тот же,
        // что с миграцией (`ARCHITECTURE.md`, 5бв): всё, что компилятор
        // видит как строку, обязано быть закрыто тестом **на настоящем
        // хранилище**.
        //
        // Но решение здесь не «снять ключ», а «не писать», и вот почему.
        // Сессия терминала одноразовая по построению (5бг): он выбрасывает
        // её вместе с каналом и здоровается заново, потому что круг
        // по локальной сети стоит миллисекунды. Значит на диске она
        // не нужна никому: пережив перезапуск телефона, она бы только
        // разошлась с той, которой у десктопа уже нет.
        if self.devices.contains_key(&bound.session.peer_ik) {
            return Ok(());
        }

        let stored = ratatosk_store::StoredSession {
            session_id,
            peer_ik: bound.session.peer_ik,
            binding: bound.binding.code(),
            snapshot: bound.session.export().to_vec(),
            established_ms: bound.session.established_ms,
        };
        self.store.put_session(&stored)?;
        Ok(())
    }

    /// Прямой канал к контакту, если сессия по нему есть (§5.4).
    ///
    /// Аватарка, как и квитанция (§9.4), почтой не ходит: тридцать килобайт
    /// в письме — это удвоение трафика и метаданных у сервера ради картинки
    /// в профиле. И рукопожатия ради неё тоже не начинаем.
    ///
    /// Файлы этим больше не пользуются — у них свой выбор,
    /// [`Engine::file_channel`], и он шире на почту.
    pub(super) fn direct_channel(&self, peer_ik: &[u8; 32]) -> Option<Transport> {
        // Спрашивается §5.4, а не перебирается список руками, и это
        // исправление ошибки, которая выглядела так: сообщения через onion
        // ходят, а файлы не идут — доезжает только само сообщение с превью.
        //
        // Прежний перебор `[Lan, Onion]` смотрел ровно на одно: есть ли
        // сессия. Сессия же переживает и выключение локальной сети, и уход
        // собеседника из неё, — она не про доступность, а про ключи. Поэтому
        // после `/lan` выключенного (или просто после ухода из общей сети)
        // у файлов оставался «прямой канал» LAN, которого нет: просьба
        // о чанках уезжала в мёртвый транспорт, срок молчания (§10.2)
        // спрашивал заново — и снова туда же, вечно.
        //
        // Сообщения при этом ходили, потому что они идут очередью §5.4,
        // а та про выключенный LAN знает. Разошлись два пути выбора
        // транспорта — разошлось и поведение.
        let availability = self.availability_of(peer_ik).ok()?;
        let mut attempt = Attempt::new();
        while let Some(Decision::Use(transport)) = attempt.next(availability) {
            // Почта сюда не годится по устройству: чанки идут мимо очереди
            // доставки, а §9.4 у почты не обещает даже «отправлено».
            if transport.is_direct() && self.sessions.for_peer(peer_ik, transport).is_some() {
                return Some(transport);
            }
        }
        None
    }

    /// Список контактов, чьи маяки транспорт должен искать в эфире (§5.1).
    ///
    /// # Почему он больше не «локальной сети»
    ///
    /// Звался он `watch_lan_peers`, и по всему ядру рассылался с оглядкой:
    /// `if self.enabled.contains(Transport::Lan)`. Это было верно ровно
    /// до 0.4, пока эфир был один. Их стало два — mDNS и BLE, — и опознаются
    /// они **одним и тем же** перебором `IK` по маяку; составной раннер
    /// поэтому и раздаёт эту команду всем (`multi::to_all`).
    ///
    /// Оглядка же осталась и стала ложью: со стенда, где LAN выключен,
    /// а Bluetooth включён, добавленный контакт до эфира не доезжал вовсе.
    /// В журнале это выглядело как «объявление нашей длины, но маяк не наш»
    /// при `известных=0` — собеседник вещал в двух метрах, его объявление
    /// разбиралось целым, и перебирать было не по чему.
    ///
    /// Поэтому список едет **без оглядки** на то, какие ступени включены.
    /// Он ничего не стоит и ничего не раскрывает: это открытые ключи,
    /// которые у нас и так есть, — а раннер, получивший его заранее,
    /// при включении сразу знает, кого слушать. Ровно этот довод уже
    /// записан у подъёма (`startup_effects`), просто дальше он не пошёл.
    pub(super) fn watch_peers(&self) -> Effect {
        // Сопряжённые устройства — наравне с контактами, и иначе нельзя.
        // Соединения односторонние (`ARCHITECTURE.md`, 5ц): каждая сторона
        // набирает своё и пишет только в него, а значит **обе** обязаны
        // найти друг друга в эфире. Десктоп объявляет маяк от своего ключа
        // сопряжения — по тому же правилу §5.1, что и контакт от `IK`, —
        // и без этой строки телефон принял бы рукопожатие и не смог бы
        // ответить.
        Effect::WatchPeers(self.contacts.keys().chain(self.devices.keys()).copied().collect())
    }

    /// Ставит в очередь §5.4 служебную просьбу: отзыв, правку, реакцию.
    ///
    /// Отдельно от [`Engine::send_own_text`], и это не дублирование: у просьбы
    /// нет своей строки в истории — в чате видно её **следствие**, а не её
    /// саму. Поэтому у неё нет и статуса доставки: `note_status` для такого
    /// `msg_id` не найдёт строки и промолчит.
    pub(super) fn enqueue_request(
        &mut self,
        now_ms: u64,
        peer_ik: [u8; 32],
        payload_type: PayloadType,
        payload: Value,
    ) -> Result<(MsgId, Vec<Effect>), EngineError> {
        let envelope =
            Envelope::new(self.entropy.msg_id(), self.clock.now(now_ms)?, payload_type, payload);
        let msg_id = envelope.msg_id;
        let effects = self.enqueue(Delivery {
            msg_id,
            peer_ik,
            envelope: envelope.encode()?,
            attempt: Attempt::new(),
            state: DeliveryState::AwaitingSession,
            queued_ms: now_ms,
            session_reset_used: false,
            silent: false,
        })?;
        Ok((msg_id, effects))
    }

    /// Осталась ли доставка на попечении ядра.
    ///
    /// Три исхода у постановки в очередь, и различить надо два от одного:
    /// доставка либо ждёт своего часа (в очереди или в отложенных), либо
    /// уже объявлена недоставимой и забыта. Первые два — «мы ещё должны»,
    /// третий — «должны не будем».
    ///
    /// Нужно это одному вопросу: рассказали ли мы собеседнику свою карточку.
    /// Отметку об этом раньше ставили по факту **постановки в очередь**,
    /// то есть до того, как выяснится, уехало ли хоть что-то, — и страховка
    /// [`Engine::push_own_card`] после неудачной рассылки отказывалась
    /// работать до конца запуска.
    pub(super) fn delivery_alive(&self, msg_id: &MsgId, recipient_ik: &[u8; 32]) -> bool {
        // По паре: вопрос всегда про **конкретного** собеседника («рассказали
        // ли мы ему карточку»), а номер в группе один на всех.
        self.outbox
            .iter()
            .chain(self.deferred.iter())
            .any(|d| d.msg_id == *msg_id && d.peer_ik == *recipient_ik)
    }

    /// Ставит сообщение в очередь доставки и делает первую попытку.
    pub(super) fn enqueue(&mut self, mut delivery: Delivery) -> Result<Vec<Effect>, EngineError> {
        let effects = self.advance(&mut delivery)?;
        // Запись хранится, пока попытка не закрыта. Закрывают её два исхода:
        // уход почтой (§9.4 — дальше «отправлено» статус не растёт) и
        // исчерпание транспортов. Всё остальное — ожидание.
        if !delivery.attempt.is_finished() {
            // **И на диск тоже** — вот этого не было, и это была самая старая
            // дыра в доставке.
            //
            // Очередь ожидающих (`remember_undelivered`) на диск ложилась
            // давно: «отправим, когда появится» — обещание, и без записи оно
            // жило бы до конца процесса. А доставка **в полёте** — та, для
            // которой транспорт нашёлся и кадр ушёл, — жила только в памяти.
            // Убей процесс между «кадр отдан транспорту» и подтверждением,
            // и сообщение оставалось в `Pending` навсегда: в очереди его нет,
            // срок сработать неоткуда, вернуться к нему некому. На Android
            // процесс убивают постоянно, а с честным «отправлено» (§9.4)
            // окно у почты выросло с нуля до минут.
            //
            // Запись идёт **до** того, как вызывающий получит эффекты, то
            // есть до настоящей отправки, — тот же порядок и та же причина,
            // что у `persist_session`: между «решили отправить» и «записали»
            // не должно быть ничего, что может не вернуться.
            //
            // Цена повтора — дубль у получателя, и его съедает дедупликация
            // (§9.2). Цена пропуска — сообщение, которое человек считает
            // отправленным, а оно никуда не денется.
            self.persist_delivery(&delivery)?;
            self.outbox.push(delivery);
        }
        Ok(effects)
    }

    /// Кладёт доставку на диск, чтобы она пережила убитый процесс.
    ///
    /// Одно место на оба случая — ожидание и полёт: строка одна и та же,
    /// а разведённые по двум местам они однажды разошлись бы в том, что
    /// именно записано.
    pub(super) fn persist_delivery(&mut self, delivery: &Delivery) -> Result<(), EngineError> {
        self.store.put_outbox(&ratatosk_store::StoredOutbox {
            msg_id: delivery.msg_id,
            recipient_ik: delivery.peer_ik,
            envelope: delivery.envelope.clone(),
            queued_ms: delivery.queued_ms,
        })?;
        Ok(())
    }

    /// Объявляет статус доставки — если он этой доставке вообще положен.
    ///
    /// **Молчаливой копии не положен никогда** (см. [`Delivery::silent`]),
    /// и проверка стоит здесь, а не у трёх вызывающих. Все три — про один
    /// исход, «уехать не вышло»: транспорты кончились, запись вытеснили
    /// из очереди ожидающих, контакт удалили. Раньше `silent` учитывался
    /// только в `arm_send`, то есть **после** того, как транспорт нашёлся, —
    /// и групповое сообщение участнику, до которого нет канала, получало
    /// статус, которого у него быть не может: один значок на тридцать двух
    /// получателей (§14).
    ///
    /// Своей строки в истории у молчаливой копии обычно и нет — но у ответа
    /// в группе она есть, потому что ответ это сообщение. На нём дыра
    /// и открылась.
    pub(super) fn note_status_of(
        &mut self,
        delivery: &Delivery,
        status: DeliveryStatus,
    ) -> Result<Vec<Effect>, EngineError> {
        if delivery.silent {
            return Ok(Vec::new());
        }
        self.note_status(delivery.msg_id, status)
    }

    /// Снимает **одну** доставку с очереди: из памяти и с диска.
    ///
    /// Ключ — пара «сообщение и получатель». Сообщение в группу это N
    /// доставок с одним номером (§11.3), и уборка по одному номеру означала
    /// бы, что дошедшая копия уносит все остальные. Ровно это и случалось.
    ///
    /// # Errors
    ///
    /// Отказ хранилища.
    pub(super) fn retire_delivery(
        &mut self,
        msg_id: &MsgId,
        recipient_ik: &[u8; 32],
    ) -> Result<(), EngineError> {
        self.deferred.retain(|d| d.msg_id != *msg_id || d.peer_ik != *recipient_ik);
        self.store.delete_outbox(msg_id, recipient_ik)?;
        Ok(())
    }

    /// Пробует следующий транспорт по §5.4.
    ///
    /// Строгая последовательность, а не гонка: [`Attempt`] выдаёт очередной
    /// транспорт только после того, как предыдущий объявлен неудавшимся,
    /// и поэтому одно сообщение физически не может уйти двумя каналами
    /// одновременно.
    pub(super) fn advance(&mut self, delivery: &mut Delivery) -> Result<Vec<Effect>, EngineError> {
        let contact = self.contacts.get(&delivery.peer_ik).ok_or(EngineError::UnknownPeer)?;
        let availability = contact.availability;

        // Обнаружение ещё не отвечало — подождём его, прежде чем расходовать
        // транспорты. Иначе §5.4 получает на вход «в LAN не видно» там, где
        // правильный ответ — «пока не знаем».
        if let Some(effect) = self.park_for_discovery(delivery) {
            return Ok(vec![effect]);
        }

        let transport = match delivery.attempt.next(availability) {
            Some(Decision::Use(t)) => t,
            Some(Decision::Undeliverable) | None => {
                // Транспорты кончились — но это ещё не приговор. Пока работает
                // только локальная сеть, «собеседника нет в сети» — самый
                // частый исход отправки, а не поломка, и показывать его
                // ошибкой значит пугать человека тем, что в порядке вещей.
                //
                // Поэтому исходов два. Смогли запомнить сообщение и вернуться
                // к нему позже — «ждём, когда появится». Не смогли (очередь
                // полна, контакта больше нет) — «не доставлено», без обещаний.
                delivery.attempt.succeed();
                // **Почему некуда — в журнал.** «Ждёт» на экране означает
                // «собеседника нет в сети» (§9.4), а за этим стоят три
                // разных «нет»: выключен, не поднят, адреса нет. Различить
                // их по экрану было нечем — и нечем было объяснить, почему
                // кадры по этому же LAN ходят, а отправка говорит «офлайн».
                //
                // Живая сессия ступень адресуемой **не делает**: у LAN
                // адрес даёт только маяк. Если в разборе стоит
                // `lan=адреса нет`, а кадры при этом ходят — вот оно.
                tracing::info!(
                    peer = %short_ik(&delivery.peer_ik),
                    tried = ?delivery.attempt.tried(),
                    refusal = %Reachability::of(availability).refusal(),
                    "отправлять некуда: лестница §5.4 кончилась"
                );
                let (remembered, mut effects) = self.remember_undelivered(delivery)?;
                let status = if remembered {
                    DeliveryStatus::Waiting
                } else {
                    DeliveryStatus::Undeliverable
                };
                effects.extend(self.note_status_of(delivery, status)?);
                return Ok(effects);
            }
        };

        let Some(session_id) = self.sessions.for_peer(&delivery.peer_ik, transport) else {
            // Сессии для этого семейства транспортов нет. §5.4 запрещает
            // продолжать LAN-сессию через onion, поэтому «нет сессии» здесь
            // означает именно новое рукопожатие, а не переиспользование.
            delivery.state = DeliveryState::AwaitingSession;
            // Рукопожатие могло уже уйти на другую ступень: у него своя
            // попытка, и §5.4 ведёт её независимо. Тогда идти надо за ним,
            // а не за своей лестницей: сессия появится там, где рукопожатие,
            // и отправка по своей ступени уехала бы в пустоту.
            let (effects, on) = self.ensure_handshake(delivery.peer_ik, transport)?;
            if on != transport {
                walk_attempt_to(&mut delivery.attempt, availability, on);
            }
            return Ok(effects);
        };

        let frames = self.seal_for(session_id, transport, &delivery.envelope)?;
        let (handoff, timer) = self.arm_send(delivery, transport, total_len(&frames));
        let mut effects = Self::delivery_sends(delivery.peer_ik, transport, frames, handoff);
        effects.push(timer);
        Ok(effects)
    }

    /// Раскладывает кадры доставки: метка передачи — на последнем.
    ///
    /// **Почему на последнем, а не на первом.** Метка ждёт ответа сервера
    /// «письмо принято», и сообщение принято тогда, когда принят последний
    /// его кусок: собрать его из неполного набора нельзя. На первом кадре
    /// метка объявила бы «отправлено» на середине отправки.
    pub(super) fn delivery_sends(
        peer_ik: [u8; 32],
        via: Transport,
        frames: Vec<Vec<u8>>,
        handoff: Option<u64>,
    ) -> Vec<Effect> {
        let last = frames.len().saturating_sub(1);
        frames
            .into_iter()
            .enumerate()
            .map(|(at, frame)| Effect::Send {
                peer_ik,
                via,
                frame,
                handoff: if at == last { handoff } else { None },
            })
            .collect()
    }

    /// Ставит отправке срок и решает, ждать ли подтверждения передачи.
    ///
    /// Одна функция на оба вида ожидания, потому что состояние у них общее
    /// (`InFlight` с меткой таймера) и разъезжаться ему нельзя. Различие —
    /// в том, чего именно ждём, и оно ровно одно:
    ///
    /// * прямой канал ждёт **квитанции собеседника** (§9.4). Успешная запись
    ///   в сокет не доказывает ничего: полуоткрытое соединение принимает
    ///   байты молча. Не пришла квитанция за срок — попытка не удалась,
    ///   и §5.4 ведёт дальше;
    /// * почта ждёт **ответа сервера на письмо**. Квитанций у неё нет
    ///   по построению, зато есть настоящее событие: сервер принял письмо
    ///   в свою очередь. До него кадр не отправлен, и говорить «отправлено»
    ///   нельзя.
    ///
    /// Раньше почта не ждала ничего: статус объявлялся в тот же миг, когда
    /// кадр клали в очередь транспорта, — то есть до всякой сети. Письмо
    /// после этого могло не уйти вовсе, а человек уже видел «отправлено».
    /// # Молчаливая копия ждёт **не** квитанции, но всё-таки ждёт
    ///
    /// Здесь стояла отдельная ветка: молчаливой копии попытка закрывалась
    /// прямо тут, до всякой сети, и запись в очередь не попадала вовсе.
    /// Это была поломка, и вот какая.
    ///
    /// «Записью в сокет» попытка закрывалась **до** того, как транспорт
    /// об этой записи отчитается. Отказ канала приезжает отдельным входом
    /// и позже — а закрытой доставки к тому моменту в очереди уже нет,
    /// и §5.4 некого вести дальше. Копия участнику, которого в тот миг
    /// не было в сети, пропадала совсем: до почты она не доходила никогда.
    /// Снаружи это и есть «участник, спавший во время разговора, сказанного
    /// не получает» — то же, что у человека, только по другой причине.
    ///
    /// Молчаливость §11.3 означает ровно две вещи: квитанции не будет
    /// и статуса не будет. Про ступени §5.4 она не означает ничего, и
    /// теперь не значит: срок у такой копии обычный, отказ канала ведёт её
    /// на следующую ступень, а вышедший на прямом канале срок читается как
    /// успех — «транспорт не пожаловался» (см. [`Engine::on_timer`]).
    pub(super) fn arm_send(
        &mut self,
        delivery: &mut Delivery,
        transport: Transport,
        frame_len: usize,
    ) -> (Option<u64>, Effect) {
        let timer = self.allocate_timer();
        let (after_ms, handoff) = if transport.is_direct() {
            // **Срок считается от размера кадра**, а не от одного лишь
            // транспорта. Мебибайт на медленной ступени едет десятки
            // секунд, и срок, выданный по имени транспорта, объявил бы его
            // неудавшимся на середине пути — а молчание в ответ
            // на отправленный кадр закрывает сессию. На эфире (0.4) это
            // выглядело как «длинный текст идёт сорок секунд и рвёт
            // переписку»; разбор — у `receipt_timeout_ms`.
            (delivery.attempt.timeout_ms_for(frame_len).unwrap_or(ONION_FALLBACK_TIMEOUT_MS), None)
        } else {
            (MAIL_HANDOFF_TIMEOUT_MS, Some(timer))
        };
        delivery.state = DeliveryState::InFlight { via: transport, timer };
        (handoff, Effect::SetTimer { after_ms, token: timer })
    }

    /// Транспорт подтвердил: кадр ушёл (§5.3).
    ///
    /// Отсюда — и только отсюда — берётся «отправлено» у почты. Метка
    /// сверяется точно, а не по порядку: по одной ступени к одному
    /// собеседнику едут и рукопожатие, и сообщения, и подтверждение письма
    /// с рукопожатием засчиталось бы сообщению, которого сервер ещё не видел.
    ///
    /// Неизвестная метка — не ошибка. Подтверждение могло опоздать: срок
    /// вышел, попытка объявлена неудавшейся, а письмо всё-таки уехало.
    /// Ронять из-за этого нечего — сообщение к тому моменту уже получило
    /// свой честный исход, а второе письмо съест дедупликация (§9.2).
    pub(super) fn on_handed(
        &mut self,
        peer_ik: [u8; 32],
        via: Transport,
        handoff: u64,
    ) -> Result<Vec<Effect>, EngineError> {
        // Рукопожатие: подтверждать человеку нечего, но срок снять обязаны.
        // Иначе он сработает на кадре, который сервер уже принял, и §5.4
        // объявит ступень неудавшейся — при том что она сработала.
        if let Some(handshake) =
            self.pending.iter_mut().find(|p| p.peer_ik == peer_ik && p.timer == Some(handoff))
        {
            handshake.timer = None;
            return Ok(Vec::new());
        }

        let mut queue = std::mem::take(&mut self.outbox);
        let mut effects = Vec::new();
        for delivery in &mut queue {
            if delivery.peer_ik != peer_ik
                || !matches!(delivery.state, DeliveryState::InFlight { via: v, timer }
                    if v == via && timer == handoff)
            {
                continue;
            }
            // §9.4: по почте статус дальше «отправлено» не растёт, ждать
            // больше нечего, и запись уходит из очереди.
            //
            // Статус — через `note_status_of`, а не напрямую: групповая
            // копия молчалива (§11.3), и один значок «отправлено»
            // на тридцати двух получателях §14 не разрешает. Прямой зов
            // эту проверку обходил.
            //
            // Очередь — по паре, и только по ней. Прежде уборка ехала
            // побочным действием статуса и по одному номеру: дошедшая
            // почтой копия уносила копии всех прочих участников.
            delivery.attempt.succeed();
            effects.extend(self.note_status_of(delivery, DeliveryStatus::Sent)?);
            self.retire_delivery(&delivery.msg_id, &delivery.peer_ik)?;
        }
        queue.retain(|d| !d.attempt.is_finished());
        self.outbox = queue;
        Ok(effects)
    }

    /// Начинает рукопожатие, если оно ещё не в пути.
    ///
    /// Второе возвращаемое значение — ступень, на которой рукопожатие
    /// **на самом деле** находится. Она не всегда та, о которой просили:
    /// рукопожатие идёт своей попыткой по §5.4 и могло уйти дальше, пока
    /// это сообщение ждало. Вызывающий обязан посмотреть на ответ, а не
    /// на свой вопрос, — иначе сессия появится на одной ступени, а отправка
    /// пойдёт по другой.
    /// # Исчерпанная лестница — повод повторить, а не начать заново
    ///
    /// **Разбор четвёртой поломки эфирной дуги, и самой дорогой.** На стенде
    /// десктоп отправил телефону **четыре** первых шага за полсекунды, три
    /// из них — за пятьсот микросекунд. Кадры были разные, то есть каждый
    /// нёс свой эфемерный ключ Noise; телефон честно завёл четыре сессии,
    /// каждая вытеснила предыдущую, и осталась четвёртая. Десктоп разобрал
    /// **первый** ответ, закрыл рукопожатие и оставил себе первую. Дальше
    /// двенадцать кадров подряд «тег не сошёлся», и само это уже
    /// не выправлялось.
    ///
    /// Откуда четыре. Лестница §5.4 в эфире одноступенчата: кроме радио
    /// пробовать нечего. Первый же отказ объявляет попытку исчерпанной,
    /// а исчерпанное рукопожатие [`Engine::retry_handshake`] выбрасывало —
    /// иначе запись в `pending` заперла бы этот вход навсегда. Выброшенное,
    /// оно переставало быть «уже в пути», и следующее сообщение из очереди
    /// чеканило новое. В очереди стояла сотня кадров замера.
    ///
    /// Правило: **новый эфемерный ключ только при смене семейства
    /// транспортов.** То же семейство — тот же самый кадр, байт в байт;
    /// ровно так уже поступает `retry_handshake`, переходя внутри семьи,
    /// и здесь это просто перестаёт быть исключением.
    ///
    /// Повторный кадр ничего не ломает у получателя: он побайтно тот же,
    /// его ловит `HandshakeReplayGuard`, и ответ уходит прежний
    /// (`HandshakeOutcome::Repeat`) — та самая ветка, что спасает контакт
    /// с потерянным первым ответом. Сессия у него остаётся одна.
    ///
    /// Запереть вход это тоже больше не может: повторив кадр, мы заводим
    /// попытке новый срок, и она перестаёт быть исчерпанной — то есть
    /// следующее сообщение снова ждёт, а не шлёт.
    pub(super) fn ensure_handshake(
        &mut self,
        peer_ik: [u8; 32],
        transport: Transport,
    ) -> Result<(Vec<Effect>, Transport), EngineError> {
        let Some(at) = self.pending.iter().position(|p| p.peer_ik == peer_ik) else {
            return Ok((self.begin_handshake(peer_ik, transport)?, transport));
        };
        if !self.pending[at].attempt.is_finished() {
            // Второе рукопожатие только потратило бы ещё одну операцию
            // у получателя и породило вторую сессию.
            let on = self.pending[at].attempt.tried().last().copied().unwrap_or(transport);
            return Ok((Vec::new(), on));
        }

        // Лестница кончилась, а рукопожатие всё ещё нужно. Повторяем его
        // с начала лестницы — и **тем же кадром**, если семейство то же.
        let availability = self.availability_of(&peer_ik)?;
        let mut attempt = Attempt::new();
        walk_attempt_to(&mut attempt, availability, transport);
        let binding = SessionBinding::of(transport);
        let frame = if binding == self.pending[at].binding {
            self.pending[at].frame.clone()
        } else {
            // Другое семейство — и вот здесь новый ключ обязателен: сессия
            // семейству принадлежит (§5.4), и прежнее состояние `snow`
            // к этой ступени не относится.
            let card = self.own_card().encode()?;
            let (message, state) = Initiator::start(&self.identity, &peer_ik, &card)?;
            let frame = self.handshake_frame(HANDSHAKE_STEP_FIRST, &message)?;
            self.pending[at].state = state;
            self.pending[at].frame = frame.clone();
            frame
        };
        let (handoff, token, set_timer) = self.arm_handshake(&attempt, transport);
        let pending = &mut self.pending[at];
        pending.attempt = attempt;
        pending.binding = binding;
        pending.timer = Some(token);
        Ok((vec![Effect::Send { peer_ik, via: transport, frame, handoff }, set_timer], transport))
    }

    pub(super) fn allocate_timer(&mut self) -> u64 {
        let token = self.next_timer_token;
        self.next_timer_token += 1;
        token
    }

    pub(super) fn begin_handshake(
        &mut self,
        peer_ik: [u8; 32],
        transport: Transport,
    ) -> Result<Vec<Effect>, EngineError> {
        // §8.2: в первом сообщении — только карточка и приветствие.
        let card = self.own_card().encode()?;
        let (message, state) = Initiator::start(&self.identity, &peer_ik, &card)?;
        let frame = self.handshake_frame(HANDSHAKE_STEP_FIRST, &message)?;

        // Попытка заводится на том же транспорте, который выбрала доставка:
        // рукопожатие и данные обязаны идти одним путём, иначе сессия
        // установится не в том семействе транспортов (§5.4).
        let mut attempt = Attempt::new();
        let availability = self.availability_of(&peer_ik)?;
        walk_attempt_to(&mut attempt, availability, transport);

        let (handoff, token, set_timer) = self.arm_handshake(&attempt, transport);
        let effects = vec![
            Effect::Send { peer_ik, via: transport, frame: frame.clone(), handoff },
            set_timer,
        ];
        self.pending.push(OutgoingHandshake {
            state,
            attempt,
            peer_ik,
            frame,
            binding: SessionBinding::of(transport),
            timer: Some(token),
        });
        Ok(effects)
    }

    /// То же, что [`Engine::arm_send`], но для рукопожатия.
    ///
    /// Возвращает метку подтверждения, метку таймера и сам таймер.
    ///
    /// Почтовое рукопожатие раньше не получало срока вовсе: ждать ответа
    /// собеседника по почте бессмысленно, а другого ожидания не было.
    /// Итог был хуже, чем кажется: письмо с рукопожатием, которое сервер
    /// не принял, никого ни о чём не извещало, и сообщения, ждавшие эту
    /// сессию, оставались в очереди навсегда. Теперь срок есть и здесь —
    /// но отмеряет он не ответ, а передачу.
    pub(super) fn arm_handshake(
        &mut self,
        attempt: &Attempt,
        transport: Transport,
    ) -> (Option<u64>, u64, Effect) {
        let token = self.allocate_timer();
        let (after_ms, handoff) = if transport.is_direct() {
            (attempt.timeout_ms().unwrap_or(ONION_FALLBACK_TIMEOUT_MS), None)
        } else {
            (MAIL_HANDOFF_TIMEOUT_MS, Some(token))
        };
        (handoff, token, Effect::SetTimer { after_ms, token })
    }

    /// Начинает рукопожатие заново на следующей ступени §5.4.
    ///
    /// Второе возвращаемое значение — судьба рукопожатия ([`HandshakeStep`]).
    /// Оно нужно вызывающему дважды: сообщения, ждавшие эту сессию, обязаны
    /// уйти на ту же новую ступень, а если ступени кончились — узнать исход.
    /// Молча оставить их в очереди нельзя (§14).
    ///
    /// # Почему именно заново
    ///
    /// Раньше на следующую ступень уходил **тот же самый** кадр первого
    /// сообщения. Экономия выглядела очевидной: рукопожатие Noise про
    /// транспорт ничего не знает, зачем считать его дважды.
    ///
    /// Затем, что сессию к семейству транспортов привязывает **каждая
    /// сторона отдельно, по тому пути, которым кадр к ней пришёл**
    /// ([`SessionBinding::of`]). Разбор поломки со стенда, шаг за шагом:
    ///
    /// 1. У обеих сторон живёт онион-сессия `S1`, переписка идёт.
    /// 2. На одной машине включают локальную сеть, собеседник виден
    ///    маячком — и §5.4 отправляет следующее сообщение первой ступенью.
    ///    Сессии для LAN нет, начинается рукопожатие по LAN.
    /// 3. Собеседник кадр принимает и заводит `S2`, привязав её к LAN.
    ///    А вот его ответ по LAN не уходит: его сторона соединения не
    ///    поднимается (односторонние соединения, ARCHITECTURE 5ц), транспорт
    ///    отвечает `Unavailable`.
    /// 4. У нас выходит срок, и мы шлём **тот же** кадр через onion.
    /// 5. Для собеседника это точный повтор: сторож рукопожатий отдаёт
    ///    [`HandshakeOutcome::Repeat`], он пересылает прежний ответ и
    ///    **оставляет `S2` привязанной к LAN**.
    /// 6. Мы этот ответ получаем через onion и привязываем ту же `S2`
    ///    к **onion** — вытеснив `S1`, свою онион-сессию.
    ///
    /// Итог: у нас онион-семейство — это `S2`, у собеседника — по-прежнему
    /// `S1`. Он шлёт по `S1`, мы её уже забыли: «кадр для неизвестной
    /// сессии — отброшен». В обратную сторону — то же самое. Переписка
    /// умирает при живом Tor с обеих сторон, и §5.4 («LAN и Tor не
    /// смешиваются в одной сессии никогда») оказывается нарушен не выбором
    /// транспорта, а бухгалтерией сессий.
    ///
    /// Отсюда первая половина правила: **переходя в другое семейство, надо
    /// начинать рукопожатие заново.** Новый кадр — новая сессия, и обе
    /// стороны привяжут её к одному и тому же семейству, потому что видели
    /// её на одном и том же пути. Цена — ещё одна операция Noise; она
    /// несравнима с молча умершей перепиской (§14).
    ///
    /// # А внутри одного семейства — наоборот
    ///
    /// Сперва правило звучало короче: «каждая ступень получает своё
    /// рукопожатие». Оно было верным по духу и слишком широким по букве,
    /// и вторая поломка со стенда выглядела ровно так же, как первая:
    /// «кадр для неизвестной сессии — отброшен», `via=Mail`.
    ///
    /// Ступеней три, а семейств два: onion и почта живут в одном
    /// ([`SessionBinding::of`]), и реестр держит **одну сессию на семейство**
    /// — новая вытесняет прежнюю. Значит, переход onion → почта по прежнему
    /// правилу заводил в одном семействе два рукопожатия, то есть две
    /// сессии на один слот. Дальше всё решал порядок: у каждой стороны
    /// побеждала та, чей ответ пришёл вторым, — а onion отвечает секундами,
    /// почта минутами, и порядок у сторон разный почти наверняка.
    ///
    /// Внутри семейства повтор безопасен ровно потому, почему он был опасен
    /// между семействами: собеседник, получив точный повтор, оставляет
    /// сессию привязанной к тому семейству, где увидел её впервые, — и это
    /// **то же самое** семейство. Обе стороны остаются при одной сессии.
    ///
    /// Поэтому кадр первого сообщения хранится, и правило целиком такое:
    ///
    /// * другое семейство (LAN ↔ Tor) — новое рукопожатие;
    /// * то же семейство (onion → почта) — тот же самый кадр.
    pub(super) fn retry_handshake(
        &mut self,
        peer_ik: [u8; 32],
        via: Transport,
    ) -> Result<(Vec<Effect>, HandshakeStep), EngineError> {
        let availability = match self.availability_of(&peer_ik) {
            Ok(a) => a,
            Err(_) => return Ok((Vec::new(), HandshakeStep::Absent)),
        };

        let mut effects = Vec::new();
        let mut step = HandshakeStep::Absent;
        let mut pending = std::mem::take(&mut self.pending);
        for handshake in &mut pending {
            if handshake.peer_ik != peer_ik || handshake.attempt.tried().last() != Some(&via) {
                continue;
            }
            match handshake.attempt.next(availability) {
                Some(Decision::Use(next)) => {
                    let next_binding = SessionBinding::of(next);
                    let frame = if next_binding == handshake.binding {
                        // Та же семья — тот же самый кадр. Разбор см. выше.
                        handshake.frame.clone()
                    } else {
                        // Другая семья — новое рукопожатие; разбор см. выше.
                        // Прежнее состояние `snow` здесь и умирает: запоздалый
                        // ответ на него больше никого не найдёт, и это
                        // правильно — та ступень признана неудавшейся.
                        let card = self.own_card().encode()?;
                        let (message, state) = Initiator::start(&self.identity, &peer_ik, &card)?;
                        let frame = self.handshake_frame(HANDSHAKE_STEP_FIRST, &message)?;
                        handshake.state = state;
                        handshake.frame = frame.clone();
                        handshake.binding = next_binding;
                        frame
                    };
                    // Новой попытке — новый срок. Без него молчание второго
                    // транспорта не приводит к третьему, и откат §5.4
                    // обрывается на середине.
                    let (handoff, token, set_timer) = self.arm_handshake(&handshake.attempt, next);
                    effects.push(Effect::Send { peer_ik, via: next, frame, handoff });
                    effects.push(set_timer);
                    handshake.timer = Some(token);
                    step = HandshakeStep::Moved(next);
                }
                Some(Decision::Undeliverable) | None => step = HandshakeStep::Exhausted,
            }
        }
        // **Исчерпанное рукопожатие остаётся, и это правка поломки.**
        //
        // Здесь стояло `pending.retain(…)`: запись выбрасывалась, чтобы
        // не запереть [`Engine::ensure_handshake`] — тот считает запись
        // в `pending` признаком «рукопожатие уже в пути». Лекарство вышло
        // хуже болезни. Выброшенное рукопожатие переставало существовать,
        // и следующее сообщение из очереди чеканило **новое** — с новым
        // эфемерным ключом Noise. На одноступенчатой лестнице эфира, где
        // отказ исчерпывает попытку сразу, сотня кадров замера дала
        // четыре рукопожатия за полсекунды и разошедшиеся сессии
        // у сторон. Разбор целиком — у `ensure_handshake`.
        //
        // Запирания теперь нет по другой причине: `ensure_handshake`,
        // увидев исчерпанную попытку, повторяет **прежний** кадр и заводит
        // ей новый срок. Вход открыт, а ключ не меняется.
        self.pending = pending;
        Ok((effects, step))
    }

    pub(super) fn availability_of(
        &self,
        peer_ik: &[u8; 32],
    ) -> Result<PeerAvailability, EngineError> {
        Ok(self.contacts.get(peer_ik).ok_or(EngineError::UnknownPeer)?.availability)
    }

    pub(super) fn handshake_frame(
        &mut self,
        step: u64,
        message: &[u8],
    ) -> Result<Vec<u8>, EngineError> {
        let mut nonce = [0u8; ratatosk_wire::NONCE_LEN];
        self.entropy.fill(&mut nonce);
        Ok(crate::frames::handshake(step, message, nonce)?)
    }

    /// Запечатывает конверт для сессии — одним кадром или несколькими.
    ///
    /// Несколькими он выходит, когда конверт не влезает в потолок ступени
    /// (§9.3): тогда [`fragment::carriers`] режет **закодированный** конверт
    /// на несущие, и каждая едет своим кадром. Получатель собирает их
    /// обратно, и собранный конверт неотличим от приехавшего целым.
    ///
    /// Резать решает ступень, а не размер сам по себе: один и тот же конверт
    /// по проводу едет целиком, а по эфиру — кусками, потому что до Android
    /// класс L не доходит вовсе (0.4.8). Поэтому `via` здесь обязателен
    /// и не имеет разумного значения по умолчанию.
    ///
    /// **Порядок кадров значим.** Цепочка сессии продвигается на каждый
    /// кадр, и кадры обязаны уйти в том порядке, в каком запечатаны, —
    /// вызывающий раскладывает их в [`Effect::Send`] подряд и не меняет
    /// местами.
    pub(super) fn seal_for(
        &mut self,
        session_id: u64,
        via: Transport,
        envelope: &[u8],
    ) -> Result<Vec<Vec<u8>>, EngineError> {
        // Источник случайности отдаётся резаку целиком: и номера кусков,
        // и метку сборки он чеканит сам — **и только если резать пришлось**.
        // Черпать заранее нельзя: случайность у ядра одна на всё, в тестах
        // она засеяна, и лишний зачерпнутый номер сдвинул бы все следующие.
        let entropy = &mut self.entropy;
        let carriers = ratatosk_proto::fragment::carriers(envelope, via, || entropy.msg_id())?;

        let bound = self.sessions.get_mut(session_id).ok_or(EngineError::UnknownPeer)?;
        let mut frames = Vec::with_capacity(carriers.len());
        for carrier in &carriers {
            frames.push(crate::frames::seal(&mut bound.session, carrier)?);
        }

        // Запись до возврата кадров, а не после их отправки: см. пояснение
        // к `persist_session`. Между продвижением цепочки и записью не должно
        // быть ничего, что может не вернуться.
        self.persist_session(session_id)?;
        Ok(frames)
    }

    /// Раскладывает запечатанные кадры в отправки одной ступенью.
    ///
    /// Отдельная функция, потому что мест четыре и в каждом соблазн
    /// написать `frames.remove(0)`: пока фрагментация не срабатывала,
    /// разница была бы незаметна — и обнаружилась бы на первом же длинном
    /// сообщении по эфиру пропажей всех кусков, кроме первого.
    pub(super) fn sends(peer_ik: [u8; 32], via: Transport, frames: Vec<Vec<u8>>) -> Vec<Effect> {
        frames
            .into_iter()
            .map(|frame| Effect::Send { peer_ik, via, frame, handoff: None })
            .collect()
    }

    /// Досылает всё, что ждало сессию с этим контактом.
    pub(super) fn flush_outbox(&mut self, peer_ik: [u8; 32]) -> Result<Vec<Effect>, EngineError> {
        let mut effects = Vec::new();
        let mut queue = std::mem::take(&mut self.outbox);

        for delivery in &mut queue {
            if delivery.peer_ik != peer_ik
                || !matches!(delivery.state, DeliveryState::AwaitingSession)
            {
                continue;
            }
            // Попытка та же самая: транспорт уже выбран, не хватало сессии.
            // Новый вызов `attempt.next` здесь съел бы транспорт зря.
            effects.extend(self.resend_current(delivery)?);
        }

        queue.retain(|d| !d.attempt.is_finished());
        self.outbox = queue;
        Ok(effects)
    }

    /// Отправляет сообщение тем транспортом, который уже выбран попыткой.
    pub(super) fn resend_current(
        &mut self,
        delivery: &mut Delivery,
    ) -> Result<Vec<Effect>, EngineError> {
        let Some(&transport) = delivery.attempt.tried().last() else {
            return self.advance(delivery);
        };
        let Some(session_id) = self.sessions.for_peer(&delivery.peer_ik, transport) else {
            return Ok(Vec::new());
        };

        let frames = self.seal_for(session_id, transport, &delivery.envelope)?;
        let (handoff, timer) = self.arm_send(delivery, transport, total_len(&frames));
        let mut effects = Self::delivery_sends(delivery.peer_ik, transport, frames, handoff);
        effects.push(timer);
        Ok(effects)
    }

    /// Запоминает сообщение, которому некуда было ехать.
    ///
    /// Попытка сбрасывается: когда сеть вернётся, §5.4 начнётся заново —
    /// с локальной сети, а не с того транспорта, на котором всё кончилось.
    /// Возвращает «запомнили ли» и события про вытесненное из очереди.
    pub(super) fn remember_undelivered(
        &mut self,
        delivery: &Delivery,
    ) -> Result<(bool, Vec<Effect>), EngineError> {
        // Ждать имеет смысл только если что-то может измениться. Условий два,
        // и оба необходимы.
        //
        // Контакт должен существовать: удалённому отправлять некому.
        let Some(contact) = self.contacts.get(&delivery.peer_ik) else {
            return Ok((false, Vec::new()));
        };
        // И должен быть хоть один путь, который когда-нибудь может открыться.
        // Если ждать нечего в буквальном смысле, обещать «отправим позже»
        // было бы выдумкой: тогда это «не доставлено», без обещаний.
        //
        // **Спрашивается это у §5.4, а не перечисляется здесь.** Перечислялось:
        // «LAN выключен, onion нет, почты нет — значит ждать нечего», — и
        // в списке не было **меша**. Собеседник, доступный только через него,
        // попадал под условие целиком: сообщение ему объявлялось недоставимым
        // и выбрасывалось, ни разу не попав в очередь ожидания.
        //
        // Снаружи это и есть «оффлайн участники пропускают все сообщения, и
        // до них не доходит даже когда они сами пишут в группу» — писать-то
        // они пишут, а будить у нас нечего: очередь пуста. Ровно то же и
        // со служебными кадрами — выходом из группы, ключами, карточками:
        // они едут той же очередью.
        //
        // На стенде это не воспроизводилось никогда: там четыре ступени
        // и почта у всех. На живых устройствах с одним мешем — всегда.
        if !Reachability::of(contact.availability).may_open() {
            return Ok((false, Vec::new()));
        }
        // По паре, а не по номеру: копии одного сообщения разным участникам
        // группы (§11.3) — разные доставки. Проверка по номеру объявляла бы
        // «уже отложено» второму и всем следующим, то есть в ожидании
        // оставался бы ровно один участник из недостижимых, а остальные
        // теряли сообщение молча.
        if self
            .deferred
            .iter()
            .any(|d| d.msg_id == delivery.msg_id && d.peer_ik == delivery.peer_ik)
        {
            return Ok((true, Vec::new()));
        }

        let mut effects = Vec::new();
        if self.deferred.len() >= MAX_DEFERRED {
            // Вытесняется самое старое: у свежего больше шансов ещё быть
            // нужным человеку. И вытесненному честно меняется статус —
            // обещание «отправим позже» снимается вместе с очередью, и UI
            // об этом узнаёт. Молча оставить «ждём» у сообщения, к которому
            // никто больше не вернётся, значит соврать на экране.
            let evicted = self.deferred.remove(0);
            self.store.delete_outbox(&evicted.msg_id, &evicted.peer_ik)?;
            effects.extend(self.note_status_of(&evicted, DeliveryStatus::Undeliverable)?);
        }

        // На диск — до того, как объявлен статус. Обещание, которого нет
        // в базе, не переживёт убитый процесс, а на экране останется.
        self.persist_delivery(delivery)?;

        let mut waiting = delivery.clone();
        waiting.attempt = Attempt::new();
        waiting.state = DeliveryState::AwaitingSession;
        waiting.session_reset_used = false;
        self.deferred.push(waiting);
        Ok((true, effects))
    }

    /// Пробует отправить заново то, что ждало случая.
    ///
    /// Зовётся на событиях, которые действительно меняют шансы: сеть
    /// сменилась, контакт объявился в эфире, сессия установилась. По таймеру
    /// — никогда: у ядра нет часов, а опрос на телефоне стоит батареи (§14).
    pub(super) fn retry_deferred(
        &mut self,
        peer_ik: Option<[u8; 32]>,
    ) -> Result<Vec<Effect>, EngineError> {
        if self.deferred.is_empty() {
            return Ok(Vec::new());
        }
        let (ready, waiting): (Vec<Delivery>, Vec<Delivery>) = std::mem::take(&mut self.deferred)
            .into_iter()
            .partition(|d| peer_ik.is_none_or(|only| d.peer_ik == only));
        self.deferred = waiting;

        let mut effects = Vec::new();
        for delivery in ready {
            // Контакта нет — но причины у этого две, и хоронить надо
            // только одну.
            //
            // Контакт **удалён**: ехать некому, обещание снимается вместе
            // с записью на диске.
            //
            // Карточка **ещё не доехала**, а человек стоит в составе группы,
            // в которой стоим и мы: это ожидание, а не конец. Похоронив его
            // здесь, мы вернули бы ровно ту поломку, ради которой копии
            // и откладываются (`park_for_card`), — первый же посторонний
            // повод к пересылке убивал бы их до приезда карточки.
            if !self.contacts.contains_key(&delivery.peer_ik) {
                if self.groups.values().any(|state| state.group.contains(&delivery.peer_ik)) {
                    self.deferred.push(delivery);
                    continue;
                }
                self.store.delete_outbox(&delivery.msg_id, &delivery.peer_ik)?;
                effects.extend(self.note_status_of(&delivery, DeliveryStatus::Undeliverable)?);
                continue;
            }
            // Запись на диске остаётся до подтверждения: попытка может опять
            // не удаться, и тогда сообщение снова ляжет в ожидание — без
            // повторной записи, потому что она уже там.
            effects.extend(self.enqueue(delivery)?);
        }
        Ok(effects)
    }

    /// Соединения с собеседником не стало: обрывом или отказом.
    ///
    /// Одно место на два входа, потому что дальше они расходятся ровно
    /// в одной строке — забывать ли адрес в локальной сети, — а всё
    /// остальное у них общее.
    pub(super) fn on_link_down(
        &mut self,
        peer_ik: [u8; 32],
        via: Transport,
        why: Failure,
    ) -> Result<Vec<Effect>, EngineError> {
        // У десктопа (§13.4) разрыв значит ровно то, что сказано, и ничего
        // больше: очереди доставки у него нет, ступеней §5.4 для него нет —
        // есть один прямой канал, и он либо есть, либо нет. Пустить это
        // в `on_delivery_failed` нельзя не только поэтому: та функция
        // спрашивает доступность **контакта**, а устройство контактом
        // не является, и весь шаг ядра упал бы на `UnknownPeer`.
        if self.devices.contains_key(&peer_ik) {
            return self.drop_device_link(peer_ik);
        }
        self.on_delivery_failed(peer_ik, via, why)
    }

    /// Прямой канал отказал — переходим к следующему транспорту (§5.4).
    pub(super) fn on_delivery_failed(
        &mut self,
        peer_ik: [u8; 32],
        via: Transport,
        why: Failure,
    ) -> Result<Vec<Effect>, EngineError> {
        // Молчание в ответ на ушедший кадр — причина перестать по этой
        // сессии **отправлять**. Не закрыть её: молчание свидетельствует
        // об одном направлении, а сессия двусторонняя.
        //
        // Закрывали — и это была настоящая поломка, найденная на стенде.
        // Мы сессию забывали, собеседник нет; он продолжал слать по ней,
        // а мы каждый его кадр отбрасывали как «неизвестная сессия»
        // и сказать ему об этом не могли: кадр не расшифрован, кто прислал —
        // неизвестно. Переписка умирала в одну сторону навсегда, при живой
        // связи с обеих.
        //
        // Отправка на покой — **до** переноса попытки: следующий шаг должен
        // увидеть, что отправлять не по чему, и начать рукопожатие.
        let stale_session =
            why == Failure::Silent && via.is_direct() && self.sessions.retire(&peer_ik, via);

        // Адрес в локальной сети забывается только при **отказе соединения**:
        // адрес был, по нему никто не ответил — значит устройства там
        // больше нет.
        //
        // При обрыве — не забывается, и это разбор живой поломки со стенда
        // (`HANDOFF.md`, 6б). Обрыв говорит о сокете, а не о присутствии:
        // одна неудачная запись — и §5.4 переставал предлагать LAN
        // собеседнику, который стоял в двух метрах и через секунду сам
        // начинал новое рукопожатие. Переписка после этого шла строго
        // в одну сторону: его кадры мы принимали и отвечали на них
        // квитанциями, а каждое **наше** сообщение объявлялось «ждёт».
        //
        // При молчании — тоже не забывается: запись в сокет удалась,
        // то есть по этому адресу кто-то слушает. Забыв его здесь, мы увели
        // бы следующую попытку с LAN на транспорты, которых может и не быть,
        // — и вместо переустановки сессии получили бы «не доставлено».
        if why == Failure::Unreachable && via == Transport::Lan {
            if let Some(contact) = self.contacts.get_mut(&peer_ik) {
                contact.availability.seen_on_lan = false;
            }
            // Вместе с признаком — и отметка времени: иначе срок соседства
            // «воскресил» бы её при ближайшем проходе, и мы снова считали
            // бы слышимым того, до кого только что не достучались.
            if let Some(heard) = self.heard.get_mut(&peer_ik) {
                heard.lan_ms = None;
            }
            // Громко, потому что последствие тихое и долгое: пока маяк
            // не прозвучит снова — или не придёт кадр, см. `note_presence`
            // — §5.4 не предложит LAN **ни одному** следующему сообщению.
            // Отсрочка на обнаружение выдаётся один раз на контакт за сеанс
            // и второй раз уже не спасёт.
            tracing::info!(
                peer = %short_ik(&peer_ik),
                "адрес в локальной сети забыт: соединиться не удалось"
            );
        }

        // Рукопожатие переносится первым: без сессии данные всё равно
        // упрутся в ожидание, и порядок эффектов станет непонятным.
        let (mut effects, step) = self.retry_handshake(peer_ik, via)?;
        let availability = self.availability_of(&peer_ik).ok();
        let mut queue = std::mem::take(&mut self.outbox);

        for delivery in &mut queue {
            if delivery.peer_ik != peer_ik {
                continue;
            }
            // Рукопожатие ушло на следующую ступень — сообщения, ждавшие
            // его сессию, обязаны уйти туда же. Иначе доставка остаётся
            // приколотой к ступени, рукопожатие которой уже брошено: сессия
            // появится на новой, `flush_outbox` отправит по старой, и кадр
            // уедет в пустоту. Найдено тестом на семь шагов, где отказ LAN
            // уводил рукопожатие в onion, а сообщение — нет.
            if let (HandshakeStep::Moved(next), Some(availability)) = (step, availability) {
                if matches!(delivery.state, DeliveryState::AwaitingSession)
                    && delivery.attempt.tried().last() == Some(&via)
                {
                    walk_attempt_to(&mut delivery.attempt, availability, next);
                }
            }
            let failed_here = match delivery.state {
                DeliveryState::InFlight { via: v, .. } => v == via,
                // Сообщение ждало сессии, а рукопожатию идти больше некуда.
                // Ждать нечего: попытка обязана дойти до конца и объявить
                // исход, иначе сообщение зависает в очереди навсегда — ровно
                // то молчание, которое §14 запрещает.
                DeliveryState::AwaitingSession => step == HandshakeStep::Exhausted,
                // Это сообщение ещё не выходило в сеть и потому здесь ничего
                // не теряло: у него свой срок, и снимет паузу он, а не чужой
                // отказ. Тронуть его тут значило бы сжечь LAN за компанию —
                // как раз тогда, когда собеседник вот-вот найдётся.
                DeliveryState::AwaitingDiscovery { .. } => false,
            };
            if !failed_here {
                continue;
            }

            // Сессия оказалась несогласованной — даём этому сообщению ещё
            // один заход по тому же транспорту, но через новое рукопожатие.
            // Это не повтор в смысле §5.4 (тот запрещает повторять транспорт
            // после отказа): отказал не транспорт, а сессия, и заменив её,
            // мы пробуем впервые. Ровно один раз на сообщение — иначе два
            // узла с расходящимся состоянием гоняли бы рукопожатия по кругу.
            if stale_session && !delivery.session_reset_used {
                delivery.session_reset_used = true;
                delivery.attempt = Attempt::new();
                delivery.state = DeliveryState::AwaitingSession;
            }
            effects.extend(self.advance(delivery)?);
        }

        queue.retain(|d| !d.attempt.is_finished());
        self.outbox = queue;
        Ok(effects)
    }
}
