/// Предел кэша на десктопе — 1000 последних сообщений на чат (§13.4).
pub const DESKTOP_CACHE_PER_CHAT: usize = 1_000;

/// Через сколько без подключения кэш десктопа стирается — 30 суток (§13.4).
///
/// К кэшу **в памяти** это отношения не имеет: он умирает вместе с процессом
/// куда раньше. Срок — про дисковый.
pub const DESKTOP_CACHE_TTL_MS: u64 = 30 * 24 * 60 * 60 * 1000;

/// Скольких чатов терминал держит историю.
///
/// **Дополнение к §13.4.** Спецификация называет предел на чат — тысячу
/// сообщений, — но не называет, сколько чатов. Без второго предела
/// произведение растёт: у человека с сотней собеседников это сто тысяч
/// сообщений в памяти долгоживущего окна, и растёт оно молча.
///
/// Вытесняется тот, в который дольше всего не заглядывали: держать историю
/// чата, который человек открыл однажды месяц назад, незачем — она всё равно
/// перечитается при следующем открытии.
pub const DESKTOP_CACHE_CHATS: usize = 64;

/// Что разрешено пересекать границу устройства (§13.4).
///
/// «Ключевой материал контактов, `IK`, `SK` и `db_key` границу устройства
/// не пересекают никогда.» Перечисление существует, чтобы это правило было
/// проверяемым в коде, а не только в тексте.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Crossing {
    /// Список чатов.
    ChatList,
    /// Расшифрованные сообщения.
    DecryptedMessages,
    /// Статусы доставки.
    Statuses,
    /// Команды на отправку.
    SendCommands,
}

impl Crossing {
    /// Всё, что разрешено передавать десктопу.
    pub const ALLOWED: [Crossing; 4] = [
        Crossing::ChatList,
        Crossing::DecryptedMessages,
        Crossing::Statuses,
        Crossing::SendCommands,
    ];
}

/// Сопряжённое устройство.
#[derive(Debug, Clone)]
pub struct PairedDevice {
    /// Идентификатор записи.
    pub device_id: [u8; 16],
    /// Публичная половина ключа сопряжения — адрес десктопа в эфире (§5.1).
    ///
    /// Нужна одному вопросу: знает ли телефон, куда звонить. Без ответа
    /// на него «десктоп не подключился» и «десктопа не видно в сети»
    /// выглядят одинаково, а чинятся по-разному.
    pub pairing_public: [u8; 32],
    /// Метка для списка на телефоне.
    pub label: String,
    /// Когда сопряжено, мс.
    pub paired_ms: u64,
    /// Когда последний раз подключалось, мс.
    pub last_seen_ms: u64,
}

impl PairedDevice {
    /// Пора ли стереть кэш на десктопе (§13.4).
    #[must_use]
    pub fn cache_expired(&self, now_ms: u64) -> bool {
        now_ms.saturating_sub(self.last_seen_ms) >= DESKTOP_CACHE_TTL_MS
    }
}

/// Отзыв сопряжения (§13.4).
///
/// «Отзыв — удаление записи и **немедленный** разрыв сессии.» Отложенный
/// разрыв означал бы окно, в котором отозванный десктоп продолжает отправлять
/// сообщения от имени пользователя.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Revocation {
    /// Какое устройство.
    pub device_id: [u8; 16],
}

/// Наибольшее число неотвеченных просьб.
///
/// Предел, а не «сколько попросят»: терминал спрашивает по нажатию человека,
/// и шестьдесят четыре неотвеченных означают, что телефон молчит, а не что
/// человек так быстро нажимает. Без предела набор идентификаторов рос бы,
/// пока десктоп открыт.
pub const MAX_OUTSTANDING: usize = 64;

/// Окно переписки, которое терминал помнит сам (§13.4).
///
/// **Не источник правды, а то, что показывают, пока правды нет.** Различие
/// не философское: любой ответ телефона заменяет соответствующий кусок
/// целиком, а не сливается с ним. Слияние потребовало бы на десктопе второй
/// копии правил §9.1 о порядке — то есть ровно того, что §13.3 держит ниже
/// границы.
///
/// Пределы — из §13.4 ([`DESKTOP_CACHE_PER_CHAT`]) и из здравого смысла
/// ([`DESKTOP_CACHE_CHATS`], см. там же, почему второй понадобился).
#[derive(Debug, Default, Clone)]
pub struct Cache {
    chats: Vec<ChatSummary>,
    /// История по чатам. Порядок внутри — от старых к новым (§9.1).
    history: BTreeMap<[u8; 16], Vec<Message>>,
    /// Чаты в порядке последнего обращения, свежие в конце.
    ///
    /// Отдельным списком, а не полем в записи: `BTreeMap` упорядочен ключом,
    /// а вытеснять надо по времени касания.
    touched: Vec<[u8; 16]>,
    /// Изменилось ли содержимое с последнего снимка.
    ///
    /// Нужен одному: не переписывать файл на диске на каждое движение.
    /// Решение «когда писать» принимает слой выше — у него есть и часы,
    /// и знание о том, закрывают ли окно.
    dirty: bool,
    /// Подтвердил ли телефон эту картинку в нынешней связи.
    ///
    /// С кэшем в памяти это всегда `true` после первого ответа. Значение
    /// поле обретает с дисковым: там оно отвечает на вопрос «показанное —
    /// это то, что есть сейчас, или то, что было, когда ноутбук выключали».
    fresh: bool,
}

impl Cache {
    /// Пустой кэш: ничего не помним, и это честно `fresh = false`.
    #[must_use]
    pub fn new() -> Cache {
        Cache::default()
    }

    /// Подтверждена ли картинка ответом телефона.
    #[must_use]
    pub fn fresh(&self) -> bool {
        self.fresh
    }

    /// Изменилось ли содержимое с последнего снимка.
    #[must_use]
    pub fn dirty(&self) -> bool {
        self.dirty
    }

    /// Что помним про список чатов.
    #[must_use]
    pub fn chats(&self) -> &[ChatSummary] {
        &self.chats
    }

    /// Что помним про историю чата.
    #[must_use]
    pub fn page(&self, chat: &[u8; 16]) -> &[Message] {
        self.history.get(chat).map_or(&[], Vec::as_slice)
    }

    /// Связь пропала: показанное больше не подтверждено.
    ///
    /// Само содержимое остаётся — оно всё ещё лучшее, что у нас есть, —
    /// но помечается как несвежее. Выбросить его значило бы гасить окно
    /// на каждый разрыв.
    fn unconfirm(&mut self) {
        self.fresh = false;
    }

    /// Телефон прислал список чатов.
    fn remember_chats(&mut self, chats: Vec<ChatSummary>) {
        // Чаты, которых больше нет, уносят с собой и свою историю: иначе
        // удалённый контакт остался бы в памяти окна до перезапуска.
        let alive: Vec<[u8; 16]> = chats.iter().map(|c| c.chat).collect();
        self.history.retain(|chat, _| alive.contains(chat));
        self.touched.retain(|chat| alive.contains(chat));
        self.chats = chats;
        self.fresh = true;
        self.dirty = true;
    }

    /// Телефон прислал страницу истории.
    ///
    /// Страница **заменяет** пересекающийся кусок, а не дописывается к нему:
    /// это ответ телефона, и он новее всего, что мы помним.
    ///
    /// `from_start` — просили ли с конца ленты (`before: None`). От этого
    /// зависит смысл **пустого** ответа, и разница не косметическая: пустая
    /// первая страница означает «в чате ничего нет», пустая при листании
    /// назад — «дальше ничего нет», то есть про край, а не про чат. Спутав
    /// их в одну сторону, `/more` в конце ленты гасил бы окно; спутав
    /// в другую — чат, очищенный на телефоне, пока окно было закрыто,
    /// так и остался бы на экране полным.
    fn remember_page(&mut self, chat: [u8; 16], page: Vec<Message>, from_start: bool) {
        self.fresh = true;
        self.dirty = true;
        if page.is_empty() {
            if from_start {
                self.history.remove(&chat);
                self.touched.retain(|known| *known != chat);
            }
            return;
        }
        let known = self.history.entry(chat).or_default();
        known.retain(|old| !page.iter().any(|fresh| fresh.msg_id == old.msg_id));
        known.extend(page);
        known.sort_by_key(|m| (m.wall_ms, m.msg_id));
        Self::trim(known);
        self.touch(chat);
    }

    /// Пришло новое сообщение.
    fn arrived(&mut self, message: Message) {
        let chat = message.chat;
        // Только в тот чат, историю которого мы и так держим. Заводить её
        // на новость значило бы набрать в память по одному сообщению
        // из каждого чата — окно, которое ничем не помогает и не кончается.
        let Some(known) = self.history.get_mut(&chat) else { return };
        self.dirty = true;
        known.retain(|old| old.msg_id != message.msg_id);
        known.push(message);
        known.sort_by_key(|m| (m.wall_ms, m.msg_id));
        Self::trim(known);
        self.touch(chat);
    }

    /// У сообщения сменился набор реакций.
    ///
    /// Заменяется **только** набор, а не сообщение: текст при реакции
    /// не менялся, и переписать его заодно значило бы однажды затереть
    /// правку, разъехавшуюся с реакцией на один шаг.
    fn reacted(&mut self, chat: &[u8; 16], msg_id: &MsgId, reactions: Vec<companion::Reaction>) {
        let Some(known) = self.history.get_mut(chat) else { return };
        if let Some(slot) = known.iter_mut().find(|old| old.msg_id == *msg_id) {
            slot.reactions = reactions;
            self.dirty = true;
        }
    }

    /// Сообщение поправили — заменяем целиком.
    fn edited(&mut self, message: Message) {
        let Some(known) = self.history.get_mut(&message.chat) else { return };
        if let Some(slot) = known.iter_mut().find(|old| old.msg_id == message.msg_id) {
            *slot = message;
            self.dirty = true;
        }
    }

    /// У вложения сдвинулся приём на телефоне.
    ///
    /// Ищется по **всем** чатам, а не в открытом: новость про вложение
    /// приходит и тогда, когда человек смотрит в другой разговор, а помним
    /// мы оба. Не поправив, мы показали бы при возврате в чат старую цифру
    /// — и «идёт приём» выглядело бы как «зависло».
    ///
    /// Согласие приезжает вместе с числами, а не выводится из них. Выводить
    /// было бы соблазнительно — «движется, значит принято», — и неверно
    /// ровно в том случае, ради которого пауза и заведена: числа стоят,
    /// а согласия уже нет.
    fn file_progress(&mut self, file_id: &[u8; 16], have_chunks: u64, accepted: bool) {
        for page in self.history.values_mut() {
            for message in page.iter_mut() {
                for file in message.files.iter_mut().filter(|f| f.file_id == *file_id) {
                    file.have_chunks = have_chunks;
                    file.accepted = accepted;
                    self.dirty = true;
                }
            }
        }
    }

    /// Вложения больше нет — убрать из того, что помним.
    ///
    /// Убирается **строка вложения, а не сообщение**: текст при отказе
    /// от файла никуда не делся, и стереть его заодно значило бы унести
    /// подпись к отвергнутой картинке.
    ///
    /// Ищется по всем чатам — как и движение приёма, и по той же причине:
    /// отказаться человек мог, глядя в другой разговор.
    fn file_gone(&mut self, file_id: &[u8; 16]) {
        for page in self.history.values_mut() {
            for message in page.iter_mut() {
                let before = message.files.len();
                message.files.retain(|file| file.file_id != *file_id);
                if message.files.len() != before {
                    self.dirty = true;
                }
            }
        }
    }

    /// Сообщений больше нет.
    fn gone(&mut self, chat: &[u8; 16], msg_ids: &[MsgId]) {
        if let Some(known) = self.history.get_mut(chat) {
            known.retain(|old| !msg_ids.contains(&old.msg_id));
        }
        // Строка под именем в списке чатов могла показывать стёртое.
        // Точного нового текста у нас нет — его знает телефон, — но и врать
        // нельзя: чистим до следующего ответа.
        if let Some(summary) = self.chats.iter_mut().find(|c| c.chat == *chat) {
            summary.last_text = String::new();
        }
        self.dirty = true;
    }

    /// Отмечает, что в чат заглядывали, и вытесняет самый забытый.
    fn touch(&mut self, chat: [u8; 16]) {
        self.touched.retain(|known| *known != chat);
        self.touched.push(chat);
        while self.touched.len() > DESKTOP_CACHE_CHATS {
            let evicted = self.touched.remove(0);
            self.history.remove(&evicted);
        }
    }

    /// Собирает содержимое в значение §6 — то, что ляжет на диск.
    fn to_value(&self) -> Value {
        let history = self
            .history
            .iter()
            .map(|(chat, page)| {
                Value::Map(vec![
                    (Value::Integer(SNAP_KEY_CHAT.into()), Value::Bytes(chat.to_vec())),
                    (
                        Value::Integer(SNAP_KEY_PAGE.into()),
                        Value::Array(page.iter().map(companion::message_value).collect()),
                    ),
                ])
            })
            .collect();
        Value::Map(vec![
            (Value::Integer(SNAP_KEY_VERSION.into()), Value::Integer(SNAP_VERSION.into())),
            (
                Value::Integer(SNAP_KEY_CHATS.into()),
                Value::Array(self.chats.iter().map(companion::chat_value).collect()),
            ),
            (Value::Integer(SNAP_KEY_HISTORY.into()), Value::Array(history)),
        ])
    }

    /// Поднимает содержимое из значения.
    ///
    /// **`fresh` остаётся ложным**, и в этом весь смысл поля: поднятое
    /// с диска — это то, что было, когда окно закрывали, а не то, что есть
    /// сейчас. Сообщение, стёртое на телефоне за это время, лежит в файле
    /// целым, и показать его без пометки значило бы соврать (§14).
    fn from_value(value: &Value) -> Result<Cache, CacheError> {
        let map = canonical::as_map(value)?;
        if canonical::as_u64(canonical::require(map, SNAP_KEY_VERSION)?)? != SNAP_VERSION {
            return Err(CacheError::Version);
        }

        let Value::Array(chats) = canonical::require(map, SNAP_KEY_CHATS)? else {
            return Err(ratatosk_codec::CodecError::TypeMismatch.into());
        };
        let Value::Array(entries) = canonical::require(map, SNAP_KEY_HISTORY)? else {
            return Err(ratatosk_codec::CodecError::TypeMismatch.into());
        };

        let mut cache = Cache::new();
        for chat in chats {
            cache.chats.push(companion::chat_from_value(chat)?);
        }
        for entry in entries {
            let entry = canonical::as_map(entry)?;
            let chat = canonical::as_array::<16>(canonical::require(entry, SNAP_KEY_CHAT)?)?;
            let Value::Array(page) = canonical::require(entry, SNAP_KEY_PAGE)? else {
                return Err(ratatosk_codec::CodecError::TypeMismatch.into());
            };
            let mut messages = Vec::with_capacity(page.len());
            for message in page {
                messages.push(companion::message_from_value(message)?);
            }
            // Пределы применяются и на чтении: файл мог быть записан сборкой
            // с другими числами, а верить размеру из файла в вопросе «сколько
            // держать в памяти» нельзя — это тот же чужой ввод.
            Self::trim(&mut messages);
            cache.history.insert(chat, messages);
            cache.touch(chat);
        }
        Ok(cache)
    }

    /// Оставляет не больше [`DESKTOP_CACHE_PER_CHAT`] последних сообщений.
    fn trim(page: &mut Vec<Message>) {
        if page.len() > DESKTOP_CACHE_PER_CHAT {
            page.drain(..page.len() - DESKTOP_CACHE_PER_CHAT);
        }
    }
}

/// Ключи полей снимка. Едут на диск — менять нельзя.
const SNAP_VERSION: u64 = 1;
const SNAP_KEY_VERSION: u64 = 1;
const SNAP_KEY_CHATS: u64 = 2;
const SNAP_KEY_HISTORY: u64 = 3;
const SNAP_KEY_CHAT: u64 = 4;
const SNAP_KEY_PAGE: u64 = 5;

/// Почему снимок кэша не сложился.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum CacheError {
    /// Снимок не собрался или не разобрался.
    #[error("снимок кэша: {0}")]
    Codec(#[from] ratatosk_codec::CodecError),
    /// Не расшифровался.
    ///
    /// Означает одно из трёх: файл от другого сопряжения, файл испорчен,
    /// файл подменили. Различать их незачем — читать нечего во всех трёх
    /// случаях, и правильное действие одно: начать с пустого кэша.
    #[error("снимок кэша не расшифровался")]
    Sealed,
    /// Снимок другой версии.
    ///
    /// Не ошибка и не повод показывать что-то человеку: формат менялся,
    /// прежний файл читать нечем. Терминал начинает с пустого — переписка
    /// живёт на телефоне, и перечитать её стоит одного круга по сети.
    #[error("снимок кэша другой версии")]
    Version,
}

/// Что случилось у терминала — для показа человеку.
///
/// Отдельный набор, а не [`crate::io::Event`], и это не дублирование:
/// у десктопа нет ни контактов, ни транспортов, ни доставки. Ему есть что
/// сказать ровно про то, что он умеет: связь, ответы на просьбы и новости
/// с телефона.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ClientEvent {
    /// Сессия с телефоном установлена.
    Linked,
    /// Каким проводом говорит телефон (§13.4).
    ///
    /// **Показывать обязательно, когда стороны разошлись.** Кодек здесь
    /// прощающий: полей, которых нет, он не требует, — и телефон постарше
    /// присылает сообщения без вложений и без реакций. Выглядит это в точности
    /// как поломка десктопа, и молчать о том, что показ неполон, §14
    /// не разрешает.
    ///
    /// `theirs` — `None`, когда телефон не понял самой просьбы: значит его
    /// сборка старее той, в которой версии появились.
    Wire {
        /// Что назвал телефон. `None` — не назвал ничего.
        theirs: Option<u32>,
        /// Что здесь.
        ours: u32,
    },
    /// Канала больше нет.
    ///
    /// Это **не** «телефон сломался», и разница существенна для §14, пункт 5:
    /// пока телефона нет в сети, десктоп не работает, и сказать об этом надо
    /// словами, а не пустым экраном.
    Unlinked,
    /// Список чатов.
    ///
    /// `fresh` отвечает на вопрос, который иначе задать нечем: это то, что
    /// есть **сейчас**, или то, что мы помним с прошлого раза? Показывать
    /// одно вместо другого без пометки — тот же врущий экран, из-за которого
    /// заведены новости об исчезновении, только переживающий перезагрузку.
    Chats {
        /// Чаты.
        chats: Vec<ChatSummary>,
        /// Подтверждено телефоном в нынешней связи.
        fresh: bool,
    },
    /// Страница истории.
    History {
        /// Какого чата.
        ///
        /// Едет вместе со страницей, потому что пустую страницу иначе
        /// не к чему отнести: сообщений в ней нет, а `chat` у каждого
        /// сообщения — единственное, откуда чат был бы виден.
        chat: [u8; 16],
        /// Сообщения, от старых к новым (§9.1).
        page: Vec<Message>,
        /// Подтверждено телефоном в нынешней связи.
        fresh: bool,
    },
    /// Пришло сообщение: принятое или своё, отправленное с телефона.
    Arrived(Message),
    /// У сообщения сменился статус доставки (§9.4).
    Status {
        /// Какого.
        msg_id: MsgId,
        /// Новый код статуса.
        status: u8,
    },
    /// Список чатов изменился — надо перечитать.
    ChatsChanged,
    /// Этих сообщений больше нет: стёрты, отозваны или унесены очисткой.
    ///
    /// **Убрать с экрана обязательно.** Без этого человек, стерший сообщение
    /// на телефоне и увидевший, что оно исчезло, продолжал бы видеть его
    /// здесь — то есть второй экран показывал бы то, чего нет (§14).
    Gone {
        /// В каком чате.
        chat: [u8; 16],
        /// Каких сообщений больше нет.
        msg_ids: Vec<MsgId>,
    },
    /// Сообщение поправили — вот оно целиком, на замену прежнему.
    Edited(Message),
    /// Кусок вложения приехал — записать его по этому смещению.
    ///
    /// Номер, а не «дописать в конец»: терминал не обязан складывать куски
    /// подряд, и запись по смещению переживает то, чего дописывание
    /// не переживает, — повтор куска после разрыва.
    FileBytes {
        /// Какого вложения.
        file_id: [u8; 16],
        /// Какой кусок. Смещение — `index * files::CHUNK_BYTES`.
        index: u64,
        /// Открытые байты.
        bytes: Vec<u8>,
    },
    /// Вложение приехало целиком.
    FileDone {
        /// Какое.
        file_id: [u8; 16],
    },
    /// У вложения на **телефоне** сдвинулся приём (§10.2).
    ///
    /// Не путать с [`ClientEvent::FileBytes`]: то про выгрузку сюда, это про
    /// приём у телефона. Порядок между ними обязательный — забрать можно
    /// только то, что телефон уже получил.
    FileProgress {
        /// Какого вложения.
        file_id: [u8; 16],
        /// Сколько кусков у телефона сейчас.
        have_chunks: u64,
        /// Сколько всего.
        chunk_total: u64,
        /// Согласен ли телефон качать его сейчас.
        accepted: bool,
    },
    /// Телефон готов принять кусок отправляемого файла — дайте его.
    ///
    /// **Единственное событие, на которое окно обязано ответить**, и потому
    /// оно здесь, а не в эффектах: байты живут у слоя выше, у терминала нет
    /// ни диска, ни права его читать. Он спрашивает — и ждёт
    /// [`ClientInput::PutChunk`].
    ///
    /// Спрашивается по одному куску, а не «дайте весь файл»: мебибайт
    /// в памяти против гигабайта, и остановиться можно между любыми двумя.
    NeedChunk {
        /// Какого файла — как его назвал телефон.
        file_id: [u8; 16],
        /// Который это файл в списке, отданном [`ClientInput::Send`].
        ///
        /// Слой выше держит пути, а `file_id` придумывает телефон — связать
        /// одно с другим можно только здесь. Без этого номера отправка
        /// нескольких файлов означала бы, что путь ищут по имени, а имена
        /// в одном сообщении вправе совпадать.
        which: u32,
        /// Какой кусок. Смещение — `index * files::CHUNK_BYTES`.
        index: u64,
    },
    /// Файлы выгружены на телефон, и телефон отправил сообщение с ними.
    ///
    /// «Отправил» здесь означает ровно то же, что и для текста: сообщение
    /// легло в историю телефона и встало в очередь §5.4. Дошло ли оно
    /// до собеседника — скажет статус, а не это событие (§14).
    Sent {
        /// Какие файлы уехали — все разом, одним сообщением.
        ///
        /// Порядок тот, в каком их выбрал человек: в нём же они лягут
        /// в сообщение (`ARCHITECTURE.md`, 5бэ).
        file_ids: Vec<[u8; 16]>,
    },
    /// Связь пропала посреди приёма вложения — он ждёт её возвращения.
    ///
    /// **Не отказ, и обрывок с диска убирать не надо.** Записанное остаётся,
    /// продолжение пойдёт с первого недостающего куска. Раньше здесь была
    /// смерть выгрузки: файл стирался, и человеку приходилось качать
    /// мебибайты заново из-за секундной потери сети.
    FetchPaused,
    /// Приём вложения продолжился с того места, где его оборвали.
    FetchResumed {
        /// Сколько кусков уже на диске.
        done: u64,
        /// Сколько их всего.
        total: u64,
    },
    /// Связь пропала посреди отправки — выгрузка ждёт её возвращения.
    ///
    /// **Не отказ.** Выгруженные куски лежат у телефона и никуда не денутся
    /// (`ARCHITECTURE.md`, 5вб), а слой выше обязан держать пути открытыми:
    /// продолжать будем с того же места. Раньше здесь был `Refused` со
    /// словами «файл отправлен не был», и это было правдой лишь наполовину —
    /// четыре выгруженных файла из пяти оставались лежать, а человек читал,
    /// что отправка не состоялась, и начинал заново.
    SendPaused,
    /// Выгрузка продолжается с того места, где её оборвали.
    ///
    /// Показывать стоит: между разрывом и этим мгновением человек видел
    /// «ждёт связи», и молчаливое продолжение он прочтёт как зависание.
    SendResumed {
        /// Сколько файлов телефон уже держит целиком.
        done: u32,
        /// Сколько их всего в сообщении.
        total: u32,
    },
    /// Отправка кончилась ничем и продолжена не будет.
    ///
    /// Отдельно от [`ClientEvent::Refused`], и разница не косметическая:
    /// отказ приходит на **любую** просьбу, в том числе на правку чужого
    /// сообщения посреди выгрузки. Слой выше, освобождавший пути по любому
    /// отказу, ронял этим живую отправку — а `NeedChunk` после этого читать
    /// было нечего, и отправка вставала молча.
    SendStopped {
        /// Почему — словами, для показа человеку.
        why: String,
    },
    /// Выгрузка сюда кончилась ничем и продолжена не будет.
    ///
    /// То же и по той же причине: недописанный файл убирает слой выше,
    /// и делать это по любому отказу телефона нельзя — обрывок исчезал бы
    /// из-за просьбы, к нему не относящейся.
    FetchStopped {
        /// Почему — словами, для показа человеку.
        why: String,
    },
    /// Вложения больше нет: от него отказались, и всё убрано.
    ///
    /// **Убрать строку с экрана обязательно.** Без этого сообщение
    /// превращается в непонятное: строка вложения на месте, показывает
    /// «0/0» и предлагает принять то, чего на телефоне уже нет.
    FileGone {
        /// Какого вложения.
        file_id: [u8; 16],
    },
    /// Превью вложения (§10.3) — или его отсутствие.
    ///
    /// `bytes: None` означает «превью нет», и это ответ, а не отказ: вложение
    /// без картинки — обычное дело. Показывать по этому поводу строку
    /// человеку незачем, нарисовать нечего — и всё.
    ///
    /// Байты **до 32 КиБ**, и это единственное место, где содержимое файла
    /// доезжает до окна целиком. Оправдано размером: тот же путь для куска
    /// в мебибайт был бы гигабайтом копирований на гигабайтный файл.
    FilePreview {
        /// Какого вложения — берётся из просьбы, не из ответа.
        file_id: [u8; 16],
        /// Байты превью, если они есть.
        bytes: Option<Vec<u8>>,
    },
    /// Выгрузка на этот компьютер прекращена — по просьбе человека.
    ///
    /// Отдельно от [`ClientEvent::Refused`], потому что это не отказ телефона
    /// и не беда: человек передумал, и показывать это как ошибку значит
    /// пугать его собственным нажатием. Но и молчать нельзя — недописанный
    /// файл на диске надо убрать, а сделать это может только слой выше.
    FetchCancelled {
        /// Какое вложение.
        file_id: [u8; 16],
    },
    /// У сообщения сменился набор реакций — вот он целиком, на замену прежнему.
    ///
    /// Без этого расхождение было бы тише прочих, но того же рода: реакция,
    /// поставленная или снятая на телефоне, не доходила бы до второго экрана
    /// вовсе, и увидеть её там можно было бы только перечитав чат.
    Reacted {
        /// В каком чате.
        chat: [u8; 16],
        /// На каком сообщении.
        msg_id: MsgId,
        /// Все реакции на нём сейчас. Пустой список — сняли последнюю.
        reactions: Vec<companion::Reaction>,
    },
    /// Сделано, сказать нечего.
    Done,
    /// Просьба не выполнена, и вот почему — словами, для показа человеку.
    ///
    /// Одно событие на два случая: так ответил телефон **или** так решили мы
    /// сами, не сумев даже спросить. Для человека это одно и то же — просьба
    /// не выполнена, и вот причина; разводить их значило бы просить UI
    /// написать два текста об одном.
    Refused(String),
    /// Спросить не у кого: сессии нет.
    ///
    /// Отдельно от [`ClientEvent::Refused`], потому что лечится это иначе
    /// и показывается иначе: не сообщением об ошибке, а состоянием окна —
    /// поле ввода серое, пока телефон не на связи.
    NotLinked,
    /// Кадр пришёл и не понят.
    ///
    /// Не отказ и не повод для тревоги сам по себе: так выглядит и чужой
    /// мусор в эфире, и наша собственная рассинхронизация. Показывать это
    /// человеку не надо — но и молчать в журнале нельзя, иначе «ничего
    /// не приходит» и «приходит непонятное» выглядят одинаково.
    Ignored(&'static str),
}

/// Что терминалу сообщили снаружи.
#[derive(Debug, Clone)]
pub enum ClientInput {
    /// Телефон найден в сети — пора здороваться.
    ///
    /// Идемпотентно, пока связь жива: маяк §5.1 повторяется, и каждый повтор,
    /// заводящий новую сессию, вытеснял бы у телефона предыдущую.
    ///
    /// Начатое, но не законченное рукопожатие повтор **заменяет**, и это
    /// осознанно: ответ мог потеряться, а ждать его вечно означало бы
    /// молчащее окно без выхода. Цена — запоздавший первый ответ, который
    /// не сойдётся с новым эфемерным ключом и уйдёт в журнал.
    Reach,
    /// Пришёл кадр.
    Received(Vec<u8>),
    /// Канал пропал.
    Lost,
    /// Человек за десктопом чего-то хочет.
    Ask(Request),
    /// Забрать вложение целиком.
    ///
    /// Отдельный вход, а не [`ClientInput::Ask`] с просьбой о куске, потому
    /// что это **не одна просьба**, а их последовательность: кусок за куском,
    /// каждый следующий — после приехавшего предыдущего. Оставь мы эту
    /// последовательность окну, каждый клиент писал бы её заново, и первый же
    /// написавший «спрошу все сразу» получил бы кадры вперемешку и файл,
    /// собранный из кусков в неверном порядке (§13.3).
    Fetch {
        /// Какое вложение.
        file_id: [u8; 16],
        /// Сколько в нём кусков — из [`ratatosk_proto::companion::Attachment`].
        chunk_total: u64,
    },
    /// Отправить файл в чат: байты возьмёт терминал, спрашивая по куску.
    ///
    /// Размер называется **до** передачи: телефон обязан проверить правило
    /// §13.4 (файл больше 20 МБ мимо общей сети платит его мобильным
    /// трафиком) прежде, чем гигабайт поедет по проводу.
    Send {
        /// В какой чат.
        chat: [u8; 16],
        /// Файлы — от одного до `MAX_ATTACHMENTS`, в порядке выбора.
        ///
        /// Превью в каждом собирает **клиент**, как и на телефоне: декодер
        /// изображений — большая поверхность атаки, и в процессе, который
        /// держит ключи, ему делать нечего. Терминал везёт готовые байты
        /// и не смотрит внутрь.
        items: Vec<OutgoingItem>,
        /// Подпись к сообщению. Пустая законна.
        text: String,
    },
    /// Вот кусок, который просили [`ClientEvent::NeedChunk`].
    PutChunk {
        /// Какой кусок.
        index: u64,
        /// Открытые байты. Шифрует телефон: ключ файла границу
        /// не пересекает (§13.4).
        bytes: Vec<u8>,
    },
    /// Передумал отправлять: выгруженное на телефоне выбросить.
    CancelSend,
    /// Прекратить выгрузку на этот компьютер.
    ///
    /// **По проводу не уходит ничего, и в этом всё устройство.** У телефона
    /// состояния выгрузки нет: каждый кусок — отдельная просьба, отвечаемая
    /// и забываемая. Прекратить — значит перестать просить следующий, и права
    /// на это у десктопа столько же, сколько на первую просьбу.
    ///
    /// Уже отправленная просьба может ещё вернуться ответом; он будет
    /// отброшен как «кусок без начатой выгрузки» — то есть лишний кадр,
    /// и ничего больше.
    CancelFetch,
}

/// Что терминал просит сделать снаружи.
#[derive(Debug, Clone)]
pub enum ClientEffect {
    /// Отправить кадр телефону.
    Send(Vec<u8>),
    /// Показать человеку.
    Show(ClientEvent),
}

/// Десктоп как терминал к телефону (§13.4).
///
/// Sans-io, как и [`crate::engine::Engine`], и по той же причине (§13.3):
/// ни сокетов, ни часов, ни хранилища внутри — вход, состояние, эффекты.
///
/// **`step` не возвращает `Result`, и это правило, а не упрощение.** У шага
/// терминала нет исхода «отказ»: всё, что не сложилось, — событие для
/// человека. Испорченный кадр, ответ не на ту просьбу, просьба без связи —
/// каждое из этого либо показывается, либо уходит в журнал, но ни одно
/// не имеет права остановить окно, в котором человек печатает.
pub struct CompanionClient {
    /// Статический ключ, выведенный из зерна приглашения.
    ///
    /// Он же — адрес десктопа на проводе: телефон узнаёт своё устройство
    /// по нему, и от него же десктоп объявляется маяком в локальной сети
    /// (§5.1), иначе телефон не смог бы его набрать.
    identity: Identity,
    /// `IK` телефона — кому звонить.
    phone_ik: [u8; 32],
    /// Onion-адрес телефона из приглашения. Пустая строка — Tor не поднят.
    phone_onion: String,
    /// Как телефон зовут — чтобы окно называлось.
    phone_name: String,
    pending: Option<PendingHandshake>,
    session: Option<Session>,
    /// Есть ли сейчас канал. Не то же, что наличие сессии: сессия — ключи,
    /// канал — сокет.
    connected: bool,
    next_id: u64,
    /// Неотвеченные просьбы — **вместе с тем, о чём спрашивали**.
    ///
    /// Не набор номеров, а карта: ответ обязан знать свой вопрос. Без этого
    /// страницу истории некуда положить — `Response::History` не несёт чата,
    /// и у пустой страницы его взять негде.
    outstanding: BTreeMap<u64, Request>,
    cache: Cache,
    /// Номер просьбы [`Request::Hello`], пока на неё не ответили.
    ///
    /// Существует ради ответа **молчанием**: телефон постарше просьбы
    /// не понимает и не отвечает вовсе. Ловится это порядком — `Hello`
    /// уходит первым, и ответ с бо́льшим номером означает, что до него
    /// очередь дошла, а до нашего не дойдёт никогда.
    hello: Option<u64>,
    /// Отправка файла на телефон, если она идёт. Одна за раз — как и приём.
    ///
    /// Обратное направление той же дороги, и состояние такое же: чей файл,
    /// сколько кусков, какой следующий. Разница в том, что здесь очередным
    /// шагом движет **не** приехавший кусок, а подтверждение телефона: он
    /// один знает, лёг ли предыдущий.
    upload: Option<Upload>,
    /// Выгрузка вложения, если она идёт. Одна за раз.
    ///
    /// **Одна, а не сколько попросят**, и это не упрощение. Кусок — мебибайт,
    /// то есть целый кадр класса L; две выгрузки разом заняли бы канал
    /// вдвое, а телефон — вдвойне (расшифровка идёт в его цикле). Человек
    /// от этого не выигрывает ничего: суммарное время то же, а переписка
    /// в это время идёт медленнее. Вторая просьба отвечается словами.
    download: Option<Download>,
    entropy: Box<dyn Entropy>,
}

/// Текст, который просьба везёт человеку, — если она его везёт.
///
/// Отдельной функцией, чтобы предел проверялся одним местом: видов просьбы
/// с текстом пять, и пятикратно повторённое правило разойдётся на шестом.
fn text_of(request: &Request) -> Option<&str> {
    match request {
        Request::SendText { text, .. }
        | Request::SendReply { text, .. }
        | Request::EditMessage { text, .. }
        | Request::FileSend { text, .. } => Some(text),
        // Эмодзи со своим пределом (§9.6) — проверяет его телефон,
        // и второе число здесь разошлось бы с первым.
        Request::SetReaction { .. } => None,
        _ => None,
    }
}

/// Один файл в очереди на отправку — то, что о нём знает терминал.
///
/// Байтов здесь нет: их даёт слой выше по просьбе [`ClientEvent::NeedChunk`].
#[derive(Debug, Clone)]
pub struct OutgoingItem {
    /// Имя для показа. **Не путь**: по проводу едет то, что покажут человеку.
    pub name: String,
    /// Сколько байт. Называется до передачи — правило §13.4 телефон
    /// проверяет прежде, чем гигабайт поедет по проводу.
    pub size_bytes: u64,
    /// Превью до 32 КиБ (§10.3), если слой выше его собрал.
    pub preview: Option<Vec<u8>>,
}

/// Отправка сообщения с вложениями — состояние последовательности просьб.
///
/// **Файлы выгружаются по одному, а сообщение получается одно.** Иначе
/// и нельзя: место под файл отводит телефон, и до его ответа неизвестен
/// даже идентификатор. Поэтому здесь очередь, а не набор.
#[derive(Debug, Clone)]
struct Upload {
    /// В какой чат — понадобится только для отказа словами.
    chat: [u8; 16],
    /// Файлы в порядке, в каком их выбрал человек. Порядок несущий:
    /// в нём же они лягут в сообщение (`ARCHITECTURE.md`, 5бэ).
    items: Vec<OutgoingItem>,
    /// Который сейчас выгружается — индекс в `items`.
    at: usize,
    /// Что телефон уже завёл: по идентификатору на каждый начатый файл,
    /// в том же порядке. Третий шаг называет их все разом.
    ids: Vec<[u8; 16]>,
    /// Какой кусок текущего файла отправляем следующим.
    next: u64,
    /// Сколько кусков у текущего файла.
    total: u64,
    /// Подпись к сообщению. Ждёт здесь третьего шага: с версии провода 8
    /// она едет с `FileSend`, а не с предложением, — потому что принадлежит
    /// **сообщению**, а сообщение рождается на третьем шаге.
    text: String,
    /// Связь оборвалась, и выгрузка ждёт: просьбы в пути больше нет,
    /// продолжать нельзя, пока телефон не скажет, что у него осталось.
    stalled: bool,
}

impl Upload {
    /// Идентификатор файла, который выгружается сейчас.
    fn current(&self) -> Option<[u8; 16]> {
        self.ids.get(self.at).copied()
    }
}

/// С чего продолжать прерванную выгрузку.
///
/// Два случая, и путать их нельзя: у одного место на телефоне уже есть
/// и нужен кусок, у другого места нет и нужно предложение. Различать их
/// по «числу кусков, равному нулю» было бы можно — пустой файл дырок
/// не имеет, — но это правило пришлось бы помнить наизусть.
#[derive(Debug, Clone, Copy)]
enum Resume {
    /// Файл заведён, но не полон: просить кусок `index` из `total`.
    Hole { at: usize, index: u64, total: u64 },
    /// Файла у телефона нет: заводить место заново.
    Fresh { at: usize },
}

/// Выгрузка вложения на десктоп — состояние последовательности просьб.
#[derive(Debug, Clone, Copy)]
struct Download {
    file_id: [u8; 16],
    /// Какой кусок ждём. Он же — точка продолжения после разрыва: куски
    /// просятся строго по порядку, и записанное на диск кончается ровно
    /// перед ним (§10.2).
    next: u64,
    /// Сколько всего.
    total: u64,
    /// Связь оборвалась, и выгрузка ждёт: просьбы в пути больше нет,
    /// а записанное на диске остаётся и переписываться не будет.
    stalled: bool,
}

impl core::fmt::Debug for CompanionClient {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        // Своя реализация, потому что внутри ключи. Производный `Debug`
        // вынес бы статический ключ сопряжения в журнал десктопа целиком.
        f.debug_struct("CompanionClient")
            .field("phone", &self.phone_name)
            .field("connected", &self.connected)
            .field("linked", &self.session.is_some())
            .field("outstanding", &self.outstanding.len())
            .finish()
    }
}

impl CompanionClient {
    /// Собирает терминал из ссылки сопряжения.
    ///
    /// Зерно превращается в статический ключ здесь и только здесь: телефон
    /// сделал то же самое у себя, и обе стороны получают один и тот же
    /// публичный ключ, не договариваясь о формате байтов (§13.4, а также
    /// `ARCHITECTURE.md`, 5ба).
    #[must_use]
    pub fn from_invite(invite: &PairingInvite, entropy: Box<dyn Entropy>) -> CompanionClient {
        CompanionClient {
            identity: Identity::from_seed(*invite.secret.as_bytes()),
            phone_ik: invite.ik,
            phone_onion: invite.onion.clone(),
            phone_name: invite.display_name.clone(),
            pending: None,
            session: None,
            connected: false,
            next_id: 1,
            outstanding: BTreeMap::new(),
            cache: Cache::new(),
            hello: None,
            download: None,
            upload: None,
            entropy,
        }
    }

    /// Свой ключ сопряжения — им десктоп объявляется в эфире (§5.1).
    #[must_use]
    pub fn ik(&self) -> [u8; 32] {
        self.identity.public().ik
    }

    /// Как эта запись называется на телефоне.
    #[must_use]
    pub fn device_id(&self) -> DeviceId {
        companion::device_id(&self.ik())
    }

    /// `IK` телефона — кому звонить.
    #[must_use]
    pub fn phone_ik(&self) -> [u8; 32] {
        self.phone_ik
    }

    /// Onion-адрес телефона. Пустая строка — его нет.
    #[must_use]
    pub fn phone_onion(&self) -> &str {
        &self.phone_onion
    }

    /// Как телефон зовут.
    #[must_use]
    pub fn phone_name(&self) -> &str {
        &self.phone_name
    }

    /// Что терминал помнит сам (§13.4).
    ///
    /// Отдаётся наружу, потому что записывать его на диск — дело слоя выше
    /// (§13.3): у самого терминала нет ни файлов, ни решения о том, хочет ли
    /// человек оставлять переписку на этой машине.
    #[must_use]
    pub fn cache(&self) -> &Cache {
        &self.cache
    }

    /// Запечатанный снимок кэша — то, что кладут на диск (§13.4).
    ///
    /// **Диска у терминала нет, и в этом весь смысл границы.** Он отдаёт
    /// готовые байты, а куда их положить и класть ли вообще — решает слой
    /// выше. Там же живёт и выбор человека: не хочет оставлять переписку
    /// на этой машине — снимок просто никто не спрашивает, и никакого
    /// второго режима внутри терминала для этого не нужно.
    ///
    /// **Что это шифрование даёт, а чего нет.** Ключ выводится из зерна
    /// сопряжения (`labels::COMPANION_CACHE`), а зерно десктоп обязан
    /// хранить открыто — иначе он не переподключится без пароля. Значит
    /// ключ лежит рядом с кэшем: защита получается от скопированного файла
    /// и от попадания в бэкап, но **не** от забранного профиля или машины.
    /// Написать это человеку рядом с переключателем обязательно (§14).
    ///
    /// `&mut self`, потому что снимок снимает признак «изменилось»: после
    /// него терминал и файл сходятся, и звать снова до следующей правки
    /// незачем.
    ///
    /// # Errors
    ///
    /// Отказ кодирования или AEAD — в обоих случаях снимок не получился,
    /// и записывать нечего.
    pub fn snapshot(&mut self) -> Result<Vec<u8>, CacheError> {
        let bytes = canonical::encode(&self.cache.to_value())?;
        let key = self.cache_key();
        let sealed = ratatosk_crypto::storage_key::seal_field(&key, &self.cache_aad(), &bytes)
            .map_err(|_| CacheError::Sealed)?;
        self.cache.dirty = false;
        Ok(sealed)
    }

    /// Поднимает кэш из снимка.
    ///
    /// Поднятое помечено неподтверждённым: это то, что было, когда окно
    /// закрывали. Сообщение, стёртое на телефоне за это время, лежит в файле
    /// целым — и снимет его первый же ответ телефона, а до тех пор человек
    /// обязан видеть, что смотрит на память, а не на сейчас.
    ///
    /// # Errors
    ///
    /// [`CacheError::Sealed`] — файл от другого сопряжения, испорчен или
    /// подменён; [`CacheError::Version`] — записан другой сборкой.
    /// Правильное действие во всех случаях одно: начать с пустого кэша,
    /// переписка живёт на телефоне.
    pub fn restore(&mut self, sealed: &[u8]) -> Result<(), CacheError> {
        let key = self.cache_key();
        let bytes = ratatosk_crypto::storage_key::open_field(&key, &self.cache_aad(), sealed)
            .map_err(|_| CacheError::Sealed)?;
        self.cache = Cache::from_value(&canonical::decode(&bytes)?)?;
        Ok(())
    }

    /// Ключ, которым запечатан снимок.
    fn cache_key(&self) -> [u8; 32] {
        *ratatosk_crypto::kdf::derive(
            ratatosk_crypto::labels::COMPANION_CACHE,
            self.identity.backup_seed(),
        )
    }

    /// Привязка снимка к своему сопряжению.
    ///
    /// Без неё файл от одного сопряжения расшифровался бы ключом другого —
    /// ключи-то разные, но перепутать файлы между каталогами проще, чем
    /// кажется, и «чужая переписка в моём окне» хуже, чем «файл не читается».
    fn cache_aad(&self) -> Vec<u8> {
        let mut aad = b"companion.cache:".to_vec();
        aad.extend_from_slice(&self.device_id());
        aad
    }

    /// Есть ли сейчас живая сессия.
    #[must_use]
    pub fn linked(&self) -> bool {
        self.session.is_some() && self.connected
    }

    /// Обрабатывает один вход.
    #[must_use]
    pub fn step(&mut self, now_ms: u64, input: ClientInput) -> Vec<ClientEffect> {
        match input {
            ClientInput::Reach => self.reach(),
            ClientInput::Received(frame) => self.on_frame(now_ms, &frame),
            ClientInput::Lost => self.on_lost(),
            ClientInput::Ask(request) => self.on_ask(&request),
            ClientInput::Fetch { file_id, chunk_total } => self.on_fetch(file_id, chunk_total),
            ClientInput::CancelFetch => self.on_cancel_fetch(),
            ClientInput::Send { chat, items, text } => self.on_send(chat, items, text),
            ClientInput::PutChunk { index, bytes } => self.on_put_chunk(index, bytes),
            ClientInput::CancelSend => self.on_cancel_send(),
        }
    }

    /// Человек выбрал файлы к отправке.
    fn on_send(
        &mut self,
        chat: [u8; 16],
        items: Vec<OutgoingItem>,
        text: String,
    ) -> Vec<ClientEffect> {
        if self.upload.is_some() {
            return vec![ClientEffect::Show(ClientEvent::Refused(
                "одно сообщение за раз — дождитесь конца или отмените".to_owned(),
            ))];
        }
        if items.is_empty() {
            return vec![ClientEffect::Show(ClientEvent::Refused(
                "отправлять нечего: файлы не выбраны".to_owned(),
            ))];
        }
        if items.len() > companion::MAX_ATTACHMENTS {
            return vec![ClientEffect::Show(ClientEvent::Refused(format!(
                "больше {} вложений в одно сообщение не кладётся (§10)",
                companion::MAX_ATTACHMENTS
            )))];
        }
        // **Пределы превью проверяются здесь, а не только на телефоне**, и это
        // не дублирование нижнего слоя. Телефон непонятую просьбу отбрасывает
        // молча — так устроено узнавание старой сборки (5бр), — и превью
        // на байт больше предела ушло бы в тишину: человек нажал «отправить»,
        // не произошло ничего, объяснения нет.
        //
        // Проверка провода при этом остаётся: она про то, чтобы чужой десктоп
        // не заставил телефон принять что попало. Эта — про то, чтобы свой
        // человек узнал причину. Разные вопросы, и оба нужны.
        //
        // Проверяются **все** до первой просьбы: узнать про негодное третье
        // превью после того, как два файла уже уехали, — худший из порядков.
        for item in &items {
            if let Some(preview) = &item.preview {
                if !ratatosk_proto::files::preview_fits(preview.len()) {
                    return vec![ClientEffect::Show(ClientEvent::Refused(format!(
                        "превью у «{}» больше {} байт — телефон такое не примет (§10.3)",
                        item.name,
                        ratatosk_proto::files::PREVIEW_LIMIT_BYTES
                    )))];
                }
            }
        }

        // Место занимается **до** ответа телефона: между просьбой и ответом
        // человек успевает нажать второй раз, и две выгрузки, начатые
        // на одном экране, разошлись бы номерами кусков.
        let first = items[0].clone();
        self.upload = Some(Upload {
            chat,
            items,
            at: 0,
            ids: Vec::new(),
            next: 0,
            total: 0,
            text,
            stalled: false,
        });
        let effects = self.on_ask(&Request::FileOffer {
            chat,
            name: first.name,
            size_bytes: first.size_bytes,
            preview: first.preview,
        });
        if !effects.iter().any(|effect| matches!(effect, ClientEffect::Send(_))) {
            self.upload = None;
        }
        effects
    }

    /// Текущий файл выгружен целиком: перейти к следующему или отправлять.
    ///
    /// Одно место на оба конца очереди — и пустого файла, и последнего куска.
    /// Разложенное по двум оно разошлось бы на первой же правке.
    fn advance_upload(&mut self) -> Vec<ClientEffect> {
        let Some(upload) = self.upload.as_mut() else {
            return vec![ClientEffect::Show(ClientEvent::Ignored("продвигать нечего"))];
        };
        upload.at += 1;
        if let Some(next) = upload.items.get(upload.at).cloned() {
            let chat = upload.chat;
            return self.on_ask(&Request::FileOffer {
                chat,
                name: next.name,
                size_bytes: next.size_bytes,
                preview: next.preview,
            });
        }
        let (file_ids, text) = (upload.ids.clone(), upload.text.clone());
        self.on_ask(&Request::FileSend { file_ids, text })
    }

    /// Слой выше принёс кусок.
    fn on_put_chunk(&mut self, index: u64, bytes: Vec<u8>) -> Vec<ClientEffect> {
        let Some(upload) = self.upload.clone() else {
            return vec![ClientEffect::Show(ClientEvent::Ignored("кусок без начатой отправки"))];
        };
        // Кусок, прочитанный до разрыва и принесённый после него. Отправлять
        // его нельзя: с какого места продолжать, скажет телефон, и до его
        // ответа номер куска — из прошлой жизни связи.
        if upload.stalled {
            return vec![ClientEffect::Show(ClientEvent::Ignored("кусок в ждущую отправку"))];
        }
        if index != upload.next {
            return vec![ClientEffect::Show(ClientEvent::Ignored("кусок не тот, который просили"))];
        }
        let Some(file_id) = upload.current() else {
            return vec![ClientEffect::Show(ClientEvent::Ignored("кусок до ответа телефона"))];
        };
        let effects = self.on_ask(&Request::FilePut { file_id, index, bytes });
        if !effects.iter().any(|effect| matches!(effect, ClientEffect::Send(_))) {
            self.upload = None;
        }
        effects
    }

    /// Человек передумал отправлять.
    fn on_cancel_send(&mut self) -> Vec<ClientEffect> {
        let Some(upload) = self.upload.take() else {
            return vec![ClientEffect::Show(ClientEvent::Ignored("отменять нечего"))];
        };
        // Телефону сказать **надо**, в отличие от прекращения приёма сюда:
        // там у него состояния нет, здесь есть — выгруженные куски лежат
        // в его хранилище и сами не денутся.
        //
        // И сказать про **каждый** начатый файл: брошенная на третьем из пяти
        // отправка оставила бы два занятых места из десяти, а освободила бы
        // их только уборка сирот — то есть не скоро.
        let mut effects = Vec::new();
        for file_id in upload.ids {
            effects.extend(self.on_ask(&Request::FileAbort { file_id }));
        }
        effects
    }

    /// Человек прекратил выгрузку.
    fn on_cancel_fetch(&mut self) -> Vec<ClientEffect> {
        match self.download.take() {
            Some(download) => {
                vec![ClientEffect::Show(ClientEvent::FetchCancelled { file_id: download.file_id })]
            }
            // Не отказ и не ошибка: человек мог нажать дважды или после конца.
            // Молчать при этом нельзя — иначе «не сработало» и «уже нечего
            // прекращать» выглядят одинаково.
            None => vec![ClientEffect::Show(ClientEvent::Ignored("прекращать нечего"))],
        }
    }

    /// Начинает выгрузку вложения.
    fn on_fetch(&mut self, file_id: [u8; 16], chunk_total: u64) -> Vec<ClientEffect> {
        if self.download.is_some() {
            return vec![ClientEffect::Show(ClientEvent::Refused(
                "одно вложение за раз — дождитесь конца или отключитесь".to_owned(),
            ))];
        }
        if chunk_total == 0 {
            // Не отказ ядра и не ошибка: у вложения нулевой длины забирать
            // нечего. Но и «готово» тут сказать нельзя — файла не будет.
            return vec![ClientEffect::Show(ClientEvent::Refused(
                "в этом вложении нечего забирать".to_owned(),
            ))];
        }
        self.download = Some(Download { file_id, next: 0, total: chunk_total, stalled: false });
        let effects = self.on_ask(&Request::FileChunk { file_id, index: 0 });
        // Просьба могла не уехать — связи нет, кадр не собрался. Оставить
        // при этом выгрузку «идущей» значило бы запереть её навсегда: второй
        // `Fetch` отвечался бы «одно вложение за раз», а первого нет.
        if !effects.iter().any(|effect| matches!(effect, ClientEffect::Send(_))) {
            self.download = None;
        }
        effects
    }

    /// Здоровается, если ещё не здоровался.
    fn reach(&mut self) -> Vec<ClientEffect> {
        if self.linked() {
            return Vec::new();
        }
        let Ok((message, pending)) = Initiator::start(&self.identity, &self.phone_ik, &[]) else {
            return vec![ClientEffect::Show(ClientEvent::Refused(
                "рукопожатие не собралось: ключ сопряжения не годится".to_owned(),
            ))];
        };

        // Нагрузка пустая, и это не упущение. §8.2 возит в ней карточку
        // отправителя; у терминала карточки нет и быть не может — он не
        // человек в чьём-то списке контактов. Телефон её и не читает: узнав
        // своё устройство по статическому ключу, он идёт другой веткой.
        self.pending = Some(pending);
        let mut nonce = [0u8; ratatosk_wire::NONCE_LEN];
        self.entropy.fill(&mut nonce);
        match frames::handshake(HANDSHAKE_STEP_FIRST, &message, nonce) {
            Ok(frame) => vec![ClientEffect::Send(frame)],
            Err(_) => {
                vec![ClientEffect::Show(ClientEvent::Ignored("кадр рукопожатия не собрался"))]
            }
        }
    }

    /// Канал пропал.
    ///
    /// **Сессия выбрасывается вместе с каналом**, и это осознанно иначе,
    /// чем у телефона с контактом. Там сессия переживает разрыв TCP, потому
    /// что новое рукопожатие может стоить суток почтового круга (§5.3), —
    /// здесь оно стоит одного круга по локальной сети. Зато сберечь сессию
    /// значит однажды отправить просьбу в сессию, которой у телефона больше
    /// нет (переустановили, потеряли базу), и получить в ответ тишину,
    /// неотличимую от «телефон занят». Тишина дороже лишнего рукопожатия.
    fn on_lost(&mut self) -> Vec<ClientEffect> {
        self.pending = None;
        self.outstanding.clear();
        // Помним прежнее, но больше за него не ручаемся.
        self.cache.unconfirm();
        let was = self.session.take().is_some();
        self.connected = false;

        self.hello = None;
        // **Отправка каналу не принадлежит и вместе с ним не умирает.**
        // Выгруженные куски лежат в хранилище телефона и переживают даже его
        // перезапуск (`ARCHITECTURE.md`, 5вб); что именно у него осталось,
        // он скажет на `Request::Staged`, когда связь вернётся. Раньше здесь
        // выгрузка выбрасывалась целиком — с пятью файлами это была потеря
        // четырёх выгруженных ради пятого.
        let mut effects = Vec::new();
        if let Some(upload) = self.upload.as_mut() {
            upload.stalled = true;
            effects.push(ClientEffect::Show(ClientEvent::SendPaused));
        }
        // Приём сюда — то же самое и по той же причине: записанные куски
        // лежат на диске десктопа, продолжать их есть чем, и просить телефон
        // снова с нулевого куска значило бы гонять по сети то, что уже
        // приехало. Точка продолжения — `next`: куски просятся по порядку.
        if let Some(download) = self.download.as_mut() {
            download.stalled = true;
            effects.push(ClientEffect::Show(ClientEvent::FetchPaused));
        }
        if was {
            effects.push(ClientEffect::Show(ClientEvent::Unlinked));
        }
        effects
    }

    /// Человек чего-то хочет.
    ///
    /// Чтение сперва отвечается **из памяти**, и только потом уезжает просьбой:
    /// у терминала уже есть, что показать, и держать окно пустым лишний круг
    /// по сети незачем. Пришедший ответ заменит показанное и снимет пометку.
    ///
    /// Всё остальное так не работает и работать не может: у распоряжений —
    /// отправки, правки, удаления, отзыва, реакции, пересылки, очистки —
    /// нет ответа «из памяти». Есть «сделано» или «нет», и придумать первое
    /// за телефон значило бы соврать (§14). Здесь это выражено веткой `_`,
    /// и она не заглушка: **не отвечать из памяти — умолчание**, а право
    /// на предварительный показ есть ровно у двух чтений.
    fn on_ask(&mut self, request: &Request) -> Vec<ClientEffect> {
        // **Предел текста — здесь, одним местом на все просьбы.** Телефон
        // проверяет его тоже, но непонятую или отвергнутую просьбу он
        // возвращает отказом, а слишком длинный текст до него ещё и может
        // не доехать: кадр не соберётся, и человек получит тишину.
        //
        // Одно место, а не пять: текст едет в пяти видах просьбы, и правило,
        // разложенное по ним, разойдётся на первой же новой.
        if let Some(text) = text_of(request) {
            if !ratatosk_proto::files::text_fits(text.len()) {
                return vec![ClientEffect::Show(ClientEvent::Refused(format!(
                    "текст длиннее {} байт — столько в одно сообщение не влезает",
                    ratatosk_proto::files::MAX_TEXT_BYTES
                )))];
            }
        }
        let mut effects = self.from_cache(request);

        if !self.linked() {
            effects.push(ClientEffect::Show(ClientEvent::NotLinked));
            return effects;
        }
        if self.outstanding.len() >= MAX_OUTSTANDING {
            effects.push(ClientEffect::Show(ClientEvent::Refused(
                "телефон не отвечает на прежние просьбы".to_owned(),
            )));
            return effects;
        }

        let id = self.next_id;
        self.next_id += 1;
        let payload = companion::request_payload(id, request);
        let Some(frame) = self.frame(PayloadType::CompanionRequest, payload) else {
            // **Словами, а не в журнал.** Здесь стояло `Ignored`, и это было
            // молчание в ответ на действие человека: он нажал «отправить»,
            // не произошло ничего, и объяснения нет. §14 запрещает ровно это.
            //
            // Заметным пробел стал вместе с превью: тридцать два килобайта
            // картинки съедают заметную долю кадра, и «не влезло» из редкости
            // превратилось в случай, который человек однажды встретит.
            effects.push(ClientEffect::Show(ClientEvent::Refused(
                "это не поместилось в один кадр — короче подпись или меньше превью".to_owned(),
            )));
            return effects;
        };
        self.outstanding.insert(id, request.clone());
        effects.push(ClientEffect::Send(frame));
        effects
    }

    /// Показывает то, что помним, — если помним хоть что-то.
    fn from_cache(&self, request: &Request) -> Vec<ClientEffect> {
        match request {
            Request::Chats if !self.cache.chats().is_empty() => {
                vec![ClientEffect::Show(ClientEvent::Chats {
                    chats: self.cache.chats().to_vec(),
                    fresh: self.cache.fresh(),
                })]
            }
            // Только первая страница: листание назад — это просьба о том,
            // чего в памяти по построению нет, и подсунуть на неё хвост
            // значило бы показать не то, что попросили.
            Request::History { chat, before: None, .. } if !self.cache.page(chat).is_empty() => {
                vec![ClientEffect::Show(ClientEvent::History {
                    chat: *chat,
                    page: self.cache.page(chat).to_vec(),
                    fresh: self.cache.fresh(),
                })]
            }
            _ => Vec::new(),
        }
    }

    /// Запечатывает нагрузку в кадр сессии.
    fn frame(&mut self, kind: PayloadType, payload: ratatosk_codec::Value) -> Option<Vec<u8>> {
        // Метка часов — нулевая, и это честнее выдуманной. HLC (§9.1) — общий
        // порядок разговора **людей**; терминал в нём не участвует, телефон
        // метку с его кадров не наблюдает, и поставить сюда своё время значило
        // бы показать число, которое ничего не значит и однажды будет принято
        // за что-то.
        let envelope = Envelope::new(self.entropy.msg_id(), Hlc::ZERO, kind, payload);
        let bytes = envelope.encode().ok()?;
        let session = self.session.as_mut()?;
        frames::seal(session, &bytes).ok()
    }

    /// Пришёл кадр.
    fn on_frame(&mut self, now_ms: u64, frame: &[u8]) -> Vec<ClientEffect> {
        let Ok(view) = ratatosk_wire::parse(frame) else {
            return vec![ClientEffect::Show(ClientEvent::Ignored("кадр не разобрался"))];
        };

        if view.header.frame_type == FrameType::Handshake {
            return self.on_handshake(now_ms, view.header.counter, frame);
        }

        let Some(session) = self.session.as_mut() else {
            return vec![ClientEffect::Show(ClientEvent::Ignored("кадр данных без сессии"))];
        };
        let plaintext = match frames::open(session, frame, now_ms) {
            Ok(plaintext) => plaintext,
            // Точный повтор кадра — не беда и не новость: локальная сеть
            // дублирует редко, но молчать об этом в журнале незачем.
            Err(ratatosk_crypto::CryptoError::MessageKeyConsumed) => {
                return vec![ClientEffect::Show(ClientEvent::Ignored("повтор уже принятого кадра"))]
            }
            Err(_) => {
                return vec![ClientEffect::Show(ClientEvent::Ignored("кадр не расшифровался"))]
            }
        };

        let Ok(envelope) = Envelope::decode(&plaintext) else {
            return vec![ClientEffect::Show(ClientEvent::Ignored("конверт не разобрался"))];
        };
        let envelope = envelope.into_parts().1;

        match envelope.payload_type {
            PayloadType::CompanionResponse => self.on_response(&envelope.payload),
            PayloadType::CompanionNotice => self.on_notice(&envelope.payload),
            // Всё остальное телефон терминалу не шлёт. Пришедшее — либо чужая
            // сборка, либо ошибка на той стороне; показывать человеку нечего.
            _ => vec![ClientEffect::Show(ClientEvent::Ignored("не разговор терминала"))],
        }
    }

    fn on_handshake(&mut self, now_ms: u64, step: u64, frame: &[u8]) -> Vec<ClientEffect> {
        if step != HANDSHAKE_STEP_RESPONSE {
            // Первое сообщение рукопожатия терминалу не адресуют: он всегда
            // звонит сам. Пришедшее — не наш разговор.
            return vec![ClientEffect::Show(ClientEvent::Ignored("не тот шаг рукопожатия"))];
        }
        let Ok(message) = frames::handshake_message(frame) else {
            return vec![ClientEffect::Show(ClientEvent::Ignored("кадр рукопожатия испорчен"))];
        };
        let Some(mut pending) = self.pending.take() else {
            return vec![ClientEffect::Show(ClientEvent::Ignored(
                "ответ на рукопожатие, которого не было",
            ))];
        };
        let Ok(session) = pending.finish(&message, now_ms) else {
            return vec![ClientEffect::Show(ClientEvent::Ignored("ответ рукопожатия не сошёлся"))];
        };

        self.session = Some(session);
        self.connected = true;
        self.outstanding.clear();

        // Список чатов спрашивается сразу и самим терминалом, а не окном.
        // Без этого первое, что видит человек после подключения, — пустота,
        // и её пришлось бы разгонять таймером в UI. Заодно снимается вопрос
        // «что делать с просьбой, пока связи нет»: до этого мгновения окно
        // ничего и не просит.
        let mut effects = vec![ClientEffect::Show(ClientEvent::Linked)];
        // **Первым делом — версия провода, и только потом чаты.** Порядок
        // здесь несущий: телефон постарже на `Hello` не ответит вовсе,
        // и узнать об этом можно лишь по тому, что ответ на следующую просьбу
        // пришёл раньше. Спроси мы чаты первыми — ловить было бы нечем.
        let asked = self.on_ask(&Request::Hello);
        if asked.iter().any(|effect| matches!(effect, ClientEffect::Send(_))) {
            // Номер только что выданной просьбы — последний розданный.
            self.hello = Some(self.next_id - 1);
        }
        effects.extend(asked);
        effects.extend(self.on_ask(&Request::Chats));
        // **Спрашиваем только когда есть что продолжать.** Пустая просьба
        // была бы безобидна, но ответ на неё — список чужих незаконченных
        // выгрузок: у телефона может быть второй десктоп, и наше дело
        // не знать о его файлах.
        //
        // Продолжается при этом **только та выгрузка, которую терминал
        // помнит сам**. Свой перезапуск он не переживает, и это нарочно:
        // после него у нас есть лишь имена и размеры, а файл с тем же именем
        // и размером — не тот же файл. Собрать сообщение из вчерашних кусков
        // и сегодняшних — тихая порча, которую человек увидит у собеседника,
        // а не у себя.
        if self.upload.is_some() {
            effects.extend(self.on_ask(&Request::Staged));
        }
        // А приём продолжается **без единого вопроса**: у телефона состояния
        // о нём нет вовсе — он просто отдаёт кусок, который просят. Спрашивать
        // тут нечего, продолжать надо с того, что записано у себя.
        effects.extend(self.resume_fetch());
        effects
    }

    /// Продолжает приём вложения с первого незаписанного куска.
    fn resume_fetch(&mut self) -> Vec<ClientEffect> {
        let Some(download) = self.download else { return Vec::new() };
        if !download.stalled {
            return Vec::new();
        }
        self.download = Some(Download { stalled: false, ..download });
        let mut effects = vec![ClientEffect::Show(ClientEvent::FetchResumed {
            done: download.next,
            total: download.total,
        })];
        let asked =
            self.on_ask(&Request::FileChunk { file_id: download.file_id, index: download.next });
        // Не уехала — значит связь опять пропала между рукопожатием и этой
        // просьбой. Оставляем ждущей: следующий круг попробует снова.
        if !asked.iter().any(|effect| matches!(effect, ClientEffect::Send(_))) {
            if let Some(download) = self.download.as_mut() {
                download.stalled = true;
            }
        }
        effects.extend(asked);
        effects
    }

    /// Телефон постарше продолжать не умеет — сказать об этом словами.
    ///
    /// **Иначе выгрузка ждала бы вечно.** Просьбу `Staged` такой телефон
    /// не понимает и отбрасывает молча (5бр); ждущая её отправка никогда
    /// не сдвинется, а на экране будет «ждёт связи» при живой связи. Версия
    /// приезжает раньше всех прочих ответов, и это единственное место,
    /// где о ней можно узнать до того, как ждать станет нечего.
    ///
    /// `theirs` — `None`, когда телефон не ответил и на `Hello`.
    fn give_up_stalled(&mut self, theirs: Option<u32>) -> Vec<ClientEffect> {
        if !self.upload.as_ref().is_some_and(|upload| upload.stalled) {
            return Vec::new();
        }
        if theirs.is_some_and(|wire| wire >= companion::STAGED_SINCE_WIRE) {
            return Vec::new();
        }
        self.upload = None;
        vec![ClientEffect::Show(ClientEvent::SendStopped {
            why: "телефон постарше и продолжать прерванную отправку не умеет — \
                  отправьте файлы заново"
                .to_owned(),
        })]
    }

    /// Телефон сказал, что у него осталось от прерванной выгрузки.
    ///
    /// **Своё узнаётся по `file_id`, а не по имени с размером.** Терминал
    /// пережил разрыв вместе со своим списком идентификаторов, а телефон
    /// не перенумеровывает выгрузки при перезапуске — значит сличать есть
    /// что точно. Имя с размером понадобилось бы только тому, кто потерял
    /// свою память, а такой и продолжать не вправе (см. `on_linked`).
    fn on_staged(&mut self, files: &[companion::StagedFile]) -> Vec<ClientEffect> {
        let Some(upload) = self.upload.as_mut() else {
            return vec![ClientEffect::Show(ClientEvent::Ignored(
                "ответ о выгрузках без начатой отправки",
            ))];
        };
        if !upload.stalled {
            return vec![ClientEffect::Show(ClientEvent::Ignored(
                "ответ о выгрузках посреди живой отправки",
            ))];
        }
        upload.stalled = false;

        // Первый файл, который придётся доделывать. Идём по **позициям
        // очереди**, а не по выданным идентификаторам: выгрузка
        // последовательна, и позиция, до которой она не дошла, выглядит
        // так же, как та, чей файл телефон потерял, — заводить место надо
        // и там, и там.
        let mut done = 0usize;
        let mut resume = None;
        for at in 0..upload.items.len() {
            let staged = upload
                .ids
                .get(at)
                .and_then(|file_id| files.iter().find(|staged| staged.file_id == *file_id));
            match staged {
                // Целый файл — считаем сделанным и идём дальше.
                Some(staged) if staged.missing.is_empty() => done = at + 1,
                // Дырка: продолжаем с неё. Не с «числа принятых»: куски
                // могли лечь не по порядку, если ответ на `FilePut`
                // потерялся, а следующий дошёл.
                Some(staged) => {
                    resume = Some(Resume::Hole {
                        at,
                        index: staged.missing[0],
                        total: staged.chunk_total,
                    });
                    break;
                }
                // Либо мы до этой позиции не дошли, либо телефон о файле
                // не помнит: его убрал срок (§13.4) или хозяин телефона.
                // В обоих случаях место заводится заново, с первого куска.
                None => {
                    resume = Some(Resume::Fresh { at });
                    break;
                }
            }
        }

        let total = u32::try_from(upload.items.len()).unwrap_or(u32::MAX);
        let mut effects = vec![ClientEffect::Show(ClientEvent::SendResumed {
            done: u32::try_from(done).unwrap_or(u32::MAX),
            total,
        })];

        match resume {
            // Дырка в уже заведённом файле: просим у окна недостающий кусок.
            Some(Resume::Hole { at, index, total }) => {
                upload.at = at;
                upload.next = index;
                upload.total = total;
                let file_id = upload.ids[at];
                let which = u32::try_from(at).unwrap_or(u32::MAX);
                effects.push(ClientEffect::Show(ClientEvent::NeedChunk { file_id, which, index }));
            }
            // Место под файл заводится заново. Хвост списка идентификаторов
            // при этом обрезается: всё, что за этой позицией, телефон завести
            // не успел, а если и успел — эти файлы нам уже не свои.
            Some(Resume::Fresh { at }) => {
                upload.at = at;
                upload.ids.truncate(at);
                let item = upload.items[at].clone();
                let chat = upload.chat;
                effects.extend(self.on_ask(&Request::FileOffer {
                    chat,
                    name: item.name,
                    size_bytes: item.size_bytes,
                    preview: item.preview,
                }));
            }
            // Всё выгружено целиком — осталось отправить. Дорога та же,
            // что у обычного конца очереди: `advance_upload` шагает
            // за последний файл и упирается в `FileSend`.
            None => {
                upload.at = upload.items.len() - 1;
                effects.extend(self.advance_upload());
            }
        }
        effects
    }

    fn on_response(&mut self, payload: &ratatosk_codec::Value) -> Vec<ClientEffect> {
        let Ok((id, response)) = companion::response_from_payload(payload) else {
            return vec![ClientEffect::Show(ClientEvent::Ignored("ответ не разобрался"))];
        };
        // Ответ на просьбу, которой не было, — либо запоздавший после разрыва,
        // либо чужой. В обоих случаях показывать его нельзя: список чатов
        // из прошлой жизни затёр бы нынешний.
        let Some(asked) = self.outstanding.remove(&id) else {
            return vec![ClientEffect::Show(ClientEvent::Ignored(
                "ответ на просьбу, которой не было",
            ))];
        };

        // Ответ с бо́льшим номером, пока не отвечено на `Hello`, — это
        // и есть «телефон старее». Очередь у него одна и в порядке: раз
        // до следующей просьбы очередь дошла, до нашей она не дойдёт.
        let mut earlier = Vec::new();
        if let Some(hello) = self.hello {
            if id > hello {
                self.hello = None;
                self.outstanding.remove(&hello);
                earlier.push(ClientEffect::Show(ClientEvent::Wire {
                    theirs: None,
                    ours: companion::WIRE_VERSION,
                }));
                earlier.extend(self.give_up_stalled(None));
            }
        }

        let shown = match response {
            Response::Hello { wire } => {
                self.hello = None;
                earlier.extend(self.give_up_stalled(Some(wire)));
                ClientEvent::Wire { theirs: Some(wire), ours: companion::WIRE_VERSION }
            }
            Response::Chats(chats) => {
                self.cache.remember_chats(chats);
                ClientEvent::Chats { chats: self.cache.chats().to_vec(), fresh: true }
            }
            Response::History(page) => {
                // Чат берётся из **вопроса**, а не из ответа: у пустой
                // страницы взять его негде, а пустая страница — законный
                // ответ на «дальше ничего нет».
                let Request::History { chat, before, .. } = asked else {
                    return vec![ClientEffect::Show(ClientEvent::Ignored(
                        "история в ответ на другую просьбу",
                    ))];
                };
                self.cache.remember_page(chat, page.clone(), before.is_none());
                ClientEvent::History { chat, page, fresh: true }
            }
            Response::FileOffer { file_id, chunk_total } => {
                let Some(upload) = self.upload.as_mut() else {
                    return vec![ClientEffect::Show(ClientEvent::Ignored(
                        "место под файл, которого не просили",
                    ))];
                };
                upload.ids.push(file_id);
                upload.total = chunk_total;
                upload.next = 0;
                let which = u32::try_from(upload.at).unwrap_or(u32::MAX);
                // Пустой файл — законный файл, и просить у окна кусок,
                // которого нет, нельзя: сразу к следующему.
                if chunk_total == 0 {
                    earlier.extend(self.advance_upload());
                    return earlier;
                }
                ClientEvent::NeedChunk { file_id, which, index: 0 }
            }
            Response::Done => match &asked {
                // Кусок лёг — просим у окна следующий. Движет отправку
                // подтверждение телефона, а не наша уверенность: он один
                // знает, лёг ли предыдущий.
                Request::FilePut { file_id, .. } => {
                    let Some(upload) = self.upload.as_mut() else {
                        return vec![ClientEffect::Show(ClientEvent::Ignored(
                            "подтверждение куска без начатой отправки",
                        ))];
                    };
                    upload.next += 1;
                    let (next, total, file_id) = (upload.next, upload.total, *file_id);
                    let which = u32::try_from(upload.at).unwrap_or(u32::MAX);
                    if next < total {
                        ClientEvent::NeedChunk { file_id, which, index: next }
                    } else {
                        earlier.extend(self.advance_upload());
                        return earlier;
                    }
                }
                Request::FileSend { file_ids, .. } => {
                    let file_ids = file_ids.clone();
                    self.upload = None;
                    ClientEvent::Sent { file_ids }
                }
                Request::FileAbort { .. } => ClientEvent::Done,
                _ => ClientEvent::Done,
            },
            Response::Refused(why) => {
                // Отказ на кусок обрывает выгрузку целиком. Продолжать
                // со следующего значило бы собрать файл с дырой и назвать
                // его готовым — а дыру человек увидит куда позже, чем
                // непришедший файл.
                if matches!(asked, Request::FileChunk { .. }) {
                    self.download = None;
                    return {
                        earlier.push(ClientEffect::Show(ClientEvent::FetchStopped { why }));
                        earlier
                    };
                }
                // Отказ на любом шаге отправки обрывает её целиком: телефон
                // либо не завёл место, либо не принял кусок, либо отказался
                // отправлять неполное, либо не помнит выгрузки вовсе.
                // Продолжать после любого из них значит слать в пустоту.
                //
                // **Событие своё, а не общий отказ.** Слой выше держит пути
                // и обязан их отпустить — но только здесь, а не по любому
                // отказу телефона: отказ приходит и на правку чужого
                // сообщения посреди выгрузки.
                if matches!(
                    asked,
                    Request::FileOffer { .. }
                        | Request::FilePut { .. }
                        | Request::FileSend { .. }
                        | Request::Staged
                ) {
                    self.upload = None;
                    return {
                        earlier.push(ClientEffect::Show(ClientEvent::SendStopped { why }));
                        earlier
                    };
                }
                ClientEvent::Refused(why)
            }
            Response::FileChunk { index, bytes } => {
                earlier.extend(self.on_chunk(&asked, index, bytes));
                return earlier;
            }
            Response::Staged { files } => {
                earlier.extend(self.on_staged(&files));
                return earlier;
            }
            // Про какое вложение — знает вопрос, а не ответ. Превью,
            // приехавшее не на свою просьбу, показать нельзя: картинка
            // от чужого файла хуже отсутствующей.
            Response::FilePreview { bytes } => match &asked {
                Request::FilePreview { file_id } => {
                    ClientEvent::FilePreview { file_id: *file_id, bytes }
                }
                _ => ClientEvent::Ignored("превью в ответ на другую просьбу"),
            },
        };
        earlier.push(ClientEffect::Show(shown));
        earlier
    }

    /// Приехал кусок вложения: записать и попросить следующий.
    ///
    /// Проверяется **и вопрос, и номер**. Номер в ответе телефона и номер,
    /// который мы ждём, обязаны совпасть: кусок, приехавший не на своё место,
    /// собрал бы файл, который выглядит целым и не является им.
    fn on_chunk(&mut self, asked: &Request, index: u64, bytes: Vec<u8>) -> Vec<ClientEffect> {
        let Request::FileChunk { file_id, index: wanted } = asked else {
            return vec![ClientEffect::Show(ClientEvent::Ignored(
                "кусок в ответ на другую просьбу",
            ))];
        };
        let Some(download) = self.download else {
            return vec![ClientEffect::Show(ClientEvent::Ignored("кусок без начатой выгрузки"))];
        };
        // Кусок, отправленный телефоном до разрыва и доехавший после него.
        // Записывать нельзя: продолжение уже назначено с `next`, и лишняя
        // запись сдвинула бы счёт.
        if download.stalled {
            return vec![ClientEffect::Show(ClientEvent::Ignored("кусок в ждущую выгрузку"))];
        }
        if *file_id != download.file_id || index != *wanted || index != download.next {
            return vec![ClientEffect::Show(ClientEvent::Ignored(
                "кусок не того файла или не тот",
            ))];
        }

        let mut effects = vec![ClientEffect::Show(ClientEvent::FileBytes {
            file_id: download.file_id,
            index,
            bytes,
        })];
        let next = index + 1;
        if next >= download.total {
            self.download = None;
            effects.push(ClientEffect::Show(ClientEvent::FileDone { file_id: download.file_id }));
            return effects;
        }

        self.download = Some(Download { next, ..download });
        let asked_next =
            self.on_ask(&Request::FileChunk { file_id: download.file_id, index: next });
        // Просьба не уехала — связь пропала между куском и следующей просьбой.
        // Раньше выгрузка здесь закрывалась; теперь она **ждёт**: записанное
        // на диске никуда не делось, и продолжить его дешевле, чем качать
        // заново. Освобождает место отмена человеком, а не разрыв.
        if !asked_next.iter().any(|effect| matches!(effect, ClientEffect::Send(_))) {
            if let Some(download) = self.download.as_mut() {
                download.stalled = true;
            }
        }
        effects.extend(asked_next);
        effects
    }

    fn on_notice(&mut self, payload: &ratatosk_codec::Value) -> Vec<ClientEffect> {
        let Ok(notice) = companion::notice_from_payload(payload) else {
            return vec![ClientEffect::Show(ClientEvent::Ignored("новость не разобралась"))];
        };
        // Новость правит и то, что помним. Иначе кэш расходился бы с экраном
        // на каждое движение — и первым же перечитыванием показал бы то,
        // чего на телефоне нет.
        vec![ClientEffect::Show(match notice {
            Notice::Message(message) => {
                self.cache.arrived(message.clone());
                ClientEvent::Arrived(message)
            }
            Notice::Status { msg_id, status } => ClientEvent::Status { msg_id, status },
            Notice::ChatsChanged => ClientEvent::ChatsChanged,
            Notice::Gone { chat, msg_ids } => {
                self.cache.gone(&chat, &msg_ids);
                ClientEvent::Gone { chat, msg_ids }
            }
            Notice::Edited(message) => {
                self.cache.edited(message.clone());
                ClientEvent::Edited(message)
            }
            Notice::Reacted { chat, msg_id, reactions } => {
                self.cache.reacted(&chat, &msg_id, reactions.clone());
                ClientEvent::Reacted { chat, msg_id, reactions }
            }
            Notice::FileProgress { file_id, have_chunks, chunk_total, accepted } => {
                self.cache.file_progress(&file_id, have_chunks, accepted);
                ClientEvent::FileProgress { file_id, have_chunks, chunk_total, accepted }
            }
            Notice::FileGone { file_id } => {
                self.cache.file_gone(&file_id);
                // Выгрузка того же вложения, если она шла, кончилась вместе
                // с ним: просить куски файла, которого нет, — верный способ
                // получить отказ на каждый и не понять почему.
                if self.download.is_some_and(|download| download.file_id == file_id) {
                    self.download = None;
                }
                ClientEvent::FileGone { file_id }
            }
        })]
    }
}

