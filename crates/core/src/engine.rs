//! Ядро протокола (§13.3).
//!
//! «В ядре: крипта, протокол, транспорты, хранилище, синхронизация.
//! В клиентах — только UI и системная интеграция. Правило без исключений:
//! никакой протокольной логики выше UniFFI-границы.»
//!
//! [`Engine`] — единственная точка входа. Он не создаёт потоков, не открывает
//! сокетов и не читает часы: время приходит параметром `now_ms`, внешний мир
//! общается с ним через [`Input`] и [`Effect`], случайность — через
//! [`Entropy`].
//!
//! # Что лежит в этом файле, а что в соседних
//!
//! Здесь — **хребет**: типы состояния ([`Engine`], [`Contact`],
//! [`GroupState`]), список отказов [`EngineError`], постройка, читатели
//! полей и развилка [`Engine::step`] → `dispatch` → `on_command`. Всё
//! остальное разложено по подмодулям:
//!
//! | Модуль | О чём |
//! |---|---|
//! | `setup` | транспорты и собственные адреса (§5.1) |
//! | `contacts` | контакты, карточки, аватарки |
//! | `messages` | текст, чтение, правка, отзыв, реакции |
//! | `files` | передача файлов (§10) |
//! | `groups` | состав группы (§11.2, §11.5, §6.7) |
//! | `group_msg` | сообщения и действия в группе (§11.1, §11.3) |
//! | `channels` | каналы фазы 2 (§3–§6) |
//! | `pairing` | сопряжённое устройство (§13.4) |
//! | `delivery` | лестница доставки (§5.4) |
//! | `receive` | приём: от байтов до сообщения |
//! | `presence` | соседство: кого слышно сейчас |
//! | `maintenance` | уборка (§12) |
//! | `views` | читатели для клиента |
//!
//! **Разделение — перенос, а не переделка.** Файл был шестнадцать тысяч
//! строк; рой (очередь 3) сделал бы его двадцатью. Ни одна строка тела
//! при переносе не менялась: единственная правка — видимость, потому что
//! приватность в Rust идёт вниз, и перенесённый метод обязан стать
//! `pub(super)`, чтобы остаться видимым тому же, кто видел его раньше.
//! Сверено списком всех 295 функций до и после.
//!
//! Здесь стояло «область этого этапа — 1:1 текст, файлы и группы ещё
//! не проходят через `step`, ветки помечены `todo!()`». Неправдой это
//! стало задолго до разделения: ни одного `todo!()` в файле давно нет.

