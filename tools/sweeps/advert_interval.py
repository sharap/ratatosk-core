"""Свёртка: у каждого радио объявление называет свой интервал.

Зачем. Интервал объявления — это то, как быстро нас можно набрать:
собеседник обязан сперва услышать объявление, и ждёт он его в среднем
один интервал. Умолчание же у платформ медленное, а предел нашей
попытки набора — восемь секунд (`DIAL_PUBLIC`).

Поломка, по которой свёртка заведена, прожила до первого замера
на устройствах. Android интервал задавал с самого начала
(`ADVERTISE_MODE_BALANCED`, 250 мс), а Linux — нет, и там действовало
умолчание BlueZ. Открытие канала к PinePhone шло 4–8 секунд и дважды
дольше десяти; набор укладывался в срок примерно раз из трёх, а три
неудачи подряд уводили ступень в выдержку на сорок пять секунд.
Снаружи это выглядело как «эфир работает в одну сторону».

То есть одна и та же мысль дошла до одной половины из двух — ровно та
беда, ради которой свёртки и существуют.

Чего свёртка **не** стережёт: ни самого числа (его держит проверка
`the_advert_names_an_interval_fast_enough_for_our_own_dial_budget`),
ни того, что контроллер этот интервал примет, — видно это только
на радио.
"""
import pathlib
import sys

# Корень дерева считается от самого файла, а не от текущего каталога:
# метелку зовут и из корня, и из CI, и по одной из редактора.
ROOT_DIR = pathlib.Path(__file__).resolve().parents[2]

# Радио у ступени два, и у каждого свой способ назвать интервал: у BlueZ
# это поля объявления, у Android — режим. Общего слова у них нет и быть
# не может, поэтому для каждого названо своё — и **место**, где смотреть.
#
# Место обязательно, и это поправка к самой себе. Первая редакция искала
# слово по всему файлу — и смолчала, когда интервал убрали из объявления:
# слово осталось в тексте проверки и в комментарии рядом. Ложная находка
# и ложная зелень лечатся одинаково — сужением правила, а не списком
# исключений.
RADIOS = {
    "crates/transport/src/bluetooth/local.rs": {
        "от": "fn announcement(",
        "до": "\n}\n",
        "слова": ("min_interval", "max_interval"),
    },
    "android/BtRadio.kt": {
        "от": "AdvertiseSettings.Builder()",
        "до": ".build()",
        "слова": ("setAdvertiseMode",),
    },
}

found = []
seen = 0

for where, rule in RADIOS.items():
    path = ROOT_DIR / where
    if not path.exists():
        found.append(f"{where}: радио пропало — свёртка смотрит не туда")
        continue
    seen += 1
    text = path.read_text(encoding="utf-8")
    start = text.find(rule["от"])
    if start < 0:
        found.append(f"{where}: не нашлось место сборки объявления ({rule['от']})")
        continue
    end = text.find(rule["до"], start)
    region = text[start:end if end > 0 else len(text)]
    missing = [word for word in rule["слова"] if word not in region]
    if missing:
        found.append(f"{where}: объявление не называет интервал ({', '.join(missing)})")

for line in found:
    print(line)
print(f"радио осмотрено: {seen}")
print("-- всего", len(found) if found else "чисто")

# Находок должно быть **ноль**.
sys.exit(1 if found else 0)
