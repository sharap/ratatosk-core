//! Поделиться контактом: карточка третьего человека, присланная в чат (§4.1).
//!
//! **Спецификация v0.1 этого не описывает.** Она знает два способа обменяться
//! контактами — QR при личной встрече и ссылка (§4.1, §4.2), — и оба
//! предполагают, что карточку даёт её владелец. Здесь карточку даёт кто-то
//! третий, и из этого следует всё остальное.
//!
//! # Подписи нет, и её не бывает
//!
//! Голая [`ContactCard`] не подписана — ни здесь, ни в QR-коде. Подпись есть
//! только у обновления адресов ([`ratatosk_codec::CardUpdate`]), потому что
//! там владелец меняет **уже известную** карточку и должен доказать, что это
//! он. А сама карточка ничего не доказывает: она **есть** заявление «вот мои
//! ключи», и доверие к нему берётся не из криптографии, а из канала.
//!
//! Поэтому присланный контакт проверить нечем, и подпись бы не помогла:
//! Алиса может завести пару ключей сама, назвать её «Кэрол» и прислать Бобу.
//! Карточка будет безупречно правильной. Кэрол ничего не подписывала и
//! подписать не могла — она не знает, что ею делятся.
//!
//! Отсюда три правила приёма, и они не про осторожность, а про то, что иначе
//! функция становится способом подмены собеседника:
//!
//! 1. **Присланный контакт непроверен всегда** — даже если у отправителя он
//!    сверен. Доверие не транзитивно: §4.2 говорит про сверку отпечатка
//!    голосом с самим человеком, и «мой друг за него ручается» — это не она.
//! 2. **Добавляет человек, а не ядро.** Карточка ложится в историю записью
//!    и ждёт решения, как предложение файла ждёт кнопки (§10.3).
//! 3. **Известный контакт не обновляется никогда.** Иначе кто угодно пришлёт
//!    «Кэрол версии 99» со своим onion-адресом и уведёт маршрут на себя.
//!    Адреса меняет только подписанный `CardUpdate` из сессии самой Кэрол.
//!
//! # Кто прислал — сказать обязательно
//!
//! Здесь ровно противоположно пересылке ([`crate::forward`]). Там мы **не**
//! называем автора, потому что утверждение «это слова N» проверить нечем.
//! Здесь мы **обязаны** назвать отправителя, потому что это единственное,
//! что получатель знает наверняка: кадр приехал по установленной сессии
//! из конкретного чата (§8.2). На этом знании он и принимает решение —
//! другого основания у него нет.
//!
//! Отдельного поля для этого не нужно и заводить его нельзя: отправитель
//! определяется чатом, а поле «от кого» в нагрузке было бы как раз тем
//! непроверяемым утверждением, которого мы избегаем.
//!
//! # Что не едет
//!
//! Локальное имя, которым пользователь подписал человека у себя. Оно
//! «по проводу не едет никогда» (§4.1, `StoredContact::local_name`): это
//! заметка о своём отношении, а не свойство контакта. Едет `display_name`
//! из самой карточки — то, как человек назвал себя сам.
//!
//! Признак сверки тоже не едет — см. правило 1.
//!
//! # Цена, которую стоит назвать вслух
//!
//! Поделившись контактом, человек рассказывает получателю, что знаком
//! с третьим, и отдаёт его адреса. Согласия у третьего никто не спрашивал,
//! и спросить негде. Это неустранимо: та же цена у любой визитки, переданной
//! из рук в руки. Но в мессенджере, который обещает приватность, о ней надо
//! говорить в UI, а не только в коде.

use ratatosk_codec::{canonical, CodecError, ContactCard, Value};

/// Ключ карточки в нагрузке.
const KEY_CARD: u64 = 1;
/// Ключ признака «переслано».
///
/// Признаком, а не отдельным типом нагрузки, как у текста
/// (`PayloadType::Forward`): тип уже занят под «карточка», а второй
/// означал бы вторую копию всего разбора. То же решение и по той же
/// причине, что у предложения файлов (`files::offer_payload`).
///
/// Необязателен на чтении: сборка постарше его не везла и покажет
/// пересланную карточку без пометки — единственное, что она потеряет.
const KEY_FORWARDED: u64 = 2;

/// Почему карточкой нельзя поделиться.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum ShareError {
    /// Такого контакта нет.
    #[error("контакт неизвестен")]
    UnknownContact,
    /// Карточка не разобралась.
    #[error("карточка испорчена")]
    BadCard,
}

/// Собирает нагрузку: одна карточка.
///
/// Одна, а не список. Поделиться тремя людьми — три сообщения, и это видно
/// в истории тремя записями: каждая со своим решением «добавить или нет»
/// и своим статусом доставки.
#[must_use]
pub fn payload(card_bytes: &[u8], forwarded: bool) -> Value {
    let mut fields = vec![(Value::Integer(KEY_CARD.into()), Value::Bytes(card_bytes.to_vec()))];
    // Ключа нет — «не переслано»: так короче обычный случай и так же
    // читает его сборка постарше.
    if forwarded {
        fields.push((Value::Integer(KEY_FORWARDED.into()), Value::Bool(true)));
    }
    Value::Map(fields)
}

/// Разбирает нагрузку и возвращает **принятые байты** карточки вместе с ней.
///
/// Байты сохраняются, а не пересобираются из полей: §6 требует, чтобы всё,
/// что когда-нибудь придётся проверить, проверялось над принятым
/// представлением. Пересобранные байты отличались бы от присланных на любом
/// расхождении версий — и совпадение перестало бы что-либо значить.
///
/// # Errors
///
/// [`CodecError::TypeMismatch`] на неверной форме, ошибка разбора карточки
/// на испорченном содержимом.
pub fn from_payload(value: &Value) -> Result<(Vec<u8>, ContactCard, bool), CodecError> {
    let map = canonical::as_map(value)?;
    let Value::Bytes(card_bytes) = canonical::require(map, KEY_CARD)? else {
        return Err(CodecError::TypeMismatch);
    };
    let card = ContactCard::decode(card_bytes)?.into_parts().1;
    // Отсутствие и `false` означают одно и то же, а ключ не того типа —
    // порчу: это уже не «сборка постарше».
    let forwarded = match canonical::get(map, KEY_FORWARDED) {
        Some(Value::Bool(flag)) => *flag,
        Some(_) => return Err(CodecError::TypeMismatch),
        None => false,
    };
    Ok((card_bytes.clone(), card, forwarded))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn card() -> ContactCard {
        ContactCard {
            ik: [1u8; 32],
            sk: [2u8; 32],
            onion: "abcdefghijklmnopqrstuvwxyz234567abcdefghijklmnopqrstuv.onion".into(),
            chatmail: "a7f3k9@nine.example".into(),
            display_name: "Кэрол".into(),
            version: 3,
            ygg: Vec::new(),
        }
    }

    #[test]
    fn a_card_travels_whole_and_comes_back_the_same() {
        let bytes = card().encode().unwrap();
        let (raw, parsed, forwarded) = from_payload(&payload(&bytes, false)).unwrap();
        assert!(!forwarded, "обычная карточка не переслана");
        assert_eq!(parsed, card());
        assert_eq!(raw, bytes, "байты сохраняются как приняты (§6), а не пересобираются");
    }

    #[test]
    fn a_broken_card_is_refused_at_the_border() {
        // Разбор на приёме, а не на показе: испорченная карточка не должна
        // добираться до истории и ждать там нажатия, которое всё равно
        // ничем не кончится.
        assert!(from_payload(&payload(b"not a card at all", false)).is_err());
        assert!(from_payload(&Value::Integer(7.into())).is_err());
    }

    #[test]
    fn a_forwarded_card_carries_its_mark() {
        // Пересылка сообщения с карточкой давала у получателя **пустое**
        // сообщение: тело у него пустое по построению, а карточка лежит
        // записью рядом и в пересылку не попадала вовсе. Признак — то,
        // чем пересланная карточка отличается от своей.
        let bytes = card().encode().unwrap();
        let (_, _, forwarded) = from_payload(&payload(&bytes, true)).unwrap();
        assert!(forwarded, "признак обязан пережить круг");
    }

    #[test]
    fn a_card_from_a_build_without_the_mark_reads_as_not_forwarded() {
        // Ключа нет — «не переслано»: сборка постарше его не везла,
        // и её нагрузка обязана разбираться по-прежнему.
        let bytes = card().encode().unwrap();
        let value = payload(&bytes, false);
        let Value::Map(fields) = &value else { panic!("нагрузка — карта") };
        assert_eq!(fields.len(), 1, "у непересланной признака в проводе быть не должно");
        let (_, _, forwarded) = from_payload(&value).unwrap();
        assert!(!forwarded);
    }
}
