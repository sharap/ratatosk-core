/// Сколько чанков отправитель шлёт вперёд подтверждённого получателем.
///
/// Окно, а не «шлём всё подряд», и это не оптимизация. Без окна ядро выдало бы
/// драйверу все чанки файла одним шагом — два гигабайта эффектов в памяти
/// у процесса, который на Android убивают за меньшее.
///
/// # Прямым каналом — два, а не четыре
///
/// Число это про отзывчивость, а не про пропускную способность. Кадры
/// к одному собеседнику идут одной очередью, и обычное сообщение,
/// отправленное посреди передачи файла, ждёт всего, что уже в полёте.
/// Четыре чанка — это четыре мебибайта ожидания на медленном Wi-Fi,
/// то есть «сообщения не отправляются, пока идёт файл». Два — вдвое меньше,
/// и при подтверждении на **каждый** чанк ([`ack_every`]) конвейер всё равно
/// не простаивает: подтверждение приходит, пока уходит следующий чанк.
///
/// # Почтой — восемь, и это **ограничитель хранилища**
///
/// У почты окно работает ещё и как договор о чужом ящике. Каждый чанк —
/// отдельное письмо, и всё, что отправлено, но не подтверждено, лежит
/// в ящике получателя. Открытое окно и есть верхняя граница того, сколько
/// его ящика мы заняли: [`mail_window_bytes`], около двенадцати мегабайт,
/// **сколько бы файл ни весил**. Получатель ушёл в офлайн — окно закрылось,
/// и передача остановилась сама, не добив его квоту.
///
/// Восемь, а не два, потому что цена круга у почты другая. Круг здесь —
/// это SMTP-очередь, IMAP получателя, его ответ и наш IMAP: минуты, а не
/// миллисекунды. Окно в два чанка означало бы два мебибайта за круг, то есть
/// сто мегабайт за сутки. Восемь укладывают тот же файл в десятки минут
/// и всё ещё занимают у получателя меньше шести процентов скупой
/// двухсотмебибайтной квоты.
///
/// Дороже это только памятью: восемь писем по полтора мегабайта — это
/// двенадцать мегабайт в очереди раннера. Много для служебной очереди
/// и приемлемо для передачи, которую человек начал сам.
#[must_use]
pub const fn window_bytes(via: Transport) -> u64 {
    match via {
        // **У эфира окно своё, и задано оно очередью записи.** Чанк там
        // класса S, то есть для транспорта он неотличим от сообщения
        // и едет срочной полосой — а мелкий кадр, не найдя места
        // в очереди, **ждёт**, и ждёт он в цикле ядра. Значит окно обязано
        // быть заведомо меньше очереди: сорок восемь килобайт — это
        // тринадцать чанков при очереди в тридцать два, то есть с запасом
        // вдвое. Связь этих двух чисел держит проверка в `transport::link`,
        // где видны оба; без неё они разъехались бы молча.
        //
        // Заодно это разумная глубина конвейера и по времени: на измеренных
        // 17 КБ/с сорок восемь килобайт — около трёх секунд.
        Transport::Bt => 48 * 1024,
        // Два мебибайта: за окном ждёт обычное сообщение, и держать
        // больше нечестно.
        Transport::Lan | Transport::Ygg | Transport::Onion => 2 * 1024 * 1024,
        // Восемь мебибайт, и это восемь писем по чанку: цена круга
        // у почты — минуты, а не миллисекунды, и окном в два мебибайта
        // предельный файл превратился бы в сотню кругов. Разбор целиком
        // в описании этой функции выше.
        Transport::Nostr | Transport::Mail => 8 * 1024 * 1024,
    }
}

/// Сколько чанков держать в полёте, не дожидаясь подтверждения.
///
/// # Окно считается в байтах, а не в чанках, и это правка развязки
///
/// Прежде окно было числом чанков, и это молча привязывало его к размеру
/// чанка: два чанка означали два мебибайта только потому, что чанк был
/// мебибайтом. Стоило размеру чанка стать другим — а на эфирной ступени
/// он таким и станет (§10.2), — и то же «два» означало бы восемь
/// килобайт в полёте, то есть остановку передачи на быстрой ступени.
///
/// Теперь у ступени спрашивается **сколько байт держать в полёте**
/// ([`window_bytes`]), а число чанков из этого выводится. Размер чанка
/// и окно перестали быть связаны, и следующая смена размера ничего
/// не сломает.
///
/// Меньше одного чанка окно не бывает: нулевое окно означало бы передачу,
/// которая не начинается.
#[must_use]
pub const fn chunk_window(via: Transport, chunk_bytes: usize) -> u64 {
    let window = window_bytes(via) / chunk_bytes as u64;
    if window == 0 {
        1
    } else {
        window
    }
}

/// Через сколько принятых чанков получатель подтверждает приём.
///
/// # Это ровно половина окна, и так было всегда
///
/// Прежде здесь стояли два числа: один прямым каналом, четыре почтой.
/// Оба оказались половиной окна своей ступени — два и восемь, — и это
/// не совпадение, а то самое правило, которым они и выбирались: половина
/// окна наименьшее, при котором окно не успевает закрыться. Подтверждение
/// на середине двигает границу как раз тогда, когда у отправителя
/// остаётся в полёте ещё половина.
///
/// Записанное правилом вместо двух чисел, оно перестаёт расходиться
/// с окном при смене размера чанка. Прежние числа при мелком чанке
/// означали бы подтверждение на каждый чанк — то есть кадр в ответ
/// на каждые четыре килобайта, вдвое больше кадров на проводе ни за что.
///
/// Меньше одного не бывает: подтверждать реже, чем приходят чанки,
/// нельзя, а «каждый» — законный предел для окна в два.
#[must_use]
pub const fn ack_every(via: Transport, chunk_bytes: usize) -> u64 {
    let half = chunk_window(via, chunk_bytes) / 2;
    if half == 0 {
        1
    } else {
        half
    }
}

/// Сколько передач вести этой ступенью одновременно (§10.2).
///
/// Считается **на весь аппарат**, а не на собеседника: канал у ступени
/// один на всех. Две загрузки от разных людей по эфиру толкаются в той же
/// очереди записи, что и две от одного, и предел, считающий собеседников,
/// защищал бы не тот ресурс.
///
/// # Почему параллель вообще вредна там, где канал узкий
///
/// Она ничего не ускоряет. Пропускная способность у ступени одна: два
/// файла по эфиру приедут ровно за то же время, что и по очереди, — только
/// оба в конце, а не один в середине. Зато цена есть, и не одна. Окна
/// складываются: два окна по тринадцать чанков — это двадцать шесть кадров
/// на очередь в тридцать два, и мелкий кадр, не найдя в ней места, **ждёт**
/// в цикле ядра. Сроки молчания идут вразнобой. А потерянный кадр бьёт
/// по обеим передачам сразу.
///
/// # Почта и nostr — случай обратный, и это не поблажка
///
/// Там узко не место, а **время**: круг у почты — минуты, и всё это время
/// канал простаивает. Одна передача за раз превратила бы три файла в три
/// последовательных часа ожидания при полностью свободной линии. Четыре
/// письма в полёте вместо одного — это не четыре канала, это один канал,
/// который перестал ждать.
///
/// Разница между ступенями здесь поэтому не «быстрая-медленная», а
/// «упирается в ширину — упирается в задержку». Эфир и onion упираются
/// в ширину; почта и nostr — в задержку; локальная сеть широка настолько,
/// что упирается в оба раза не она.
#[must_use]
pub const fn parallel_files(via: Transport) -> usize {
    match via {
        // Широко и быстро: десяток мелких картинок гуськом — заметная
        // и ничем не оправданная задержка.
        Transport::Lan => 4,
        // Меш шире эфира, но у́же локальной сети, и маршрут в нём умеет
        // перестраиваться на ходу. Две — осторожная середина.
        Transport::Ygg => 2,
        // **Одна.** Эфир — одно радио и очередь записи в тридцать два
        // кадра; onion — цепочка через три реле, где вторая передача
        // отбирает ширину у первой и ничего не добавляет.
        Transport::Bt | Transport::Onion => 1,
        // Упираются в задержку, а не в ширину — разбор выше.
        Transport::Nostr | Transport::Mail => 4,
    }
}

/// После скольких безответных сроков передача уступает ступень (§10.2).
///
/// **Иначе замолчавшая передача запирает канал для всех остальных.**
/// Предел одновременных загрузок на эфире равен одному: пока файл числится
/// идущим, следующий стоит в очереди. А «идущим» он числится и тогда, когда
/// собеседник ушёл из эфира посреди передачи — она не оборвана, она молчит,
/// и срок молчания у неё удваивается: восемнадцать секунд, тридцать шесть,
/// семьдесят две. Через несколько минут приём стоит целиком, причём
/// за файлом, которого никто не отдаёт.
///
/// Двух безответных сроков довольно, чтобы отличить потерянный кадр
/// от ушедшего собеседника: первый возвращается тем же сроком, второй
/// не возвращается вовсе. Уступив ступень, передача не пропадает — она
/// встаёт в ту же очередь и получит место, когда его освободит следующая.
pub const YIELD_AFTER_STALLS: u32 = 2;

/// Запас сверх времени одного окна у срока молчания (§10.2).
///
/// Втрое. Срок обязан заведомо пережить то, что уже в полёте, — иначе
/// получатель объявит застоем чанк, который в этот миг идёт по проводу, —
/// но и только: за этой чертой лишнее ожидание уже ничего не страхует,
/// а стоит прямо и дорого. Каждый потерянный кадр стоит ровно одного
/// такого срока тишины.
pub const STALL_WINDOW_FACTOR: u64 = 3;

/// Наименьший срок молчания — десять секунд.
///
/// Нужен быстрым ступеням: по локальной сети окно уходит за две секунды,
/// и втрое от этого дало бы шесть — срок, который объявит застоем обычную
/// заминку планировщика. Ниже этой черты срок перестаёт быть страховкой
/// и становится источником лишних просьб.
pub const MIN_STALL_MS: u64 = 10_000;

/// Скромная скорость для ступеней, у которых своей нет.
///
/// Почта и nostr скорости не называют: ждать ответа сервера бессмысленно,
/// а письмо, кроме сети, лежит ещё и в очереди SMTP. Тридцать килобайт
/// в секунду — то же скромное число, что у onion: одна цепочка Tor через
/// три реле это не канал, а обещание канала.
pub const SLOW_BYTES_PER_SEC: u64 = 30 * 1024;

/// Сколько ждать чанк, прежде чем спросить заново (§10.2).
///
/// Сторожит получатель, и срок отсчитывается от **последнего пришедшего**
/// чанка: каждый заводит срок заново. То есть это ответ на вопрос «за это
/// время не пришло ничего».
///
/// # Срок считается, а не пишется, и это правка поломки
///
/// Здесь стояли пять чисел, по одному на ступень, и каждое было выведено
/// вручную из окна своей ступени. Оно и разошлось. Эфирное число — десять
/// минут — считалось от окна в **два мебибайта**, каким окно было, пока
/// чанк был класса L. С переходом эфира на класс S (0.4.8) окно стало
/// сорока восемью килобайтами, то есть шестью секундами хода, а срок
/// остался десятиминутным: **в сто раз больше, чем ему полагалось**.
///
/// Наружу это вышло так, как выходит всякий слишком терпеливый срок: файлы
/// «зависают на определённой стадии», хотя сообщения ходят. Один потерянный
/// кадр — чанк или подтверждение — и передача молчит десять минут, потом
/// двадцать, потом сорок. Ничего не сломано, просто никто не спрашивает.
///
/// Поэтому число выводится: время одного окна при скромной скорости
/// ступени, умноженное на [`STALL_WINDOW_FACTOR`], но не меньше
/// [`MIN_STALL_MS`]. Сменится окно, размер чанка или скорость — срок
/// поедет за ними сам.
///
/// # Почему срок обязан пережить окно
///
/// Срок короче времени передачи не «ускоряет возобновление», а ломает
/// передачу совсем. Получатель объявляет молчанием чанк, который в этот
/// момент идёт по проводу, и просит начать заново; отправитель отматывает
/// окно и кладёт в ту же линию второй экземпляр того же куска. Линия
/// становится медленнее, следующий срок выходит ещё вернее, и передача
/// разгоняет сама себя в обратную сторону. Снаружи: «файл начинает
/// загружаться и никогда не догружается» — с настоящим прогрессом между
/// срывами, потому что что-то всё-таки доезжает.
///
/// # И почему не обязан переживать его намного
///
/// Потому что цена ошибки несимметрична. Спросить рано стоит одной мелкой
/// просьбы и, в худшем случае, одного лишнего окна чанков — а повтор чанка
/// получатель отбросит, он у него уже есть. Спросить поздно стоит всего
/// этого срока, целиком, в тишине. Запас поэтому взят втрое, а не вдесятеро.
///
/// # Почта считается дважды
///
/// Её байты проходят сеть от отправителя на сервер и с сервера получателю,
/// и едут они раздутыми в письме, а не голым кадром. Отсюда двойка
/// в расчёте и [`mail_window_bytes`] вместо [`window_bytes`].
#[must_use]
pub const fn stall_ms(via: Transport) -> u64 {
    // Окно и число проходов сети — единственное, чем ступени здесь
    // различаются. Всё остальное — общая арифметика.
    let (bytes, hops) = match via {
        Transport::Nostr | Transport::Mail => (mail_window_bytes(), 2),
        Transport::Lan | Transport::Ygg | Transport::Onion | Transport::Bt => {
            (window_bytes(via), 1)
        }
    };
    // `unwrap_or` не константна, поэтому разбор руками.
    let speed = match crate::transport_policy::floor_bytes_per_sec(via) {
        Some(speed) => speed,
        None => SLOW_BYTES_PER_SEC,
    };
    let window_ms = bytes.saturating_mul(hops).saturating_mul(1_000) / speed;
    let value = window_ms.saturating_mul(STALL_WINDOW_FACTOR);
    // `Ord::max` тоже не константна.
    if value < MIN_STALL_MS {
        MIN_STALL_MS
    } else {
        value
    }
}

/// Наибольший срок молчания при отступлении — двенадцать часов.
pub const MAX_STALL_MS: u64 = 12 * 3600 * 1000;

/// Срок молчания на `attempt`-й безответной попытке подряд.
///
/// Удвоение с потолком. Нужно оно ровно одному случаю — почте, и случай
/// этот не редкий: собеседник ушёл на выходные. Без отступления получатель
/// спрашивал бы про брошенную передачу письмом каждые полчаса — сорок восемь
/// писем в сутки, каждое со своим следом у chatmail-сервера (§2.2)
/// и со своим куском чужой квоты. С отступлением их семь за те же сутки.
///
/// Счётчик обнуляет **любой** пришедший чанк, а не удачная просьба: удачей
/// здесь считается движение файла, а не то, что письмо ушло.
///
/// Прямых каналов это почти не касается: там срок и так секунды, а обрыв
/// ловится разрывом сессии. Но правило одно на все транспорты — отдельная
/// ветка «почте отступать, остальным нет» разошлась бы с первой же правкой.
#[must_use]
pub const fn stall_backoff_ms(via: Transport, attempt: u32) -> u64 {
    let base = stall_ms(via);
    // Множитель ограничен заранее, и `if` здесь вместо `min` не по вкусу:
    // `Ord::min` не константна. Без ограничения `1 << attempt` уехал бы
    // в панику за сутки брошенной передачи.
    let shift = if attempt > 20 { 20 } else { attempt };
    let value = base.saturating_mul(1u64 << shift);
    if value > MAX_STALL_MS {
        MAX_STALL_MS
    } else {
        value
    }
}

/// Ключ идентификатора файла в нагрузке.
const KEY_FILE_ID: u64 = 1;
/// Ключ списка файлов в предложении.
const KEY_FILES: u64 = 2;
/// Ключ признака «переслано» у предложения файлов.
///
/// Отдельным признаком, а не отдельным типом нагрузки, как у текста
/// (`PayloadType::Forward`), и причина прозаична: тип уже занят под
/// «предложение файлов», а второй означал бы вторую копию всего разбора
/// вложений. Признак необязателен на чтении — сборка постарше покажет
/// пересланный файл без пометки, и это единственное, что она потеряет.
const KEY_FORWARDED: u64 = 3;
/// Ключ подписи к файлам.
const KEY_CAPTION: u64 = 1;
/// Ключ имени файла.
const KEY_NAME: u64 = 2;
/// Ключ размера.
const KEY_SIZE: u64 = 3;
/// Ключ файлового ключа (§10.1).
const KEY_FILE_KEY: u64 = 4;
/// Ключ превью.
const KEY_PREVIEW: u64 = 6;
/// Ключ размера чанка (§10.2).
///
/// Пишется только когда отличается от [`CHUNK_BYTES`]: так обычный случай
/// короче на проводе, и так же читает его сборка постарше — у неё
/// отсутствие ключа означает ровно то, чем она и режет.
const KEY_CHUNK: u64 = 7;
/// Ключ номера чанка — он же номер, с которого просят продолжить.
const KEY_INDEX: u64 = 2;
/// Ключ байтов чанка.
const KEY_BYTES: u64 = 3;
/// Ключ признака «до меня ничего не доходит» в просьбе.
const KEY_STALLED: u64 = 3;
/// Карта кусков объявления §9.1: бит на кусок.
const KEY_BITMAP: u64 = 4;

/// Почему файл не принят.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum FileError {
    /// Больше [`MAX_FILE_BYTES`].
    #[error("файл больше {MAX_FILE_BYTES} байт")]
    TooLarge,
    /// Файлов в сообщении больше [`MAX_FILES_PER_MESSAGE`].
    #[error("к одному сообщению можно приложить не больше {MAX_FILES_PER_MESSAGE} файлов")]
    TooMany,
    /// Имя пустое, слишком длинное или содержит путь.
    #[error("недопустимое имя файла")]
    BadName,
    /// Превью больше [`PREVIEW_LIMIT_BYTES`].
    #[error("превью больше {PREVIEW_LIMIT_BYTES} байт")]
    PreviewTooLarge,
    /// Размер чанка нулевой или больше того, что влезает в кадр.
    #[error("недопустимый размер чанка")]
    BadChunk,
}

/// Предложение одного файла — то, что едет в `PayloadType::FileOffer`.
///
/// Ключ файла едет здесь же, и иначе нельзя: §10.1 передаёт `file_key`
/// «в сообщении», то есть по уже установленной сессии. Отдельного обмена
/// ключами для файлов нет и не нужно — кадр с предложением уже зашифрован
/// сессионным ключом.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FileOffer {
    /// Идентификатор файла — по нему адресуются чанки.
    pub file_id: FileId,
    /// Имя для показа. **Не путь**: см. [`check_name`].
    pub name: String,
    /// Размер открытого содержимого.
    pub size_bytes: u64,
    /// Ключ файла (§10.1).
    pub key: FileKey,
    /// Превью изображения до [`PREVIEW_LIMIT_BYTES`] (§10.3).
    pub preview: Option<Vec<u8>>,
    /// Каким чанком нарезан файл (§10.2).
    ///
    /// **Едет в предложении, а не выводится заново каждой стороной.**
    /// Нумерация чанков обязана совпасть у обеих, а вывод из ступени
    /// разошёлся бы ровно в тот миг, когда §5.4 уведёт файл на другую
    /// ступень посреди передачи. Выбирает его отправитель, один раз,
    /// при составлении предложения — [`chunk_bytes_for`].
    ///
    /// Отсюда оговорка: файл, предложенный по эфиру, сохранит мелкий чанк
    /// и на локальной сети. Цена — больше кругов на большом файле;
    /// выгода — он вообще доезжает.
    ///
    /// Сборка постарше этого поля не пришлёт, и тогда читается
    /// [`CHUNK_BYTES`] — ровно то, чем она и режет.
    pub chunk_bytes: usize,
}

/// Проверяет имя файла.
///
/// Имя приходит от собеседника и попадает на экран, а при сохранении —
/// в имя файла на диске. Поэтому здесь отвергаются разделители пути,
/// управляющие символы и «точечные» имена: получатель хранит файл под своим
/// `file_id` и чужое имя путём не считает, но правило дешевле привычки —
/// первый же клиент, который склеит имя с каталогом, получит запись куда
/// угодно.
///
/// # Errors
///
/// [`FileError::BadName`].
pub fn check_name(name: &str) -> Result<(), FileError> {
    let trimmed = name.trim();
    if trimmed.is_empty() || trimmed.chars().count() > MAX_FILE_NAME_CHARS {
        return Err(FileError::BadName);
    }
    if trimmed == "." || trimmed == ".." {
        return Err(FileError::BadName);
    }
    if trimmed.chars().any(|c| c == '/' || c == '\\' || c.is_control()) {
        return Err(FileError::BadName);
    }
    Ok(())
}

/// Запас под одно предложение файла помимо превью.
///
/// `file_id` (16), ключ файла (32), размер, ключи CBOR — и имя длиной
/// до [`MAX_FILE_NAME_CHARS`], которое в UTF-8 занимает до четырёх байт
/// на символ. Число с запасом, и достаточность запаса проверяется тестом
/// `a_message_with_ten_previewed_files_fits_one_frame` на настоящем
/// конверте, а не на оценке.
pub const OFFER_RESERVE_BYTES: usize = 256 + MAX_FILE_NAME_CHARS * 4;

/// Наибольшая длина текста сообщения в **байтах** (не символах).
///
/// # Выведен из класса M, а не из класса L, и это правка поломки
///
/// Прежде предел выводился из класса L: из мебибайта вычиталось всё, что
/// могут занять десять вложений с превью, и человеку оставалось семьсот
/// килобайт. Арифметика честная, существо негодное: **кадр класса L
/// до Android не доходит вовсе** (0.4.8). Не теряется с потерями —
/// молчит. Снаружи это выглядело как «сообщение отправлено и не дошло».
///
/// Теперь предел выведен из класса M: текст, отправленный **без
/// вложений**, помещается в кадр класса M и по эфиру доезжает — пусть
/// и с повторами, которых требует §9.4. Шестьдесят с лишним килобайт —
/// это около тридцати тысяч знаков кириллицы; мебибайт текста
/// не сообщение, а файл, и отправлять его надо файлом.
///
/// **Чего этот предел не чинит.** Сообщение **с вложениями** по-прежнему
/// может оказаться классом L, и виноват не текст: десять превью
/// по тридцать два килобайта дают триста двадцать два килобайта сами
/// по себе. Это отдельная развилка, и разбор её — в 0.4.8.
///
/// Одно число на все случаи, а не два: «столько, если без файлов,
/// и столько, если с ними» — правило, которое клиент однажды применит
/// не то.
///
/// **Байты, а не символы**, и клиент обязан считать так же: кириллица
/// в UTF-8 идёт по два байта, эмодзи по четыре, и счётчик символов
/// в поле ввода обманул бы человека ровно вдвое.
pub const MAX_TEXT_BYTES: usize = SizeClass::M.max_payload() - ENVELOPE_RESERVE_BYTES;

/// Помещается ли текст сообщения в предел.
#[must_use]
pub const fn text_fits(bytes: usize) -> bool {
    bytes <= MAX_TEXT_BYTES
}

/// Проверяет одно предложение файла — до отправки и на приёме.
///
/// # Errors
///
/// [`FileError`] по первому нарушению.
pub fn check_offer(offer: &FileOffer) -> Result<(), FileError> {
    check_name(&offer.name)?;
    if offer.size_bytes > MAX_FILE_BYTES {
        return Err(FileError::TooLarge);
    }
    if offer.preview.as_ref().is_some_and(|p| !preview_fits(p.len())) {
        return Err(FileError::PreviewTooLarge);
    }
    // **Размер чанка приходит от собеседника, значит проверяется.** Ноль
    // означал бы деление на ноль в [`chunk_count`] и бесконечную передачу;
    // слишком большой — чанк, не влезающий в кадр, который должен его
    // нести. Верхняя граница та же, что у нашего наибольшего чанка:
    // больше него не бывает ни у кого.
    if offer.chunk_bytes == 0 || offer.chunk_bytes > CHUNK_BYTES {
        return Err(FileError::BadChunk);
    }
    Ok(())
}

/// Проверяет весь список вложений сообщения.
///
/// # Errors
///
/// [`FileError::TooMany`] или ошибка любого из файлов.
pub fn check_offers(offers: &[FileOffer]) -> Result<(), FileError> {
    if offers.len() > MAX_FILES_PER_MESSAGE {
        return Err(FileError::TooMany);
    }
    for offer in offers {
        check_offer(offer)?;
    }
    Ok(())
}

/// Принимать ли файл такого размера автоматически.
///
/// `None` означает «никогда»: человек принимает каждый файл руками. Это
/// законная настройка, а не отключённая функция.
#[must_use]
pub const fn auto_accept(size_bytes: u64, threshold: Option<u64>) -> bool {
    match threshold {
        Some(limit) => size_bytes <= limit,
        None => false,
    }
}

/// Собирает нагрузку предложения: подпись и список файлов.
#[must_use]
pub fn offer_payload(caption: &str, offers: &[FileOffer], forwarded: bool) -> Value {
    let files = offers
        .iter()
        .map(|offer| {
            let mut entry = vec![
                (Value::Integer(KEY_FILE_ID.into()), Value::Bytes(offer.file_id.to_vec())),
                (Value::Integer(KEY_NAME.into()), Value::Text(offer.name.clone())),
                (Value::Integer(KEY_SIZE.into()), Value::Integer(offer.size_bytes.into())),
                (Value::Integer(KEY_FILE_KEY.into()), Value::Bytes(offer.key.to_vec())),
            ];
            if let Some(preview) = &offer.preview {
                entry.push((Value::Integer(KEY_PREVIEW.into()), Value::Bytes(preview.clone())));
            }
            if offer.chunk_bytes != CHUNK_BYTES {
                let size = u64::try_from(offer.chunk_bytes).unwrap_or(CHUNK_BYTES as u64);
                entry.push((Value::Integer(KEY_CHUNK.into()), Value::Integer(size.into())));
            }
            Value::Map(entry)
        })
        .collect();
    let mut fields = vec![
        (Value::Integer(KEY_CAPTION.into()), Value::Text(caption.to_owned())),
        (Value::Integer(KEY_FILES.into()), Value::Array(files)),
    ];
    // Ключа нет — «не переслано»: так короче обычный случай и так же
    // читает его сборка постарше.
    if forwarded {
        fields.push((Value::Integer(KEY_FORWARDED.into()), Value::Bool(true)));
    }
    Value::Map(fields)
}

/// Разбирает нагрузку предложения.
///
/// Проверяется всё: число файлов, длина каждого поля, имя, размер, превью.
/// Список приходит от собеседника, и единственная защита от «предложения»
/// на тысячу файлов — вот эта проверка.
///
/// # Errors
///
/// [`CodecError::TypeMismatch`], если структура не та или что-то не прошло
/// [`check_offers`].
pub fn offer_from_payload(value: &Value) -> Result<(String, Vec<FileOffer>, bool), CodecError> {
    let map = canonical::as_map(value)?;
    let Value::Text(caption) = canonical::require(map, KEY_CAPTION)? else {
        return Err(CodecError::TypeMismatch);
    };
    let Value::Array(items) = canonical::require(map, KEY_FILES)? else {
        return Err(CodecError::TypeMismatch);
    };
    if items.len() > MAX_FILES_PER_MESSAGE {
        return Err(CodecError::TypeMismatch);
    }

    let mut offers = Vec::with_capacity(items.len());
    for item in items {
        let entry = canonical::as_map(item)?;
        // Превью необязательно: у документа его нет вовсе. Отсутствие ключа —
        // законный случай, а вот ключ не того типа — нет.
        let preview = match canonical::get(entry, KEY_PREVIEW) {
            Some(Value::Bytes(bytes)) => Some(bytes.clone()),
            Some(_) => return Err(CodecError::TypeMismatch),
            None => None,
        };
        // Отсутствие ключа законно — так шлёт сборка постарше; ключ
        // не того типа — нет. Годность самого числа проверит `check_offers`
        // ниже, вместе со всем остальным, что пришло от собеседника.
        let chunk_bytes = match canonical::get(entry, KEY_CHUNK) {
            Some(value) => {
                usize::try_from(canonical::as_u64(value)?).map_err(|_| CodecError::TypeMismatch)?
            }
            None => CHUNK_BYTES,
        };
        offers.push(FileOffer {
            chunk_bytes,
            file_id: canonical::as_array::<16>(canonical::require(entry, KEY_FILE_ID)?)?,
            name: match canonical::require(entry, KEY_NAME)? {
                Value::Text(name) => name.clone(),
                _ => return Err(CodecError::TypeMismatch),
            },
            size_bytes: canonical::as_u64(canonical::require(entry, KEY_SIZE)?)?,
            key: canonical::as_array::<32>(canonical::require(entry, KEY_FILE_KEY)?)?,
            preview,
        });
    }
    if check_offers(&offers).is_err() {
        return Err(CodecError::TypeMismatch);
    }
    // Признак необязателен: сборка постарше его не везла. Отсутствие
    // и `false` означают одно и то же, а ключ не того типа — порчу.
    let forwarded = match canonical::get(map, KEY_FORWARDED) {
        Some(Value::Bool(flag)) => *flag,
        Some(_) => return Err(CodecError::TypeMismatch),
        None => false,
    };
    Ok((caption.clone(), offers, forwarded))
}

/// Собирает нагрузку чанка.
#[must_use]
pub fn chunk_payload(file_id: FileId, index: u64, sealed: &[u8]) -> Value {
    Value::Map(vec![
        (Value::Integer(KEY_FILE_ID.into()), Value::Bytes(file_id.to_vec())),
        (Value::Integer(KEY_INDEX.into()), Value::Integer(index.into())),
        (Value::Integer(KEY_BYTES.into()), Value::Bytes(sealed.to_vec())),
    ])
}

/// Разбирает нагрузку чанка.
///
/// Длина проверяется здесь: чанк больше положенного означает либо чужую
/// сборку, либо попытку заставить нас держать в памяти больше, чем нужно.
///
/// # Errors
///
/// [`CodecError::TypeMismatch`].
pub fn chunk_from_payload(value: &Value) -> Result<(FileId, u64, Vec<u8>), CodecError> {
    let map = canonical::as_map(value)?;
    let file_id = canonical::as_array::<16>(canonical::require(map, KEY_FILE_ID)?)?;
    let index = canonical::as_u64(canonical::require(map, KEY_INDEX)?)?;
    let Value::Bytes(sealed) = canonical::require(map, KEY_BYTES)? else {
        return Err(CodecError::TypeMismatch);
    };
    if sealed.len() > CHUNK_BYTES + CHUNK_TAG_LEN || sealed.len() < CHUNK_TAG_LEN {
        return Err(CodecError::TypeMismatch);
    }
    Ok((file_id, index, sealed.clone()))
}

/// Собирает просьбу продолжить передачу с указанного чанка (§10.2).
///
/// Она же подтверждение: «всё до этого номера у меня есть». Кадр один, но
/// **говорит он две разные вещи**, и различает их флаг `stalled`.
///
/// # Почему флаг, а не догадка
///
/// Найдено на живом стенде, и стоило это зависшей передачи. Сначала кадр был
/// один и без флага: отправитель сам решал, подтверждение перед ним или
/// просьба начать заново, — по тому, продвинулся ли номер. Догадка неверна.
///
/// Получатель подтверждает **следующий недостающий** чанк, а у отправителя
/// в это время в полёте ещё несколько. Сроки молчания у получателя выходят
/// вразнобой, и в какой-то момент он честно просит номер, который уже просил.
/// Отправитель читает это как «ничего не дошло», отматывает отправку назад
/// и шлёт по второму разу то, что уже в пути. Каждый повтор у получателя —
/// новый срок молчания и новая просьба, и передача сама себя разгоняет:
/// файл «грузится вечно», а очередь кадров к этому собеседнику забита
/// мебибайтами, из-за чего не уходят и обычные сообщения.
///
/// Получатель прекрасно знает, что имеет в виду. Поэтому он это и говорит:
/// `stalled = false` — «принял, шлите дальше» (окно едет вперёд, ничего
/// не пересылается), `stalled = true` — «за целый срок ничего не пришло,
/// начните с этого номера» (отправка отматывается). Догадок больше нет.
#[must_use]
pub fn request_payload(file_id: FileId, next_index: u64, stalled: bool) -> Value {
    Value::Map(vec![
        (Value::Integer(KEY_FILE_ID.into()), Value::Bytes(file_id.to_vec())),
        (Value::Integer(KEY_INDEX.into()), Value::Integer(next_index.into())),
        (Value::Integer(KEY_STALLED.into()), Value::Bool(stalled)),
    ])
}

/// Объявление доступности вложения — `HaveChunks` из §9.1.
///
/// Карта по битам: бит на кусок, младший бит первого байта — кусок
/// ноль. Пустая карта законна и означает «нет ничего» — так объявляет
/// тот, у кого передача только началась.
///
/// # Зачем карта, а не «есть целиком»
///
/// Частичный держатель — тоже держатель. У кого-то есть начало,
/// у кого-то середина, и спрашивать надо того, у кого есть **нужный**
/// кусок; §9.1 потому и объявляет карту, а не факт.
#[must_use]
pub fn have_payload(file_id: FileId, bitmap: &[u8]) -> Value {
    Value::Map(vec![
        (Value::Integer(KEY_FILE_ID.into()), Value::Bytes(file_id.to_vec())),
        (Value::Integer(KEY_BITMAP.into()), Value::Bytes(bitmap.to_vec())),
    ])
}

/// Разбирает объявление доступности (§9.1).
///
/// # Errors
///
/// [`CodecError::TypeMismatch`].
pub fn have_from_payload(value: &Value) -> Result<(FileId, Vec<u8>), CodecError> {
    let map = canonical::as_map(value)?;
    let file_id = canonical::as_array::<16>(canonical::require(map, KEY_FILE_ID)?)?;
    let Value::Bytes(bitmap) = canonical::require(map, KEY_BITMAP)? else {
        return Err(CodecError::TypeMismatch);
    };
    Ok((file_id, bitmap.clone()))
}

/// Есть ли у объявившего этот кусок — по его карте (§9.1).
///
/// Карта короче номера означает «нет»: сборка постарше объявила
/// меньше, чем у нас кусков, и придумывать за неё нельзя.
#[must_use]
pub fn bitmap_has(bitmap: &[u8], index: u64) -> bool {
    let (byte, bit) = (index / 8, index % 8);
    let Ok(byte) = usize::try_from(byte) else { return false };
    bitmap.get(byte).is_some_and(|cell| cell & (1 << bit) != 0)
}

/// Разбирает просьбу продолжить передачу.
///
/// Возвращает номер и признак «до меня ничего не доходит».
///
/// # Errors
///
/// [`CodecError::TypeMismatch`].
pub fn request_from_payload(value: &Value) -> Result<(FileId, u64, bool), CodecError> {
    let map = canonical::as_map(value)?;
    let file_id = canonical::as_array::<16>(canonical::require(map, KEY_FILE_ID)?)?;
    let index = canonical::as_u64(canonical::require(map, KEY_INDEX)?)?;
    let Value::Bool(stalled) = canonical::require(map, KEY_STALLED)? else {
        return Err(CodecError::TypeMismatch);
    };
    Ok((file_id, index, *stalled))
}

