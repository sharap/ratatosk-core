//! Граница между ядром и вводом-выводом.
//!
//! Ядро sans-io: оно возвращает команды и принимает события, но само ничего
//! не ждёт. Раннер — единственное место, где эти команды превращаются
//! в реальные операции. Подменив раннер на фейковый, получаем детерминированную
//! симуляцию (§16) без единой правки в протокольном коде.

use ratatosk_proto::transport_policy::Transport;

/// Адрес получателя.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PeerAddress {
    /// `IK` контакта — по нему ядро находит сессию.
    pub ik: [u8; 32],
    /// Onion-адрес, если известен.
    pub onion: Option<String>,
    /// Chatmail-адрес, если известен.
    pub chatmail: Option<String>,
}

/// Что ядро просит сделать.
#[derive(Debug, Clone)]
pub enum TransportCommand {
    /// Отправить кадр указанным транспортом.
    ///
    /// Ровно один транспорт на команду: §5.4 запрещает одновременную отправку
    /// одного сообщения по нескольким.
    Send {
        /// Кому.
        peer: PeerAddress,
        /// Каким транспортом.
        via: Transport,
        /// Готовый кадр — уже дополненный до класса размера.
        frame: Vec<u8>,
        /// Метка, которую надо вернуть событием [`TransportEvent::Handed`],
        /// когда кадр действительно уйдёт.
        ///
        /// Смотреть на неё обязан только тот транспорт, у которого «ушло»
        /// и «принято» разнесены во времени, — почта. Прямые каналы её
        /// не трогают: там доказательством служит квитанция собеседника
        /// (§9.4), а она говорит больше.
        ///
        /// `None` означает «подтверждения никто не ждёт», и молчание в ответ
        /// на такую отправку — не потеря.
        handoff: Option<u64>,
    },
    /// Установить соединение, не отправляя данных.
    Connect {
        /// С кем.
        peer: PeerAddress,
        /// Каким транспортом.
        via: Transport,
    },
    /// Разорвать соединение.
    Disconnect {
        /// С кем.
        peer: PeerAddress,
    },
    /// Включить или выключить транспорт (§5.4).
    ///
    /// Что это значит, решает сам транспорт: LAN занимает или освобождает
    /// порт и перестаёт объявляться, onion поднимает или роняет Tor-клиент
    /// вместе с сервисом. Команда одна на все, потому что решение одно
    /// на все: человек нажал переключатель.
    SetEnabled {
        /// Какой транспорт.
        transport: Transport,
        /// Включить или выключить.
        enabled: bool,
    },
    /// Настройки почтового ящика (§5.3). `None` — ящика нет, остановиться.
    ///
    /// Едет командой, а не читается раннером из базы: §13.3 запрещает
    /// протокольному состоянию просачиваться вниз иначе как через границу
    /// ядра. Та же причина, что и у списка маяков.
    ///
    /// **Внутри пароль.** У [`MailAccount`] написан свой `Debug`, и здесь
    /// это существенно: команды попадают в журнал целиком.
    ///
    /// [`MailAccount`]: ratatosk_proto::mail::MailAccount
    SetMailAccount(Option<ratatosk_proto::mail::MailAccount>),
    /// Сходить на chatmail-сервер за новым ящиком (§5.3).
    ///
    /// Ссылку ядро уже разобрало и признало годной — здесь остаётся только
    /// сходить. Ответ уезжает событием [`TransportEvent::MailAccountCreated`]
    /// либо [`TransportEvent::MailAccountFailed`].
    CreateMailAccount {
        /// Ссылка вида `https://chatmail.example/new`.
        url: String,
        /// Идти ли через Tor.
        via_tor: bool,
    },
    /// Чьи маяки искать в эфире LAN (§5.1).
    ///
    /// Маяк вычисляется от `IK` и ротируется каждые 15 минут, поэтому
    /// «найти контакт» — это пересчитать ожидаемое значение для каждого
    /// известного `IK` и сравнить. Без списка транспорту сравнивать не с чем.
    WatchLanPeers(Vec<[u8; 32]>),
    /// Поднять LAN заново после смены сети.
    ///
    /// Слушающий сокет и объявление mDNS привязаны к интерфейсу, которого
    /// больше нет, а известные адреса принадлежали прежней сети. Всё это
    /// надо завести заново, а не чинить по частям.
    RestartLan,
}

/// Что случилось во внешнем мире.
#[derive(Debug, Clone)]
pub enum TransportEvent {
    /// Пришли байты.
    Received {
        /// Каким транспортом.
        via: Transport,
        /// От кого, если транспорт это сообщает.
        ///
        /// Почта не сообщает: `From:` может быть подделан, и доверять ему
        /// нельзя — источник определяется по `session_id` и проверке тега (§7.3).
        peer_hint: Option<[u8; 32]>,
        /// Сами байты.
        frame: Vec<u8>,
    },
    /// Соединение установлено.
    Connected {
        /// С кем.
        peer_ik: [u8; 32],
        /// Каким транспортом.
        via: Transport,
    },
    /// Соединение разорвано.
    Disconnected {
        /// С кем.
        peer_ik: [u8; 32],
        /// Каким транспортом.
        via: Transport,
    },
    /// Контакт замечен в LAN по маяку (§5.1).
    SeenOnLan {
        /// Чей маяк совпал.
        peer_ik: [u8; 32],
    },
    /// Транспорт заработал: с этого мгновения §5.4 вправе его выбирать.
    ///
    /// «Включён» и «работает» — разные вещи, и разделяют их секунды или
    /// десятки секунд: у почты это вход на сервер, у onion — публикация
    /// сервиса. Пока ступень не объявила о себе, §5.4 её не выбирает,
    /// и сообщение честно ждёт вместо того, чтобы сгореть на транспорте,
    /// которого пока нет.
    ///
    /// Onion пользуется не этим событием, а [`TransportEvent::TorReady`]:
    /// ему вместе с готовностью надо сообщить адрес, а адрес известен
    /// только после публикации. Заводить ради этого поле, пустое у всех
    /// остальных, было бы хуже, чем два события.
    Ready {
        /// Какая ступень.
        transport: Transport,
    },
    /// Вход на почтовый сервер не удался (§5.3, §14).
    ///
    /// Не то же, что «завести ящик не вышло»: ящик есть, а войти в него
    /// не получилось — пароль сменили, сервер лежит, Tor не пускает.
    /// Человек, у которого молча перестала работать почта, читает это
    /// как поломку приложения; сказать правду стоит одной строки.
    ///
    /// Ядра это не касается вовсе: почта просто не становится ступенью,
    /// и §5.4 ведёт себя так же, как до заведения ящика. Поэтому событие
    /// идёт мимо `Engine::step`, прямо в UI.
    MailLoginFailed {
        /// Что именно не вышло — словами, для показа человеку.
        reason: String,
    },
    /// Кадр ушёл: сервер принял письмо (§5.3, §9.4).
    ///
    /// Событие почты и только почты. У прямых каналов «записали в сокет»
    /// ничего не доказывает — полуоткрытое соединение принимает байты
    /// молча, — и потому доказательством там служит квитанция. У почты
    /// квитанций нет по построению (§9.4), зато есть настоящий ответ
    /// сервера на `DATA`: письмо принято и поставлено в очередь.
    ///
    /// Между командой и этим событием проходят секунды напрямую и десятки
    /// секунд через Tor — вход, `MAIL FROM`, тело письма. Всё это время
    /// кадр **не отправлен**, и говорить обратное нельзя (§14).
    Handed {
        /// Кому.
        peer_ik: [u8; 32],
        /// Каким транспортом.
        via: Transport,
        /// Метка из [`TransportCommand::Send`].
        handoff: u64,
    },
    /// Попытка соединения не удалась в отведённый таймаут (§5.4).
    ConnectFailed {
        /// С кем.
        peer_ik: [u8; 32],
        /// Каким транспортом.
        via: Transport,
    },
    /// Как идёт подъём Tor (§5.2, §13.1).
    ///
    /// Событие существует ради одного вопроса, на который иначе нечем
    /// ответить: «оно ещё поднимается или уже не поднимется?» Bootstrap
    /// занимает десятки секунд в хорошем случае и не кончается никогда
    /// в плохом — когда сеть Tor недоступна, — и снаружи эти два случая
    /// неотличимы. Молчать о них §14 не разрешает.
    TorProgress {
        /// Доля готовности, от 0 до 1.
        fraction: f32,
        /// Что происходит сейчас — словами arti, для показа человеку.
        note: String,
        /// Почему подъём стоит, если он стоит.
        ///
        /// Именно это отвечает на «arti стартовал, но не может подключиться»:
        /// пустое поле означает «идёт, просто долго», непустое — «встал,
        /// и вот причина».
        blocked: Option<String>,
    },
    /// Tor поднялся и опубликовал onion-сервис (§5.2, §13.1).
    ///
    /// Несёт адрес, потому что до этого мгновения его никто не знает: ключ
    /// сервиса лежит в хранилище arti, и адрес становится известен, только
    /// когда сервис запущен. Ядро на это событие объявляет адрес контактам
    /// (§4.3) — иначе о нём не узнает никто, кроме тех, кто отсканирует
    /// новый QR.
    TorReady {
        /// Опубликованный адрес вида `<56 символов>.onion`.
        onion: String,
    },
    /// Chatmail-сервер завёл ящик (§5.3).
    MailAccountCreated {
        /// Адрес, который выдал сервер.
        address: String,
        /// Пароль, который выдал сервер.
        ///
        /// Тип, а не `String`: события драйвер пишет в журнал целиком.
        password: ratatosk_proto::mail::Secret,
    },
    /// Сервер объявил предел письма (`SIZE` в ответе на `EHLO`, RFC 1870).
    ///
    /// Уезжает после каждого удачного входа по SMTP. Отдельным событием,
    /// а не полем в [`TransportEvent::Ready`], по двум причинам: предел
    /// сообщает SMTP, а объём ящика — IMAP, и это два разных разговора
    /// с двумя разными моментами; и предел бывает **неизвестен**, а поле
    /// с `None` в общем событии читалось бы как «предела нет».
    ///
    /// Это предел **нашего** сервера. Предел сервера получателя невидим
    /// и таким останется: письмо уходит релеем, о котором мы не знаем ничего.
    MailLetterLimit {
        /// Байт на письмо. `None` — сервер не назвал числа.
        bytes: Option<u64>,
    },
    /// Сервер сказал, сколько занято в ящике и сколько всего (IMAP `QUOTA`).
    ///
    /// Уезжает после входа по IMAP и после каждой разборки ящика: числа
    /// меняются от того, что мы сами оттуда вычищаем.
    ///
    /// **В байтах.** RFC 2087 считает `STORAGE` килобайтами, и множитель
    /// применён при разборе: два места, считающие в разных единицах, —
    /// вопрос времени, а не вероятности.
    ///
    /// Событие не приходит вовсе, если сервер не умеет `QUOTA` или объявил
    /// ящик безлимитным. Молчание здесь означает «объём неизвестен», и это
    /// не то же, что «ноль».
    MailQuota {
        /// Занято, байт.
        used_bytes: u64,
        /// Весь объём, байт.
        limit_bytes: u64,
    },
    /// Завести ящик не вышло (§5.3, §14).
    ///
    /// Отдельным событием, а не молчанием: человек нажал «завести почту»
    /// и ждёт ответа. Причина — словами, потому что «сервер отказал»,
    /// «сети нет» и «ссылка не та» чинятся по-разному.
    MailAccountFailed {
        /// Что именно не вышло.
        reason: String,
    },
}

/// Отказ транспорта.
#[derive(Debug, thiserror::Error)]
pub enum TransportError {
    /// Ошибка ввода-вывода.
    #[error("ошибка ввода-вывода: {0}")]
    Io(#[from] std::io::Error),
    /// Транспорт выключен пользователем или сборкой.
    #[error("транспорт недоступен")]
    Unavailable,
    /// Не уложились в таймаут (§5.4).
    #[error("таймаут соединения")]
    Timeout,
    /// Адрес получателя неизвестен.
    #[error("адрес получателя неизвестен")]
    NoAddress,
    /// Очередь на запись переполнена, кадр не принят.
    ///
    /// Это не отказ соединения: оно живо, просто пишет медленнее, чем в него
    /// кладут. Отличать важно — на отказ §5.4 переходит к следующему
    /// транспорту, а на затор переходить некуда: там та же сеть.
    ///
    /// Возвращается только на объёмных кадрах (класс L, чанки файлов).
    /// Мелкий кадр вместо этого дожидается места в очереди: терять
    /// сообщение или квитанцию ради миллисекунды нечестно.
    #[error("очередь на запись переполнена")]
    Busy,
    /// Отказ службы обнаружения (mDNS, §5.1).
    #[error("обнаружение недоступно: {0}")]
    Discovery(String),
    /// Отказ с внятной причиной, которую можно показать человеку.
    ///
    /// Отдельно от [`TransportError::Unavailable`] («транспорта нет
    /// в сборке») и [`TransportError::Timeout`] («не дождались»): здесь путь
    /// есть и ответ пришёл, но ответ — отказ. Сервер сказал «слишком много
    /// попыток», TLS не установился, вход отвергнут.
    ///
    /// Различие не в устройстве, а в том, что человек может с этим сделать.
    /// «Транспорт недоступен» он прочтёт как поломку приложения; «сервер
    /// ответил 429» — как повод подождать.
    #[error("{0}")]
    Refused(String),
}

/// Исполнитель команд ядра.
#[allow(async_fn_in_trait)]
pub trait Runner {
    /// Выполняет команду.
    async fn execute(&mut self, command: TransportCommand) -> Result<(), TransportError>;

    /// Ждёт следующее событие.
    ///
    /// `None` означает, что раннер остановлен.
    async fn next_event(&mut self) -> Option<TransportEvent>;
}
