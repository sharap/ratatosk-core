#!/usr/bin/env python3
"""Метелка: объявление регистрируется одним способом, и после снятия есть пауза.

Правило словами: **все регистрации объявления идут через `announce`,
а между снятием прежнего объявления и новым стоит пауза `ADVERT_SETTLE`.**

Заведена по настоящей поломке, снятой с PinePhone 25 ноября.

`drop` у ручки объявления в `bluer` только роняет `oneshot::Sender`;
само снятие делает фоновая задача, и `UnregisterAdvertisement` уезжает
по D-Bus уже после того, как `drop` вернулся (прочитано в `bluer-0.17.4`,
`src/adv.rs`: в `Drop` там пустое тело с пояснением «required for drop
order»). Значит новая регистрация идёт наперегонки со снятием прежней.
У контроллера без расширенного объявления место под объявление одно,
и новая регистрация в этой гонке отказывает:

    09:38:51  эфир: объявились slot=1995110 ключ=a672eede
    09:45:02  эфир не поднялся error=объявление: Failed to register
                advertisement
    09:45:02  ступень перестала работать — §5.4 её больше не выбирает

Эфир на том устройстве жил ровно до первой границы слота — и дальше
лежал до перезапуска приложения.

Проверить это прогоном **нельзя**: `Adapter` у `bluer` — чужой
конкретный тип, подделки у нас нет, а гонка живёт в чужой фоновой
задаче. Убери паузу — ни одна проверка не покраснеет. Та же причина,
что у `platform_gates` и `power_watched`.

Чего эта метелка **не** стережёт: что паузы хватает. Срок снятия
принадлежит `bluetoothd`; ровно поэтому сверх паузы стоит повтор,
и его наличие метелка как раз стережёт — через правило «регистрация
только через `announce`».

**Комментарии снимаются перед сличением.** Это четвёртый случай одной
ошибки в этом наборе (`advert_interval` искала слово по всему файлу,
`enum_arms` не снимала полный путь, `incoming_said` дала ложную зелень
от фразы в соседнем комментарии) — и здесь она была бы особенно
вероятна: разбор правки поминает и `ADVERT_SETTLE`, и `announce`
прямо рядом с кодом.

Находок должно быть ноль. Поломка проверяется так: убрать паузу после
`drop(handle)` — метелка краснеет; позвать `adapter.advertise` в петле
напрямую, минуя `announce`, — тоже.
"""
import pathlib
import re
import sys

# Корень дерева считается от самого файла, а не от текущего каталога:
# метелку зовут и из корня, и из CI, и по одной из редактора.
ROOT = pathlib.Path(__file__).resolve().parents[2]

RADIO = "crates/transport/src/bluetooth/local.rs"

# Единственное место, где `bluer` просят объявиться. Всё остальное
# ходит через него — в нём и живёт повтор.
GATE = "async fn announce("


def without_comments(source: str) -> str:
    """Убирает строчные и документирующие комментарии целиком.

    Грубо нарочно: цена ошибки в другую сторону — пропущенная находка —
    невелика, а ложная тревога стоит доверия ко всему набору. Строковых
    литералов с `//` в этом файле нет; появись они, правило сузим.
    """
    kept = []
    for line in source.split("\n"):
        stripped = line.lstrip()
        if stripped.startswith("//"):
            continue
        kept.append(re.sub(r"\s//.*$", "", line))
    return "\n".join(kept)


bad = []
path = ROOT / RADIO
if not path.exists():
    bad.append(f"{RADIO}: файла нет — метёлке нечего смотреть")
    code = ""
else:
    code = without_comments(path.read_text(encoding="utf-8"))

if code:
    if GATE not in code:
        bad.append(
            f"{RADIO}: нет `{GATE}` — регистрация объявления обязана ходить "
            f"одним путём, в котором живёт повтор"
        )
    # Пауза стоит ровно между снятием и новой регистрацией: сличается
    # пара строк, а не присутствие имени где-нибудь в файле.
    pair = re.search(r"drop\(handle\);\s*tokio::time::sleep\(ADVERT_SETTLE\)\.await;", code)
    if not pair:
        bad.append(
            f"{RADIO}: после `drop(handle)` нет `sleep(ADVERT_SETTLE)` — снятие "
            f"объявления асинхронно, и новая регистрация пойдёт наперегонки с ним"
        )
    # Прямых обращений к `advertise` должно быть ровно одно — внутри
    # `announce`. Второе означает путь, в котором повтора нет.
    direct = re.findall(r"\.advertise\(", code)
    if len(direct) != 1:
        bad.append(
            f"{RADIO}: обращений `.advertise(` {len(direct)}, а должно быть одно — "
            f"внутри `announce`; лишнее означает путь без повтора"
        )

# Молчание — не «чисто»: сколько правил осмотрено, видно всегда.
print("\n".join(bad) if bad else "чисто (правил вокруг регистрации объявления осмотрено: 3)")
sys.exit(1 if bad else 0)
