    fn a_message_and_an_edit_are_told_apart() {
        // Оба несут `Message` в одном и том же поле, и различает их только
        // код вида. Разойдись коды — «поправлено» показалось бы вторым
        // сообщением, то есть дублем в чате.
        let message = Message {
            msg_id: [1u8; 16],
            chat: [2u8; 16],
            mine: true,
            text: "текст".into(),
            wall_ms: 4,
            status: None,
            reactions: Vec::new(),
            edited_ms: None,
            forwarded: false,
            reply_to: None,
            files: Vec::new(),
        };
        let arrived =
            notice_from_payload(&through_cbor(&notice_payload(&Notice::Message(message.clone()))))
                .unwrap();
        let edited =
            notice_from_payload(&through_cbor(&notice_payload(&Notice::Edited(message.clone()))))
                .unwrap();
        assert_eq!(arrived, Notice::Message(message.clone()));
        assert_eq!(edited, Notice::Edited(message));
        assert_ne!(arrived, edited);
    }

    #[test]
    fn response_kinds_have_their_own_numbering() {
        // Регрессия, найденная круговым тестом до первой сборки. Все три
        // набора видов звались `KIND_*`, и в ответах `Done` получил единицу
        // — ту же, что `Chats`. Разбор брал первую подходящую ветку,
        // «сделано» превращалось в «список чатов» и падало на отсутствующем
        // поле со списком.
        //
        // Здесь коды закреплены поимённо: совпадение внутри одного набора
        // сломает этот тест, а не поведение на стенде.
        let kinds = |response: &Response| {
            let value = response_payload(1, response);
            let map = canonical::as_map(&value).unwrap().to_vec();
            canonical::as_u64(canonical::get(&map, KEY_KIND).unwrap()).unwrap()
        };
        assert_eq!(kinds(&Response::Chats(Vec::new())), RESPONSE_CHATS);
        assert_eq!(kinds(&Response::History(Vec::new())), RESPONSE_HISTORY);
        assert_eq!(kinds(&Response::Done), RESPONSE_DONE);
        assert_eq!(kinds(&Response::Refused(String::new())), RESPONSE_REFUSED);
        assert_eq!(
            kinds(&Response::FileChunk { index: 0, bytes: Vec::new() }),
            RESPONSE_FILE_CHUNK
        );
        assert_eq!(kinds(&Response::Hello { wire: 1 }), RESPONSE_HELLO);
        assert_eq!(
            kinds(&Response::FileOffer { file_id: [1u8; 16], chunk_total: 1 }),
            RESPONSE_FILE_OFFER
        );
        assert_eq!(kinds(&Response::FilePreview { bytes: None }), RESPONSE_FILE_PREVIEW);
        assert_eq!(kinds(&Response::Staged { files: Vec::new() }), RESPONSE_STAGED);

        let all = [
            RESPONSE_CHATS,
            RESPONSE_HISTORY,
            RESPONSE_DONE,
            RESPONSE_REFUSED,
            RESPONSE_FILE_CHUNK,
            RESPONSE_HELLO,
            RESPONSE_FILE_OFFER,
            RESPONSE_FILE_PREVIEW,
            RESPONSE_STAGED,
        ];
        for (at, code) in all.iter().enumerate() {
            assert!(
                !all[..at].contains(code),
                "два вида ответа делят код {code} — разбор возьмёт первый"
            );
        }
    }

    #[test]
    fn a_paused_download_is_told_apart_from_a_stalled_one() {
        // Одни и те же числа, и разница только в согласии: «идёт приём»
        // против «человек остановил». Без этого поля пауза выглядела бы
        // как зависший приём — стоят числа, а почему, неизвестно.
        let going = Notice::FileProgress {
            file_id: [1u8; 16],
            have_chunks: 4,
            chunk_total: 9,
            accepted: true,
        };
        // Обновление полей через `..` у варианта перечисления не работает —
        // выписываем целиком, и это к лучшему: видно, что различие ровно одно.
        let paused = Notice::FileProgress {
            file_id: [1u8; 16],
            have_chunks: 4,
            chunk_total: 9,
            accepted: false,
        };
        let back = |notice: &Notice| notice_from_payload(&through_cbor(&notice_payload(notice)));
        assert_eq!(back(&going).unwrap(), going);
        assert_eq!(back(&paused).unwrap(), paused);
        assert_ne!(back(&going).unwrap(), back(&paused).unwrap());
    }

    #[test]
    fn pausing_and_declining_are_told_apart_on_the_wire() {
        // Поля у них одинаковы, а означают разное и необратимое по-разному:
        // пауза оставляет приехавшее, отказ уносит и его, и запись.
        let pause = Request::PauseFile { file_id: [1u8; 16] };
        let decline = Request::DeclineFile { file_id: [1u8; 16] };
        let back = |request: &Request| {
            request_from_payload(&through_cbor(&request_payload(1, request))).unwrap().1
        };
        assert_eq!(back(&pause), pause);
        assert_eq!(back(&decline), decline);
        assert_ne!(back(&pause), back(&decline));
    }

    #[test]
    fn an_older_build_answers_hello_with_silence_and_that_is_the_signal() {
        // Здесь проверяется **свойство разбора**, на котором держится вся
        // проверка версий: сборка, не знающая вида `Hello`, не разберёт
        // просьбу вовсе — а телефон неразобранную просьбу отбрасывает молча
        // (`Engine::on_device_frame`). Значит молчание и есть ответ «я старее».
        //
        // Ловится оно порядком: `Hello` спрашивается до списка чатов, и ответ
        // на список, пришедший первым, означает, что на `Hello` ответа не будет.
        let hello = through_cbor(&request_payload(1, &Request::Hello));
        let map = canonical::as_map(&hello).unwrap();
        let kind = canonical::as_u64(canonical::get(map, KEY_KIND).unwrap()).unwrap();
        assert_eq!(kind, REQUEST_HELLO);
        assert!(kind > REQUEST_CHATS, "новый вид обязан быть новым числом, а не занятым");
    }

