//! Провод между телефоном и десктопом-компаньоном (§13.4).
//!
//! Телефон — единственный носитель идентичности и единственное хранилище
//! истории. Десктоп является терминалом к нему: своих `IK`/`SK`, своего
//! onion-адреса и своего chatmail-аккаунта у него нет, и для всех контактов
//! существует **один** пользователь.
//!
//! # Новой криптографии здесь нет, и это главное свойство
//!
//! §13.4 называет режим компаньона «локальным RPC поверх уже построенных
//! механизмов». Сопряжение — тот же Noise IK, что и с контактом; кадр тот же
//! (§7); транспорт тот же (§5.4: сперва LAN, потом onion, и сессия одного
//! семейства не продолжается в другом). Меняется только то, что внутри кадра,
//! — и оно описано здесь.
//!
//! Отсюда следует и объём этого модуля: он про **представление**, а не про
//! безопасность. Всё, что защищает канал, уже написано и проверено для
//! контактов.
//!
//! # Кто чей ключ
//!
//! Ролей две, и путать их нельзя.
//!
//! * **Телефон** отвечает на рукопожатие своим долговременным `IK` (§3).
//!   Ничего нового он для сопряжения не заводит.
//! * **Десктоп** отвечает **ключом сопряжения** — X25519, который телефон
//!   генерирует на каждое сопряжение и отдаёт в QR целиком, вместе
//!   с секретной половиной.
//!
//! Ключ сопряжения — не идентичность. Он одноразовый по назначению
//! («вот этот ноутбук»), отзывается удалением записи и не даёт десктопу
//! никакого положения в глазах контактов: они видят одного пользователя
//! и его единственный `IK`.
//!
//! Секретная половина существует ровно в двух местах: в показанном QR
//! и на десктопе. Телефон её не хранит — ему довольно публичной, чтобы
//! узнать своё устройство в рукопожатии. Хранить обе значило бы держать
//! рядом с историей ещё и ключ, которым эту историю можно запросить.
//!
//! # Чего этот провод не делает
//!
//! Квитанций (§9.4) у него нет: канал локальный, и «доставлено» здесь
//! означало бы «телефон в сети», а это и так видно по тому, отвечает ли он.
//! Своей очереди доставки тоже нет — запрос, оставшийся без ответа,
//! десктоп повторяет сам, когда канал вернётся.

