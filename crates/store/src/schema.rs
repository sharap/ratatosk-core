/// Подписка на канал и поколения ключа чтения (фаза 2, §10.3, §10.4, §6.4).
///
/// # `channel_subscriptions` — это **наша сторона**, а не канал
///
/// Про сам канал говорит подписанное представление; здесь лежит то, что
/// знаем только мы: с какой ссылки пришли и на чём остановились.
///
/// **`min_version` — то, ради чего таблица и заведена.** §10.3 шаг 4:
/// представление ниже названной ссылкой версии не принимать. На этом
/// держится §10.7 — отзыва ссылки не бывает, но владелец поднимает
/// версию, и старые ссылки перестают пускать. Без источника этого числа
/// правило было в коде и не действовало.
///
/// **`kind_claimed` — обещание ссылки, а не факт.** Расхождение
/// с подписанным документом означает, что ссылка обещает доступ, которого
/// нет; это отказ, а не подсказка.
///
/// **`state` нужен ровно потому, что §10.5 обещает часы ожидания.**
/// Без него «заявка отправлена» и «впустили» неотличимы после
/// перезапуска, а показывать человеку надо именно разницу.
///
/// Адресов из ссылки здесь нет: они недоверенные, одноразовые — по ним
/// стучатся за представлением — и живут неделями, а строка проживёт год.
/// Хранить их значило бы завести кэш, устаревающий молча.
///
/// # `channel_archive_keys` — поколения, и они **сосуществуют**
///
/// §6.4: архив не теряется при повороте, читатель держит прежние
/// поколения для истории и получает новое для будущего. Значит поворот
/// строк не удаляет; чистит их только окно сидирования, и то лишь когда
/// выброшено всё, что они разворачивают.
///
/// У открытого канала поколение ровно одно — ключ из ссылки (§10.4),
/// и поворота там не бывает: ключ у всех, кому ссылку переслали,
/// и отобрать его нельзя ни у кого.
