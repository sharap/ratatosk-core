//! Доказательство работы на запись в канал (фаза 2, §11).
//!
//! # Зачем оно вообще
//!
//! В открытом канале состав неизвестен, сервера нет, ограничителя частоты
//! нет. PoW — цена за право сказать слово там, где не действует
//! приглашение. Больше ни для чего он здесь не нужен: в канале
//! по приглашению впускает владелец, и цена уже уплачена впуском.
//!
//! # Чего он **не** делает, и это надо знать до применения
//!
//! §11 говорит это прямо, и повторить стоит: PoW поднимает пол против
//! тривиального флуда. **Против видеокарты он не работает, а телефон
//! наказывает всерьёз.** Это фильтр первого уровня, а не защита; баны
//! за подписью и приглашения он не отменяет.
//!
//! Отсюда и предел [`MAX_BITS`]: сложность задаёт владелец канала,
//! и без потолка одна опечатка в его настройке сделала бы канал
//! непишущим для всех, у кого телефон.
//!
//! # С чем связывается
//!
//! `(group_id, author_ik, хэш тела)`. Иначе работу переиспользуют
//! в другом канале или под другим текстом.
//!
//! **Эпохи здесь нет, хотя §11 её называет.** В нашем блоке поля эпохи
//! не существует, и добавлять его ради связывания не нужно: тело блока —
//! это шифротекст цепочки отправителя, и он различен у каждого сообщения
//! по построению. Переиспользовать работу «в другой эпохе под тем же
//! текстом» нельзя, потому что тот же текст в другой эпохе даёт другое
//! тело. Эпоха понадобится have-вектору (§7.2), и вот там её и заводить.
//!
//! # Почему обычный хэш, а не `derive_key`
//!
//! Здесь ничего не выводится: результат не ключ, а число, у которого
//! считают нули. Разделение областей даёт приставка [`DOMAIN`] — она
//! и не даёт спутать эту работу ни с какой другой.

use crate::error::{CryptoError, Result};

/// Приставка, отделяющая эту работу от всякой другой.
///
/// Менять нельзя: она входит в то, что считает и проверяет чужая
/// сторона, то есть в совместимость на проводе.
pub const DOMAIN: &[u8] = b"ratatosk v0 pow\x00";

/// Наибольшая сложность, которую вправе назначить владелец канала.
///
/// Двадцать четыре бита — около шестнадцати миллионов хэшей, единицы
/// секунд на телефоне. **Потолок не декоративный:** сложность задаёт
/// владелец (§11), и без него одна опечатка в его настройке сделала бы
/// канал непишущим для всех, у кого нет видеокарты, — причём молча,
/// потому что отказ выглядел бы как «долго считается».
pub const MAX_BITS: u32 = 24;

/// Сколько нонсов перебрать, прежде чем сдаться.
///
/// Предел стоит не ради скорости, а ради **честного отказа**. Поиск
/// вероятностный: при законной сложности он сойдётся за считанные
/// миллионы попыток, но гарантии этому нет никакой. Без предела
/// отправка одного сообщения могла бы не вернуться никогда, и наружу
/// это вышло бы зависшим приложением, а не сообщением об ошибке.
///
/// Число — с большим запасом к [`MAX_BITS`]: шестнадцать ожидаемых
/// попыток на каждую нужную. Не сойтись за столько — событие, у которого
/// вероятность меньше, чем у отказа диска.
pub const MAX_TRIES: u64 = 1 << 28;

/// Хэш, у которого считают ведущие нули.
fn digest(group: &[u8; 16], author_ik: &[u8; 32], body: &[u8], nonce: u64) -> [u8; 32] {
    let mut hasher = blake3::Hasher::new();
    hasher.update(DOMAIN);
    hasher.update(group);
    hasher.update(author_ik);
    // **Длины тела здесь нет, и это выяснилось поломкой.**
    //
    // Она стояла — «иначе склейка короткого тела с хвостом даст ту же
    // работу, что длинное тело», — и сломать проверку при ней не удалось:
    // убери длину, и ни один тест не падал. Причина простая. Склейка
    // неоднозначна только тогда, когда границу переменного поля нельзя
    // восстановить; здесь тело зажато между полями **постоянной ширины**
    // (шестнадцать байт канала и тридцать два автора слева, восемь байт
    // нонса справа), и граница читается с обоих концов.
    //
    // Поле, которое нельзя провалить, — не защита, а строка, которую
    // будет поддерживать следующий. Появится после тела что-нибудь
    // переменной длины — длину придётся вернуть, и тогда у неё будет
    // проверка, которую можно сломать.
    hasher.update(body);
    hasher.update(&nonce.to_le_bytes());
    *hasher.finalize().as_bytes()
}

/// Сколько ведущих нулевых бит у этого хэша.
fn leading_zero_bits(hash: &[u8; 32]) -> u32 {
    let mut bits = 0;
    for byte in hash {
        bits += byte.leading_zeros();
        if *byte != 0 {
            break;
        }
    }
    bits
}

/// Годится ли этот нонс при такой сложности.
///
/// Нулевая сложность — годится любой, и работы не требуется вовсе.
/// Так у всякого канала по приглашению и у всякой группы.
#[must_use]
pub fn holds(group: &[u8; 16], author_ik: &[u8; 32], body: &[u8], nonce: u64, bits: u32) -> bool {
    if bits == 0 {
        return true;
    }
    leading_zero_bits(&digest(group, author_ik, body, nonce)) >= bits
}

/// Ищет нонс, дающий нужное число нулей.
///
/// Перебор с нуля, а не со случайного места: работа связана с телом,
/// а тело различно у каждого сообщения, и начинать с одного и того же
/// нонса безопасно. Случайное начало дало бы только иллюзию разнообразия
/// и лишний источник недетерминизма в симуляции (§16).
///
/// # Errors
///
/// [`CryptoError::Pow`] — сложность выше [`MAX_BITS`] либо перебор
/// не сошёлся за [`MAX_TRIES`] попыток.
pub fn solve(group: &[u8; 16], author_ik: &[u8; 32], body: &[u8], bits: u32) -> Result<u64> {
    if bits == 0 {
        return Ok(0);
    }
    if bits > MAX_BITS {
        return Err(CryptoError::Pow);
    }
    for nonce in 0..MAX_TRIES {
        if leading_zero_bits(&digest(group, author_ik, body, nonce)) >= bits {
            return Ok(nonce);
        }
    }
    Err(CryptoError::Pow)
}

#[cfg(test)]
mod tests {
    use super::*;

    const GROUP: [u8; 16] = [7u8; 16];
    const AUTHOR: [u8; 32] = [9u8; 32];

    #[test]
    fn what_was_solved_holds() {
        for bits in [1u32, 4, 8, 12] {
            let nonce = solve(&GROUP, &AUTHOR, "слово".as_bytes(), bits).expect("сошлось");
            assert!(holds(&GROUP, &AUTHOR, "слово".as_bytes(), nonce, bits), "сложность {bits}");
        }
    }

    #[test]
    fn work_for_one_channel_does_not_count_in_another() {
        // **Главная проверка модуля.** Не свяжи мы работу с каналом,
        // одного найденного нонса хватило бы, чтобы писать всюду.
        let nonce = solve(&GROUP, &AUTHOR, "слово".as_bytes(), 12).expect("сошлось");
        assert!(!holds(&[8u8; 16], &AUTHOR, "слово".as_bytes(), nonce, 12), "другой канал");
        assert!(!holds(&GROUP, &[10u8; 32], "слово".as_bytes(), nonce, 12), "другой автор");
        assert!(!holds(&GROUP, &AUTHOR, "другое".as_bytes(), nonce, 12), "другое тело");
    }

    #[test]
    fn a_body_that_is_a_prefix_of_another_gets_different_work() {
        // Стояла здесь проверка «длина тела в хэше», и сломать её
        // не удалось: длину можно было убрать, и ничего не падало.
        // Склейка неоднозначна только там, где границу переменного поля
        // не восстановить, а здесь тело зажато полями постоянной ширины.
        //
        // Осталось то, что проверка действительно стережёт: тело, которое
        // короче или длиннее на символ, — это другая работа.
        let nonce = solve(&GROUP, &AUTHOR, "абв".as_bytes(), 12).expect("сошлось");
        assert!(!holds(&GROUP, &AUTHOR, "аб".as_bytes(), nonce, 12));
        assert!(!holds(&GROUP, &AUTHOR, "абвг".as_bytes(), nonce, 12));
    }

    #[test]
    fn a_harder_target_is_not_met_by_an_easier_solution() {
        // Нонс, найденный на малой сложности, обязан не подходить
        // к большой — иначе владелец поднял бы её, ничего не изменив.
        // Перебираются несколько тел: один найденный нонс случайно может
        // дать и больше нулей, чем просили.
        let mut easier_failed_somewhere = false;
        for body in ["один".as_bytes(), "два".as_bytes(), "три".as_bytes(), "четыре".as_bytes()]
        {
            let nonce = solve(&GROUP, &AUTHOR, body, 4).expect("сошлось");
            if !holds(&GROUP, &AUTHOR, body, nonce, 16) {
                easier_failed_somewhere = true;
            }
        }
        assert!(easier_failed_somewhere, "лёгкая работа обязана не проходить за тяжёлую");
    }

    #[test]
    fn zero_bits_cost_nothing_and_accept_anything() {
        // Так у канала по приглашению и у всякой группы: работы нет,
        // и любой нонс годится. Отдельная проверка затем, чтобы нулевая
        // сложность не оказалась однажды «невыполнимой».
        assert_eq!(solve(&GROUP, &AUTHOR, "слово".as_bytes(), 0).expect("без работы"), 0);
        for nonce in [0u64, 1, u64::MAX] {
            assert!(holds(&GROUP, &AUTHOR, "слово".as_bytes(), nonce, 0));
        }
    }

    #[test]
    fn a_difficulty_past_the_ceiling_is_refused_instead_of_hanging() {
        // Потолок — про честный отказ. Без него владелец, поставивший
        // сорок бит, сделал бы канал непишущим, и выглядело бы это
        // не отказом, а зависшим приложением.
        assert!(solve(&GROUP, &AUTHOR, "слово".as_bytes(), MAX_BITS + 1).is_err());
        assert!(solve(&GROUP, &AUTHOR, "слово".as_bytes(), 64).is_err());
    }

    #[test]
    fn leading_zeros_are_counted_across_byte_boundaries() {
        // Счёт нулей — место, где легко ошибиться на байт: посчитай мы
        // только целые нулевые байты, сложность 9 равнялась бы восьми.
        assert_eq!(leading_zero_bits(&[0u8; 32]), 256);
        let mut hash = [0u8; 32];
        hash[0] = 0b0000_0001;
        assert_eq!(leading_zero_bits(&hash), 7);
        hash[0] = 0;
        hash[1] = 0b0100_0000;
        assert_eq!(leading_zero_bits(&hash), 9, "нули обязаны считаться через границу байта");
    }
}
