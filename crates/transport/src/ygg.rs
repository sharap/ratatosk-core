    #[tokio::test]
    async fn a_peer_without_a_key_is_refused_before_any_socket() {
        // Отказ по имени, а не по таймауту: ключа нет — соединяться не с кем,
        // и платить за это восемью секундами человек не должен.
        let mut runner =
            YggRunner::start(YggConfig { enabled: false, port: 0 }, &[9u8; 32]).await.unwrap();
        // Включение с портом 0 привязывается к своему адресу — а его
        // на машине проверки нет, поэтому ступень остаётся выключенной.
        // Проверяется здесь другое: отказ приходит **до** сокета.
        // Без `{verdict:?}`: `Link` намеренно не печатается — в нём две
        // отправляющие половины, и показывать их в отказе нечего.
        let verdict = runner.ensure_link(&peer(None));
        assert!(
            matches!(verdict, Err(TransportError::NoAddress)),
            "ключа нет — отказ обязан прийти по имени, а не по таймауту"
        );
    }

    #[cfg(feature = "ygg-node")]
    #[tokio::test]
    async fn switching_on_an_embedded_node_returns_before_it_rises() {
        // Смысл поставки. Подъём своего узла — это соединение с пирами,
        // то есть секунды, а ждались они внутри `Driver::apply`: ядро
        // объявляет включённые транспорты первым делом при старте, и до
        // конца этого ожидания приложение не показывало даже переписку
        // из своей базы.
        //
        // Пир заведомо мёртвый: проверяется не подъём, а то, что команда
        // не ждёт его исхода.
        let mut runner =
            YggRunner::start(YggConfig { enabled: false, port: 0 }, &[9u8; 32]).await.unwrap();
        let setup = ratatosk_proto::ygg::YggSetup::Embedded {
            seed: ratatosk_proto::ygg::NodeSeed::new(vec![1u8; 32]),
            peers: vec!["tcp://127.0.0.1:1".to_owned()],
        };
        runner.execute(TransportCommand::SetYgg(setup)).await.expect("настройка принимается");

        let switched = tokio::time::timeout(
            Duration::from_millis(500),
            runner
                .execute(TransportCommand::SetEnabled { transport: Transport::Ygg, enabled: true }),
        )
        .await
        .expect("включение обязано вернуться, не дожидаясь подъёма");
        assert!(switched.is_ok(), "включение принято: подъём пошёл в фон");
        assert!(!runner.is_ready(), "готовность объявляется после подъёма, а не при включении");
    }

    #[tokio::test]
    async fn a_changed_network_forgets_the_links_and_says_so() {
        // Сокеты прежней сети об обрыве ещё не знают — узнают на первой
        // записи. §5.4 без этой новости заплатил бы сроком ожидания за то,
        // что уже известно.
        let mut runner =
            YggRunner::start(YggConfig { enabled: false, port: 0 }, &[9u8; 32]).await.unwrap();
        // Набор, удавшийся сразу: проверяется смена сети, а не сеть.
        let (writer, _reader) = tokio::io::duplex(64);
        let link = Link::dialing(
            async move { Ok::<_, TransportError>(writer) },
            [2u8; 32],
            Transport::Ygg,
            runner.events_tx.clone(),
        );
        runner.links.insert([2u8; 32], link);

        runner
            .execute(TransportCommand::NetworkChanged)
            .await
            .expect("о смене сети сказать можно всегда");
        assert!(runner.links.is_empty(), "связи прежней сети мертвы, держать их не за что");

        // Пропускаем состоявшееся соединение: оно приезжает первым.
        let dropped = tokio::time::timeout(Duration::from_secs(5), async {
            while let Some(event) = runner.next_event().await {
                if let TransportEvent::Disconnected { peer_ik, via } = event {
                    return Some((peer_ik, via));
                }
            }
            None
        })
        .await
        .expect("новость об обрыве обязана приехать в срок");
        assert_eq!(dropped, Some(([2u8; 32], Transport::Ygg)), "обрыв обязан быть назван");
    }

