/// bech32 (BIP-173) — ровно столько, сколько нужно NIP-19.
///
/// # Почему своя реализация, а не чужой крейт
///
/// Тот же довод, что у адреса Yggdrasil (`ygg::address_of`), и тот же
/// порядок величин: шестьдесят строк на чистом `std` против зависимости
/// ради одной функции. Проверено оно так же — стендом на `rustc`, который
/// гоняет её на векторах BIP-173 и NIP-19, а не «написано по описанию».
mod bech32 {
    /// Алфавит bech32. Порядок значащий: индекс символа и есть его значение.
    const CHARSET: &[u8; 32] = b"qpzry9x8gf2tvdw0s3jn54khce6mua7l";

    /// Контрольная сумма BIP-173.
    fn polymod(values: &[u8]) -> u32 {
        const GEN: [u32; 5] = [0x3b6a_57b2, 0x2650_8e6d, 0x1ea1_19fa, 0x3d42_33dd, 0x2a14_62b3];
        let mut chk: u32 = 1;
        for value in values {
            let top = chk >> 25;
            chk = ((chk & 0x1ff_ffff) << 5) ^ u32::from(*value);
            for (n, g) in GEN.iter().enumerate() {
                if (top >> n) & 1 == 1 {
                    chk ^= g;
                }
            }
        }
        chk
    }

    /// Развёртка префикса: старшие пятёрки, ноль, младшие пятёрки.
    fn hrp_expand(hrp: &str) -> Vec<u8> {
        let mut out: Vec<u8> = hrp.bytes().map(|c| c >> 5).collect();
        out.push(0);
        out.extend(hrp.bytes().map(|c| c & 31));
        out
    }

    /// Пересыпает биты из группы в группу.
    ///
    /// `pad` различает две стороны: на записи хвост добивается нулями,
    /// на чтении добитый хвост обязан быть нулевым и короче группы —
    /// иначе строка несёт байты, которых в ней нет.
    fn convert_bits(data: &[u8], from: u32, to: u32, pad: bool) -> Option<Vec<u8>> {
        let mut acc: u32 = 0;
        let mut bits: u32 = 0;
        let mut out = Vec::new();
        let max = (1u32 << to) - 1;
        for value in data {
            let value = u32::from(*value);
            if (value >> from) != 0 {
                return None;
            }
            acc = (acc << from) | value;
            bits += from;
            while bits >= to {
                bits -= to;
                out.push(((acc >> bits) & max) as u8);
            }
        }
        if pad {
            if bits > 0 {
                out.push(((acc << (to - bits)) & max) as u8);
            }
        } else if bits >= from || ((acc << (to - bits)) & max) != 0 {
            return None;
        }
        Some(out)
    }

    /// Собирает строку `<префикс>1<данные><контрольная сумма>`.
    pub(super) fn encode(hrp: &str, payload: &[u8]) -> String {
        let data = convert_bits(payload, 8, 5, true).expect("8→5 с добивкой не отказывает");
        let mut values = hrp_expand(hrp);
        values.extend_from_slice(&data);
        values.extend_from_slice(&[0; 6]);
        let checksum = polymod(&values) ^ 1;

        let mut out = String::with_capacity(hrp.len() + 1 + data.len() + 6);
        out.push_str(hrp);
        out.push('1');
        for value in data {
            out.push(CHARSET[value as usize] as char);
        }
        for n in 0..6 {
            let value = ((checksum >> (5 * (5 - n))) & 31) as usize;
            out.push(CHARSET[value] as char);
        }
        out
    }

    /// Разбирает строку, требуя ровно этот префикс.
    ///
    /// `None` на всё подозрительное: чужой префикс, смешанный регистр,
    /// символ вне алфавита, не сошедшаяся контрольная сумма. Разбирать
    /// «почти правильную» строку нельзя — она означает опечатку в ключе,
    /// то есть чужую личность.
    pub(super) fn decode(hrp_want: &str, text: &str) -> Option<Vec<u8>> {
        if text.bytes().any(|c| !(33..=126).contains(&c)) {
            return None;
        }
        // Смешанный регистр запрещён: строка целиком либо строчная, либо
        // прописная. Иначе одна и та же строка имела бы два вида, а
        // контрольная сумма считается по одному из них.
        let lower = text.to_ascii_lowercase();
        if lower != text && text.to_ascii_uppercase() != text {
            return None;
        }

        let split = lower.rfind('1')?;
        let (hrp, rest) = lower.split_at(split);
        if hrp != hrp_want || rest.len() < 7 {
            return None;
        }

        let mut data = Vec::with_capacity(rest.len() - 1);
        for c in rest[1..].bytes() {
            data.push(u8::try_from(CHARSET.iter().position(|x| *x == c)?).ok()?);
        }

        let mut values = hrp_expand(hrp);
        values.extend_from_slice(&data);
        if polymod(&values) != 1 {
            return None;
        }

        convert_bits(&data[..data.len() - 6], 5, 8, false)
    }
}

