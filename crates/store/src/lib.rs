//! Локальное хранилище (§12).
//!
//! SQLite (`rusqlite`). Чувствительные поля шифруются на уровне приложения
//! ключом `db_key`; метаданные схемы остаются открытыми.
//!
//! Поиск — **не** FTS5 по открытому тексту, как предполагала §12 и первая
//! схема. Индекс хранит хэши слов на `db_key` ([`tokens`]): полнотекстовый
//! индекс положил бы рядом с зашифрованными телами их незашифрованную копию
//! и свёл бы `body_enc` к декорации.
//!
//! Хранилище синхронное и это осознанно: SQLite синхронен по природе, а ядро
//! (§13.3) построено как sans-io — недетерминизм в нём допускается только
//! от сети, но не от диска. Поэтому [`Store`] — обычный трейт с блокирующими
//! методами, а не async.

