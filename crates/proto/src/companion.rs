    fn the_secret_never_reaches_the_log() {
        // Приглашение проходит командами и входами, а их драйвер пишет
        // в журнал целиком. Производный `Debug` вынес бы ключ сопряжения
        // в открытый лог на устройстве.
        let printed = format!("{:?}", invite());
        assert!(printed.contains("<скрыт>"));
        assert!(!printed.contains("9, 9, 9"), "байты ключа не должны печататься: {printed}");
    }

