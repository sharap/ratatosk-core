//! Уведомления чата: чего человек от него хочет (фаза 2, §14).
//!
//! # Чего здесь нет, и это не забывчивость
//!
//! **Упоминаний.** «Уведомлять только когда упомянули» — обычная
//! настройка, и завести её нельзя: разметки упоминаний в протоколе нет
//! ни в одном кадре, и отличить «назвали меня» от «написали слово,
//! похожее на имя» ядру нечем. Настройка, за которой не стоит
//! поведения, хуже отсутствующей: человек её включит и будет думать,
//! что она работает.
//!
//! **Звуков, вибрации и вида шторки.** Это показ, а не протокол
//! (§13.3), и решает его клиент. Ядро отвечает на один вопрос:
//! **говорить об этом чате или молчать**.

/// Что делать с уведомлениями чата.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Mode {
    /// Говорить. Умолчание — и оно же то, чего человек не выбирал.
    #[default]
    Speak,
    /// Молчать.
    Silent,
}

impl Mode {
    /// Число для диска. Ноль — умолчание, и это не случайность:
    /// столбец добавляется миграцией со значением по умолчанию,
    /// и прежние чаты обязаны прочитаться как «говорить».
    #[must_use]
    pub const fn code(self) -> u32 {
        match self {
            Mode::Speak => 0,
            Mode::Silent => 1,
        }
    }

    /// Обратно с диска. Незнакомое читается как «говорить».
    ///
    /// Не отказ: строку кладём мы сами, и сборка постарше, встретив код
    /// из новой, обязана не замолчать, а продолжать говорить. Ошибиться
    /// в сторону молчания значит потерять сообщение молча — худший
    /// из двух исходов.
    #[must_use]
    pub const fn from_code(code: u32) -> Mode {
        match code {
            1 => Mode::Silent,
            _ => Mode::Speak,
        }
    }
}

/// Настройка уведомлений одного чата.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct Notify {
    /// Чего хочет человек.
    pub mode: Mode,
    /// До какого момента, мс. Ноль — «пока не передумаю».
    ///
    /// Срок нужен затем же, зачем он нужен правам (§6.3): «замолчать
    /// до утра» — это то, что человек делает чаще всего, а снимать
    /// настройку руками он забудет. Ноль здесь означает бессрочно,
    /// а не «уже истёк»: истёкшим сроком выражается возврат к умолчанию,
    /// и путать их нельзя.
    pub until_ms: u64,
}

impl Notify {
    /// Говорить ли об этом чате **сейчас**.
    ///
    /// Один ответ на оба поля, и считает его ядро: срок истекает сам,
    /// и клиент, считающий это у себя, разошёлся бы с ядром на границе
    /// суток.
    #[must_use]
    pub const fn speaks_at(self, now_ms: u64) -> bool {
        match self.mode {
            Mode::Speak => true,
            // Срок вышел — молчание кончилось, и настройка снова
            // умолчание. Стирать её при этом незачем: запись мала,
            // а стирание потребовало бы повода просыпаться.
            Mode::Silent => self.until_ms != 0 && now_ms >= self.until_ms,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn silence_without_a_deadline_lasts_until_it_is_taken_off() {
        let forever = Notify { mode: Mode::Silent, until_ms: 0 };
        assert!(!forever.speaks_at(0));
        assert!(!forever.speaks_at(u64::MAX));
    }

    #[test]
    fn silence_with_a_deadline_ends_by_itself() {
        // Числа свои: граница обязана быть включающей с той стороны,
        // где молчание кончается, — «до девяти» значит, что в девять
        // уже говорим.
        let until_nine = Notify { mode: Mode::Silent, until_ms: 9_000 };
        assert!(!until_nine.speaks_at(8_999));
        assert!(until_nine.speaks_at(9_000));
        assert!(until_nine.speaks_at(9_001));
    }

    #[test]
    fn speaking_is_the_default_and_ignores_the_deadline() {
        // Срок у «говорить» бессмыслен, и читается он как ничто:
        // иначе снятое молчание с остатком срока однажды замолчало бы
        // снова.
        let speak = Notify { mode: Mode::Speak, until_ms: 1 };
        assert!(speak.speaks_at(0));
        assert_eq!(Notify::default(), Notify { mode: Mode::Speak, until_ms: 0 });
    }

    #[test]
    fn an_unknown_code_from_disk_reads_as_speaking() {
        assert_eq!(Mode::from_code(0), Mode::Speak);
        assert_eq!(Mode::from_code(1), Mode::Silent);
        assert_eq!(Mode::from_code(7), Mode::Speak);
    }
}
