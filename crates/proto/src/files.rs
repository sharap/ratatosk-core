    #[test]
    fn the_window_is_bytes_and_survives_a_smaller_chunk() {
        // **Развязка размера чанка и окна.** Прежде окно было числом
        // чанков, и «два» означало два мебибайта только потому, что чанк
        // был мебибайтом. Эфирной ступени чанк предстоит уменьшить
        // (§10.2), и прежнее «два» дало бы восемь килобайт в полёте —
        // то есть остановку передачи там, где канал быстрый.
        for via in [Transport::Lan, Transport::Ygg, Transport::Onion] {
            assert_eq!(
                chunk_window(via, CHUNK_BYTES),
                2,
                "прямым каналом окно как было — два чанка"
            );
        }
        assert_eq!(chunk_window(Transport::Mail, CHUNK_BYTES), 8, "почтой — восемь, как было");

        // А вот ради чего всё: чанк вчетверо мельче мебибайта даёт вчетверо
        // больше чанков в окне, и байт в полёте остаётся столько же.
        let small = 4 * 1024;
        for via in [Transport::Lan, Transport::Onion] {
            let chunks = chunk_window(via, small);
            assert_eq!(chunks * small as u64, window_bytes(via), "байт в полёте столько же");
            assert!(chunks > 2, "мелкому чанку положено большее окно, а не то же: {chunks}");
        }

        // И граница: чанк больше целого окна не обнуляет передачу.
        assert_eq!(
            chunk_window(
                Transport::Lan,
                usize::try_from(window_bytes(Transport::Lan)).unwrap() * 2
            ),
            1,
            "окно в ноль чанков означало бы передачу, которая не начинается"
        );
    }

    #[test]
    fn the_stall_deadline_outlasts_a_window_but_not_by_much() {
        // **Проверка с двух сторон, и вторая появилась дорого.**
        //
        // Снизу: срок молчания короче времени передачи не ускоряет
        // возобновление, а ломает её совсем. Получатель объявляет молчанием
        // чанк, который прямо сейчас идёт по проводу, отправитель отматывает
        // окно и кладёт в ту же линию второй экземпляр того же куска — и
        // передача разгоняет сама себя в обратную сторону.
        //
        // Сверху: **этого-то и не проверялось**, и оттого эфирный срок
        // прожил целую дугу вчетверо длиннее, чем следовало. Число там было
        // посчитано от окна в два мебибайта; окно стало сорока восемью
        // килобайтами, а число осталось — десять минут вместо восемнадцати
        // секунд. Нижняя граница на такое не жалуется: ей чем больше,
        // тем лучше. Наружу вышло «файлы зависают на определённой стадии,
        // хотя сообщения ходят»: один потерянный кадр — и тишина на десять
        // минут, потом на двадцать.
        //
        // Скорость берётся **из политики** (`floor_bytes_per_sec`), а не
        // пишется здесь числом. Второе такое число однажды разошлось бы
        // с первым, и разошлось бы молча.
        for via in
            [Transport::Lan, Transport::Bt, Transport::Ygg, Transport::Onion, Transport::Mail]
        {
            // Почтой байты проходят сеть дважды: до сервера и с сервера,
            // — и едут раздутыми в письме, а не голым кадром.
            let (window_bytes, hops) = match via {
                Transport::Mail | Transport::Nostr => (mail_window_bytes(), 2),
                // Размером **этой** ступени, а не своим умолчанием: эфир
                // режет мельче, и мерить его чужим числом значило бы
                // проверять не то окно, которое там будет.
                _ => {
                    let chunk = chunk_bytes_for(via);
                    (chunk_window(via, chunk) * chunk as u64, 1)
                }
            };
            let speed =
                crate::transport_policy::floor_bytes_per_sec(via).unwrap_or(SLOW_BYTES_PER_SEC);
            let needed_ms = window_bytes * hops * 1_000 / speed;
            assert!(
                stall_ms(via) >= needed_ms,
                "в срок молчания обязано помещаться целое окно {via:?}: нужно {needed_ms} мс, \
                 отведено {}",
                stall_ms(via)
            );
            // Потолок — тот же расчёт с запасом, плюс нижняя черта: она
            // законно поднимает срок у быстрых ступеней, где окно уходит
            // за секунды.
            let allowed = needed_ms * STALL_WINDOW_FACTOR + MIN_STALL_MS;
            assert!(
                stall_ms(via) <= allowed,
                "срок молчания {via:?} оторвался от своего окна: окно идёт {needed_ms} мс, \
                 а ждём {} при потолке {allowed}. Каждый потерянный кадр стоит этого срока \
                 целиком — перечитайте разбор у `stall_ms`",
                stall_ms(via)
            );
        }
        // По локальной сети мебибайт уходит за миллисекунды, и срок там нужен
        // не для скорости, а чтобы оборванная передача вообще возобновилась.
        assert!(
            stall_ms(Transport::Lan) < stall_ms(Transport::Onion),
            "у транспортов разная цена мебибайта — значит и сроки разные"
        );
        assert!(
            stall_ms(Transport::Onion) < stall_ms(Transport::Mail),
            "круг почты — минуты, и срок обязан это признавать"
        );
    }

    #[test]
    fn a_lost_frame_in_the_air_costs_seconds_and_not_minutes() {
        // **Число поимённо, потому что дорого обошлось именно оно.**
        // Эфир — единственная ступень, где потеря кадра дело обычное,
        // и цена ей — ровно этот срок тишины. Полминуты человек считает
        // задержкой; десять минут он считает поломкой и закрывает
        // приложение.
        let air = stall_ms(Transport::Bt);
        assert!(
            air <= 60_000,
            "потерянный кадр в эфире обязан стоить секунд, а не минут: сейчас {air} мс"
        );
        // И всё-таки заведомо больше одного окна: см. разбор выше.
        let chunk = chunk_bytes_for(Transport::Bt);
        let window_ms = chunk_window(Transport::Bt, chunk) * chunk as u64 * 1_000
            / crate::transport_policy::floor_bytes_per_sec(Transport::Bt).expect("ступень прямая");
        assert!(air > window_ms, "окно идёт {window_ms} мс, а застой объявляется через {air}");
    }

