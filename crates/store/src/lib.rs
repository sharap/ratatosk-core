/// Ключ в служебной таблице: по какому формату построен поисковый индекс.
///
/// Хранит [`tokens::INDEX_FORMAT`]. Отсутствие записи или **любое другое**
/// значение означает, что индекс надо построить заново: сравнение идёт
/// на равенство, а не «меньше», — откат на прежнюю сборку тоже повод
/// пересобрать, а не повод искать по чужим токенам.
///
/// **Не версия схемы, и это существенно.** Сперва признаком служило
/// `user_version`: «база младше девятой — переиндексировать». Работало ровно
/// до следующей миграции, потому что версия схемы отвечает на вопрос «какие
/// таблицы есть», а не «заполнены ли они». Наполнение индекса — операция над
/// **данными**, у неё своя жизнь: индекс может понадобиться перестроить
/// и без единой правки схемы — при смене токенизации, например.
///
/// Побочная польза: чтобы заставить базу переиндексироваться, достаточно
/// стереть эту строку.
pub const META_SEARCH_INDEX: &str = "search_index_format";

/// Ключ в служебной таблице: когда уборка (§12) проходила в последний раз.
///
/// На диске, а не в памяти, и это существенно: телефон перезапускается чаще,
/// чем раз в шесть часов. Считай мы от старта процесса, интервал не наступал
/// бы никогда, и уборка держалась бы на одном счётчике сообщений — то есть
/// не работала бы у того, кто переписывается мало, а именно у него база и
/// живёт годами.
///
/// Открыто: «когда последний раз прибирались» не говорит ни о переписке,
/// ни о собеседниках.
pub const META_LAST_COMPACTION: &str = "last_compaction_ms";

/// Ключ в служебной таблице: до какого места в чате уже отправлена квитанция
/// о прочтении (§9.4).
///
/// Открыто, и это не послабление: `chat_id` и метки HLC и так лежат
/// в `messages` открытым текстом — по ним строится порядок (§9.1) и индекс.
/// Запечатывать здесь то, что рядом лежит в открытую, значило бы изображать
/// защиту, а не давать её.
#[must_use]
pub fn read_upto_key(chat_id: &[u8; 16]) -> String {
    use std::fmt::Write as _;

    let mut key = String::from("read_upto/");
    for byte in chat_id {
        let _ = write!(key, "{byte:02x}");
    }
    key
}

