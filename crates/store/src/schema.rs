/// **Что это чинит.** Кадр про группу, которой узел ещё не знает, ложится
/// в очередь до появления недостающего — представления группы, карточки
/// участника, ключа отправителя. Очередь жила только в памяти, и убийство
/// приложения уносило её целиком: кадр, заставший перезапуск, пропадал
/// совсем. Снаружи это выглядит как «сообщение не пришло», хотя оно
/// приходило и лежало.
///
/// # Ни одного внешнего ключа, и это не упущение
///
/// Ни на `messages`, ни на `chats`: **ничего этого ещё нет** — в том
/// и смысл очереди. Кадр лежит именно потому, что группа неизвестна,
/// а сообщение под его номером не заведено. Внешний ключ отверг бы
