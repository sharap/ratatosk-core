//! Объявление BLE шестой ступени (0.4).
//!
//! Ступень Bluetooth не требует ни точки доступа, ни интернета — только двух
//! устройств в одной комнате. Всё, что ей нужно сверх уже написанного
//! кадрирования, — это **найти собеседника в эфире**: канал дальше идёт
//! потоком (L2CAP CoC), а поток — ровно то, чем параметризован `link`.
//!
//! Здесь лежит формат объявления и ничего больше: ни сокетов, ни адаптера,
//! ни сканирования. Раннер (`ratatosk_transport`) берёт отсюда байты, кладёт
//! их в объявление своей платформы и разбирает ими же чужие.
//!
//! # Что везёт объявление
//!
//! Две вещи и обе обязательные:
//!
//! * **запись маяка** — те же шестнадцать байт, что уходят в TXT-запись
//!   mDNS (§5.1): случайная соль и значение, выведенное из `IK`, слота
//!   и соли. Опознать по ней контакт может только тот, у кого его `IK`
//!   уже есть; постороннему она не говорит ничего и меняется со временем;
//! * **номер PSM** — порт канала L2CAP, на котором мы слушаем. Документация
//!   Android про `createL2capChannel` прямо говорит, что приложение обязано
//!   добыть PSM у удалённого устройства **вне канала**; вот он и добывается
//!   объявлением. GATT-сервер при такой раскладке не нужен ни на одной
//!   стороне.
//!
//! Больше в объявление не влезает почти ничего, и это не фигура речи:
//! у legacy-объявления BLE полезной нагрузки [`ADV_PAYLOAD_MAX`] байт
//! на всё сразу. Арифметика бюджета собрана в [`advert_total_len`]
//! и закреплена проверкой, а не глазами.
//!
//! # Чего в объявлении нет — и почему
//!
//! **Нет опознавателя «это Ratatosk».** Соблазн поставить в начало байт-магию
//! велик: разбор становится дешевле, а чужие объявления отсеиваются сразу.
//! Плата за это — ровно то, ради чего писан маяк: магия говорит всякому
//! сканирующему «на этом устройстве стоит вот этот мессенджер». Маяк прячет
//! **кого** — и было бы странно тут же объявить **что**.
//!
//! Поэтому опознание идёт не по магии, а по маяку: [`Advert::matches`]
//! против известных `IK`. Дороже это ровно на три хеша BLAKE3 на контакт
//! (слоты −1, 0, +1) — при сотне контактов это сотни хешей на объявление,
//! то есть доли миллисекунды, и платится эта цена только за объявления
//! с нашим кодом производителя и нашей длиной.
//!
//! **Нет и номера версии формата.** Версию заменяет длина: полезная нагрузка
//! ровно [`PAYLOAD_LEN`] байт, и формат с другим составом будет другой
//! длины. Байт версии стоил бы того же, чем плоха магия, — он тоже
//! опознаватель, — а дал бы то же самое.
//!
//! # Чего это всё равно не прячет
//!
//! Код производителя [`COMPANY_ID`] и постоянная длина нагрузки — это
//! **признак**, по которому наши объявления отличимы от прочих. Честный
//! итог поэтому не «нас не видно», а «нас видно хуже»: наблюдатель в эфире
//! может сказать «здесь устройство, объявляющее восемнадцать байт под кодом
//! 0xFFFF», но не может сказать, чьё оно и кому предназначено, и через
//! четверть часа то же устройство объявляет другое.
//!
//! # Объявление никто не подписывает
//!
//! И подписать его нечем: подпись Ed25519 — шестьдесят четыре байта, вдвое
//! больше всего объявления. Значит запись маяка можно **повторить**: кто
//! записал чужое объявление, может в течение слота вещать его сам и увести
//! наш набор на себя.
//!
//! Стоит это ему одного неудавшегося рукопожатия. Правду про то, кто
//! на другом конце, говорит §8.2, а не эфир: статический ключ инициатора
//! в Noise IK зашифрован на ключ отвечающего, так что подставной приёмник
//! не узнаёт даже того, кто к нему пришёл. Объявление — приглашение
//! попробовать, и ничего сверх этого оно не обещает.
//!
//! # Код производителя нам не принадлежит
//!
//! [`COMPANY_ID`] равен `0xFFFF`, и это **не** выделенный нам код: коды
//! производителей раздаёт Bluetooth SIG, и у нас его нет. Что именно SIG
//! пишет про `0xFFFF`, я не проверял по первоисточнику и потому не
//! утверждаю здесь ничего; известно лишь, что значение это ничьё
//! и встречается у устройств, которым код не выделяли.
//!
//! Практическое следствие ровно одно: чужое объявление под тем же кодом
//! возможно, и разбор обязан его пережить — он и переживает, потому что
//! опознание идёт маяком. Что делать к выпуску — получать код или брать
//! шестнадцатибитный UUID сервиса — решается не здесь.

use ratatosk_crypto::identity::beacon;

/// Полезная нагрузка legacy-объявления BLE, байт.
///
/// Предел жёсткий: объявление длиннее платформа не примет вовсе.
/// Расширенное объявление (Bluetooth 5) даёт больше, но есть не везде,
/// и рассчитывать на него — значит завести ступень, работающую
/// на половине устройств.
pub const ADV_PAYLOAD_MAX: usize = 31;

/// Сколько занимает структура «флаги»: длина, тип, значение.
///
/// Ставится она не нами, а платформой, и обойтись без неё нельзя:
/// без флагов объявление не считается пригодным для подключения.
const FLAGS_AD_LEN: usize = 3;

/// Накладные расходы структуры «данные производителя»: байт длины,
/// байт типа (`0xFF`) и два байта кода производителя.
const MANUFACTURER_AD_OVERHEAD: usize = 4;

/// Код производителя, под которым едет нагрузка.
///
/// Нам он не принадлежит — см. разбор в начале модуля.
pub const COMPANY_ID: u16 = 0xFFFF;

/// Длина записи маяка — соль и значение (§5.1).
pub const RECORD_LEN: usize = 16;

/// Длина нагрузки: запись маяка и номер PSM.
///
/// Она же и номер версии формата — другого в объявлении нет.
pub const PAYLOAD_LEN: usize = RECORD_LEN + 2;

/// Первый PSM динамического диапазона Bluetooth LE.
///
/// Ниже него слушать нельзя без `CAP_NET_BIND_SERVICE` — это не наше
/// правило, а ядерное: `L2CAP_PSM_LE_DYN_START` в `l2cap.h`, и `bluer`
/// объявляет его же константой `PSM_LE_DYN_START`.
pub const PSM_LE_DYN_START: u16 = 0x0080;

/// Наибольший PSM Bluetooth LE (`L2CAP_PSM_LE_DYN_END`, он же `PSM_LE_MAX`).
pub const PSM_LE_MAX: u16 = 0x00ff;

/// Что прочиталось из объявления.
///
/// Заметьте, чего здесь нет: `IK`. Объявление его не везёт и везти не может
/// — в этом весь смысл маяка. Превратить объявление в контакт умеет только
/// тот, у кого `IK` уже есть, и делает он это [`Advert::matches`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Advert {
    /// Запись маяка: соль и значение (§5.1).
    pub record: [u8; RECORD_LEN],
    /// Номер PSM, на котором объявивший слушает канал L2CAP.
    pub psm: u16,
}

impl Advert {
    /// Этот ли контакт объявился.
    ///
    /// Слоты −1, 0 и +1, как и в локальной сети: без соседних слотов контакт
    /// становится невидимым на границе каждые пятнадцать минут, и виноваты
    /// в этом не часы, а мы.
    #[must_use]
    pub fn matches(&self, ik: &[u8; 32], slot: u64) -> bool {
        beacon::matches(&self.record, ik, slot)
    }
}

/// Почему объявление не годится.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum AdvertError {
    /// Длина нагрузки не наша.
    ///
    /// **Обычное дело, а не поломка.** Под кодом производителя `0xFFFF`
    /// вещает кто угодно, и раннеру эта ошибка встретится чаще всех прочих
    /// вместе взятых. В журнал её надо класть на уровне трассировки —
    /// или не класть вовсе.
    #[error("длина нагрузки {0} байт, а формат ждёт {PAYLOAD_LEN}")]
    Length(usize),
    /// PSM вне динамического диапазона Bluetooth LE.
    ///
    /// При сборке это наша ошибка: слушать на таком номере мы не сможем.
    /// При разборе — либо объявление не наше вовсе, либо кто-то пытается
    /// направить наш набор на фиксированный номер; ни то ни другое
    /// продолжать не стоит.
    #[error("PSM {0:#06x} вне диапазона {PSM_LE_DYN_START:#06x}..={PSM_LE_MAX:#06x}")]
    Psm(u16),
}

/// Годится ли номер для канала L2CAP поверх LE.
#[must_use]
pub const fn psm_is_dynamic_le(psm: u16) -> bool {
    psm >= PSM_LE_DYN_START && psm <= PSM_LE_MAX
}

/// Собирает нагрузку объявления.
///
/// Отдаётся именно нагрузка, а не готовое объявление целиком, и это
/// не полумера: структуры объявления собирает платформа. На Linux `bluer`
/// берёт `manufacturer_data` таблицей «код → байты», на Android
/// `AdvertiseData.addManufacturerData` — тем же. Собери мы тридцать один
/// байт сами, их всё равно пришлось бы разбирать обратно.
///
/// Порядок байт номера PSM — старшим вперёд, как во всём остальном
/// протоколе. Код производителя платформа кладёт младшим вперёд сама,
/// и к нашей нагрузке это отношения не имеет.
///
/// # Ошибки
///
/// [`AdvertError::Psm`], если номер не из динамического диапазона LE.
/// Это не придирка: такой номер означает, что слушать нам не дадут, —
/// и объявить его значило бы позвать собеседника в никуда.
pub fn payload(record: &[u8; RECORD_LEN], psm: u16) -> Result<[u8; PAYLOAD_LEN], AdvertError> {
    if !psm_is_dynamic_le(psm) {
        return Err(AdvertError::Psm(psm));
    }
    let mut out = [0u8; PAYLOAD_LEN];
    out[..RECORD_LEN].copy_from_slice(record);
    out[RECORD_LEN..].copy_from_slice(&psm.to_be_bytes());
    Ok(out)
}

/// Разбирает нагрузку чужого объявления.
///
/// Ждёт **только** байты под кодом [`COMPANY_ID`] — распутывать структуры
/// объявления не её дело, это уже сделала платформа.
///
/// Успех здесь **не означает**, что объявился знакомый: он означает, что
/// байты сложены как наши. Знакомый ли — отвечает [`Advert::matches`],
/// и только он.
///
/// # Ошибки
///
/// [`AdvertError::Length`] — не наша длина; [`AdvertError::Psm`] — номер
/// вне динамического диапазона LE.
pub fn parse(data: &[u8]) -> Result<Advert, AdvertError> {
    if data.len() != PAYLOAD_LEN {
        return Err(AdvertError::Length(data.len()));
    }
    let record: [u8; RECORD_LEN] = data[..RECORD_LEN].try_into().expect("срез нужной длины");
    let psm = u16::from_be_bytes(data[RECORD_LEN..].try_into().expect("срез длины 2"));
    if !psm_is_dynamic_le(psm) {
        return Err(AdvertError::Psm(psm));
    }
    Ok(Advert { record, psm })
}

/// Во сколько байт объявления обходится ступень целиком.
///
/// Флаги плюс структура данных производителя плюс нагрузка. Считается
/// здесь затем, чтобы бюджет [`ADV_PAYLOAD_MAX`] был **посчитан**,
/// а не предположен: в `HANDOFF.md` (6з) это записано как то, что надо
/// померить до первой строки раннера.
///
/// Имя устройства в этот счёт не входит и входить не должно. Android
/// добавляет его в объявление сам, если не сказать обратного
/// (`setIncludeDeviceName(false)`), и стоит оно двух байт плюс длина имени
/// — то есть и бюджет рвёт, и вещает в эфир имя телефона. Раннеру это
/// правило записано в спецификации 0.4.
#[must_use]
pub const fn advert_total_len() -> usize {
    FLAGS_AD_LEN + MANUFACTURER_AD_OVERHEAD + PAYLOAD_LEN
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Номер из середины диапазона — в разборе он ничем не лучше краёв,
    /// но в тексте проверок читается как «обычный».
    const SOME_PSM: u16 = 0x0091;

    #[test]
    fn a_payload_survives_a_round_trip_through_the_air() {
        let record = beacon::record(&[7u8; 32], 100, [3u8; 8]);
        let bytes = payload(&record, SOME_PSM).expect("номер из динамического диапазона");
        let back = parse(&bytes).expect("свою же нагрузку обязаны разобрать");
        assert_eq!(back, Advert { record, psm: SOME_PSM });
    }

    #[test]
    fn the_payload_layout_is_frozen() {
        // Формат уезжает в эфир, и разбирать его будет чужая сборка — та,
        // что стоит на втором устройстве и обновляется отдельно. Поэтому
        // раскладка закрепляется вектором, а не описанием: перестановка
        // полей местами проходит все прочие проверки этого модуля целиком.
        let record: [u8; RECORD_LEN] = [
            0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d,
            0x0e, 0x0f,
        ];
        let bytes = payload(&record, 0x00a5).expect("номер из диапазона");
        assert_eq!(
            bytes,
            [
                0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d,
                0x0e, 0x0f, 0x00, 0xa5,
            ],
            "запись маяка, затем PSM старшим байтом вперёд"
        );
    }

    #[test]
    fn the_whole_advert_fits_a_legacy_packet() {
        // Ровно то, что `HANDOFF.md` (6з) велел померить, а не предположить.
        assert!(
            advert_total_len() <= ADV_PAYLOAD_MAX,
            "объявление {} байт при пределе {ADV_PAYLOAD_MAX}",
            advert_total_len()
        );
        // Запас называется числом нарочно: он и есть ответ на вопрос
        // «что ещё влезет». Шесть байт — это ещё одна структура с четырьмя
        // байтами внутри. Имя устройства в них не помещается ни у кого:
        // структура стоит два байта плюс само имя, а имена телефонов
        // начинаются от десятка символов. Отсюда и правило выключать имя
        // руками — не из экономии, а потому что иначе объявления не будет
        // вовсе.
        assert_eq!(ADV_PAYLOAD_MAX - advert_total_len(), 6, "запас объявления");
    }

    #[test]
    fn a_psm_outside_the_le_range_is_refused_on_both_ends() {
        let record = beacon::record(&[1u8; 32], 1, [0u8; 8]);

        // Сборка: слушать на таком номере нам не дадут (ниже
        // `PSM_LE_DYN_START` нужен `CAP_NET_BIND_SERVICE`), и объявить его
        // значило бы позвать собеседника в никуда.
        assert_eq!(payload(&record, 0x0001), Err(AdvertError::Psm(0x0001)));
        assert_eq!(payload(&record, PSM_LE_DYN_START - 1), Err(AdvertError::Psm(0x007f)));
        assert_eq!(payload(&record, PSM_LE_MAX + 1), Err(AdvertError::Psm(0x0100)));
        // Классический BR/EDR-диапазон — тоже мимо: канал у нас LE.
        assert_eq!(payload(&record, 0x1001), Err(AdvertError::Psm(0x1001)));

        // Края диапазона принимаются: это границы, а не запреты.
        assert!(payload(&record, PSM_LE_DYN_START).is_ok());
        assert!(payload(&record, PSM_LE_MAX).is_ok());

        // Разбор: тот же отказ, и по той же причине — набирать такой номер
        // мы не пойдём.
        let mut bytes = payload(&record, SOME_PSM).expect("номер из диапазона");
        bytes[RECORD_LEN..].copy_from_slice(&0x0001u16.to_be_bytes());
        assert_eq!(parse(&bytes), Err(AdvertError::Psm(0x0001)));
    }

    #[test]
    fn foreign_bytes_are_refused_by_length_and_not_by_luck() {
        // Под кодом производителя `0xFFFF` вещает кто угодно, и разбор
        // обязан это пережить.
        assert_eq!(parse(&[]), Err(AdvertError::Length(0)));
        assert_eq!(parse(&[0u8; PAYLOAD_LEN - 1]), Err(AdvertError::Length(PAYLOAD_LEN - 1)));
        assert_eq!(parse(&[0u8; PAYLOAD_LEN + 1]), Err(AdvertError::Length(PAYLOAD_LEN + 1)));

        // А вот нагрузка нашей длины от постороннего разберётся — и это
        // не дыра: разбор говорит только «байты сложены как наши».
        // Знакомство проверяется маяком, и посторонний его не проходит.
        let mut foreign = [0u8; PAYLOAD_LEN];
        foreign[RECORD_LEN..].copy_from_slice(&SOME_PSM.to_be_bytes());
        let advert = parse(&foreign).expect("длина и номер годные");
        assert!(!advert.matches(&[9u8; 32], 100), "чужие байты не становятся контактом");
    }

    #[test]
    fn only_the_contact_recognises_the_advert() {
        let mine = [5u8; 32];
        let stranger = [6u8; 32];
        let record = beacon::record(&mine, 200, [1u8; 8]);
        let advert = parse(&payload(&record, SOME_PSM).expect("номер")).expect("нагрузка");

        assert!(advert.matches(&mine, 200));
        assert!(!advert.matches(&stranger, 200), "посторонний не узнаёт контакт");
    }

    #[test]
    fn the_advert_survives_a_slot_boundary_but_not_a_stale_quarter_hour() {
        // Соседние слоты приняты — иначе контакт пропадает из эфира каждые
        // пятнадцать минут из-за расхождения часов на секунду.
        let ik = [4u8; 32];
        let record = beacon::record(&ik, 300, [2u8; 8]);
        let advert = parse(&payload(&record, SOME_PSM).expect("номер")).expect("нагрузка");
        for slot in [299, 300, 301] {
            assert!(advert.matches(&ik, slot), "слот {slot} обязан приниматься");
        }
        // А запись прошлого часа — уже нет: в этом и смысл ротации.
        assert!(!advert.matches(&ik, 304));
    }

    #[test]
    fn the_advert_changes_when_the_slot_does() {
        // Объявление, не меняющееся со временем, — это долговременный
        // опознаватель устройства, то есть ровно то, чего §5.1 избегает.
        let ik = [8u8; 32];
        let salt = [3u8; 8];
        let now = payload(&beacon::record(&ik, 400, salt), SOME_PSM).expect("номер");
        let later = payload(&beacon::record(&ik, 401, salt), SOME_PSM).expect("номер");
        assert_ne!(now, later);
    }
}
