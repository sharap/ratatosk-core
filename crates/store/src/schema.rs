/// Размер чанка хранится вместе с файлом (§10.2 + пересылка).
///
/// **Что это чинит.** Размер чанка выбирает отправитель в 0.4.8 по худшей
/// ступени: по эфиру файл режется на куски по `AIR_CHUNK_BYTES`, иначе —
/// по `CHUNK_BYTES`. Дальше он нужен на **каждый** кусок, и пережить
/// перезапуск обязан, а в записи файла лежали только размер и число
/// чанков. Восстанавливался он из этой пары перебором обоих кандидатов —
/// точно, но лишь пока кандидатов двое.
///
/// Пересылке этого мало, и вот почему. У пересланного файла нарезка
/// **чужая**: её выбрал тот, кто отправлял его первым, по своей ступени,
/// а не по нашей. Восстановить её перебором нельзя — перебор знает лишь
/// наши собственные размеры, а тот, кто резал, мог однажды получить
/// третий. Столбец отвечает на вопрос «как этот файл нарезан» правдой,
/// а не выводом.
///
/// # Старые записи проставляются тем же правилом, каким их резали
///
/// Не умолчанием: умолчание сказало бы про уже лежащий файл неправду,
/// и пересылка эфирного файла, принятого до этой миграции, читала бы его
/// кусками по мебибайту. Оба числа вписаны здесь литералами и такими
/// и останутся — на момент этой миграции живые записи резались именно
/// ими, и правдой о прошлом остаются они, даже если константы в коде
/// однажды поменяются.
///
/// Порядок проверки — мелкий раньше крупного, как и было у перебора:
/// на файле в один чанк подходят оба, и мелкий безопаснее — он проходит
/// по любой ступени. Пустой файл (нуль чанков) не подходит ни одному
/// и получает размер провода: резать в нём нечего.
///
/// # Выгружаемые с десктопа файлы — тем же столбцом
///
/// `staged_files` (§13.4) — та же нарезка в том же смысле: десктоп шлёт
/// куски по номерам, а номера эти телефон назначил, когда договаривался
/// о выгрузке. Оставь столбец только у `files` — и выгрузка, пережившая
/// перезапуск телефона, мерила бы приходящие куски чужим числом
/// и отвергала бы законные.
pub const MIGRATION_0026: &str = r#"
ALTER TABLE files ADD COLUMN chunk_bytes INTEGER NOT NULL DEFAULT 0;

UPDATE files
   SET chunk_bytes = 3765
 WHERE size_bytes > 0
   AND chunk_total = (size_bytes + 3764) / 3765;

UPDATE files
   SET chunk_bytes = 1048245
 WHERE chunk_bytes = 0;

ALTER TABLE staged_files ADD COLUMN chunk_bytes INTEGER NOT NULL DEFAULT 0;

UPDATE staged_files
   SET chunk_bytes = 3765
 WHERE size_bytes > 0
   AND chunk_total = (size_bytes + 3764) / 3765;

UPDATE staged_files
   SET chunk_bytes = 1048245
 WHERE chunk_bytes = 0;
"#;

