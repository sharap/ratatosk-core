    /// Прогоняет нагрузку через настоящее кодирование (§6).
    ///
    /// Разбирать построенное значение напрямую недостаточно, и это не
    /// педантизм: повторяющиеся ключи в карте ловит именно кодирование
    /// (`canonical::encode` отвергает их), а по проводу нагрузка едет
    /// закодированной. Проверка «собрал и тут же разобрал» пропустила бы
    /// два поля с одним номером — самую вероятную ошибку в таблице
    /// из полутора десятков ключей.
    fn through_cbor(value: &Value) -> Value {
        let bytes = canonical::encode(value).expect("нагрузка обязана кодироваться");
        canonical::decode(&bytes).expect("и разбираться обратно")
    }

