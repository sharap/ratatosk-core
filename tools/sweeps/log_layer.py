"""Свёртка: строку журнала всюду складывает `fmt`-слой, а платформа даёт
только писателя.

Зачем. Подписчик у ядра один на процесс и ставится в `crates/ffi`:
там же и развилка платформ — `logcat` под Android, поток ошибок и файл
на десктопе. Развилка эта про то, **куда** писать, и ни про что больше.

Поломка, из которой правило выросло. Под Android слой брался у чужого
крейта целиком, вместе с его форматированием, а оно писало поля впритык
к тексту: в журнал телефона приходило «список контактов
принятизвестных=0ключи=» вместо «принят известных=0 ключи=». Полгода
никто не замечал, потому что на десктопе журнал читаемый, а телефонный
читают редко — и ровно тогда, когда уже разбирают поломку. Нашлось
на живом Redmi.

Отсюда правило: слой журнала заводится `tracing_subscriber::fmt::layer()`
в каждой ветке, а платформенный крейт попадает в строку `.with_writer(…)`
и никуда больше. Готовый чужой слой (`..._android::layer(…)`) не ставится.

Чего свёртка **не** стережёт: что строка в самом деле читаема — это
проверка `a_journal_line_separates_its_fields_from_the_text_and_from_each_other`;
и что писатель доносит её до `logcat` — это видно только с устройства.
Свёртка стережёт связь между тем и другим: что проверенный слой и есть
тот, который ставится.
"""
import pathlib
import re
import sys

# Корень дерева считается от самого файла, а не от текущего каталога:
# метелку зовут и из корня, и из CI, и по одной из редактора.
ROOT_DIR = pathlib.Path(__file__).resolve().parents[2]

# Единственное место, где ядро заводит подписчика. Стенд и компаньон
# сюда не входят сознательно: стенд ставит свой и в `logcat` не пишет,
# а компаньон зовёт именно эти функции.
WHERE = "crates/ffi/src/lib.rs"

# Как слой обязан заводиться. Строка целиком, а не по частям: `fmt`
# встречается в файле и в комментариях, и правило смолчало бы.
MUST_BUILD = "tracing_subscriber::fmt::layer()"

# Готовый слой от платформенного крейта — то, чем поломка и была.
# Ищется по хвосту имени: крейтов таких несколько (`tracing-android`,
# `paranoid-android`), и запрещён не крейт, а способ им пользоваться.
FOREIGN_LAYER = re.compile(r"\b\w*_android::layer\s*\(")

# Присваивание слоя. До первой точки с запятой: слой, собранный иначе
# (`match`, своя функция), в этот кусок не уложится — и будет назван.
ASSIGNED = re.compile(r"let layer\s*=\s*(.*?);", re.DOTALL)

found = []
seen = 0

path = ROOT_DIR / WHERE
if not path.exists():
    found.append(f"{WHERE}: подписчик пропал — свёртка смотрит не туда")
else:
    text = path.read_text(encoding="utf-8")
    for match in ASSIGNED.finditer(text):
        seen += 1
        line = text.count("\n", 0, match.start()) + 1
        if MUST_BUILD not in match.group(1):
            found.append(
                f"{WHERE}:{line}: слой журнала собран не `{MUST_BUILD}` — "
                f"форматирование строки уехало в чужой крейт"
            )
    if seen == 0:
        found.append(f"{WHERE}: слоёв журнала не нашлось вовсе — правилу не за чем следить")
    for match in FOREIGN_LAYER.finditer(text):
        line = text.count("\n", 0, match.start()) + 1
        found.append(
            f"{WHERE}:{line}: ставится готовый слой платформы — "
            f"от неё нужен только писатель"
        )

for line in found:
    print(line)
print(f"мест, где заводится слой журнала, осмотрено: {seen}")
print("-- всего", len(found) if found else "чисто")

# Находок должно быть **ноль**.
sys.exit(1 if found else 0)
