//! Чтение вложения в стороне от цикла ядра (§10.2).
//!
//! # Зачем отдельная вещь
//!
//! Сначала клиент забирал файл через ядро: [`Engine`] отдавал по куску,
//! и каждый кусок был заходом в общую очередь драйвера. Для одного куска
//! это незаметно, для файла — нет. Открытие вложения на полгигабайта — это
//! пятьсот заходов, и каждый занимает цикл ядра на время чтения с диска
//! и расшифровки мебибайта. Всё это время не уходят сообщения, не идут
//! квитанции, не срабатывают таймеры: человек открыл свою фотографию —
//! и мессенджер замер.
//!
//! Причина не в скорости расшифровки, а в том, что она стояла не там.
//! Чтение вложения **ничего не меняет** в состоянии — значит, ему незачем
//! стоять в очереди за тем, что меняет.
//!
//! # Как устроено
//!
//! Ядро отвечает на **один** вопрос: «открой мне этот файл». Ответ —
//! [`FileReader`], в котором лежит всё нужное и ничего лишнего: ключ файла,
//! число кусков и второй доступ к тем же байтам ([`ChunkSource`]). Дальше
//! клиент читает сам, из своего потока, сколько угодно долго, и ядро об этом
//! ничего не знает.
//!
//! Ключ при этом **не пересекает границу §13.3**: он живёт внутри читателя,
//! наружу выходят только расшифрованные байты. Клиент держит непрозрачную
//! ручку, а не ключевой материал.
//!
//! # Снимок, а не окно
//!
//! Читатель берёт ключ и число кусков в момент открытия и больше в базу
//! не заглядывает — иначе он снова зависел бы от ядра. Отсюда два честных
//! следствия. Файл, который **дозагружается** прямо сейчас, читается ровно
//! настолько, насколько успел приехать: чего нет, то `None`, и надо открыть
//! заново. Файл, который **удалили**, пока читатель открыт, перестаёт
//! читаться, когда исчезнут байты, — читатель не воскрешает удалённое
//! и не держит его на диске.
//!
//! [`Engine`]: crate::Engine

use std::path::PathBuf;

use ratatosk_crypto::file::FileKey;
use ratatosk_store::{ChunkSource, FileId};
use zeroize::Zeroizing;

/// Открытое на чтение вложение.
///
/// Создаётся [`Engine::open_file`](crate::Engine::open_file). Читать можно
/// из любого потока и параллельно с работой ядра — ради этого он и заведён.
pub struct FileReader {
    file_id: FileId,
    /// Обнуляется при уничтожении: ключ файла — такой же ключевой материал,
    /// как сессионный, и оставлять его в освобождённой памяти незачем.
    key: Zeroizing<FileKey>,
    chunk_total: u64,
    size_bytes: u64,
    /// Путь к исходнику — у **своего**, отправленного файла.
    ///
    /// Своё вложение и принятое читаются по-разному, и это не асимметрия ради
    /// экономии: отправитель ничего у себя не запечатывал. Он читает файл
    /// с диска по пути, пока идёт передача (копия гигабайта ради отправки
    /// потребовала бы вдвое больше места, чем у файла есть), — значит и
    /// открывать своё вложение надо оттуда же, открытым текстом.
    source: Option<PathBuf>,
    bytes: Box<dyn ChunkSource + Send + Sync>,
}

impl std::fmt::Debug for FileReader {
    /// Без ключа. Отладочный вывод попадает в журналы, а журналы — наружу.
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("FileReader")
            .field("file_id", &self.file_id)
            .field("chunk_total", &self.chunk_total)
            .field("size_bytes", &self.size_bytes)
            .field("own", &self.source.is_some())
            .finish_non_exhaustive()
    }
}

impl FileReader {
    /// Собирает читателя. Зовётся только ядром: ключ берётся из базы.
    pub(crate) fn new(
        file_id: FileId,
        key: FileKey,
        chunk_total: u64,
        size_bytes: u64,
        source: Option<PathBuf>,
        bytes: Box<dyn ChunkSource + Send + Sync>,
    ) -> FileReader {
        FileReader { file_id, key: Zeroizing::new(key), chunk_total, size_bytes, source, bytes }
    }

    /// Идентификатор файла.
    #[must_use]
    pub fn file_id(&self) -> FileId {
        self.file_id
    }

    /// Сколько всего кусков.
    #[must_use]
    pub fn chunk_total(&self) -> u64 {
        self.chunk_total
    }

    /// Размер файла целиком.
    #[must_use]
    pub fn size_bytes(&self) -> u64 {
        self.size_bytes
    }

    /// Своё ли это вложение — то, которое отправляли мы.
    #[must_use]
    pub fn own(&self) -> bool {
        self.source.is_some()
    }

    /// Расшифрованный кусок. `None` — показать нечего.
    ///
    /// Куски идут подряд, от нуля до `chunk_total - 1`; все, кроме
    /// последнего, длиной `CHUNK_BYTES`.
    ///
    /// `None` возвращается на три разных случая, и различать их клиенту
    /// не нужно: номер за концом файла, кусок ещё не приехал, кусок
    /// не прошёл проверку тега. Во всех трёх показывать нечего, а гадать
    /// о причине — не работа показа.
    ///
    /// # Errors
    ///
    /// Отказ чтения байтов. У своего вложения это чаще всего значит, что
    /// исходник удалили или перенесли: ядро его не копировало.
    pub fn chunk(&self, index: u64) -> Result<Option<Vec<u8>>, ratatosk_store::StoreError> {
        if index >= self.chunk_total {
            return Ok(None);
        }
        let Some(source) = self.source.as_deref() else {
            let Some(sealed) = self.bytes.chunk(&self.file_id, index)? else { return Ok(None) };
            return Ok(ratatosk_crypto::file::open_chunk(&self.key, &self.file_id, index, &sealed)
                .ok()
                .map(|plain| plain.to_vec()));
        };

        // Своё вложение лежит открытым текстом там, где его положил человек:
        // расшифровывать нечего, надо просто взять кусок.
        let offset = index * ratatosk_proto::files::CHUNK_BYTES as u64;
        let plain = self.bytes.read_at(source, offset, ratatosk_proto::files::CHUNK_BYTES)?;
        if plain.is_empty() {
            return Ok(None);
        }
        Ok(Some(plain))
    }
}
