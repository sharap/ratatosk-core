pub const MAX_GROUP_TITLE_CHARS: usize = MAX_LOCAL_NAME_CHARS;

/// Сколько неотправленных сообщений помнить до появления сети.
///
/// Список ограничен: очередь, растущая без предела, на телефоне кончается
