"""Свёртка: обе половины радио говорят о входящем канале.

Зачем. У ступени эфира два радио — `bluetooth/local.rs` (BlueZ)
и `android/BtRadio.kt` (мост), — и приём у них устроен одинаково:
слушающий сокет, цикл `accept`, номер каналу. Но **говорила о приёме
только одна**.

Поломка, из которой правило выросло. 24 ноября ПК набирал Redmi: сокет
открывался за четверть секунды, канал не оживал за десять, и набор
объявлялся напрасным. Что при этом происходило на телефоне — дошло ли
до `accept`, тот ли номер канала слушается, — сказать было нечем:
принимающая половина моста не писала ни строки. Разбор упёрся в тишину,
и единственным выводом стало «мы не знаем».

Отсюда правило: о входящем канале говорят **обе** половины, и обе же
говорят, когда приём кончился. И обе называют номер слушающего канала:
объявляем мы его сами, и набор не туда виден только сличением двух
журналов.

Образцы берутся **в кавычках**, и это поправка к себе же. Первая
редакция искала слова по всему файлу — и смолчала, когда строку про
входящий канал убрали: фраза осталась в соседнем комментарии, которым
эта же правка и объяснялась. Ровно та ложная зелень, что уже случалась
у `advert_interval`. Кавычка отличает сказанное от упомянутого.

Чего свёртка **не** стережёт: что строки совпадают дословно (языки
разные, и общего слова нет), и что приём в самом деле работает — это
видно только с устройства.
"""
import pathlib
import sys

# Корень дерева считается от самого файла, а не от текущего каталога:
# метелку зовут и из корня, и из CI, и по одной из редактора.
ROOT_DIR = pathlib.Path(__file__).resolve().parents[2]

# У каждой половины свои слова: Rust пишет через `tracing`, Kotlin — через
# `Log`. Сличается не текст, а то, что о каждом из трёх событий сказано.
RADIOS = {
    "crates/transport/src/bluetooth/local.rs": {
        "о входящем канале": '"эфир: входящий канал"',
        "о непринятом канале": '"эфир: канал не принят"',
        "о номере слушающего канала": '"эфир: канал L2CAP занят"',
    },
    "android/BtRadio.kt": {
        "о входящем канале": 'Log.i(TAG, "входящий канал',
        "о непринятом канале": '"приём каналов кончился',
        "о номере слушающего канала": '"слушаем L2CAP: psm',
    },
}

found = []
seen = 0

for where, needles in RADIOS.items():
    path = ROOT_DIR / where
    if not path.exists():
        found.append(f"{where}: радио пропало — свёртка смотрит не туда")
        continue
    seen += 1
    text = path.read_text(encoding="utf-8")
    for what, needle in needles.items():
        if needle not in text:
            found.append(f"{where}: молчит {what} — «{needle}» в файле нет")

for line in found:
    print(line)
print(f"радио осмотрено: {seen}")
print("-- всего", len(found) if found else "чисто")

# Находок должно быть **ноль**.
sys.exit(1 if found else 0)
