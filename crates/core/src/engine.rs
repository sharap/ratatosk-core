/// Номер первого сообщения рукопожатия в поле `counter` заголовка.
///
/// **Уточнение к §8.3.** Спецификация говорит, что кадры рукопожатия идут
/// с `session_id = 0`, но не говорит, как получатель отличает первое
/// сообщение `-> e, es, s, ss` от ответа `<- e, ee, se`. Оба приходят с нулём.
///
/// Формат кадра менять не пришлось: `counter` в заголовке (§7.1) — это
/// «номер сообщения в отправляющей цепочке», и для рукопожатия он
/// естественно читается как номер шага. Ноль — первое, единица — ответ.
/// В §8.3 это стоит дописать одной фразой.
pub const HANDSHAKE_STEP_FIRST: u64 = 0;
/// Номер ответного сообщения рукопожатия.
pub const HANDSHAKE_STEP_RESPONSE: u64 = 1;

/// Какие транспорты включены у только что заведённого ядра.
///
/// Локальная сеть — выключена: §5.1 требует этого прямо, и причина
/// не в трафике, а в том, что маяк в эфире выдаёт присутствие устройства
/// всем, кто слушает. Такое включают осознанно.
///
/// Onion и почта — включены: это транспорты, ради которых мессенджер
/// и существует, и выключенными по умолчанию они означали бы устройство,
/// которое из коробки не работает нигде.
const DEFAULT_TRANSPORTS: TransportSet =
    TransportSet::none().with(Transport::Onion).with(Transport::Mail);

/// Транспорты, которым нечего ждать: включили — значит работает.
///
/// Локальная сеть занимает порт при открытии аккаунта, до всякой команды,
/// и больше ей ждать нечего. Все остальные говорят о своей готовности сами
/// ([`Input::TransportReady`]).
///
/// Почта была здесь и не должна была: «включена» она с коробки (§5.4),
/// а работать ей не на чем, пока не заведён ящик и транспорт не вошёл
/// на сервер. Ядро при этом считало её рабочей ступенью и уводило на неё
/// сообщения — в никуда, потому что почтового раннера ещё нет вовсе.
/// Наружу это выглядело как «отправлено» у сообщения, которого никто
/// не отправлял, — то самое, что §14 запрещает прямо.
const IMMEDIATE_TRANSPORTS: TransportSet = TransportSet::none().with(Transport::Lan);

/// Страховочный таймаут попытки, если транспорт своего не задаёт.
///
/// [`Attempt::timeout_ms`] возвращает `None` для почты — её ответа ждать
/// бессмысленно (§5.4). Но запись в очереди без таймера зависла бы навсегда,
/// поэтому у прямых каналов таймаут есть всегда, а это значение — то же,
/// что вернула бы политика. Своего числа здесь нет намеренно: два срока
/// ожидания ответа, живущие в разных файлах, однажды разойдутся.
const ONION_FALLBACK_TIMEOUT_MS: u64 = ratatosk_proto::transport_policy::ONION_REPLY_TIMEOUT_MS;

/// Сколько ждать от почты подтверждения, что сервер принял письмо.
///
/// Это **не** срок ожидания ответа собеседника — по почте его ждут часами,
/// и §9.4 прямо говорит, что дальше «отправлено» статус не растёт. Это срок
/// на одно действие: вход на сервер, `MAIL FROM`, тело, ответ на `DATA`.
///
/// Пять минут — щедро и намеренно. Через Tor сюда входит построение цепочки
/// и вход на сервер, а впереди в очереди могут стоять чужие письма: почта
/// шлёт их по одному, потому что соединение с сервером одно. Занижать
/// нечего — время идёт не за счёт человека: пока письмо не ушло, сообщение
/// честно висит «отправляется», а не «отправлено».
///
/// Но и не бесконечность. Молчащий сервер обязан однажды стать внятной
/// неудачей, иначе сообщение навсегда останется в состоянии, из которого
/// нет выхода, — а это то же молчание, только с крутящимся кружком (§14).
const MAIL_HANDOFF_TIMEOUT_MS: u64 = 300_000;

/// Сколько ждать, пока обнаружение (§5.1) ответит, есть ли собеседник в сети.
///
/// Нужно ровно на холодном старте и после смены сети: `seen_on_lan` не
/// переживает перезапуск намеренно — адрес в локальной сети живёт столько же,
/// сколько подключение, и поднимать его с диска значило бы врать. Но mDNS
/// отвечает не мгновенно, и без этой паузы первое же сообщение после запуска
/// объявлялось недоставленным раньше, чем собеседник вообще успевал найтись.
///
/// Три секунды: mDNS в локальной сети отвечает за сотни миллисекунд даже на
/// телефоне, а человек, нажавший «отправить», столько подождёт. Ожидание
/// выдаётся один раз на контакт за сеанс, поэтому собеседник, которого в этой
/// сети нет, стоит трёх секунд один раз, а не при каждой отправке.
const LAN_DISCOVERY_GRACE_MS: u64 = 3_000;

/// Наибольшая длина локального имени контакта, в символах Unicode.
