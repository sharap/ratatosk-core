    fn a_duplicate_part_is_noticed_and_not_counted_twice() {
        // Дубль здесь не редкость, а устройство ступени: одно и то же
        // событие приезжает с каждого реле, на которое мы его положили.
        use crate::fragment::{Accepted, Reassembler};

        let part = Part { uid: [3u8; 16], index: 0, total: 2 };
        let mut reassembler = Reassembler::new();
        let first =
            reassembler.accept(part.uid, 0, 2, "первая".as_bytes(), 600_000, 0).expect("принята");
        assert!(matches!(first, Accepted::Pending { have: 1, total: 2 }));
        let again =
            reassembler.accept(part.uid, 0, 2, "первая".as_bytes(), 600_000, 0).expect("принята");
        assert_eq!(again, Accepted::Duplicate);
    }

