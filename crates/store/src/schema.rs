/// Представление канала и разобранные из него выдачи (фаза 2, §6.1–§6.3).
///
/// # Почему документ, а не набор блоков
///
/// Снятие права — отрицательное утверждение: «этого больше нет».
/// Отдельными блоками его не выразить, потому что **неприход надгробия
/// неотличим от «не отзывали»**, а в рое неприход штатен. Версионированный
/// документ этого лишён: пришла версия новее — в ней написано всё, что
/// действует; не пришла — действует прежняя.
///
/// # `block_bytes` сырые, и это не запас
///
/// То же правило, что у `messages.envelope_bytes` и `contacts.card_bytes`:
/// подпись проверяется над **принятыми** байтами, а не над тем, что мы
/// из них разобрали и собрали заново. Разойдись канонизация на один байт —
/// и документ, проверившийся при приёме, перестал бы проверяться после
/// перезапуска. Хранить разобранное и пересобирать значит держать две
/// канонизации в согласии вечно.
///
/// Прежние версии не хранятся. Судейство одноразово — «при первом приёме,
/// по версии, действовавшей тогда» (§6.2), — и его итог ложится
/// в сообщение, а не пересчитывается из истории документов.
///
/// # `channel_grants` — производная, и так к ней и надо относиться
///
/// Истина лежит в `block_bytes`; здесь — разобранное, чтобы «вправе ли
/// он писать» было индексом, а не разбором CBOR на каждое входящее
/// сообщение. Таблица переписывается **целиком** при приёме новой версии,
/// в одной транзакции с ней.
///
/// Столбец `version` в строке выдачи — сторож этого правила, а не
/// удобство. Разойдись он с `channel_representations.version`, значит
/// транзакция разъехалась, и увидеть это надо проверкой, а не догадкой
/// о том, почему человек вдруг перестал писать.
///
/// # Чего здесь нет
///
/// Владельца среди выдач нет никогда: у него все права и отнять их нельзя
/// (5вп). Строка «владельцу всё» была бы данными, которые обязаны
/// совпадать с правилом, — то есть вторым местом, где это правило живёт.
