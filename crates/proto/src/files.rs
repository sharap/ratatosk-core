//! Файлы (§10).
//!
//! Файл шифруется случайным `file_key` (32 байта), передаваемым в сообщении.
//! `chunk_id = BLAKE3_derive_key("ratatosk v0 file", file_key ‖ index)`.
//! Хэш для проверки целостности считается **от шифротекста**.
//!
//! Content-addressing по хэшу открытого содержимого не применяется (§10.1):
//! он позволил бы проверять наличие у вас конкретного известного файла.
//! Это не оптимизация, а решение модели угроз — менять его нельзя, не
//! переписав §2.
//!
//! # Почтой файлы ходят тем же протоколом
//!
//! **Расхождение со спецификацией**: §10.2 требует для чанков прямого
//! канала, §10.3 разрешает почте только «до 20 МБ вложением в одном письме».
//! У части людей почта — единственный транспорт, и буква обоих параграфов
//! означает для них «файлов нет».
//!
//! Поэтому чанки едут и почтой — по одному в письме, тем же оконным
//! протоколом. Отдельного механизма нет, и это главное решение: один
//! протокол на все транспорты означает, что передача, начатая почтой,
//! продолжается прямым каналом с того же места, стоит ему появиться.
//!
//! Различаются транспорты **тремя числами**, и все три живут здесь:
//! [`chunk_window`], [`ack_every`], [`stall_ms`]. Прежнее «оконный протокол
//! поверх почты не работает в принципе» было не выводом, а нежеланием
//! посчитать эти числа для почты; разбор — в `ARCHITECTURE.md`, 5аб.

use ratatosk_codec::{canonical, CodecError, Value};
use ratatosk_crypto::file::CHUNK_TAG_LEN;
use ratatosk_wire::SizeClass;

use crate::transport_policy::Transport;

/// Идентификатор файла.
pub type FileId = [u8; 16];

/// Запас под CBOR-конверт вокруг чанка (§9.1).
///
/// Чанк едет не голым: он лежит в поле `payload` конверта, рядом с `msg_id`,
/// меткой HLC, типом нагрузки и, для групп, `group_id`. Всё это тоже обязано
/// поместиться в кадр. Реальная накладка — около сотни байт; 256 взяты
/// с запасом, а достаточность запаса проверяется тестом
/// `a_full_chunk_fits_in_one_frame_with_its_envelope` на настоящем конверте,
/// а не на оценке.
pub const ENVELOPE_RESERVE_BYTES: usize = 256;

/// Размер чанка при передаче прямым каналом — класс L (§10.2).
///
/// **Расхождение со спецификацией, разрешённое в пользу арифметики.**
/// §10.2 говорит «чанками по 1 МиБ», §5.5 задаёт класс L равным 1 МиБ.
/// Вместе это невыполнимо: 1 МиБ — размер **кадра целиком**, включая
/// 42 байта заголовка, 16 байт тега и хотя бы один байт паддинга (§7).
/// Чанк ровно в 1 МиБ не помещается в кадр, который должен его нести.
///
/// Поэтому размер выводится из класса, а не задаётся числом: получается
/// чуть меньше мебибайта. Захардкоженная константа снова разошлась бы
/// с классом при первом же изменении формата заголовка.
pub const CHUNK_BYTES: usize = SizeClass::L.max_payload() - ENVELOPE_RESERVE_BYTES - CHUNK_TAG_LEN;

/// Размер чанка на эфирной ступени — класс S (§10.2).
///
/// **Число выводится из класса, а не задаётся руками**, ровно по той же
/// причине, что и [`CHUNK_BYTES`]: захардкоженная константа разошлась бы
/// с классом при первой же правке заголовка.
///
/// Почему эфиру отдельный размер — разбор целиком у [`chunk_bytes_for`].
pub const AIR_CHUNK_BYTES: usize =
    SizeClass::S.max_payload() - ENVELOPE_RESERVE_BYTES - CHUNK_TAG_LEN;

/// Каким чанком резать файл, который поедет этой ступенью.
///
/// # Почему у эфира размер свой
///
/// Кадр класса L до Android не доходит вовсе, а класс M теряется
/// на пятнадцати-двадцати пяти процентах — измерено замерами `/probe`
/// (0.4.8). Класс S проходит без единой потери, сотня за сотней. Лечится
/// это не транспортом: транспорт обязан довезти кадр любого класса или
/// честно отказать, а «этот класс у нас не ходит» — свойство передачи
/// файла, и решается оно размером чанка.
///
/// # Размер едет в предложении, а не выводится заново
///
/// Обе стороны обязаны одинаково нумеровать чанки, иначе передача
/// разваливается молча. Выводить размер из ступени на приёме нельзя:
/// §5.4 вправе увести файл на другую ступень посреди передачи, и стороны
/// разойдутся. Поэтому размер выбирается **один раз**, при составлении
/// предложения, и едет в нём полем ([`FileOffer::chunk_bytes`]).
///
/// Отсюда и оговорка, которую стоит знать: файл, предложенный по эфиру,
/// сохранит мелкий чанк и на локальной сети. Цена — больше кругов
/// на большом файле; выгода — он вообще доезжает.
#[must_use]
pub const fn chunk_bytes_for(via: Transport) -> usize {
    match via {
        Transport::Bt => AIR_CHUNK_BYTES,
        Transport::Lan | Transport::Ygg | Transport::Onion | Transport::Nostr | Transport::Mail => {
            CHUNK_BYTES
        }
    }
}

/// Предел размера **письма** (§5.3).
///
/// Мегабайты десятичные: ограничение приходит от почтовых серверов, а они
/// считают именно так.
///
/// Живёт здесь, а не только в транспорте, потому что от него зависит
/// арифметика чанка: кадр класса L обязан помещаться в письмо вместе
/// с base64 и бронёй ([`letter_bytes`]). Транспорт сверяется с этим же
/// числом — см. `chatmail::MAX_MESSAGE_BYTES`.
pub const MAX_LETTER_BYTES: u64 = 20_000_000;

/// Предел размера файла для почты — 100 МБ (§10.3, **расхождение
/// со спецификацией**).
///
/// §10.3 ставит здесь 20 МБ, и это число было верным, пока «файл почтой»
/// означало «файл одним письмом». Теперь файл едет тем же чанковым
/// протоколом (§10.2), что и по прямому каналу, — просто каждый чанк
/// уезжает отдельным письмом. Ограничение размера письма к размеру файла
/// после этого отношения не имеет.
///
/// # Что тогда ограничивает и почему именно так
///
/// Не письмо и **не ящик получателя**. Ящик защищает окно: отправитель
/// держит в полёте не больше [`chunk_window`] чанков, то есть
/// [`mail_window_bytes`] байт чужого ящика, сколько бы файл ни весил.
/// Получатель, ушедший в офлайн посреди передачи, копит окно и на этом
/// останавливается — окно закрыто, следующего письма не будет, пока он
/// не подтвердит.
///
/// Ограничивает **время**. Мебибайт чанка становится письмом на полтора
/// мебибайта, письмо идёт через SMTP-очередь и IMAP получателя, и всё это
/// через Tor. Сто мегабайт — около сотни писем: десятки минут при удачном
/// канале. Это ещё обозримо; гигабайт почтой — это сутки, о которых
/// честнее сказать «нужен прямой канал» (§14), чем показывать полоску,
/// которая не сдвинется до завтра.
///
/// Число, а не отсутствие числа: без предела передача, которую нельзя
/// закончить, всё равно началась бы — и §14 требует сказать об этом до
/// начала, а не после.
pub const MAIL_FILE_LIMIT_BYTES: u64 = 100_000_000;

/// Предел выгрузки с десктопа-компаньона мимо общей сети — 20 МБ (§13.4).
///
/// Отдельная константа, хотя число совпадает с прежним почтовым пределом.
/// Совпадение случайное: здесь ограничение не почтовое, а про **чужой
/// мобильный трафик**. Десктоп без общей сети выгружает файл через канал
/// телефона, и платит за это человек с телефоном. Свяжи эти два предела
/// одной константой — и первое же послабление почте молча раздало бы
/// чужой трафик.
pub const COMPANION_DIRECT_LIMIT_BYTES: u64 = 20_000_000;

/// Запас на всё, что едет вокруг кадра в письме.
///
/// Сюда попадают четыре разные вещи: заголовки письма вместе с адресами,
/// границы MIME и обе части конверта RFC 3156, броня OpenPGP с контрольной
/// суммой и семибайтовый заголовок пакета SEIPD (`chatmail::armor`).
/// По факту это около шестисот байт при коротких адресах; два килобайта
/// взяты так, чтобы запас пережил и длинный адрес.
///
/// Запас обязан быть **сверху**: по этой оценке ядро считает, сколько
/// чужого ящика занимает окно. Оценка снизу означала бы, что мы обещаем
/// собеседнику меньше, чем занимаем. Сторожит это тест
/// `a_letter_with_a_chunk_fits_the_limit` в `chatmail`, и сверяет он
/// оценку с **настоящим** собранным письмом.
pub const LETTER_OVERHEAD_BYTES: usize = 2048;

/// Во сколько байт письма обходится кадр такой длины.
///
/// Кадр едет в письме бронированным base64 (§5.3): четыре знака на каждые
/// три байта, плюс перевод строки каждые 76 знаков (RFC 2045), плюс
/// [`LETTER_OVERHEAD_BYTES`] на заголовки и броню.
///
/// Считается, а не берётся числом, потому что от него зависит сразу
/// три вещи: помещается ли чанк в письмо вообще, сколько ящика получателя
/// занимает окно ([`mail_window_bytes`]) и каким должен быть срок молчания
/// ([`stall_ms`]).
#[must_use]
pub const fn letter_bytes(frame_len: usize) -> usize {
    let base64 = frame_len.div_ceil(3) * 4;
    let lines = base64.div_ceil(LINE_LEN) * 2;
    base64 + lines + LETTER_OVERHEAD_BYTES
}

/// Длина строки base64 в письме — та же, что у транспорта (RFC 2045).
const LINE_LEN: usize = 76;

/// Сколько ящика получателя занимает открытое окно почтовой передачи.
///
/// Это и есть ответ на «а как же ограничение хранилища на chatmail»:
/// величина **не зависит от размера файла**. Ящик на 200 МиБ (столько даёт
/// нарочно скупой сервер вроде `tarpit.fun`) переживает передачу любого
/// разрешённого файла, потому что больше окна в нём одновременно не лежит,
/// а прочитанные письма наш приём удаляет сразу (`chatmail::imap`).
#[must_use]
pub const fn mail_window_bytes() -> u64 {
    chunk_window(Transport::Mail, CHUNK_BYTES) * letter_bytes(SizeClass::L.frame_len()) as u64
}

/// Предел размера превью — 32 КиБ, класс M (§10.3).
pub const PREVIEW_LIMIT_BYTES: usize = 32 * 1024;

/// Ключ файла.
pub type FileKey = [u8; 32];

/// Идентификатор чанка (§10.1) — он же ключ, которым чанк запечатан.
///
/// Деривация одна и живёт в `ratatosk_crypto::file`: §8.1 велит держать
/// комбинирование примитивов в одном модуле, покрытом тест-векторами.
/// Здесь — только имя, под которым её знает §10.1.
#[must_use]
pub fn chunk_id(file_key: &FileKey, index: u64) -> [u8; 32] {
    *ratatosk_crypto::file::chunk_key(file_key, index)
}

/// Сколько чанков в файле такого размера.
#[must_use]
pub fn chunk_count(size_bytes: u64, chunk_bytes: usize) -> u64 {
    if size_bytes == 0 {
        return 0;
    }
    size_bytes.div_ceil(chunk_bytes as u64)
}

/// Класс кадра для чанка файла — всегда L (§5.5).
#[must_use]
pub const fn chunk_size_class() -> SizeClass {
    SizeClass::L
}

/// Можно ли отправить файл этим транспортом (§10.3).
///
/// Спрашивают обе стороны и об одном и том же файле: получатель — прежде
/// чем попросить чанки почтой, отправитель — прежде чем их послать. Ответ
/// обязан совпасть, поэтому правило одно и лежит здесь, а не в двух местах
/// ядра.
#[must_use]
pub const fn may_send_over(size_bytes: u64, transport: Transport) -> bool {
    match transport {
        Transport::Lan | Transport::Ygg | Transport::Onion => true,
        // Bluetooth **везёт файлы**, и это решение по измерению, а не
        // по надежде. Мерилось на стенде (`HANDOFF.md`, 6з): мебибайт
        // проходит за десятки секунд — то есть файл в мегабайт едет
        // примерно минуту, а фотография в триста килобайт — секунд
        // двадцать. Для передачи, которую человек начал сам, это цена,
        // а не поломка.
        //
        // Две вещи, без которых этого разрешения не было бы, и обе
        // сделаны: чанк едет **своим каналом** L2CAP и потому не держит
        // за собой ни квитанций, ни переписки; и срок ожидания считается
        // от размера кадра, а не от имени ступени, — иначе мебибайт
        // объявлялся бы неудавшимся на середине пути.
        //
        // Предела по размеру здесь нет, в отличие от почты: ограничение
        // §10.3 («больше двадцати мегабайт — только прямым каналом»)
        // эфиру не мешает, он прямой. Двадцать мегабайт по нему — это
        // около четверти часа, и человеку это скажет не отказ, а время
        // на экране.
        Transport::Bt => true,
        // Nostr не везёт файлов вовсе, и это не «пока», а устройство
        // ступени. Чанк — кадр класса L, мебибайт (§5.5); реле ограничивают
        // событие десятками килобайт и вдобавок считают частоту. Один чанк
        // разложился бы на два десятка событий подряд, то есть на верный
        // отказ по частоте, — а окно `chunk_window` послало бы их восемь
        // таких разом.
        //
        // Предел по размеру, как у почты, здесь ничего бы не спас:
        // не проходит **любой** чанк, потому что класс у него всегда L.
        // Поэтому отказ безусловный, и разбирать его человеку не надо:
        // ниже стоит почта, и файл поедет ею.
        Transport::Nostr => false,
        Transport::Mail => size_bytes <= MAIL_FILE_LIMIT_BYTES,
    }
}

/// Почему передача файла стоит.
///
/// # Зачем это перечисление
///
/// Здесь был один текст на все случаи — «Файл будет отправлен, когда
/// получатель появится в сети», — и он оказался дорог. Четыре разных
/// состояния выглядели на экране одинаково, и **отладить по такому экрану
/// нельзя**: открытая поломка «файл не качается, потом качается сам»
/// стоила двух потраченных гипотез ровно потому, что различить их было
/// нечем.
///
/// Но это не только леса для отладки. §14 требует говорить правду
/// о происходящем, а «ждёт канала» вместо «ваш почтовый ящик переполнен»
/// — правда хуже той, которая у нас есть: во втором случае человек может
/// что-то сделать, и не сказать ему об этом нечестно.
///
/// # Пятая причина, которой не было вовсе
///
/// [`FileWait::Silent`] не покрывалась ничем: «мы не спросили» и
/// «мы спросили, а в ответ тишина» выглядели одинаково — то есть
/// не выглядели никак. Это разные поломки, и чинятся они в разных местах.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FileWait {
    /// Канала нет ни одного: собеседника не достать ничем.
    Nowhere,
    /// Годная дорога есть только почтой, а файл ей не по размеру (§10.3)
    /// — или свой сервер объявил предел письма меньше чанка.
    TooBig,
    /// Дорога годная есть, сессии по ней нет — рукопожатие начато.
    Handshaking,
    /// Свой почтовый ящик переполнен: чанкам некуда лечь.
    ///
    /// Спрашивается только на **приёме**: чанки ложатся в наш ящик.
    /// У отправки полный свой ящик ничего не значит — письма уходят
    /// в чужой.
    MailboxFull,
    /// Просьба ушла, чанков нет.
    ///
    /// Единственная причина, которая говорит о **собеседнике**,
    /// а не о нашей стороне: канал есть, спросили — молчит.
    Silent,
    /// Ступень занята другими передачами — ждём своей очереди (§10.2).
    ///
    /// Не поломка и не помеха: очередь заведена нарочно
    /// ([`parallel_files`]), потому что параллель на узком канале ничего
    /// не ускоряет, а мешает всем сразу. Сказать об этом человеку всё
    /// равно обязаны — иначе файл, честно стоящий в очереди, выглядит
    /// на экране зависшим.
    Queued,
}

impl FileWait {
    /// Что сказать человеку — дословно (§14).
    ///
    /// Тексты нейтральны к направлению: событие приходит и тому, кто
    /// отправляет, и тому, кто принимает, а «файл будет отправлен»
    /// у принимающего было бы неправдой.
    #[must_use]
    pub const fn text(self) -> &'static str {
        match self {
            FileWait::Nowhere => {
                "Связи с собеседником сейчас нет — передача продолжится, \
                                  когда он появится"
            }
            FileWait::TooBig => {
                "Файл слишком велик для почты — передача продолжится, \
                                 когда собеседник окажется на прямой связи"
            }
            FileWait::Handshaking => "Связь устанавливается — передача продолжится сразу после",
            FileWait::MailboxFull => {
                "Ваш почтовый ящик переполнен — освободите место, \
                                      и передача продолжится"
            }
            FileWait::Silent => "Собеседник пока не прислал ни одного куска — попросим ещё раз",
            FileWait::Queued => "Сейчас передаются другие файлы — этот продолжится следом",
        }
    }

    /// Короткое имя причины — для журнала и стенда, не для человека.
    ///
    /// Отдельно от [`FileWait::text`] нарочно: тот текст показывают,
    /// а это ищут глазами в выводе. Слить их — значит однажды показать
    /// человеку `mailbox-full`.
    #[must_use]
    pub const fn label(self) -> &'static str {
        match self {
            FileWait::Nowhere => "канала нет",
            FileWait::TooBig => "велик для почты",
            FileWait::Handshaking => "идёт рукопожатие",
            FileWait::MailboxFull => "свой ящик полон",
            FileWait::Silent => "спросили, молчат",
            FileWait::Queued => "ждёт очереди ступени",
        }
    }
}

/// Правило для десктопа-компаньона (§13.4).
///
/// Передача файлов больше [`COMPANION_DIRECT_LIMIT_BYTES`] с десктопа
/// разрешена **только когда оба устройства в одной сети** — иначе выгрузка
/// идёт через мобильный канал телефона. UI обязан сообщать об этом явно.
#[must_use]
pub const fn companion_may_upload(size_bytes: u64, same_network: bool) -> bool {
    size_bytes <= COMPANION_DIRECT_LIMIT_BYTES || same_network
}

/// Помещается ли превью в свой предел.
