"""Метёлка: копия моста в приложении не расходится с той, что лежит здесь.

Зачем. `android/BtRadio.kt` в этом дереве — не черновик: по нему написаны
проверки (`scan_budget`, `controller_asked`, `advert_interval`), и именно
он читается при разборе. А **ездит на устройство** другой файл — тот, что
лежит в дереве приложения (`Ratatosk-android`). Два места, одно правило,
и никто их не сличает.

Поломка, по которой метёлка заведена, прожила две недели. Правки 8–9 ноября
— окно квоты обзора, расспрос контроллера, предел пакета на запись, внятный
отказ канала — были написаны **только здесь**. В приложении осталась
прежняя копия, и ни одна сборка на телефон их не получила. Разошлись файлы
на девяносто строк, и всё это время прогон был зелёным: метёлки сверяли
файл, который никуда не едет.

Чего метёлка **не** стережёт:

* что соседнее дерево вообще есть. Нет — сверять не с чем, и об этом
  говорится вслух: ноль осмотренных файлов не то же, что «чисто»;
* что копия в приложении собирается. Kotlin в этом дереве не строится
  и не проверяется ничем;
* прочие файлы моста. Сличается ровно `BtRadio.kt` — тот, у которого
  здесь есть свои метёлки, то есть тот, про который можно соврать.
"""
import pathlib
import sys

# Корень дерева считается от самого файла: метёлку зовут и из корня, и из CI.
ROOT_DIR = pathlib.Path(__file__).resolve().parents[2]

HERE = ROOT_DIR / "android/BtRadio.kt"
# Приложение лежит **рядом** с ядром, а не внутри: у него свой репозиторий,
# своя сборка и свой срок жизни.
THERE = ROOT_DIR.parent / "Ratatosk-android/app/src/main/java/org/ratatosk/bt/BtRadio.kt"

found = []
seen = 0

if not HERE.exists():
    found.append("android/BtRadio.kt: мост пропал — метёлка смотрит не туда")
elif not THERE.exists():
    # Не находка: соседнего дерева может не быть ни в CI, ни на чужой машине.
    # Но и не «чисто»: сверено ноль файлов, и сказать это обязательно.
    print(f"соседнего дерева нет ({THERE}) — сверять не с чем")
else:
    seen = 1
    mine = HERE.read_text(encoding="utf-8").splitlines()
    theirs = THERE.read_text(encoding="utf-8").splitlines()
    if mine != theirs:
        first = next(
            (n for n, (a, b) in enumerate(zip(mine, theirs), 1) if a != b),
            min(len(mine), len(theirs)) + 1,
        )
        found.append(
            f"android/BtRadio.kt: копия в приложении разошлась со строки {first} "
            f"(здесь {len(mine)} строк, там {len(theirs)}) — на устройство едет она, "
            f"а метёлки читают эту"
        )

for line in found:
    print(line)
print(f"копий сверено: {seen}")
print("-- всего", len(found) if found else "чисто")

# Находок должно быть **ноль**.
sys.exit(1 if found else 0)
