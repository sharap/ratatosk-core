//! Пересылка сообщения в другой чат.
//!
//! **Спецификация v0.1 этого не описывает.** Дополнение, и §17 просит такие
//! вещи называть отдельно.
//!
//! # Автор не указывается, и это решение, а не упущение
//!
//! Переслать — значит отправить **своё новое сообщение** с чужими словами.
//! Получатель видит пометку «переслано» и не видит, от кого.
//!
//! Причина не в приватности вообще, а в том, что указать автора мы можем
//! только на словах. Подпись автора (§6) считается над байтами его конверта;
//! при пересылке конверт наш, метка HLC наша, ключ сессии наш — от исходного
//! сообщения остаётся один текст. Имя рядом с ним получатель проверить
//! не может: подставить туда любого может кто угодно, и первым это сделает
//! не тот, для кого функцию писали. Непроверяемое утверждение о третьем
//! человеке — ровно то, чего §14 просит не показывать.
//!
//! Вторая причина проще: пересылка рассказывает получателю о том, кто ещё есть
//! в переписке, а согласия на этот рассказ никто не давал.
//!
//! Пометка при этом обязательна. Без неё чужие слова выглядят своими, а это
//! неправда в обратную сторону — и о ней собеседник тоже имеет право знать.
//!
//! # Что едет
//!
//! Только текст. Вложений в v0.1 ещё нет (§10 — следующий этап), и когда они
//! появятся, пересылка файла будет означать пересылку **ключа и хэша** —
//! отдельное решение с отдельными последствиями, а не расширение этого.
//!
//! Отдельного формата полезной нагрузки у пересылки нет: едет тот же текст,
//! что и в обычном сообщении, разница — в типе конверта (`PayloadType::Forward`).
//! Из этого следует и совместимость: клиент, который типа не знает, сообщение
//! **не покажет** — это лучше, чем показать чужие слова без пометки, потеряв
//! ровно то, о чём весь модуль.

/// Сколько сообщений можно переслать одной командой.
///
/// Предел здесь мягче, чем у отзыва: каждое переслáнное сообщение — отдельная
/// запись в очереди §5.4 и отдельный кадр, поэтому «переслать сотню» означает
/// сотню кадров подряд. Двадцать — это переписка, которую пересылают целиком,
/// а не выгрузка чата.
pub const MAX_FORWARD_IDS: usize = 20;
