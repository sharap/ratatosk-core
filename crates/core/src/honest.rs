    #[test]
    fn the_nostr_warning_names_the_price_before_the_benefit() {
        // Порядок здесь — не стиль, а суть §14: предупреждение, в котором
        // выгода стоит первой, а цена в конце, прочитывается как реклама
        // с оговоркой. Проверяется грубо — расстоянием между словами,
        // — и этого довольно, чтобы переписанная в рекламную строка
        // не прошла молча.
        let price = NOSTR_WARNING.find("видят").expect("цена названа");
        let remedy = NOSTR_WARNING.find("выбираете вы").expect("и средство тоже");
        assert!(price < remedy, "цена обязана стоять раньше средства");

        // И ровно то, чего ступень стоит, названо словами, а не намёком:
        // граф переписки виден реле, содержимое — нет.
        assert!(NOSTR_WARNING.contains("содержимого они не видят"));

        // И обещание про Tor стоит **с условием**: у ступени есть
        // переключатель, и безусловное «скрывает Tor» было бы верно лишь
        // при настройке по умолчанию — то есть неправдой в тех самых
        // местах, ради которых переключатель и заведён.
        assert!(
            NOSTR_WARNING.contains("по умолчанию скрывает Tor"),
            "обещание про Tor подано без оговорки: {NOSTR_WARNING}"
        );
    }

    #[test]
    fn the_direct_warning_names_the_price_and_leaves_the_choice() {
        // Размен, а не запрет: там, где Tor заблокирован, ступень без этого
        // переключателя не работает вовсе, и предупреждение, кончающееся
        // на одном запугивании, толкало бы человека выключить ступень
        // целиком — то есть остаться вовсе без связи.
        assert!(NOSTR_DIRECT_WARNING.contains("адрес вашего устройства"), "цена названа");
        assert!(NOSTR_DIRECT_WARNING.contains("постоянный"), "и то, что ключ не сменить легко");
        assert!(
            NOSTR_DIRECT_WARNING.contains("там, где Tor не работает"),
            "и случай, ради которого переключатель есть"
        );
    }

