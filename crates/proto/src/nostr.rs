    #[test]
    fn a_part_fits_a_cautious_relay() {
        // Та же арифметика, что в объяснении `PART_BYTES`, посчитанная
        // заново: правка одного числа не должна молча разойтись с остальными.
        // Разойдись она — реле отвергало бы каждое событие, и снаружи это
        // выглядело бы как «nostr не работает», без единой подсказки.
        const FRAME_OF_EVENT_BYTES: usize = 1024;
        let raw = PART_BYTES + PART_HEADER_LEN;
        let base64 = raw.div_ceil(3) * 4;
        let whole = base64 + FRAME_OF_EVENT_BYTES;
        assert!(
            whole < SAFE_EVENT_BYTES,
            "часть с обвязкой не влезает: {whole} из {SAFE_EVENT_BYTES}"
        );

        // И запас обязан остаться заметным: предел у каждого реле свой,
        // а наш — только пол, ниже которого не опускается никто.
        //
        // **Здесь первая редакция требовала половины и не сходилась
        // сорока четырьмя байтами.** Права оказалась не проверка, а код:
        // половина была взята с потолка, а пояснение к `PART_BYTES` меряет
        // запас иначе — восемь килобайт против тех одиннадцати с половиной,
        // что влезли бы. Цифру в утверждении надо выводить из того, что
        // написано в объяснении, а не придумывать рядом: разойдясь, они
        // означают проверку, которая ловит собственную выдумку.
        //
        // Настоящее требование — целое событие в три четверти пола.
        assert!(
            whole * 4 <= SAFE_EVENT_BYTES * 3,
            "событие занимает {whole} из {SAFE_EVENT_BYTES} — запаса почти нет"
        );

        // Самый крупный кадр режется на число частей, которое сборщик §9.3
        // принимает. Кадры класса L этой ступенью не ходят вовсе, но
        // проверить потолок дешевле, чем однажды упереться в него.
        let biggest = ratatosk_wire::SizeClass::L.frame_len();
        let parts = biggest.div_ceil(PART_BYTES) as u64;
        assert!(parts <= crate::fragment::MAX_FRAGMENTS, "частей больше, чем сборщик берёт");
        assert!(u16::try_from(parts).is_ok(), "номер части не влезает в поле заголовка");
    }

    #[test]
    fn a_frame_of_the_small_class_fits_a_cautious_relay() {
        // Ровно то число, на котором стоит вся ступень: кадр класса S
        // обязан уезжать одним событием, иначе резать придётся даже
        // обычное сообщение. Четыре килобайта в base64 — примерно пять
        // с половиной, и запас до предела остаётся троекратный.
        let frame = ratatosk_wire::SizeClass::S.frame_len();
        let base64 = frame.div_ceil(3) * 4;
        assert!(base64 < SAFE_EVENT_BYTES, "кадр S не влезает: {base64} из {SAFE_EVENT_BYTES}");

        // А класс M — уже нет, и это не досада, а то, что раннер обязан
        // знать заранее: его придётся резать.
        let big = ratatosk_wire::SizeClass::M.frame_len().div_ceil(3) * 4;
        assert!(big > SAFE_EVENT_BYTES, "класс M внезапно влез — пересмотреть резку");
    }
