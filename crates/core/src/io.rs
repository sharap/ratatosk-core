//! Вход и выход ядра.
//!
//! Ядро — чистая функция состояния: `(состояние, вход, время) → (состояние,
//! эффекты)`. Оно ничего не ждёт и ничего не делает само; всё, что должно
//! случиться во внешнем мире, возвращается списком [`Effect`].
//!
//! Из этого следует главное свойство, ради которого §17 требует делать
//! харнесс первым: чтобы прогнать неделю разделения сети (§16), достаточно
//! подавать входы и исполнять эффекты в цикле с виртуальным временем.

use ratatosk_crdt::MsgId;
use ratatosk_proto::transport_policy::Transport;
use ratatosk_proto::DeliveryStatus;

/// Идентификатор чата — 1:1 или группы.
pub type ChatId = [u8; 16];

/// Что пользователь просит сделать.
#[derive(Debug, Clone)]
pub enum Command {
    /// Отправить текст.
    SendText {
        /// Куда.
        chat: ChatId,
        /// Что.
        text: String,
    },
    /// Отправить файл (§10).
    SendFile {
        /// Куда.
        chat: ChatId,
        /// Путь на диске.
        path: std::path::PathBuf,
    },
    /// Добавить контакт по карточке из QR или ссылки (§4.2).
    AddContact {
        /// Канонические байты карточки.
        card_bytes: Vec<u8>,
        /// Получена при личной встрече — отпечаток сверять не нужно (§4.2).
        met_in_person: bool,
    },
    /// Подтвердить сверку отпечатка голосом (§4.2).
    MarkVerified {
        /// Чей отпечаток сверили.
        peer_ik: [u8; 32],
    },
    /// Создать группу.
    CreateGroup {
        /// Название.
        title: String,
    },
    /// Пригласить в группу (§11.2).
    InviteToGroup {
        /// Группа.
        chat: ChatId,
        /// Кого.
        peer_ik: [u8; 32],
    },
    /// Исключить из группы. Только создатель (§11.2).
    EvictFromGroup {
        /// Группа.
        chat: ChatId,
        /// Кого.
        peer_ik: [u8; 32],
    },
    /// Отметить сообщения прочитанными.
    MarkRead {
        /// Чат.
        chat: ChatId,
        /// До какого сообщения включительно.
        up_to: MsgId,
    },
    /// Включить или выключить LAN (§5.1).
    SetLanEnabled(bool),
}

/// Что произошло снаружи.
#[derive(Debug, Clone)]
pub enum Input {
    /// Команда от UI.
    Command(Command),
    /// Пришли байты из транспорта.
    Received {
        /// Каким транспортом.
        via: Transport,
        /// Байты кадра.
        frame: Vec<u8>,
    },
    /// Контакт замечен в LAN (§5.1).
    SeenOnLan {
        /// Чей маяк совпал.
        peer_ik: [u8; 32],
    },
    /// Соединение установлено.
    Connected {
        /// С кем.
        peer_ik: [u8; 32],
        /// Каким транспортом.
        via: Transport,
    },
    /// Соединение разорвано или не удалось (§5.4).
    ConnectionLost {
        /// С кем.
        peer_ik: [u8; 32],
        /// Каким транспортом.
        via: Transport,
    },
    /// Сработал таймер, поставленный эффектом [`Effect::SetTimer`].
    Timer {
        /// Метка таймера.
        token: u64,
    },
}

/// Что ядро просит сделать внешний мир.
#[derive(Debug, Clone)]
pub enum Effect {
    /// Отправить кадр. Ровно один транспорт на эффект (§5.4).
    Send {
        /// Кому.
        peer_ik: [u8; 32],
        /// Каким транспортом.
        via: Transport,
        /// Готовый кадр.
        frame: Vec<u8>,
    },
    /// Установить соединение.
    Connect {
        /// С кем.
        peer_ik: [u8; 32],
        /// Каким транспортом.
        via: Transport,
    },
    /// Поставить таймер.
    SetTimer {
        /// Через сколько мс.
        after_ms: u64,
        /// Метка, которая вернётся во [`Input::Timer`].
        token: u64,
    },
    /// Включить или выключить объявление в LAN.
    SetLanEnabled(bool),
    /// Чьи маяки искать в эфире LAN (§5.1).
    ///
    /// Маяк ротируется и вычисляется от `IK` контакта, поэтому транспорт
    /// обязан знать список известных контактов: сравнивать принятую
    /// TXT-запись ему иначе не с чем. Список едет эффектом, а не читается
    /// транспортом из ядра, потому что §13.3 запрещает протокольному
    /// состоянию просачиваться вниз иначе как через эту границу.
    WatchLanPeers(Vec<[u8; 32]>),
    /// Сообщить UI о событии.
    Notify(Event),
}

/// Событие для UI.
#[derive(Debug, Clone)]
pub enum Event {
    /// Пришло сообщение.
    MessageReceived {
        /// В каком чате.
        chat: ChatId,
        /// Идентификатор.
        msg_id: MsgId,
    },
    /// Изменился статус доставки (§9.4).
    StatusChanged {
        /// Какое сообщение.
        msg_id: MsgId,
        /// Новый статус.
        status: DeliveryStatus,
    },
    /// Добавлен контакт.
    ContactAdded {
        /// Чей.
        peer_ik: [u8; 32],
        /// Отпечаток для показа пользователю (§3).
        fingerprint: String,
        /// Сверен ли отпечаток. Пока нет — UI обязан пометить контакт
        /// непроверенным (§4.2).
        verified: bool,
    },
    /// Изменился состав группы (§11.2).
    GroupMembershipChanged {
        /// Какая группа.
        chat: ChatId,
    },
    /// Ход передачи файла (§10.2).
    FileProgress {
        /// Какой файл.
        file_id: [u8; 16],
        /// Принято чанков.
        received: u64,
        /// Всего чанков.
        total: u64,
    },
    /// Сообщение, которое обязано быть показано дословно (§14).
    ///
    /// Отдельный вариант нужен, чтобы формулировки из §14 нельзя было
    /// «улучшить» в клиенте: раздел существует ровно затем, чтобы обещания
    /// продукта не разошлись со свойствами протокола.
    HonestNotice {
        /// Текст.
        text: &'static str,
    },
}
