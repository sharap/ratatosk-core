//! Ответ на сообщение.
//!
//! **Спецификация v0.1 этого не описывает.** Дополнение, и §17 просит такие
//! вещи называть отдельно.
//!
//! # Едет ссылка, а не цитата
//!
//! В кадре — `msg_id` того сообщения, на которое отвечают, и текст ответа.
//! Отрывка цитаты нет, и это решение, а не экономия.
//!
//! Цитату каждая сторона рисует **из своей копии** сообщения. Значит, её
//! нельзя подделать: отправив ссылку, собеседник не может вложить в цитату
//! слова, которых человек не говорил. Присланный отрывок проверить было бы
//! нечем — тот же довод, по которому пересылка не несёт имени автора
//! (`crate::forward`). Цитата, которую нельзя проверить, убеждает ровно так же,
//! как настоящая, и именно поэтому её тут нет.
//!
//! Заодно кадр остаётся маленьким: ответ на длинное сообщение не удваивается
//! в размере, а класс размера (§5.5) не растёт от того, на что отвечают.
//!
//! # Чего у этого решения стоит
//!
//! Если исходного сообщения у получателя нет — он его удалил, или оно
//! не дошло, или ушло уборкой (§12), — цитировать нечего. Тогда UI обязан
//! сказать прямо: «сообщение недоступно». Не придумывать текст, не прятать
//! ответ, не показывать пустую рамку — сказать. Это ровно тот случай, ради
//! которого §14 написан: показать нечего, и врать об этом нельзя.
//!
//! **Сам ответ при этом сохраняется всегда.** Ссылка, которую не удалось
//! разрешить, не повод потерять текст: ответ — это слова человека, и они
//! ценнее контекста, который к ним прилагался.
//!
//! # Отвечать можно на любое сообщение своего чата
//!
//! И на своё, и на чужое. Запрет здесь не на что опереть, а правило «только
//! на чужое» пришлось бы объяснять.
//!
//! Ссылка на сообщение **другого** чата отвергается получателем: чтобы
//! назвать такой `msg_id`, собеседник должен знать идентификатор, которого
//! ему знать неоткуда. Текст ответа при этом сохраняется — теряется только
//! ссылка.

use ratatosk_codec::{canonical, CodecError, Value};
use ratatosk_crdt::MsgId;

/// Ключ идентификатора сообщения, на которое отвечают.
const KEY_TARGET: u64 = 1;
/// Ключ текста ответа.
const KEY_TEXT: u64 = 2;

/// Почему ответ не принят.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum ReplyError {
    /// Ответ без слов: цитата — не сообщение, показывать было бы нечего.
    #[error("ответ без текста")]
    Empty,
    /// Сообщения, на которое отвечают, в этом чате нет.
    #[error("сообщение, на которое отвечают, не найдено")]
    TargetMissing,
}

/// Годится ли текст в ответ.
///
/// Отдельно от [`from_payload`], потому что зовётся дважды и с разных сторон:
/// на границе UniFFI — чтобы человек узнал об отказе сразу, пока у него открыто
/// поле ввода, — и в ядре, потому что граница проверок не гарантирует. Правило
/// при этом одно, записанное в одном месте.
///
/// # Errors
///
/// [`ReplyError::Empty`], если после обрезки пробелов ничего не осталось.
pub fn check(text: &str) -> Result<(), ReplyError> {
    if text.trim().is_empty() {
        return Err(ReplyError::Empty);
    }
    Ok(())
}

/// Собирает полезную нагрузку ответа.
#[must_use]
pub fn payload(target: MsgId, text: &str) -> Value {
    Value::Map(vec![
        (Value::Integer(KEY_TARGET.into()), Value::Bytes(target.to_vec())),
        (Value::Integer(KEY_TEXT.into()), Value::Text(text.to_owned())),
    ])
}

/// Разбирает полезную нагрузку ответа.
///
/// Всё приходит от собеседника, поэтому проверяется и длина идентификатора,
/// и то, что текст не пуст: ответ без слов — это не ответ, а ссылка,
/// показать которую человеку нечем.
///
/// # Errors
///
/// [`CodecError::TypeMismatch`], если структура не та или текст пуст.
pub fn from_payload(value: &Value) -> Result<(MsgId, String), CodecError> {
    let map = canonical::as_map(value)?;
    let target = canonical::as_array::<16>(canonical::require(map, KEY_TARGET)?)?;
    let Value::Text(text) = canonical::require(map, KEY_TEXT)? else {
        return Err(CodecError::TypeMismatch);
    };
    if check(text).is_err() {
        return Err(CodecError::TypeMismatch);
    }
    Ok((target, text.clone()))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_reply_round_trips() {
        let (target, text) = from_payload(&payload([5u8; 16], "согласен")).unwrap();
        assert_eq!(target, [5u8; 16]);
        assert_eq!(text, "согласен");
    }

    #[test]
    fn a_reply_without_words_is_refused() {
        // Своя проверка — до отправки, чтобы человек узнал сразу.
        assert_eq!(check("  "), Err(ReplyError::Empty));
        // И на приёме: ответ без слов показать нечем.
        assert!(from_payload(&payload([1u8; 16], "  ")).is_err());
    }

    #[test]
    fn a_wrong_sized_identifier_is_refused() {
        let bad = Value::Map(vec![
            (Value::Integer(KEY_TARGET.into()), Value::Bytes(vec![0u8; 4])),
            (Value::Integer(KEY_TEXT.into()), Value::Text("да".into())),
        ]);
        assert!(from_payload(&bad).is_err());
    }

    #[test]
    fn the_quote_itself_never_travels() {
        // Тест на форму кадра, а не на поведение: в нагрузке ровно два ключа.
        // Появившийся третий (отрывок цитаты) означал бы, что текст, который
        // получатель не может проверить, всё-таки поехал.
        let Value::Map(entries) = payload([1u8; 16], "да") else {
            panic!("ожидалась карта")
        };
        assert_eq!(entries.len(), 2, "цитата в кадр не кладётся — только ссылка");
    }
}
