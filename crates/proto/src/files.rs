//! Файлы (§10).
//!
//! Файл шифруется случайным `file_key` (32 байта), передаваемым в сообщении.
//! `chunk_id = BLAKE3_derive_key("ratatosk v0 file", file_key ‖ index)`.
//! Хэш для проверки целостности считается **от шифротекста**.
//!
//! Content-addressing по хэшу открытого содержимого не применяется (§10.1):
//! он позволил бы проверять наличие у вас конкретного известного файла.
//! Это не оптимизация, а решение модели угроз — менять его нельзя, не
//! переписав §2.
//!
//! # Почтой файлы ходят тем же протоколом
//!
//! **Расхождение со спецификацией**: §10.2 требует для чанков прямого
//! канала, §10.3 разрешает почте только «до 20 МБ вложением в одном письме».
//! У части людей почта — единственный транспорт, и буква обоих параграфов
//! означает для них «файлов нет».
//!
//! Поэтому чанки едут и почтой — по одному в письме, тем же оконным
//! протоколом. Отдельного механизма нет, и это главное решение: один
//! протокол на все транспорты означает, что передача, начатая почтой,
//! продолжается прямым каналом с того же места, стоит ему появиться.
//!
//! Различаются транспорты **тремя числами**, и все три живут здесь:
//! [`chunk_window`], [`ack_every`], [`stall_ms`]. Прежнее «оконный протокол
//! поверх почты не работает в принципе» было не выводом, а нежеланием
//! посчитать эти числа для почты; разбор — в `ARCHITECTURE.md`, 5аб.

use ratatosk_codec::{canonical, CodecError, Value};
use ratatosk_crypto::file::CHUNK_TAG_LEN;
use ratatosk_wire::SizeClass;

use crate::transport_policy::Transport;

/// Идентификатор файла.
pub type FileId = [u8; 16];

/// Запас под CBOR-конверт вокруг чанка (§9.1).
///
/// Чанк едет не голым: он лежит в поле `payload` конверта, рядом с `msg_id`,
/// меткой HLC, типом нагрузки и, для групп, `group_id`. Всё это тоже обязано
/// поместиться в кадр. Реальная накладка — около сотни байт; 256 взяты
/// с запасом, а достаточность запаса проверяется тестом
/// `a_full_chunk_fits_in_one_frame_with_its_envelope` на настоящем конверте,
/// а не на оценке.
pub const ENVELOPE_RESERVE_BYTES: usize = 256;

/// Размер чанка при передаче прямым каналом — класс L (§10.2).
///
/// **Расхождение со спецификацией, разрешённое в пользу арифметики.**
/// §10.2 говорит «чанками по 1 МиБ», §5.5 задаёт класс L равным 1 МиБ.
/// Вместе это невыполнимо: 1 МиБ — размер **кадра целиком**, включая
/// 42 байта заголовка, 16 байт тега и хотя бы один байт паддинга (§7).
/// Чанк ровно в 1 МиБ не помещается в кадр, который должен его нести.
///
/// Поэтому размер выводится из класса, а не задаётся числом: получается
/// чуть меньше мебибайта. Захардкоженная константа снова разошлась бы
/// с классом при первом же изменении формата заголовка.
pub const CHUNK_BYTES: usize = SizeClass::L.max_payload() - ENVELOPE_RESERVE_BYTES - CHUNK_TAG_LEN;

/// Предел размера **письма** (§5.3).
///
/// Мегабайты десятичные: ограничение приходит от почтовых серверов, а они
/// считают именно так.
///
/// Живёт здесь, а не только в транспорте, потому что от него зависит
/// арифметика чанка: кадр класса L обязан помещаться в письмо вместе
/// с base64 и бронёй ([`letter_bytes`]). Транспорт сверяется с этим же
/// числом — см. `chatmail::MAX_MESSAGE_BYTES`.
pub const MAX_LETTER_BYTES: u64 = 20_000_000;

/// Предел размера файла для почты — 100 МБ (§10.3, **расхождение
/// со спецификацией**).
///
/// §10.3 ставит здесь 20 МБ, и это число было верным, пока «файл почтой»
/// означало «файл одним письмом». Теперь файл едет тем же чанковым
/// протоколом (§10.2), что и по прямому каналу, — просто каждый чанк
/// уезжает отдельным письмом. Ограничение размера письма к размеру файла
/// после этого отношения не имеет.
///
/// # Что тогда ограничивает и почему именно так
///
/// Не письмо и **не ящик получателя**. Ящик защищает окно: отправитель
/// держит в полёте не больше [`chunk_window`] чанков, то есть
/// [`mail_window_bytes`] байт чужого ящика, сколько бы файл ни весил.
/// Получатель, ушедший в офлайн посреди передачи, копит окно и на этом
/// останавливается — окно закрыто, следующего письма не будет, пока он
/// не подтвердит.
///
/// Ограничивает **время**. Мебибайт чанка становится письмом на полтора
/// мебибайта, письмо идёт через SMTP-очередь и IMAP получателя, и всё это
/// через Tor. Сто мегабайт — около сотни писем: десятки минут при удачном
/// канале. Это ещё обозримо; гигабайт почтой — это сутки, о которых
/// честнее сказать «нужен прямой канал» (§14), чем показывать полоску,
/// которая не сдвинется до завтра.
///
/// Число, а не отсутствие числа: без предела передача, которую нельзя
/// закончить, всё равно началась бы — и §14 требует сказать об этом до
/// начала, а не после.
pub const MAIL_FILE_LIMIT_BYTES: u64 = 100_000_000;

/// Предел выгрузки с десктопа-компаньона мимо общей сети — 20 МБ (§13.4).
///
/// Отдельная константа, хотя число совпадает с прежним почтовым пределом.
/// Совпадение случайное: здесь ограничение не почтовое, а про **чужой
/// мобильный трафик**. Десктоп без общей сети выгружает файл через канал
/// телефона, и платит за это человек с телефоном. Свяжи эти два предела
/// одной константой — и первое же послабление почте молча раздало бы
/// чужой трафик.
pub const COMPANION_DIRECT_LIMIT_BYTES: u64 = 20_000_000;

/// Запас на всё, что едет вокруг кадра в письме.
///
/// Сюда попадают четыре разные вещи: заголовки письма вместе с адресами,
/// границы MIME и обе части конверта RFC 3156, броня OpenPGP с контрольной
/// суммой и семибайтовый заголовок пакета SEIPD (`chatmail::armor`).
/// По факту это около шестисот байт при коротких адресах; два килобайта
/// взяты так, чтобы запас пережил и длинный адрес.
///
/// Запас обязан быть **сверху**: по этой оценке ядро считает, сколько
/// чужого ящика занимает окно. Оценка снизу означала бы, что мы обещаем
/// собеседнику меньше, чем занимаем. Сторожит это тест
/// `a_letter_with_a_chunk_fits_the_limit` в `chatmail`, и сверяет он
/// оценку с **настоящим** собранным письмом.
pub const LETTER_OVERHEAD_BYTES: usize = 2048;

/// Во сколько байт письма обходится кадр такой длины.
///
/// Кадр едет в письме бронированным base64 (§5.3): четыре знака на каждые
/// три байта, плюс перевод строки каждые 76 знаков (RFC 2045), плюс
/// [`LETTER_OVERHEAD_BYTES`] на заголовки и броню.
///
/// Считается, а не берётся числом, потому что от него зависит сразу
/// три вещи: помещается ли чанк в письмо вообще, сколько ящика получателя
/// занимает окно ([`mail_window_bytes`]) и каким должен быть срок молчания
/// ([`stall_ms`]).
#[must_use]
pub const fn letter_bytes(frame_len: usize) -> usize {
    let base64 = frame_len.div_ceil(3) * 4;
    let lines = base64.div_ceil(LINE_LEN) * 2;
    base64 + lines + LETTER_OVERHEAD_BYTES
}

/// Длина строки base64 в письме — та же, что у транспорта (RFC 2045).
const LINE_LEN: usize = 76;

/// Сколько ящика получателя занимает открытое окно почтовой передачи.
///
/// Это и есть ответ на «а как же ограничение хранилища на chatmail»:
/// величина **не зависит от размера файла**. Ящик на 200 МиБ (столько даёт
/// нарочно скупой сервер вроде `tarpit.fun`) переживает передачу любого
/// разрешённого файла, потому что больше окна в нём одновременно не лежит,
/// а прочитанные письма наш приём удаляет сразу (`chatmail::imap`).
#[must_use]
pub const fn mail_window_bytes() -> u64 {
    chunk_window(Transport::Mail) * letter_bytes(SizeClass::L.frame_len()) as u64
}

/// Предел размера превью — 32 КиБ, класс M (§10.3).
pub const PREVIEW_LIMIT_BYTES: usize = 32 * 1024;

/// Ключ файла.
pub type FileKey = [u8; 32];

/// Идентификатор чанка (§10.1) — он же ключ, которым чанк запечатан.
///
/// Деривация одна и живёт в `ratatosk_crypto::file`: §8.1 велит держать
/// комбинирование примитивов в одном модуле, покрытом тест-векторами.
/// Здесь — только имя, под которым её знает §10.1.
#[must_use]
pub fn chunk_id(file_key: &FileKey, index: u64) -> [u8; 32] {
    *ratatosk_crypto::file::chunk_key(file_key, index)
}

/// Сколько чанков в файле такого размера.
#[must_use]
pub fn chunk_count(size_bytes: u64) -> u64 {
    if size_bytes == 0 {
        return 0;
    }
    size_bytes.div_ceil(CHUNK_BYTES as u64)
}

/// Класс кадра для чанка файла — всегда L (§5.5).
#[must_use]
pub const fn chunk_size_class() -> SizeClass {
    SizeClass::L
}

/// Можно ли отправить файл этим транспортом (§10.3).
///
/// Спрашивают обе стороны и об одном и том же файле: получатель — прежде
/// чем попросить чанки почтой, отправитель — прежде чем их послать. Ответ
/// обязан совпасть, поэтому правило одно и лежит здесь, а не в двух местах
/// ядра.
#[must_use]
pub const fn may_send_over(size_bytes: u64, transport: Transport) -> bool {
    match transport {
        Transport::Lan | Transport::Ygg | Transport::Onion => true,
        // Bluetooth **везёт файлы**, и это решение по измерению, а не
        // по надежде. Мерилось на стенде (`HANDOFF.md`, 6з): мебибайт
        // проходит за десятки секунд — то есть файл в мегабайт едет
        // примерно минуту, а фотография в триста килобайт — секунд
        // двадцать. Для передачи, которую человек начал сам, это цена,
        // а не поломка.
        //
        // Две вещи, без которых этого разрешения не было бы, и обе
        // сделаны: чанк едет **своим каналом** L2CAP и потому не держит
        // за собой ни квитанций, ни переписки; и срок ожидания считается
        // от размера кадра, а не от имени ступени, — иначе мебибайт
        // объявлялся бы неудавшимся на середине пути.
        //
        // Предела по размеру здесь нет, в отличие от почты: ограничение
        // §10.3 («больше двадцати мегабайт — только прямым каналом»)
        // эфиру не мешает, он прямой. Двадцать мегабайт по нему — это
        // около четверти часа, и человеку это скажет не отказ, а время
        // на экране.
        Transport::Bt => true,
        // Nostr не везёт файлов вовсе, и это не «пока», а устройство
        // ступени. Чанк — кадр класса L, мебибайт (§5.5); реле ограничивают
        // событие десятками килобайт и вдобавок считают частоту. Один чанк
        // разложился бы на два десятка событий подряд, то есть на верный
        // отказ по частоте, — а окно `chunk_window` послало бы их восемь
        // таких разом.
        //
        // Предел по размеру, как у почты, здесь ничего бы не спас:
        // не проходит **любой** чанк, потому что класс у него всегда L.
        // Поэтому отказ безусловный, и разбирать его человеку не надо:
        // ниже стоит почта, и файл поедет ею.
        Transport::Nostr => false,
        Transport::Mail => size_bytes <= MAIL_FILE_LIMIT_BYTES,
    }
}

/// Почему передача файла стоит.
///
/// # Зачем это перечисление
///
/// Здесь был один текст на все случаи — «Файл будет отправлен, когда
/// получатель появится в сети», — и он оказался дорог. Четыре разных
/// состояния выглядели на экране одинаково, и **отладить по такому экрану
/// нельзя**: открытая поломка «файл не качается, потом качается сам»
/// стоила двух потраченных гипотез ровно потому, что различить их было
/// нечем.
///
/// Но это не только леса для отладки. §14 требует говорить правду
/// о происходящем, а «ждёт канала» вместо «ваш почтовый ящик переполнен»
/// — правда хуже той, которая у нас есть: во втором случае человек может
/// что-то сделать, и не сказать ему об этом нечестно.
///
/// # Пятая причина, которой не было вовсе
///
/// [`FileWait::Silent`] не покрывалась ничем: «мы не спросили» и
/// «мы спросили, а в ответ тишина» выглядели одинаково — то есть
/// не выглядели никак. Это разные поломки, и чинятся они в разных местах.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FileWait {
    /// Канала нет ни одного: собеседника не достать ничем.
    Nowhere,
    /// Годная дорога есть только почтой, а файл ей не по размеру (§10.3)
    /// — или свой сервер объявил предел письма меньше чанка.
    TooBig,
    /// Дорога годная есть, сессии по ней нет — рукопожатие начато.
    Handshaking,
    /// Свой почтовый ящик переполнен: чанкам некуда лечь.
    ///
    /// Спрашивается только на **приёме**: чанки ложатся в наш ящик.
    /// У отправки полный свой ящик ничего не значит — письма уходят
    /// в чужой.
    MailboxFull,
    /// Просьба ушла, чанков нет.
    ///
    /// Единственная причина, которая говорит о **собеседнике**,
    /// а не о нашей стороне: канал есть, спросили — молчит.
    Silent,
}

impl FileWait {
    /// Что сказать человеку — дословно (§14).
    ///
    /// Тексты нейтральны к направлению: событие приходит и тому, кто
    /// отправляет, и тому, кто принимает, а «файл будет отправлен»
    /// у принимающего было бы неправдой.
    #[must_use]
    pub const fn text(self) -> &'static str {
        match self {
            FileWait::Nowhere => {
                "Связи с собеседником сейчас нет — передача продолжится, \
                                  когда он появится"
            }
            FileWait::TooBig => {
                "Файл слишком велик для почты — передача продолжится, \
                                 когда собеседник окажется на прямой связи"
            }
            FileWait::Handshaking => "Связь устанавливается — передача продолжится сразу после",
            FileWait::MailboxFull => {
                "Ваш почтовый ящик переполнен — освободите место, \
                                      и передача продолжится"
            }
            FileWait::Silent => "Собеседник пока не прислал ни одного куска — попросим ещё раз",
        }
    }

    /// Короткое имя причины — для журнала и стенда, не для человека.
    ///
    /// Отдельно от [`FileWait::text`] нарочно: тот текст показывают,
    /// а это ищут глазами в выводе. Слить их — значит однажды показать
    /// человеку `mailbox-full`.
    #[must_use]
    pub const fn label(self) -> &'static str {
        match self {
            FileWait::Nowhere => "канала нет",
            FileWait::TooBig => "велик для почты",
            FileWait::Handshaking => "идёт рукопожатие",
            FileWait::MailboxFull => "свой ящик полон",
            FileWait::Silent => "спросили, молчат",
        }
    }
}

/// Правило для десктопа-компаньона (§13.4).
///
/// Передача файлов больше [`COMPANION_DIRECT_LIMIT_BYTES`] с десктопа
/// разрешена **только когда оба устройства в одной сети** — иначе выгрузка
/// идёт через мобильный канал телефона. UI обязан сообщать об этом явно.
#[must_use]
pub const fn companion_may_upload(size_bytes: u64, same_network: bool) -> bool {
    size_bytes <= COMPANION_DIRECT_LIMIT_BYTES || same_network
}

/// Помещается ли превью в свой предел.
#[must_use]
pub const fn preview_fits(bytes: usize) -> bool {
    bytes <= PREVIEW_LIMIT_BYTES
}

/// Наибольший размер файла в v1 — 2 ГиБ.
///
/// Предел нужен не арифметике (счётчик чанков `u64` и так не переполнится),
/// а трём вещам сразу. Учёт принятых чанков — строка на чанк, и без верхней
/// границы её нечем оценить. Очередь §5.4 обслуживает один файл целиком,
/// и без предела один файл занимает канал на неопределённый срок. И честность:
/// оставшееся время можно показать только там, где известен размер.
pub const MAX_FILE_BYTES: u64 = 2 * 1024 * 1024 * 1024;

/// Сколько файлов можно прикрепить к одному сообщению.
///
/// Предел на приёме, как у квитанций и отзыва: список приходит от собеседника.
/// Десять — это «скинуть фотографии с прогулки», а не выгрузка галереи.
pub const MAX_FILES_PER_MESSAGE: usize = 10;

/// Наибольшая длина имени файла в символах.
pub const MAX_FILE_NAME_CHARS: usize = 255;

/// Порог автоматического приёма по умолчанию — 512 КиБ.
///
/// Значение по умолчанию, а не правило: порог настраивается, и «никогда»
/// (`None`) — законная настройка. Мелочь вроде фотографии приезжает сама,
/// как в любом мессенджере; всё, что крупнее, ждёт нажатия. Чужой клиент
/// не должен уметь занять память телефона, не спросив.
pub const DEFAULT_AUTO_ACCEPT_BYTES: u64 = 512 * 1024;

/// Сколько чанков отправитель шлёт вперёд подтверждённого получателем.
///
/// Окно, а не «шлём всё подряд», и это не оптимизация. Без окна ядро выдало бы
/// драйверу все чанки файла одним шагом — два гигабайта эффектов в памяти
/// у процесса, который на Android убивают за меньшее.
///
/// # Прямым каналом — два, а не четыре
///
/// Число это про отзывчивость, а не про пропускную способность. Кадры
/// к одному собеседнику идут одной очередью, и обычное сообщение,
/// отправленное посреди передачи файла, ждёт всего, что уже в полёте.
/// Четыре чанка — это четыре мебибайта ожидания на медленном Wi-Fi,
/// то есть «сообщения не отправляются, пока идёт файл». Два — вдвое меньше,
/// и при подтверждении на **каждый** чанк ([`ack_every`]) конвейер всё равно
/// не простаивает: подтверждение приходит, пока уходит следующий чанк.
///
/// # Почтой — восемь, и это **ограничитель хранилища**
///
/// У почты окно работает ещё и как договор о чужом ящике. Каждый чанк —
/// отдельное письмо, и всё, что отправлено, но не подтверждено, лежит
/// в ящике получателя. Открытое окно и есть верхняя граница того, сколько
/// его ящика мы заняли: [`mail_window_bytes`], около двенадцати мегабайт,
/// **сколько бы файл ни весил**. Получатель ушёл в офлайн — окно закрылось,
/// и передача остановилась сама, не добив его квоту.
///
/// Восемь, а не два, потому что цена круга у почты другая. Круг здесь —
/// это SMTP-очередь, IMAP получателя, его ответ и наш IMAP: минуты, а не
/// миллисекунды. Окно в два чанка означало бы два мебибайта за круг, то есть
/// сто мегабайт за сутки. Восемь укладывают тот же файл в десятки минут
/// и всё ещё занимают у получателя меньше шести процентов скупой
/// двухсотмебибайтной квоты.
///
/// Дороже это только памятью: восемь писем по полтора мегабайта — это
/// двенадцать мегабайт в очереди раннера. Много для служебной очереди
/// и приемлемо для передачи, которую человек начал сам.
#[must_use]
pub const fn chunk_window(via: Transport) -> u64 {
    match via {
        // Bluetooth здесь с прямыми каналами, и опасение «два мебибайта
        // в полёте на медленном канале — это затор» снято тем, что
        // затора теперь нет: объёмные кадры едут по эфиру **отдельным
        // каналом** L2CAP и за собой ничего не держат. Два чанка —
        // наименьшее окно, которое вообще считается конвейером, и больше
        // на этой скорости не нужно.
        Transport::Lan | Transport::Bt | Transport::Ygg | Transport::Onion => 2,
        // Nostr стоит рядом с почтой, и до этой ветки доходить нечему:
        // [`may_send_over`] чанков туда не пускает вовсе. Число тут затем,
        // что разбор обязан быть исчерпывающим, и выбрано оно **не наугад**:
        // случись ступени однажды научиться возить чанки, умолчание не
        // должно оказаться оптимистичнее самой терпеливой из соседних.
        Transport::Nostr | Transport::Mail => 8,
    }
}

/// Через сколько принятых чанков получатель подтверждает приём.
///
/// Прямым каналом — каждый. Подтверждение — крохотный кадр класса S (§5.5)
/// рядом с мебибайтом чанка, экономить на нём нечего, а редкие подтверждения
/// при маленьком окне останавливают передачу.
///
/// Почтой — каждый четвёртый, то есть половина окна. Не ради экономии:
/// подтверждение почтой — это отдельное письмо, и восемь писем в ответ
/// на восемь писем удваивают и трафик, и след у сервера (§2.2). Половина
/// окна — наименьшее число, при котором окно не успевает закрыться:
/// подтверждение на четвёртом чанке двигает границу как раз тогда, когда
/// у отправителя остаётся ещё четыре в полёте.
#[must_use]
pub const fn ack_every(via: Transport) -> u64 {
    match via {
        Transport::Lan | Transport::Bt | Transport::Ygg | Transport::Onion => 1,
        // Опять рядом с почтой и опять недостижимо — см. `chunk_window`.
        Transport::Nostr | Transport::Mail => 4,
    }
}

/// Сколько ждать чанк, прежде чем спросить заново (§10.2).
///
/// Сторожит получатель, и срок отсчитывается от **последнего пришедшего**
/// чанка: каждый заводит срок заново. То есть это ответ на вопрос «за это
/// время не пришло ничего».
///
/// **Зависит от транспорта, и это не тонкость, а условие работоспособности.**
/// Чанк — мебибайт (класс L, §5.5). По локальной сети он уходит
/// за миллисекунды, через три реле Tor — за десятки секунд, а ждать
/// получателю приходится ещё и того, что уже в полёте: окно
/// [`chunk_window`] держит на линии до двух мебибайт.
///
/// Срок короче этого времени не «ускоряет возобновление», а ломает передачу
/// совсем. Получатель объявляет молчанием чанк, который в этот момент идёт
/// по проводу, и просит начать заново; отправитель отматывает окно и кладёт
/// в ту же линию **второй экземпляр** того же мебибайта. Линия становится
/// медленнее, следующий срок выходит ещё вернее, и передача разгоняет сама
/// себя в обратную сторону. Снаружи: «файл начинает загружаться и никогда
/// не догружается» — с настоящим прогрессом между срывами, потому что
/// что-то всё-таки доезжает.
///
/// Числа поэтому пессимистичные. Локальная сеть: десять секунд это запас
/// в тысячу раз, и он ни на что не влияет. Onion: два мебибайта окна
/// при скромных тридцати килобайтах в секунду это семьдесят секунд, отсюда
/// две минуты. Дорого ждать столько впустую — но обрыв канала ловится
/// не этим сроком, а разрывом сессии (§5.4), после которого передачу
/// возобновляет появление канала. Этот срок — последняя страховка,
/// и ей положено быть терпеливой.
///
/// # Почта — полчаса, и это тот же расчёт, доведённый до конца
///
/// Окно почты — восемь чанков, то есть около двенадцати мегабайт писем
/// ([`mail_window_bytes`]). Эти двенадцать мегабайт проходят сеть **дважды**:
/// от отправителя на сервер и с сервера получателю. При тех же скромных
/// тридцати килобайтах в секунду это тринадцать минут — и это ещё до того,
/// как письмо полежит в SMTP-очереди. Полчаса — вдвое, и тест
/// `the_stall_deadline_outlasts_a_window_on_every_transport` держит именно
/// это соотношение.
#[must_use]
pub const fn stall_ms(via: Transport) -> u64 {
    match via {
        Transport::Lan => 10_000,
        // Меш ближе к onion, чем к локальной сети: маршрут может
        // перестроиться на ходу, и чанк, ушедший по прежнему пути,
        // опаздывает на секунды. Десять секунд объявляли бы застой там,
        // где идёт обычная передача.
        Transport::Ygg | Transport::Onion => 120_000,
        // Эфир — своя ветка, и число здесь **посчитано по измеренной
        // скорости**, а не списано у соседа. Окно — два чанка, то есть
        // два мебибайта; при скромных двадцати килобайтах в секунду
        // (`floor_bytes_per_sec`) они идут почти две минуты. Срок молчания
        // короче этого не ускорил бы возобновление, а сломал бы передачу
        // совсем — получатель объявлял бы застоем чанк, который в этот
        // миг идёт по воздуху.
        //
        // Пять минут — те же две с запасом почти втрое. Запас здесь стоит
        // дёшево: обрыв канала ловится не этим сроком, а разрывом связи,
        // и срок — последняя страховка.
        Transport::Bt => 300_000,
        // И здесь рядом с почтой, по той же причине — см. `chunk_window`.
        Transport::Nostr | Transport::Mail => 30 * 60_000,
    }
}

/// Наибольший срок молчания при отступлении — двенадцать часов.
pub const MAX_STALL_MS: u64 = 12 * 3600 * 1000;

/// Срок молчания на `attempt`-й безответной попытке подряд.
///
/// Удвоение с потолком. Нужно оно ровно одному случаю — почте, и случай
/// этот не редкий: собеседник ушёл на выходные. Без отступления получатель
/// спрашивал бы про брошенную передачу письмом каждые полчаса — сорок восемь
/// писем в сутки, каждое со своим следом у chatmail-сервера (§2.2)
/// и со своим куском чужой квоты. С отступлением их семь за те же сутки.
///
/// Счётчик обнуляет **любой** пришедший чанк, а не удачная просьба: удачей
/// здесь считается движение файла, а не то, что письмо ушло.
///
/// Прямых каналов это почти не касается: там срок и так секунды, а обрыв
/// ловится разрывом сессии. Но правило одно на все транспорты — отдельная
/// ветка «почте отступать, остальным нет» разошлась бы с первой же правкой.
#[must_use]
pub const fn stall_backoff_ms(via: Transport, attempt: u32) -> u64 {
    let base = stall_ms(via);
    // Множитель ограничен заранее, и `if` здесь вместо `min` не по вкусу:
    // `Ord::min` не константна. Без ограничения `1 << attempt` уехал бы
    // в панику за сутки брошенной передачи.
    let shift = if attempt > 20 { 20 } else { attempt };
    let value = base.saturating_mul(1u64 << shift);
    if value > MAX_STALL_MS {
        MAX_STALL_MS
    } else {
        value
    }
}

/// Ключ идентификатора файла в нагрузке.
const KEY_FILE_ID: u64 = 1;
/// Ключ списка файлов в предложении.
const KEY_FILES: u64 = 2;
/// Ключ признака «переслано» у предложения файлов.
///
/// Отдельным признаком, а не отдельным типом нагрузки, как у текста
/// (`PayloadType::Forward`), и причина прозаична: тип уже занят под
/// «предложение файлов», а второй означал бы вторую копию всего разбора
/// вложений. Признак необязателен на чтении — сборка постарше покажет
/// пересланный файл без пометки, и это единственное, что она потеряет.
const KEY_FORWARDED: u64 = 3;
/// Ключ подписи к файлам.
const KEY_CAPTION: u64 = 1;
/// Ключ имени файла.
const KEY_NAME: u64 = 2;
/// Ключ размера.
const KEY_SIZE: u64 = 3;
/// Ключ файлового ключа (§10.1).
const KEY_FILE_KEY: u64 = 4;
/// Ключ превью.
const KEY_PREVIEW: u64 = 6;
/// Ключ номера чанка — он же номер, с которого просят продолжить.
const KEY_INDEX: u64 = 2;
/// Ключ байтов чанка.
const KEY_BYTES: u64 = 3;
/// Ключ признака «до меня ничего не доходит» в просьбе.
const KEY_STALLED: u64 = 3;

/// Почему файл не принят.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum FileError {
    /// Больше [`MAX_FILE_BYTES`].
    #[error("файл больше {MAX_FILE_BYTES} байт")]
    TooLarge,
    /// Файлов в сообщении больше [`MAX_FILES_PER_MESSAGE`].
    #[error("к одному сообщению можно приложить не больше {MAX_FILES_PER_MESSAGE} файлов")]
    TooMany,
    /// Имя пустое, слишком длинное или содержит путь.
    #[error("недопустимое имя файла")]
    BadName,
    /// Превью больше [`PREVIEW_LIMIT_BYTES`].
    #[error("превью больше {PREVIEW_LIMIT_BYTES} байт")]
    PreviewTooLarge,
}

/// Предложение одного файла — то, что едет в `PayloadType::FileOffer`.
///
/// Ключ файла едет здесь же, и иначе нельзя: §10.1 передаёт `file_key`
/// «в сообщении», то есть по уже установленной сессии. Отдельного обмена
/// ключами для файлов нет и не нужно — кадр с предложением уже зашифрован
/// сессионным ключом.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FileOffer {
    /// Идентификатор файла — по нему адресуются чанки.
    pub file_id: FileId,
    /// Имя для показа. **Не путь**: см. [`check_name`].
    pub name: String,
    /// Размер открытого содержимого.
    pub size_bytes: u64,
    /// Ключ файла (§10.1).
    pub key: FileKey,
    /// Превью изображения до [`PREVIEW_LIMIT_BYTES`] (§10.3).
    pub preview: Option<Vec<u8>>,
}

/// Проверяет имя файла.
///
/// Имя приходит от собеседника и попадает на экран, а при сохранении —
/// в имя файла на диске. Поэтому здесь отвергаются разделители пути,
/// управляющие символы и «точечные» имена: получатель хранит файл под своим
/// `file_id` и чужое имя путём не считает, но правило дешевле привычки —
/// первый же клиент, который склеит имя с каталогом, получит запись куда
/// угодно.
///
/// # Errors
///
/// [`FileError::BadName`].
pub fn check_name(name: &str) -> Result<(), FileError> {
    let trimmed = name.trim();
    if trimmed.is_empty() || trimmed.chars().count() > MAX_FILE_NAME_CHARS {
        return Err(FileError::BadName);
    }
    if trimmed == "." || trimmed == ".." {
        return Err(FileError::BadName);
    }
    if trimmed.chars().any(|c| c == '/' || c == '\\' || c.is_control()) {
        return Err(FileError::BadName);
    }
    Ok(())
}

/// Запас под одно предложение файла помимо превью.
///
/// `file_id` (16), ключ файла (32), размер, ключи CBOR — и имя длиной
/// до [`MAX_FILE_NAME_CHARS`], которое в UTF-8 занимает до четырёх байт
/// на символ. Число с запасом, и достаточность запаса проверяется тестом
/// `a_message_with_ten_previewed_files_fits_one_frame` на настоящем
/// конверте, а не на оценке.
pub const OFFER_RESERVE_BYTES: usize = 256 + MAX_FILE_NAME_CHARS * 4;

/// Наибольшая длина текста сообщения в **байтах** (не символах).
///
/// **Выводится, а не назначается.** Текст едет в одном кадре с предложениями
/// файлов (`offer_payload`), и худший случай — десять вложений, у каждого
/// превью в 32 КиБ и имя в 255 символов. Всё это обязано поместиться в кадр
/// класса L вместе с текстом; значит текст — это то, что от кадра остаётся.
///
/// Одно число на все случаи, а не два: «столько, если без файлов, и столько,
/// если с ними» — правило, которое клиент однажды применит не то. Ценой
/// становится то, что у сообщения без вложений остаётся неиспользованный
/// запас, — и это дешевле ошибки.
///
/// **Байты, а не символы**, и клиент обязан считать так же: кириллица
/// в UTF-8 идёт по два байта, эмодзи по четыре, и счётчик символов
/// в поле ввода обманул бы человека ровно вдвое.
pub const MAX_TEXT_BYTES: usize = SizeClass::L.max_payload()
    - ENVELOPE_RESERVE_BYTES
    - MAX_FILES_PER_MESSAGE * (PREVIEW_LIMIT_BYTES + OFFER_RESERVE_BYTES);

/// Помещается ли текст сообщения в предел.
#[must_use]
pub const fn text_fits(bytes: usize) -> bool {
    bytes <= MAX_TEXT_BYTES
}

/// Проверяет одно предложение файла — до отправки и на приёме.
///
/// # Errors
///
/// [`FileError`] по первому нарушению.
pub fn check_offer(offer: &FileOffer) -> Result<(), FileError> {
    check_name(&offer.name)?;
    if offer.size_bytes > MAX_FILE_BYTES {
        return Err(FileError::TooLarge);
    }
    if offer.preview.as_ref().is_some_and(|p| !preview_fits(p.len())) {
        return Err(FileError::PreviewTooLarge);
    }
    Ok(())
}

/// Проверяет весь список вложений сообщения.
///
/// # Errors
///
/// [`FileError::TooMany`] или ошибка любого из файлов.
pub fn check_offers(offers: &[FileOffer]) -> Result<(), FileError> {
    if offers.len() > MAX_FILES_PER_MESSAGE {
        return Err(FileError::TooMany);
    }
    for offer in offers {
        check_offer(offer)?;
    }
    Ok(())
}

/// Принимать ли файл такого размера автоматически.
///
/// `None` означает «никогда»: человек принимает каждый файл руками. Это
/// законная настройка, а не отключённая функция.
#[must_use]
pub const fn auto_accept(size_bytes: u64, threshold: Option<u64>) -> bool {
    match threshold {
        Some(limit) => size_bytes <= limit,
        None => false,
    }
}

/// Собирает нагрузку предложения: подпись и список файлов.
#[must_use]
pub fn offer_payload(caption: &str, offers: &[FileOffer], forwarded: bool) -> Value {
    let files = offers
        .iter()
        .map(|offer| {
            let mut entry = vec![
                (Value::Integer(KEY_FILE_ID.into()), Value::Bytes(offer.file_id.to_vec())),
                (Value::Integer(KEY_NAME.into()), Value::Text(offer.name.clone())),
                (Value::Integer(KEY_SIZE.into()), Value::Integer(offer.size_bytes.into())),
                (Value::Integer(KEY_FILE_KEY.into()), Value::Bytes(offer.key.to_vec())),
            ];
            if let Some(preview) = &offer.preview {
                entry.push((Value::Integer(KEY_PREVIEW.into()), Value::Bytes(preview.clone())));
            }
            Value::Map(entry)
        })
        .collect();
    let mut fields = vec![
        (Value::Integer(KEY_CAPTION.into()), Value::Text(caption.to_owned())),
        (Value::Integer(KEY_FILES.into()), Value::Array(files)),
    ];
    // Ключа нет — «не переслано»: так короче обычный случай и так же
    // читает его сборка постарше.
    if forwarded {
        fields.push((Value::Integer(KEY_FORWARDED.into()), Value::Bool(true)));
    }
    Value::Map(fields)
}

/// Разбирает нагрузку предложения.
///
/// Проверяется всё: число файлов, длина каждого поля, имя, размер, превью.
/// Список приходит от собеседника, и единственная защита от «предложения»
/// на тысячу файлов — вот эта проверка.
///
/// # Errors
///
/// [`CodecError::TypeMismatch`], если структура не та или что-то не прошло
/// [`check_offers`].
pub fn offer_from_payload(value: &Value) -> Result<(String, Vec<FileOffer>, bool), CodecError> {
    let map = canonical::as_map(value)?;
    let Value::Text(caption) = canonical::require(map, KEY_CAPTION)? else {
        return Err(CodecError::TypeMismatch);
    };
    let Value::Array(items) = canonical::require(map, KEY_FILES)? else {
        return Err(CodecError::TypeMismatch);
    };
    if items.len() > MAX_FILES_PER_MESSAGE {
        return Err(CodecError::TypeMismatch);
    }

    let mut offers = Vec::with_capacity(items.len());
    for item in items {
        let entry = canonical::as_map(item)?;
        // Превью необязательно: у документа его нет вовсе. Отсутствие ключа —
        // законный случай, а вот ключ не того типа — нет.
        let preview = match canonical::get(entry, KEY_PREVIEW) {
            Some(Value::Bytes(bytes)) => Some(bytes.clone()),
            Some(_) => return Err(CodecError::TypeMismatch),
            None => None,
        };
        offers.push(FileOffer {
            file_id: canonical::as_array::<16>(canonical::require(entry, KEY_FILE_ID)?)?,
            name: match canonical::require(entry, KEY_NAME)? {
                Value::Text(name) => name.clone(),
                _ => return Err(CodecError::TypeMismatch),
            },
            size_bytes: canonical::as_u64(canonical::require(entry, KEY_SIZE)?)?,
            key: canonical::as_array::<32>(canonical::require(entry, KEY_FILE_KEY)?)?,
            preview,
        });
    }
    if check_offers(&offers).is_err() {
        return Err(CodecError::TypeMismatch);
    }
    // Признак необязателен: сборка постарше его не везла. Отсутствие
    // и `false` означают одно и то же, а ключ не того типа — порчу.
    let forwarded = match canonical::get(map, KEY_FORWARDED) {
        Some(Value::Bool(flag)) => *flag,
        Some(_) => return Err(CodecError::TypeMismatch),
        None => false,
    };
    Ok((caption.clone(), offers, forwarded))
}

/// Собирает нагрузку чанка.
#[must_use]
pub fn chunk_payload(file_id: FileId, index: u64, sealed: &[u8]) -> Value {
    Value::Map(vec![
        (Value::Integer(KEY_FILE_ID.into()), Value::Bytes(file_id.to_vec())),
        (Value::Integer(KEY_INDEX.into()), Value::Integer(index.into())),
        (Value::Integer(KEY_BYTES.into()), Value::Bytes(sealed.to_vec())),
    ])
}

/// Разбирает нагрузку чанка.
///
/// Длина проверяется здесь: чанк больше положенного означает либо чужую
/// сборку, либо попытку заставить нас держать в памяти больше, чем нужно.
///
/// # Errors
///
/// [`CodecError::TypeMismatch`].
pub fn chunk_from_payload(value: &Value) -> Result<(FileId, u64, Vec<u8>), CodecError> {
    let map = canonical::as_map(value)?;
    let file_id = canonical::as_array::<16>(canonical::require(map, KEY_FILE_ID)?)?;
    let index = canonical::as_u64(canonical::require(map, KEY_INDEX)?)?;
    let Value::Bytes(sealed) = canonical::require(map, KEY_BYTES)? else {
        return Err(CodecError::TypeMismatch);
    };
    if sealed.len() > CHUNK_BYTES + CHUNK_TAG_LEN || sealed.len() < CHUNK_TAG_LEN {
        return Err(CodecError::TypeMismatch);
    }
    Ok((file_id, index, sealed.clone()))
}

/// Собирает просьбу продолжить передачу с указанного чанка (§10.2).
///
/// Она же подтверждение: «всё до этого номера у меня есть». Кадр один, но
/// **говорит он две разные вещи**, и различает их флаг `stalled`.
///
/// # Почему флаг, а не догадка
///
/// Найдено на живом стенде, и стоило это зависшей передачи. Сначала кадр был
/// один и без флага: отправитель сам решал, подтверждение перед ним или
/// просьба начать заново, — по тому, продвинулся ли номер. Догадка неверна.
///
/// Получатель подтверждает **следующий недостающий** чанк, а у отправителя
/// в это время в полёте ещё несколько. Сроки молчания у получателя выходят
/// вразнобой, и в какой-то момент он честно просит номер, который уже просил.
/// Отправитель читает это как «ничего не дошло», отматывает отправку назад
/// и шлёт по второму разу то, что уже в пути. Каждый повтор у получателя —
/// новый срок молчания и новая просьба, и передача сама себя разгоняет:
/// файл «грузится вечно», а очередь кадров к этому собеседнику забита
/// мебибайтами, из-за чего не уходят и обычные сообщения.
///
/// Получатель прекрасно знает, что имеет в виду. Поэтому он это и говорит:
/// `stalled = false` — «принял, шлите дальше» (окно едет вперёд, ничего
/// не пересылается), `stalled = true` — «за целый срок ничего не пришло,
/// начните с этого номера» (отправка отматывается). Догадок больше нет.
#[must_use]
pub fn request_payload(file_id: FileId, next_index: u64, stalled: bool) -> Value {
    Value::Map(vec![
        (Value::Integer(KEY_FILE_ID.into()), Value::Bytes(file_id.to_vec())),
        (Value::Integer(KEY_INDEX.into()), Value::Integer(next_index.into())),
        (Value::Integer(KEY_STALLED.into()), Value::Bool(stalled)),
    ])
}

/// Разбирает просьбу продолжить передачу.
///
/// Возвращает номер и признак «до меня ничего не доходит».
///
/// # Errors
///
/// [`CodecError::TypeMismatch`].
pub fn request_from_payload(value: &Value) -> Result<(FileId, u64, bool), CodecError> {
    let map = canonical::as_map(value)?;
    let file_id = canonical::as_array::<16>(canonical::require(map, KEY_FILE_ID)?)?;
    let index = canonical::as_u64(canonical::require(map, KEY_INDEX)?)?;
    let Value::Bool(stalled) = canonical::require(map, KEY_STALLED)? else {
        return Err(CodecError::TypeMismatch);
    };
    Ok((file_id, index, *stalled))
}

