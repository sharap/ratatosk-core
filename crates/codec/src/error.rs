//! Ошибки кодека.

use thiserror::Error;

/// Отказ разобрать или собрать структуру.
#[derive(Debug, Clone, PartialEq, Eq, Error)]
pub enum CodecError {
    /// Не удалось закодировать значение.
    #[error("ошибка кодирования CBOR")]
    Encode,

    /// Не удалось разобрать CBOR.
    #[error("ошибка разбора CBOR")]
    Decode,

    /// В карте встретился один и тот же ключ дважды.
    ///
    /// RFC 8949 требует уникальности ключей, но важнее практическая причина:
    /// при дубле одна реализация возьмёт первое значение, другая — последнее,
    /// подпись сойдётся у обеих, а прочитают они разное. Это классическое
    /// расхождение реализаций, и принимать такие структуры нельзя.
    #[error("повторяющийся ключ в карте")]
    DuplicateKey {
        /// Закодированное представление ключа — для диагностики.
        key: Vec<u8>,
    },

    /// Байты разобрались, но не в каноническом виде (§6).
    ///
    /// Отвергается, а не «чинится»: приняв неканоническую форму, мы получили бы
    /// два байтовых представления одной структуры и, значит, две разные подписи.
    #[error("структура не в детерминированной форме")]
    NotCanonical,

    /// Обязательное поле отсутствует.
    #[error("отсутствует обязательное поле {key}")]
    MissingField {
        /// Числовой ключ поля.
        key: u64,
    },

    /// Поле есть, но не того типа.
    #[error("поле неожиданного типа")]
    TypeMismatch,

    /// Мажорная версия протокола старше поддерживаемой (§6).
    #[error("версия протокола {got} новее поддерживаемой {supported}")]
    FutureVersion {
        /// Версия из структуры.
        got: u64,
        /// Версия этой сборки.
        supported: u64,
    },

    /// Некорректный URI контакт-карточки (§4.1).
    #[error("некорректная ссылка контакта")]
    BadContactUri,

    /// Версия карточки не выросла (§4.3).
    ///
    /// Получатель принимает только строго большую версию: иначе откат к старым
    /// адресам был бы способом увести переписку на прежний, уже
    /// скомпрометированный, канал.
    #[error("версия карточки не выросла: {got} против известной {known}")]
    StaleCardVersion {
        /// Версия из полученной карточки.
        got: u64,
        /// Уже известная версия.
        known: u64,
    },

    /// В `CardUpdate` изменились `IK`/`SK` (§4.3).
    ///
    /// Это уже другая идентичность, а не обновление адресов.
    #[error("обновление карточки меняет идентичность")]
    IdentityChanged,
}

/// Результат операции кодека.
pub type Result<T> = core::result::Result<T, CodecError>;
